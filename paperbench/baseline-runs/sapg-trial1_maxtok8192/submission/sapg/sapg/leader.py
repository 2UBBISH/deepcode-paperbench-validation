"""Leader policy aggregation and update for SAPG.

The leader is the *deployed* policy.  It is trained on the union of all
transitions collected by every follower (off-policy data from the leader's
perspective).  Because the data was generated by the followers, the PPO
clipped surrogate objective is evaluated with importance weights that account
for the mismatch between the follower behaviour policy and the leader policy.

Key idea (paper): "aggregate all off-policy data from followers to train a
leader policy via PPO's clipped surrogate objective".  No transition is
wasted -- every follower's rollout contributes to the leader update.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Dict, List, Optional

import torch
import torch.nn as nn

from .buffer import AggregatedBuffer, RolloutBuffer
from .networks import GaussianPolicy, ValueNetwork
from .ppo import (
    KLScheduler,
    PPOHyperParams,
    clip_grad_norm_,
    compute_ppo_loss,
    explained_variance,
    normalize_advantages,
)


@dataclass
class LeaderStats:
    """Aggregated diagnostics for a single leader update."""

    policy_loss: float = 0.0
    value_loss: float = 0.0
    entropy: float = 0.0
    bounds_loss: float = 0.0
    approx_kl: float = 0.0
    clip_fraction: float = 0.0
    total_loss: float = 0.0
    explained_variance: float = 0.0
    grad_norm: float = 0.0
    learning_rate: float = 0.0
    num_updates: int = 0
    num_transitions: int = 0
    # Off-policy diagnostics
    mean_importance_weight: float = 1.0
    max_importance_weight: float = 1.0

    def to_dict(self, prefix: str = "leader/") -> Dict[str, float]:
        out = {
            "policy_loss": self.policy_loss,
            "value_loss": self.value_loss,
            "entropy": self.entropy,
            "bounds_loss": self.bounds_loss,
            "approx_kl": self.approx_kl,
            "clip_fraction": self.clip_fraction,
            "total_loss": self.total_loss,
            "explained_variance": self.explained_variance,
            "grad_norm": self.grad_norm,
            "learning_rate": self.learning_rate,
            "num_updates": float(self.num_updates),
            "num_transitions": float(self.num_transitions),
            "mean_importance_weight": self.mean_importance_weight,
            "max_importance_weight": self.max_importance_weight,
        }
        return {f"{prefix}{k}": v for k, v in out.items()}


class Leader:
    """The deployed leader policy trained on aggregated follower data.

    The leader shares the same ``B_theta`` / ``C_psi`` networks as the
    followers but is conditioned on its own parameter vector ``phi`` (the
    "leader" phi).  During the leader update, each aggregated transition is
    re-evaluated under the *follower* phi that produced it (stored in the
    buffer) to compute the behaviour log-probability, and under the leader phi
    to compute the new log-probability.  The ratio between the two is the
    off-policy importance weight used inside the clipped surrogate.
    """

    def __init__(
        self,
        policy: GaussianPolicy,
        value: ValueNetwork,
        optimizer: torch.optim.Optimizer,
        phi: Optional[torch.Tensor] = None,
        hparams: Optional[PPOHyperParams] = None,
        kl_scheduler: Optional[KLScheduler] = None,
        device: str = "cpu",
        use_importance_weights: bool = True,
    ) -> None:
        self.policy = policy
        self.value = value
        self.optimizer = optimizer
        self.hparams = hparams or PPOHyperParams()
        self.kl_scheduler = kl_scheduler
        self.device = device
        self.use_importance_weights = use_importance_weights

        phi_dim = getattr(policy, "phi_dim", 0)
        if phi is not None:
            self.phi = phi.to(device)
        elif phi_dim > 0:
            # Leader gets its own distinct conditioning vector.
            self.phi = torch.zeros(1, phi_dim, device=device)
        else:
            self.phi = None

    # ------------------------------------------------------------------
    # Inference (deployment)
    # ------------------------------------------------------------------
    @torch.no_grad()
    def act(self, obs, lstm_state=None, deterministic: bool = False):
        """Act with the leader policy (used for evaluation / deployment)."""
        return self.policy.act(
            obs,
            self.phi,
            block_ids=None,
            lstm_state=lstm_state,
            deterministic=deterministic,
        )

    # ------------------------------------------------------------------
    # Aggregation helpers
    # ------------------------------------------------------------------
    @staticmethod
    def aggregate(buffers: List[RolloutBuffer], device: str = "cpu") -> AggregatedBuffer:
        """Concatenate all followers' rollouts into a single buffer."""
        return AggregatedBuffer(buffers, device=device)

    # ------------------------------------------------------------------
    # Leader update
    # ------------------------------------------------------------------
    def update(
        self,
        buffers: List[RolloutBuffer],
        last_values: Optional[List[torch.Tensor]] = None,
        last_dones: Optional[List[torch.Tensor]] = None,
        generator: Optional[torch.Generator] = None,
    ) -> LeaderStats:
        """Update the leader on the union of all followers' transitions.

        Parameters
        ----------
        buffers:
            One :class:`RolloutBuffer` per follower.  Advantages must already
            be computed (``compute_advantages`` called) for each buffer.
        last_values / last_dones:
            Optional bootstrap values/dones per follower (unused if advantages
            are pre-computed).
        generator:
            Optional RNG for reproducible shuffling.
        """
        hp = self.hparams
        device = self.device

        # 1. Aggregate ALL transitions from ALL followers (no data waste).
        agg = AggregatedBuffer(buffers, device=device)
        num_transitions = agg.num_transitions
        if num_transitions == 0:
            return LeaderStats()

        # 2. Determine mini-batch count: mini-batch size = num_envs * 4.
        num_envs = sum(b.num_envs for b in buffers)
        mini_batch_size = max(1, num_envs * 4)
        num_minibatches = max(1, num_transitions // mini_batch_size)

        stats = LeaderStats(num_transitions=num_transitions)
        n_updates = 0
        iw_sum = 0.0
        iw_max = 0.0
        iw_count = 0

        for _epoch in range(max(1, hp.mini_epochs)):
            for batch in agg.get_minibatches(
                num_minibatches, shuffle=True, generator=generator
            ):
                obs = batch["obs"].to(device)
                actions = batch["actions"].to(device)
                old_log_probs = batch["log_probs"].to(device)
                values_old = batch["values"].to(device)
                advantages = batch["advantages"].to(device)
                returns = batch["returns"].to(device)
                block_ids = batch.get("block_ids")
                if block_ids is not None:
                    block_ids = block_ids.to(device)
                phis = batch.get("phis")
                if phis is not None:
                    phis = phis.to(device)
                lstm_states = batch.get("lstm_states")
                if lstm_states is not None:
                    lstm_states = lstm_states.to(device)

                # Normalize advantages (standard PPO practice).
                adv_norm = normalize_advantages(advantages)

                # --- Behaviour log-probs (follower phi that produced data) ---
                if self.use_importance_weights and phis is not None:
                    with torch.no_grad():
                        beh_log_probs, _ = self.policy.evaluate_actions(
                            obs, actions, phis, block_ids, lstm_states
                        )
                else:
                    beh_log_probs = old_log_probs

                # --- New log-probs under the leader phi ---
                new_log_probs, entropy = self.policy.evaluate_actions(
                    obs, actions, self.phi, block_ids, lstm_states
                )

                # --- Value prediction under the leader phi ---
                values, _ = self.value(obs, self.phi, lstm_states)

                # --- Off-policy importance weights ---
                # ratio_behaviour = pi_leader / pi_follower (detached)
                with torch.no_grad():
                    iw = torch.exp(new_log_probs.detach() - beh_log_probs.detach())
                    iw = torch.clamp(iw, max=10.0)
                    iw_sum += float(iw.mean().item())
                    iw_max = max(iw_max, float(iw.max().item()))
                    iw_count += 1

                # --- PPO loss (clipped surrogate uses old_log_probs as anchor) ---
                # We anchor the surrogate on the behaviour log-probs so that the
                # clipping correctly bounds the off-policy update.
                loss, info = compute_ppo_loss(
                    new_log_probs=new_log_probs,
                    old_log_probs=beh_log_probs,
                    values=values,
                    returns=returns,
                    advantages=adv_norm,
                    entropy=entropy,
                    actions=actions,
                    clip_eps=hp.clip_eps,
                    entropy_coeff=hp.entropy_coeff,
                    critic_coeff=hp.critic_coeff,
                    bounds_loss_coeff=hp.bounds_loss_coeff,
                    action_bound=hp.action_bound,
                )

                self.optimizer.zero_grad()
                loss.backward()
                grad_norm = clip_grad_norm_(
                    list(self.policy.parameters()) + list(self.value.parameters()),
                    max_norm=hp.grad_norm_clip,
                )
                self.optimizer.step()

                # --- Adaptive LR via KL scheduler ---
                if self.kl_scheduler is not None:
                    self.kl_scheduler.step(info["approx_kl"])

                # --- Accumulate diagnostics ---
                stats.policy_loss += info["policy_loss"]
                stats.value_loss += info["value_loss"]
                stats.entropy += info["entropy"]
                stats.bounds_loss += info["bounds_loss"]
                stats.approx_kl += info["approx_kl"]
                stats.clip_fraction += info["clip_fraction"]
                stats.total_loss += info["total_loss"]
                stats.grad_norm += grad_norm
                n_updates += 1

        if n_updates > 0:
            stats.policy_loss /= n_updates
            stats.value_loss /= n_updates
            stats.entropy /= n_updates
            stats.bounds_loss /= n_updates
            stats.approx_kl /= n_updates
            stats.clip_fraction /= n_updates
            stats.total_loss /= n_updates
            stats.grad_norm /= n_updates
        stats.num_updates = n_updates

        if iw_count > 0:
            stats.mean_importance_weight = iw_sum / iw_count
            stats.max_importance_weight = iw_max

        # Explained variance over the aggregated value targets.
        with torch.no_grad():
            all_values = torch.cat([b.values.reshape(-1) for b in buffers])
            all_returns = torch.cat([b.returns.reshape(-1) for b in buffers])
            stats.explained_variance = explained_variance(all_values, all_returns)

        if self.kl_scheduler is not None:
            stats.learning_rate = self.kl_scheduler.current_lr
        else:
            stats.learning_rate = self.optimizer.param_groups[0]["lr"]

        return stats


def build_leader(
    policy: GaussianPolicy,
    value: ValueNetwork,
    optimizer: torch.optim.Optimizer,
    phi_dim: int = 0,
    hparams: Optional[PPOHyperParams] = None,
    kl_scheduler: Optional[KLScheduler] = None,
    device: str = "cpu",
    seed: int = 0,
    use_importance_weights: bool = True,
) -> Leader:
    """Factory building a leader with its own conditioning vector ``phi``."""
    if phi_dim > 0:
        g = torch.Generator().manual_seed(seed + 12345)
        phi = (torch.randn(1, phi_dim, generator=g) * 0.1).to(device)
    else:
        phi = None
    return Leader(
        policy=policy,
        value=value,
        optimizer=optimizer,
        phi=phi,
        hparams=hparams,
        kl_scheduler=kl_scheduler,
        device=device,
        use_importance_weights=use_importance_weights,
    )
