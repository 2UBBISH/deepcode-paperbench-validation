# GC-IQL agent
# ---------------------------------------------------------------------------
class GCIQL:
    """Goal-conditioned IQL baseline.

    Thin wrapper around :class:`fre.rl.iql.IQL` in which the ``z`` slot carries
    the ground-truth goal (concatenated to the observation, as the addendum
    prescribes).  Rewards are the hindsight goal-conditioned rewards
    (0 if ``s == g`` else -1); environment rewards are never used.
    """

    def __init__(
        self,
        obs_dim: int,
        action_dim: int,
        goal_dim: Optional[int] = None,
        hidden_layers: Sequence[int] = (512, 512, 512),
        activation: str = "relu",
        expectile: float = 0.8,
        temperature: float = 3.0,
        discount: float = 0.88,
        target_update_rate: float = 0.001,
        learning_rate: float = 1e-4,
        grad_clip_norm: float = 10.0,
        tanh_squash: bool = True,
        num_qs: int = 2,
        layernorm: bool = False,
        device: str = "cpu",
        p_current_goal: float = P_CURRENT_GOAL,
        p_geometric_goal: float = P_GEOMETRIC_GOAL,
        p_random_goal: float = P_RANDOM_GOAL,
        geometric_p: float = GEOMETRIC_P,
        equality_tolerance: float = 0.0,
        discretize_fn: Optional[Callable[[np.ndarray], np.ndarray]] = None,
        seed: int = 0,
        **iql_kwargs: Any,
    ) -> None:
        self.obs_dim = int(obs_dim)
        self.action_dim = int(action_dim)
        self.goal_dim = int(goal_dim) if goal_dim is not None else self.obs_dim
        self.target_update_rate = float(target_update_rate)
        self.equality_tolerance = float(equality_tolerance)
        self.discretize_fn = discretize_fn
        self.device = device
        self.rng = np.random.default_rng(seed)

        kwargs: Dict[str, Any] = dict(
            hidden_layers=tuple(hidden_layers),
            activation=activation,
            expectile=expectile,
            temperature=temperature,
            discount=discount,
            target_update_rate=target_update_rate,
            learning_rate=learning_rate,
            grad_clip_norm=grad_clip_norm,
            tanh_squash=tanh_squash,
            num_qs=num_qs,
            layernorm=layernorm,
            device=device,
        )
        kwargs.update(iql_kwargs)
        self.agent = IQL(
            obs_dim=self.obs_dim,
            action_dim=self.action_dim,
            latent_dim=self.goal_dim,
            **kwargs,
        )
        self.agent.to(device)

        self.goal_sampler = GoalSampler(
            dataset=None,
            p_current_goal=p_current_goal,
            p_geometric_goal=p_geometric_goal,
            p_random_goal=p_random_goal,
            geometric_p=geometric_p,
            tolerance=equality_tolerance,
            seed=seed,
        )

    # -- observation preprocessing ------------------------------------------
    def prepare(self, states: np.ndarray) -> np.ndarray:
        """Apply the shared observation preprocessing (e.g. 32-bin AntMaze XY)."""
        states = np.asarray(states, dtype=np.float32)
        if self.discretize_fn is not None:
            states = np.asarray(self.discretize_fn(states), dtype=np.float32)
        return states

    def attach_dataset(self, dataset: Any) -> "GCIQL":
        """Attach the offline dataset so that hindsight goals can be sampled."""
        self.goal_sampler.dataset = dataset
        try:
            self.goal_sampler.traj_index = FlatTrajectoryIndex.from_dataset(dataset)
        except (ValueError, AttributeError, TypeError):
            self.goal_sampler.traj_index = None
        return self

    # -- goal-conditioned reward --------------------------------------------
    def reward_and_done(self, states: np.ndarray, goals: np.ndarray):
        return goal_rewards_and_dones(
            states, goals, tolerance=self.equality_tolerance
        )

    def sample_goals(
        self, states: np.ndarray, indices: Optional[np.ndarray] = None
    ) -> GoalBatch:
        batch = self.goal_sampler.sample(self.prepare(states), indices=indices)
        return batch

    # -- training ------------------------------------------------------------
    def _sample_batch(self, dataset: Any, batch_size: int) -> Tuple[Dict[str, np.ndarray], np.ndarray]:
        """Sample transitions; prefer flat arrays so indices stay available."""
        traj_index = self.goal_sampler.traj_index
        if traj_index is not None and traj_index.actions is not None:
            indices = traj_index.sample_indices(batch_size, rng=self.rng)
            batch = traj_index.transitions(indices)
            batch["rewards"] = self.reward_and_done(
                batch["observations"], batch["observations"]
            )[0]  # placeholder, replaced by goal-conditioned rewards below
            return batch, indices

        # Fall back to the replay buffer's own transition sampler.
        batch = None
        if hasattr(dataset, "sample_transitions"):
            try:
                batch = dataset.sample_transitions(batch_size)
            except TypeError:
                batch = dataset.sample_transitions(batch_size, )
        if batch is None:
            raise ValueError("Dataset does not support transition sampling.")
        batch = dict(batch)
        obs = batch.get("observations", batch.get("obs"))
        batch["observations"] = np.asarray(obs, dtype=np.float32)
        batch["obs"] = batch["observations"]
        nxt = batch.get("next_observations", batch.get("next_obs"))
        batch["next_observations"] = np.asarray(nxt, dtype=np.float32)
        batch["next_obs"] = batch["next_observations"]
        dones = batch.get("terminals", batch.get("dones"))
        if dones is None:
            dones = np.zeros(batch_size, dtype=np.float32)
        batch["terminals"] = np.asarray(dones, dtype=np.float32).reshape(-1)
        batch["dones"] = batch["terminals"]
        return batch, np.full(batch_size, -1, dtype=np.int64)

    def update(
        self,
        dataset: Any,
        batch_size: int = 512,
        target_update: bool = True,
        states: Optional[np.ndarray] = None,
    ) -> Dict[str, float]:
        """One IQL update on goal-relabelled transitions."""
        if states is None:
            batch, indices = self._sample_batch(dataset, batch_size)
            obs = batch["observations"]
            next_obs = batch["next_observations"]
            anchors = obs
        else:
            anchors = self.prepare(np.asarray(states, dtype=np.float32))
            obs, next_obs, indices = anchors, anchors, None
            batch = {
                "observations": obs,
                "obs": obs,
                "next_observations": next_obs,
                "next_obs": next_obs,
                "terminals": np.zeros(anchors.shape[0], dtype=np.float32),
                "dones": np.zeros(anchors.shape[0], dtype=np.float32),
            }
            if hasattr(dataset, "sample_actions"):
                batch["actions"] = dataset.sample_actions(anchors.shape[0])

        goals = self.sample_goals(obs, indices=indices)
        # Goal-conditioned rewards of the GC-IQL preprocessor.
        rewards, dones = self.reward_and_done(obs, goals.goals)
        # Current-goal rows terminate immediately (reward 0, mask True).
        batch = dict(batch)
        batch["terminals"] = dones.astype(np.float32)
        batch["dones"] = dones.astype(np.float32)

        info: Dict[str, float] = {}
        call_kwargs: Dict[str, Any] = {
            "batch": batch,
            "rewards": rewards.astype(np.float32),
            "z": goals.goals.astype(np.float32),
            "next_z": goals.goals.astype(np.float32),
        }
        signature = None
        try:
            signature = inspect.signature(self.agent.update)
        except (TypeError, ValueError):  # pragma: no cover - exotic callables
            signature = None
        if signature is not None and "target_update" in signature.parameters:
            parameter = signature.parameters["target_update"]
            default = parameter.default
            if isinstance(default, float):
                call_kwargs["target_update"] = self.target_update_rate
            elif default is inspect.Parameter.empty:
                call_kwargs["target_update"] = target_update
            else:
                call_kwargs["target_update"] = bool(target_update)
            explicit_polyak = True
        else:
            explicit_polyak = False

        result = self.agent.update(**call_kwargs)
        if isinstance(result, dict):
            info.update(
                {
                    k: float(v)
                    for k, v in result.items()
                    if isinstance(v, (int, float, np.floating))
                }
            )
        if not explicit_polyak and target_update and hasattr(self.agent, "update_targets"):
            self.agent.update_targets(self.target_update_rate)

        counts = goals.type_counts()
        info.setdefault("gc_iql/reward_mean", float(np.mean(rewards)))
        info.setdefault("gc_iql/fraction_success", float(np.mean(dones)))
        for name, count in counts.items():
            info[f"gc_iql/goal_{name}"] = float(count) / max(len(goals), 1)
        return info

    def train_steps(
        self,
        dataset: Any,
        steps: int,
        batch_size: int = 512,
        log_interval: int = 1000,
        logger: Any = None,
        prefix: str = "gc_iql",
    ) -> List[Dict[str, float]]:
        self.attach_dataset(dataset)
        history: List[Dict[str, float]] = []
        for step in range(int(steps)):
            info = self.update(dataset, batch_size=batch_size)
            if (step + 1) % max(int(log_interval), 1) == 0:
                history.append({"step": float(step + 1), **info})
                if logger is not None:
                    try:
                        logger.log_metrics(info, step=step + 1, prefix=prefix)
                    except TypeError:
                        logger.log_metrics({f"{prefix}/{k}": v for k, v in info.items()}, step=step + 1)
        return history

    # -- evaluation helpers --------------------------------------------------
    def select_action(
        self,
        obs: np.ndarray,
        goal: np.ndarray,
        deterministic: bool = True,
        clip: bool = True,
    ) -> np.ndarray:
        obs = self.prepare(np.asarray(obs, dtype=np.float32))
        goal = self.prepare(np.asarray(goal, dtype=np.float32))
        if obs.ndim == 1:
            single = True
            obs_b = obs[None]
        else:
            single = False
            obs_b = obs
        if goal.ndim == 1:
            goal_b = np.broadcast_to(goal[None], (obs_b.shape[0], goal.shape[0])).copy()
        else:
            goal_b = np.broadcast_to(goal, (obs_b.shape[0], goal.shape[-1])).copy()
        action = self.agent.select_action(
            obs_b, goal_b, deterministic=deterministic, clip=clip
        )
        action = np.asarray(action, dtype=np.float32)
        return action[0] if single else action

    def value_of(self, obs: np.ndarray, goal: np.ndarray) -> np.ndarray:
        obs = self.prepare(np.asarray(obs, dtype=np.float32))
        goal = self.prepare(np.asarray(goal, dtype=np.float32))
        return np.asarray(self.agent.value_of(obs, goal), dtype=np.float32)

    # -- persistence ---------------------------------------------------------
    def state_dict(self) -> Dict[str, Any]:
        state = {
            "agent": self.agent.state_dict(),
            "obs_dim": self.obs_dim,
            "action_dim": self.action_dim,
            "goal_dim": self.goal_dim,
        }
        return state

    def save(self, path: str) -> str:
        directory = os.path.dirname(os.path.abspath(path))
        if directory:
            os.makedirs(directory, exist_ok=True)
        torch.save(self.state_dict(), path)
        return path

    def load(self, path: str, map_location: Optional[str] = None) -> "GCIQL":
        payload = torch.load(path, map_location=map_location or self.device)
        state = payload.get("agent", payload)
        if hasattr(self.agent, "load_state_dict"):
            self.agent.load_state_dict(state)
        return self

    def to(self, device: str) -> "GCIQL":
        self.device = device
        self.agent.to(device)
        return self

    # -- factory -------------------------------------------------------------
    @classmethod
    def from_config(
        cls,
        config: Any,
        obs_dim: int,
        action_dim: int,
        goal_dim: Optional[int] = None,
        discretize_fn: Optional[Callable[[np.ndarray], np.ndarray]] = None,
        **overrides: Any,
    ) -> "GCIQL":
        def _cfg(name: str, default: Any) -> Any:
            return getattr(config, name, default)

        kwargs: Dict[str, Any] = dict(
            obs_dim=obs_dim,
            action_dim=action_dim,
            goal_dim=goal_dim,
            hidden_layers=tuple(_cfg("rl_hidden_layers", (512, 512, 512))),
            activation=_cfg("rl_activation", "relu"),
            expectile=_cfg("iql_expectile", 0.8),
            temperature=_cfg("iql_temperature", 3.0),
            discount=_cfg("discount", 0.88),
            target_update_rate=_cfg("target_update_rate", 0.001),
            learning_rate=_cfg("learning_rate", 1e-4),
            grad_clip_norm=_cfg("grad_clip_norm", 10.0),
            tanh_squash=_cfg("rl_tanh_squash", True),
            num_qs=_cfg("rl_num_qs", 2),
            layernorm=_cfg("rl_layernorm", False),
            device=_cfg("device", "cpu"),
            p_current_goal=_cfg("gc_p_current_goal", P_CURRENT_GOAL),
            p_geometric_goal=_cfg("gc_p_geometric_goal", P_GEOMETRIC_GOAL),
            p_random_goal=_cfg("gc_p_random_goal", P_RANDOM_GOAL),
            geometric_p=_cfg("gc_geometric_p", GEOMETRIC_P),
            equality_tolerance=_cfg("gc_equality_tolerance", 0.0),
            discretize_fn=discretize_fn,
            seed=_cfg("seed", 0),
        )
        kwargs.update(overrides)
        return cls(**kwargs)


def make_gc_iql(
    config: Any,
    obs_dim: int,
    action_dim: int,
    goal_dim: Optional[int] = None,
    discretize_fn: Optional[Callable[[np.ndarray], np.ndarray]] = None,
    **overrides: Any,
) -> GCIQL:
    """Build a GC-IQL baseline from a ``fre.config.default.Config``-like object."""
    return GCIQL.from_config(
        config,
        obs_dim,
        action_dim,
        goal_dim=goal_dim,
        discretize_fn=discretize_fn,
        **overrides,
    )


def train_gc_iql(
    config: Any,
    dataset: Any,
    obs_dim: int,
    action_dim: int,
    steps: Optional[int] = None,
    batch_size: Optional[int] = None,
    log_interval: int = 1000,
    logger: Any = None,
    discretize_fn: Optional[Callable[[np.ndarray], np.ndarray]] = None,
    **overrides: Any,
) -> Tuple[GCIQL, List[Dict[str, float]]]:
    """Train the GC-IQL baseline on an offline dataset (convenience driver)."""
    agent = make_gc_iql(
        config,
        obs_dim,
        action_dim,
        discretize_fn=discretize_fn,
        **overrides,
    )
    agent.attach_dataset(dataset)
    if steps is None:
        steps = int(getattr(config, "policy_steps", lambda: 850_000)()) if callable(
            getattr(config, "policy_steps", None)
        ) else int(getattr(config, "policy_steps", 850_000))
    if batch_size is None:
        batch_size = int(getattr(config, "batch_size", 512))
    history = agent.train_steps(
        dataset, steps=int(steps), batch_size=int(batch_size),
        log_interval=log_interval, logger=logger,
    )
    return agent, history


def make_gc_policy_fn(
    agent: GCIQL,
    goal: np.ndarray,
    deterministic: bool = True,
    clip: bool = True,
    discretize: bool = True,
) -> Callable[[np.ndarray], np.ndarray]:
    """Wrap a trained GC-IQL agent into ``act_fn(obs) -> action``.

    The agent is given the ground-truth goal of the evaluation task, exactly as
    the addendum describes.
    """
    goal_arr = np.asarray(goal, dtype=np.float32)

    def act_fn(obs: np.ndarray) -> np.ndarray:
        if discretize:
            return agent.select_action(obs, goal_arr, deterministic=deterministic, clip=clip)
        obs = np.asarray(obs, dtype=np.float32)
        obs_b = obs[None] if obs.ndim == 1 else obs
        goal_b = np.broadcast_to(goal_arr[None], (obs_b.shape[0], goal_arr.shape[-1]))
        action = np.asarray(
            agent.agent.select_action(obs_b, goal_b, deterministic=deterministic, clip=clip),
            dtype=np.float32,
        )
        return action[0] if obs.ndim == 1 else action

    return act_fn
