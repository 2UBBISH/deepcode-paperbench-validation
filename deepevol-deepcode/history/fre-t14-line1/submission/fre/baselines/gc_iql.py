"""GC-IQL baseline: goal-conditioned implicit Q-learning.

Paper specification (Addendum, "Additional Details on GC-IQL"):

    "GC-IQL is just IQL with the additional goal state.

     Specifically, given a random state, a random goal state is sampled from
     1) future states in the trajectory using a geometric distribution,
     2) a random goal in the dataset, or 3) the current state is the goal,
     in which case the reward is 0 and the mask/terminal flag is True. In
     other cases, reward is -1.  The ratio is p_randomgoal=0.3,
     p_geometric_goal=0.5, p_current_goal=0.2.

     To give the information to the neural network, goals and observations are
     concatenated.

     No environment rewards are used to train GC-IQL.  The reward passed to IQL
     are the goal-conditioned rewards generated by the preprocessor as
     described above, which is 0 if the state==goal and -1 otherwise.

     Evaluation: the goal-conditioned agent is given the ground-truth goal that
     the specific evaluation task contains, to condition on."

Implementation notes
--------------------
* The goal is supplied to the shared IQL implementation
  (:class:`fre.rl.iql.IQL`) through its ``z`` argument: IQL concatenates ``z``
  to the observation, which is *exactly* "goals and observations are
  concatenated" from the addendum.  ``latent_dim`` is therefore set to the goal
  dimension instead of FRE's 128-dim task latent.
* Hindsight relabeling is implemented on flat dataset indices so the geometric
  goal really is a *future state of the same trajectory* as the anchor state
  (this is what the "geometric distribution over future states" means).  A
  trajectory index is derived from ``terminals``/``timeouts`` when the replay
  buffer does not expose one.
* For AntMaze the ground-truth goals live on the same 32-bin XY grid that FRE,
  GC-BC and OPAL are evaluated on, so goal achievement can be checked with
  exact equality (shared discretization, see ``fre/envs/antmaze_eval.py``).
  For continuous domains a small equality tolerance is used.
"""

