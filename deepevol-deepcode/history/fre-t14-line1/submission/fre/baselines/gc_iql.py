# ---------------------------------------------------------------------------
# Paper-exact constants (Addendum: "Additional Details on GC-IQL")
# ---------------------------------------------------------------------------
P_RANDOM_GOAL = 0.3
P_GEOMETRIC_GOAL = 0.5
P_CURRENT_GOAL = 0.2

# The addendum says "a geometric distribution" without giving its parameter.
# p = 0.5 (i.e. mean offset of 2 steps) is the value used by the
# controllable_agent / HIQL style goal samplers; documented default.
GEOMETRIC_P = 0.5

# Goal types, in the canonical order used by `GoalSampler`.
GOAL_TYPES = ("current", "geometric", "random")
_CURRENT, _GEOMETRIC, _RANDOM = 0, 1, 2


# ---------------------------------------------------------------------------
# Reward / done preprocessor
# ---------------------------------------------------------------------------
def goal_rewards_and_dones(
    states: np.ndarray,
    goals: np.ndarray,
    tolerance: float = 0.0,
) -> Tuple[np.ndarray, np.ndarray]:
    """Goal-conditioned reward preprocessor of the GC-IQL baseline.

    ``reward = 0`` if ``state == goal`` (within ``tolerance``), else ``-1``;
    the terminal/done flag is ``True`` exactly when the goal is achieved.

    Returns ``(rewards, dones)`` both of shape ``(B,)`` (float32 / bool).
    """
    states = np.asarray(states, dtype=np.float64)
    goals = np.asarray(goals, dtype=np.float64)
    if states.shape != goals.shape:
        states = np.reshape(states, goals.shape)
    if tolerance and tolerance > 0.0:
        distance = np.linalg.norm(states - goals, axis=-1)
        reached = distance <= tolerance
    else:
        reached = np.all(states == goals, axis=-1)
    rewards = np.where(reached, 0.0, -1.0).astype(np.float32)
    dones = reached.astype(bool)
    return rewards, dones


@dataclass
class GoalBatch:
    """A batch of hindsight-relabelled goals for GC-IQL."""

    states: np.ndarray           # (B, obs_dim) anchor states
    goals: np.ndarray            # (B, goal_dim)
    rewards: np.ndarray          # (B,)  0 if s == g else -1
    dones: np.ndarray            # (B,)  bool
    types: np.ndarray            # (B,)  int, index into GOAL_TYPES
    dataset_indices: Optional[np.ndarray] = None

    def __len__(self) -> int:
        return int(self.states.shape[0])

    @property
    def batch_size(self) -> int:
        return len(self)

    def type_counts(self) -> Dict[str, int]:
        counts = {name: 0 for name in GOAL_TYPES}
        for t in np.asarray(self.types).reshape(-1):
            counts[GOAL_TYPES[int(t)]] += 1
        return counts

    def as_dict(self) -> Dict[str, Any]:
        return {
            "states": self.states,
            "goals": self.goals,
            "rewards": self.rewards,
            "dones": self.dones,
            "types": self.types,
        }


# ---------------------------------------------------------------------------
# Trajectory bookkeeping (needed for "future states in the trajectory")
# ---------------------------------------------------------------------------
class FlatTrajectoryIndex:
    """Flat dataset arrays plus trajectory boundaries.

    Provides everything the geometric goal sampler needs:
    ``observations``, ``actions``, ``next_observations``, ``terminals`` and,
    per flat index, the id of the episode it belongs to and the last index of
    that episode.

    Built from a :class:`fre.rl.replay_buffer.ReplayBuffer`-like object; every
    access is defensive because the buffer may expose either attributes or
    properties (or neither).
    """

    def __init__(
        self,
        observations: np.ndarray,
        actions: Optional[np.ndarray] = None,
        next_observations: Optional[np.ndarray] = None,
        terminals: Optional[np.ndarray] = None,
        trajectory_ids: Optional[np.ndarray] = None,
        timeouts: Optional[np.ndarray] = None,
    ) -> None:
        observations = np.asarray(observations)
        if observations.ndim != 2:
            raise ValueError(
                f"FlatTrajectoryIndex expects (N, D) observations, got {observations.shape}"
            )
        self.observations = observations.astype(np.float32)
        n = self.observations.shape[0]

        self.actions = None if actions is None else np.asarray(actions, dtype=np.float32)
        if next_observations is None:
            # Reconstruct by shifting within trajectories (fall back to self).
            nxt = self.observations.copy()
            if n > 1:
                nxt[:-1] = self.observations[1:]
            self.next_observations = nxt
        else:
            self.next_observations = np.asarray(next_observations, dtype=np.float32)

        if terminals is None:
            self.terminals = np.zeros(n, dtype=bool)
        else:
            self.terminals = np.asarray(terminals).reshape(-1).astype(bool)

        if timeouts is None:
            self.timeouts = np.zeros(n, dtype=bool)
        else:
            self.timeouts = np.asarray(timeouts).reshape(-1).astype(bool)

        if trajectory_ids is None:
            trajectory_ids = self._infer_trajectory_ids()
        self.trajectory_ids = np.asarray(trajectory_ids).reshape(-1).astype(np.int64)

        self.traj_starts, self.traj_ends, self.traj_lengths = self._boundaries()

    # -- construction helpers ------------------------------------------------
    def _infer_trajectory_ids(self) -> np.ndarray:
        """Episode ids from terminals/timeouts (either flag ends an episode)."""
        n = self.observations.shape[0]
        if n == 0:
            return np.zeros(0, dtype=np.int64)
        ends = self.terminals | self.timeouts
        if not np.any(ends):
            # A single (very long) trajectory.
            return np.zeros(n, dtype=np.int64)
        new_episode = np.concatenate([[True], ends[:-1]])
        return np.cumsum(new_episode).astype(np.int64) - 1

    def _boundaries(self) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
        ids = self.trajectory_ids
        n = ids.shape[0]
        if n == 0:
            empty = np.zeros(0, dtype=np.int64)
            return empty, empty, empty
        num_traj = int(ids.max()) + 1
        starts = np.full(num_traj, n, dtype=np.int64)
        ends = np.full(num_traj, -1, dtype=np.int64)
        for i in range(n):
            t = int(ids[i])
            if i < starts[t]:
                starts[t] = i
            if i > ends[t]:
                ends[t] = i
        lengths = ends - starts + 1
        return starts, ends, np.maximum(lengths, 0)

    # -- sampling ------------------------------------------------------------
    @property
    def num_transitions(self) -> int:
        return int(self.observations.shape[0])

    @property
    def obs_dim(self) -> int:
        return int(self.observations.shape[1])

    def sample_indices(self, num: int, rng: Optional[np.random.Generator] = None) -> np.ndarray:
        rng = np.random.default_rng() if rng is None else rng
        return rng.integers(0, self.num_transitions, size=int(num))

    def future_indices(
        self,
        indices: np.ndarray,
        geometric_p: float = GEOMETRIC_P,
        rng: Optional[np.random.Generator] = None,
    ) -> np.ndarray:
        """Geometric-distributed future index inside the same trajectory."""
        rng = np.random.default_rng() if rng is None else rng
        indices = np.asarray(indices, dtype=np.int64).reshape(-1)
        offsets = rng.geometric(p=float(geometric_p), size=indices.shape[0])
        candidate = indices + offsets
        end = self.traj_ends[self.trajectory_ids[indices]]
        return np.minimum(candidate, end)

    def transitions(self, indices: np.ndarray) -> Dict[str, np.ndarray]:
        """Materialise a transition batch for the given flat indices."""
        indices = np.asarray(indices, dtype=np.int64).reshape(-1)
        batch: Dict[str, np.ndarray] = {
            "observations": self.observations[indices],
            "next_observations": self.next_observations[indices],
            "terminals": self.terminals[indices].astype(np.float32),
            "dones": self.terminals[indices].astype(np.float32),
            "timeouts": self.timeouts[indices].astype(np.float32),
        }
        if self.actions is not None:
            batch["actions"] = self.actions[indices]
        # Aliases used by fre.rl.iql.IQL.
        batch["obs"] = batch["observations"]
        batch["next_obs"] = batch["next_observations"]
        return batch

    # -- factory -------------------------------------------------------------
    @classmethod
    def from_dataset(cls, dataset: Any) -> "FlatTrajectoryIndex":
        def _get(*names: str) -> Optional[Any]:
            for name in names:
                value = getattr(dataset, name, None)
                if value is None:
                    continue
                if callable(value):
                    try:
                        value = value()
                    except TypeError:
                        continue
                return value
            return None

        observations = _get("observations", "states", "obs")
        if observations is None:
            raise ValueError(
                "Dataset does not expose flat 'observations'/'states' arrays; cannot "
                "build a FlatTrajectoryIndex."
            )
        actions = _get("actions")
        next_observations = _get("next_observations", "next_states")
        terminals = _get("terminals", "dones")
        timeouts = _get("timeouts")
        trajectory_ids = _get("trajectory_ids", "episode_ids")
        return cls(
            observations=observations,
            actions=actions,
            next_observations=next_observations,
            terminals=terminals,
            trajectory_ids=trajectory_ids,
            timeouts=timeouts,
        )


# ---------------------------------------------------------------------------
# Goal sampler
# ---------------------------------------------------------------------------
class GoalSampler:
    """HER goal sampling with the GC-IQL ratios 0.2 / 0.5 / 0.3.

    * ``current``  (p = 0.2): the goal *is* the anchor state -> reward 0, done.
    * ``geometric``(p = 0.5): a future state of the same trajectory, sampled
      from a geometric distribution (clipped to the end of the episode).
    * ``random``   (p = 0.3): a uniformly random state from the dataset.
    """

    def __init__(
        self,
        dataset: Any = None,
        traj_index: Optional[FlatTrajectoryIndex] = None,
        p_current_goal: float = P_CURRENT_GOAL,
        p_geometric_goal: float = P_GEOMETRIC_GOAL,
        p_random_goal: float = P_RANDOM_GOAL,
        geometric_p: float = GEOMETRIC_P,
        tolerance: float = 0.0,
        seed: Optional[int] = None,
    ) -> None:
        self.dataset = dataset
        if traj_index is None and dataset is not None:
            try:
                traj_index = FlatTrajectoryIndex.from_dataset(dataset)
            except (ValueError, AttributeError, TypeError):
                traj_index = None
        self.traj_index = traj_index

        total = float(p_current_goal + p_geometric_goal + p_random_goal)
        if total <= 0:
            raise ValueError("Goal sampling probabilities must sum to a positive value.")
        self.probs = np.asarray(
            [
                float(p_current_goal) / total,
                float(p_geometric_goal) / total,
                float(p_random_goal) / total,
            ]
        )
        self.geometric_p = float(geometric_p)
        self.tolerance = float(tolerance)
        self.rng = np.random.default_rng(seed)

    # -- random goal source --------------------------------------------------
    def _random_states(self, num: int) -> np.ndarray:
        if self.traj_index is not None:
            idx = self.traj_index.sample_indices(num, rng=self.rng)
            return self.traj_index.observations[idx]
        # Fallback: ask the dataset for random states.
        if hasattr(self.dataset, "sample_states"):
            states = self.dataset.sample_states(int(num))
            return np.asarray(states, dtype=np.float32)
        if hasattr(self.dataset, "observations"):
            obs = np.asarray(self.dataset.observations)
            idx = self.rng.integers(0, obs.shape[0], size=int(num))
            return obs[idx]
        raise ValueError("Cannot sample random goal states from the given dataset.")

    def _future_states(self, anchor_indices: np.ndarray, anchor_states: np.ndarray) -> np.ndarray:
        if self.traj_index is not None:
            future = self.traj_index.future_indices(
                anchor_indices, geometric_p=self.geometric_p, rng=self.rng
            )
            return self.traj_index.observations[future]
        # Fallback (no trajectory structure available): approximate the future
        # goal with an independent random dataset state.
        return self._random_states(anchor_states.shape[0])

    # -- main API ------------------------------------------------------------
    def sample(
        self,
        states: np.ndarray,
        indices: Optional[np.ndarray] = None,
        goals: Optional[np.ndarray] = None,
    ) -> GoalBatch:
        """Sample goals for the given anchor ``states`` ``(B, obs_dim)``."""
        states = np.asarray(states, dtype=np.float32)
        batch_size = int(states.shape[0])
        types = self.rng.choice(3, size=batch_size, p=self.probs).astype(np.int64)
        if goals is None:
            goals = np.array(states, dtype=np.float32, copy=True)

        if indices is None:
            indices = np.full(batch_size, -1, dtype=np.int64)
        else:
            indices = np.asarray(indices, dtype=np.int64).reshape(-1)

        # current goals: goal := state (already set).
        geom_mask = types == _GEOMETRIC
        rand_mask = types == _RANDOM

        if np.any(geom_mask):
            geom_idx = indices[geom_mask]
            if np.any(geom_idx < 0) and self.traj_index is not None:
                geom_idx = self.traj_index.sample_indices(int(geom_mask.sum()), rng=self.rng)
            goals[geom_mask] = self._future_states(geom_idx, states[geom_mask])

        if np.any(rand_mask):
            goals[rand_mask] = self._random_states(int(rand_mask.sum()))

        rewards, dones = goal_rewards_and_dones(states, goals, tolerance=self.tolerance)
        return GoalBatch(
            states=states,
            goals=goals,
            rewards=rewards,
            dones=dones,
            types=types,
            dataset_indices=indices if np.all(indices >= 0) else None,
        )


