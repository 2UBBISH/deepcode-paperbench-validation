@dataclass
class AIRSConfig:
    """Configuration for the AIRS explanation adapter.

    The paper does not specify these hyper-parameters, so the defaults below are the
    documented reproduction choices (README).
    """

    task: Optional[str] = None
    backend: str = "auto"  # auto | upstream | attention | gradient | occlusion
    steps: int = 16  # smoothing / path samples (unspecified in the paper)
    noise_scale: float = 0.0  # SmoothGrad-style Gaussian noise std added to states
    baseline: str = "zeros"  # zeros | mean | min | max | <array>
    aggregate: str = "sum_abs"  # sum_abs | mean_abs | l2 | max_abs | sum_signed
    multiply_by_inputs: bool = False  # IG-style (x - baseline) factor
    normalize: bool = True  # min-max the per-state importance to [0, 1]
    internal_batch_size: int = 16
    occlusion_features: int = 0  # 0 = all features (occlusion backend only)
    attention_key: Optional[str] = None  # attribute name of a relevance hook, if any
    device: str = "auto"
    seed: Optional[int] = None
    model: Any = None
    policy: Any = None
    action: Any = None  # fixed action used to score states (optional)
    notes: str = ""
    extra: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "task": self.task,
            "backend": self.backend,
            "steps": self.steps,
            "noise_scale": self.noise_scale,
            "baseline": self.baseline,
            "aggregate": self.aggregate,
            "multiply_by_inputs": self.multiply_by_inputs,
            "normalize": self.normalize,
            "internal_batch_size": self.internal_batch_size,
            "occlusion_features": self.occlusion_features,
            "attention_key": self.attention_key,
            "device": self.device,
            "seed": self.seed,
            "notes": self.notes,
            "extra": dict(self.extra),
        }

    def clone(self, **overrides: Any) -> "AIRSConfig":
        data = {
            k: v
            for k, v in self.__dict__.items()
            if k not in ("model", "policy", "action", "extra")
        }
        data["extra"] = dict(self.extra)
        unknown: Dict[str, Any] = {}
        for key, value in overrides.items():
            if key in data:
                data[key] = value
            else:
                unknown[key] = value
        cfg = AIRSConfig(**data)
        cfg.extra.update(unknown)
        return cfg

    @classmethod
    def from_mapping(
        cls, mapping: Optional[Dict[str, Any]] = None, **overrides: Any
    ) -> "AIRSConfig":
        """Build from a (YAML-parsed) mapping; unknown keys land in ``extra``."""
        cfg = cls()
        data = dict(mapping or {})
        data.update(overrides)
        unknown: Dict[str, Any] = {}
        for key, value in data.items():
            if key in ("lambda", "lambda_"):
                continue
            if hasattr(cfg, key) and key not in ("extra",):
                setattr(cfg, key, value)
            else:
                unknown[key] = value
        cfg.extra.update(unknown)
        return cfg


