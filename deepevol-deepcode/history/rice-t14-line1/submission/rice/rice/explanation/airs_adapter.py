"""AIRS explanation adapter for RICE (Table 6 / Appendix C.3).

The RICE paper (Cheng et al., ICML 2024) uses AIRS (Yu et al., 2023) as one of the
*additional* explanation methods in the secondary comparison of Section C.3:

    "We investigate the impact of other explanation methods (i.e., AIRS (Yu et al.,
     2023) and Integrated Gradients (Sundararajan et al., 2017)) on four Mujoco games.
     we fix the refining method and use different explanation methods to identify
     critical steps for refinement. The results are reported in Table 6. We observe
     that using the explanation generated by our mask network, the refining achieves
     the best outcome across all four applications. Using other explanation methods
     (Integrated Gradients and AIRS), our framework still achieves better results than
     the random baseline, suggesting that our framework can work with different
     explanation method choices."

The paper only reports the *trend* (ours > AIRS > Integrated Gradients > Random, see
``TABLE6_ORDERING``) and does not specify AIRS' internals.  This module therefore
provides:

* an upstream hook -- if the original AIRS implementation/package is importable
  (``AIRS_UPSTREAM_MODULE`` env var or a package exposing ``airs``), it is used and
  wrapped;
* an *attention-based* backend that extracts per-state relevance from attention
  weights (or from a user supplied relevance hook) when the policy exposes them;
* a black-box fallback that follows the same spirit as AIRS while remaining
  architecture-independent (RICE's black-box assumption): smoothed input-gradient
  saliency (SmoothGrad-style, Sundararajan et al. 2017 / Smilkov et al. 2017) and,
  if no differentiable model is available, occlusion-based relevance.

All backends produce per-feature attributions ``(N, D)`` that are aggregated into a
per-state importance score ``(N,)`` -- exactly the same duck-typed surface as
``random_explanation.py``, ``statemask_adapter.py`` and ``integrated_gradients.py``
(``importance`` / ``score`` / ``mask_prob_zero`` / ``select_index`` /
``critical_state`` / ``state_dict`` ...), so the fidelity evaluator
(``rice.evaluation.fidelity_score``) and the refining loop
(``rice.algorithms.refine`` via ``rice.explanation``) can treat every explanation
identically.

Deviations from the paper (documented for the README, since the paper is silent):
    * number of smoothing/path samples             -> ``steps=16``
    * attribution backend when nothing is inferable -> ``"gradient"`` (else ``"occlusion"``)
    * aggregation rule for a state                  -> ``"sum_abs"``
    * normalization of the importance scores        -> min-max to ``[0, 1]``
"""

