def _make_rng(seed: Optional[int] = None, rng: Any = None) -> Any:
    """Return an RNG exposing ``uniform``/``choice``/``integers``."""
    if rng is not None:
        return rng
    if RNG is not None:
        try:
            return RNG(seed)
        except Exception:
            pass
    return np.random.default_rng(seed)


def _resolve_device(device: str) -> str:
    """Resolve ``"auto"`` to ``cuda`` when available, else ``cpu``."""
    device = str(device or "auto").lower()
    if device not in _DEVICE_ALIASES:
        device = "auto"
    if device == "auto":
        if _TORCH_AVAILABLE:
            try:
                return "cuda" if torch.cuda.is_available() else "cpu"
            except Exception:  # pragma: no cover
                return "cpu"
        return "cpu"
    if device == "cuda" and _TORCH_AVAILABLE:
        try:
            if not torch.cuda.is_available():
                return "cpu"
        except Exception:  # pragma: no cover
            return "cpu"
    return device


def _as_states(states: Any) -> np.ndarray:
    """Coerce a list/array/tensor of states into a 2-D float32 array."""
    if states is None:
        return np.zeros((0, 0), dtype=np.float32)
    if isinstance(states, np.ndarray):
        arr = states
    elif _TORCH_AVAILABLE and isinstance(states, torch.Tensor):  # pragma: no cover
        arr = states.detach().cpu().numpy()
    elif isinstance(states, (Sequence, list, tuple)):
        if len(states) == 0:
            return np.zeros((0, 0), dtype=np.float32)
        first = states[0]
        if np.isscalar(first) or (isinstance(first, np.ndarray) and first.ndim == 0):
            arr = np.asarray(states, dtype=np.float32)
        else:
            arr = np.stack([flatten_obs(s) for s in states])
    else:
        arr = np.asarray(states, dtype=np.float32)
    arr = np.asarray(arr, dtype=np.float32)
    if arr.ndim == 1:
        arr = arr.reshape(1, -1)
    return arr


def _unpack_states(states: Any) -> Tuple[np.ndarray, bool, List[Any]]:
    """Return ``(flattened_states, was_batch, raw_list)``.

    ``was_batch`` is ``True`` when the input looked like a trajectory (list of states
    / 2-D array) rather than a single state.
    """
    was_batch = True
    raw: List[Any]
    if isinstance(states, (list, tuple)):
        raw = list(states)
        if len(states) == 0:
            return np.zeros((0, 0), dtype=np.float32), True, []
        first = states[0]
        if np.isscalar(first) or (hasattr(first, "ndim") and getattr(first, "ndim") == 0):
            raw = [states]
            was_batch = False
    elif isinstance(states, np.ndarray):
        raw = list(states)
        if states.ndim == 1:
            was_batch = False
    else:
        raw = [states]
        was_batch = False
    return _as_states(raw), was_batch, raw


def _model_from(obj: Any) -> Any:
    """Extract a callable neural module from a model / SB3 model / policy."""
    if obj is None:
        return None
    if hasattr(obj, "policy") and not callable(obj):  # SB3-like model object
        return obj.policy
    if hasattr(obj, "policy") and callable(obj):
        # both callable and has .policy -> prefer the inner policy when it is a module
        inner = getattr(obj, "policy")
        if _TORCH_AVAILABLE and isinstance(inner, torch.nn.Module):
            return inner
        if inner is not None:
            return inner
    return obj


def resolve_attribution_fn(model: Any) -> Optional[Callable[[Any], np.ndarray]]:
    """Normalize ``model`` into ``obs -> vector output`` (numpy in / numpy out).

    Accepts torch ``nn.Module`` objects, Stable-Baselines3 policies/models, or plain
    callables.  Returns ``None`` when nothing usable is available.
    """
    module = _model_from(model)
    if module is None:
        return None

    if _TORCH_AVAILABLE and isinstance(module, torch.nn.Module):

        def _fn(obs: Any) -> np.ndarray:  # noqa: D401
            with torch.no_grad():
                x = torch.as_tensor(_as_states(obs), dtype=torch.float32)
                out = module(x)
                if isinstance(out, (tuple, list)):
                    out = out[0]
                if isinstance(out, torch.distributions.Distribution):  # pragma: no cover
                    out = out.mean
                return out.detach().cpu().numpy()

        return _fn

    if callable(module):

        def _fn_callable(obs: Any) -> np.ndarray:  # noqa: D401
            out = module(_as_states(obs))
            if _TORCH_AVAILABLE and isinstance(out, torch.Tensor):  # pragma: no cover
                out = out.detach().cpu().numpy()
            if isinstance(out, (tuple, list)):
                out = out[0]
            return np.asarray(out, dtype=np.float32)

        return _fn_callable

    return None


def upstream_available() -> bool:
    """Whether an upstream AIRS implementation is importable."""
    candidate = os.environ.get(_UPSTREAM_ENV) or _UPSTREAM_MODULE
    try:
        importlib.import_module(candidate)
        return True
    except Exception:
        return False


def _load_upstream() -> Any:
    """Best-effort import of the original AIRS implementation (or ``None``)."""
    candidate = os.environ.get(_UPSTREAM_ENV) or _UPSTREAM_MODULE
    try:
        return importlib.import_module(candidate)
    except Exception:
        return None


