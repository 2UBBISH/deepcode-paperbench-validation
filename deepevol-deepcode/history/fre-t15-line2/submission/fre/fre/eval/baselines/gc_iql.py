def task_goal_state(
    task: Any,
    obs_dim: Optional[int] = None,
    reference_state: Any = None,
    position_dims: Sequence[int] = (0, 1),
    discretized: bool = True,
) -> np.ndarray:
    """Build the ground-truth goal vector a GC agent conditions on.

    "Evaluation: the goal-conditioned agent is given the ground-truth goal that
    the specific evaluation task contains" (Addendum).  When the task defines a
    low-dimensional goal (e.g. an AntMaze ``(x, y)`` target) the coordinates are
    written into ``position_dims`` of a reference state so that the vector lives
    in the observation space the policy was trained on.
    """
    metadata = getattr(task, "metadata", None) or {}
    for key in ("goal_state", "goal_observation", "goal"):
        if isinstance(metadata, dict) and metadata.get(key) is not None:
            goal = np.asarray(metadata[key], dtype=np.float64).reshape(-1)
            if obs_dim is None or goal.shape[0] >= int(obs_dim):
                return goal
            base = np.zeros(int(obs_dim), dtype=np.float64) if reference_state is None else np.array(
                reference_state, dtype=np.float64
            ).reshape(-1)
            out = np.array(base, dtype=np.float64)
            for i, dim in enumerate(list(position_dims)[: goal.shape[0]]):
                if 0 <= int(dim) < out.shape[0]:
                    out[int(dim)] = goal[i]
            return out
    goal = getattr(task, "goal", None)
    if goal is None:
        raise ValueError(f"task '{getattr(task, 'name', task)}' does not define a ground-truth goal")
    goal = np.asarray(goal, dtype=np.float64).reshape(-1)
    if obs_dim is None or goal.shape[0] >= int(obs_dim):
        return goal
    base = (
        np.zeros(int(obs_dim), dtype=np.float64)
        if reference_state is None
        else np.array(reference_state, dtype=np.float64).reshape(-1)
    )
    out = np.array(base, dtype=np.float64)
    for i, dim in enumerate(list(position_dims)[: goal.shape[0]]):
        if 0 <= int(dim) < out.shape[0]:
            out[int(dim)] = goal[i]
    return out


