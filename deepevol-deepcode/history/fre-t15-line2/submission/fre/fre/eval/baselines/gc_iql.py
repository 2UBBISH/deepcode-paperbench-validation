class GCIQLAgent(BaselineAgent):  # type: ignore[misc]
    """Goal-conditioned IQL agent (the GC-IQL baseline of the paper)."""

    name = "GC-IQL"
    num_skills = 1
    is_goal_conditioned = True
    uses_latent = False

    def __init__(
        self,
        replay_buffer: Any = None,
        obs_dim: Optional[int] = None,
        act_dim: Optional[int] = None,
        goal_dim: Optional[int] = None,
        config: Optional[GCIQLConfig] = None,
        device: Optional[str] = None,
        seed: Optional[int] = None,
        **config_overrides,
    ) -> None:
        if not _HAS_TORCH:
            raise RuntimeError("GC-IQL requires PyTorch (torch is not importable)")
        try:
            super().__init__()
        except Exception:
            pass

        if config is None:
            config = GCIQLConfig.from_dict(None, **config_overrides)
        elif config_overrides:
            config = GCIQLConfig.from_dict(config.to_dict(), **config_overrides)
        self.config = config

        self.replay_buffer = replay_buffer
        self.obs_dim = int(obs_dim if obs_dim is not None else getattr(replay_buffer, "obs_dim", 0))
        self.act_dim = int(act_dim if act_dim is not None else getattr(replay_buffer, "act_dim", 0))
        self.goal_dim = int(goal_dim) if goal_dim else self.obs_dim
        if self.obs_dim <= 0 or self.act_dim <= 0:
            raise ValueError("obs_dim and act_dim must be provided (or inferred from the replay buffer)")

        self.device = torch.device(device or config.device or ("cuda" if torch.cuda.is_available() else "cpu"))
        self.seed = int(seed if seed is not None else config.seed)
        self.rng = np.random.default_rng(self.seed)

        self.q = GCQNetwork(
            self.obs_dim, self.act_dim, self.goal_dim,
            hidden_dims=config.hidden_dims, activation=config.activation,
            layer_norm=config.layer_norm, num_qs=config.num_qs,
        ).to(self.device)
        self.v = GCValueNetwork(
            self.obs_dim, self.goal_dim,
            hidden_dims=config.hidden_dims, activation=config.activation,
            layer_norm=config.layer_norm,
        ).to(self.device)
        self.target_v = GCValueNetwork(
            self.obs_dim, self.goal_dim,
            hidden_dims=config.hidden_dims, activation=config.activation,
            layer_norm=config.layer_norm,
        ).to(self.device)
        self.target_v.load_state_dict(self.v.state_dict())
        for param in self.target_v.parameters():
            param.requires_grad_(False)
        self.policy = GCPolicyNetwork(
            self.obs_dim, self.act_dim, self.goal_dim,
            hidden_dims=config.hidden_dims, activation=config.activation,
            layer_norm=config.layer_norm, tanh_squash=config.tanh_squash,
            log_std_min=config.log_std_min, log_std_max=config.log_std_max,
        ).to(self.device)

        self.optimizer = torch.optim.Adam(self.parameters(), lr=float(config.learning_rate))
        self.train_step_count = 0
        self._goal_cache: Dict[str, np.ndarray] = {}
        self._reference_state: Optional[np.ndarray] = None

    # -- helpers -----------------------------------------------------------
    def parameters(self) -> List[Any]:
        params: List[Any] = []
        for module in (self.q, self.v, self.policy):
            params.extend(list(module.parameters()))
        return params

    @property
    def discount(self) -> float:
        return float(self.config.discount)

    @property
    def expectile(self) -> float:
        return float(self.config.expectile)

    @property
    def awr_temperature(self) -> float:
        return float(self.config.awr_temperature)

    def reference_state(self) -> np.ndarray:
        """A dataset state used to lift low-dimensional goals into observation space."""
        if self._reference_state is not None:
            return self._reference_state
        state = None
        if self.replay_buffer is not None:
            try:
                state = as_2d(self.replay_buffer.sample_states(1, rng=self.rng))[0]
            except Exception:
                state = None
            if state is None:
                try:
                    state = as_2d(self.replay_buffer.state_at(0, 0))[0]
                except Exception:
                    state = None
        if state is None:
            state = np.zeros(self.obs_dim, dtype=np.float64)
        self._reference_state = np.asarray(state, dtype=np.float64)
        return self._reference_state

    # -- goal-conditioned HER relabelling ---------------------------------
    def sample_goals(self, batch: Any) -> Dict[str, np.ndarray]:
        observations = getattr(batch, "observations", None)
        if observations is None:
            raise ValueError("batch does not expose observations")
        return sample_her_goals(
            observations=observations,
            traj_index=getattr(batch, "traj_index", None),
            step_index=getattr(batch, "step_index", None),
            replay_buffer=self.replay_buffer,
            trajectory_lengths=None,
            rng=self.rng,
            p_random_goal=self.config.p_random_goal,
            p_geometric_goal=self.config.p_geometric_goal,
            p_current_goal=self.config.p_current_goal,
            geometric_p=self.config.geometric_p,
            tolerance=self.config.goal_tolerance,
            reward_at_goal=self.config.reward_at_goal,
            reward_otherwise=self.config.reward_otherwise,
            goal_dims=self.config.goal_dims,
            goal_weights=self.config.goal_weights,
        )

    # -- IQL update --------------------------------------------------------
    def update(self, batch: Any = None) -> Dict[str, float]:
        """One IQL update on a HER-relabelled batch (paper: "goals and
        observations are concatenated", reward 0 at the goal and -1 otherwise)."""
        if batch is None:
            if self.replay_buffer is None:
                raise ValueError("a replay buffer or an explicit batch is required for training")
            batch = self.replay_buffer.sample_transitions(int(self.config.batch_size), rng=self.rng)

        goals_np = self.sample_goals(batch)
        rewards = np.asarray(goals_np["rewards"], dtype=np.float32)
        done_her = np.asarray(goals_np["terminals"], dtype=np.float32)
        terminals = np.asarray(getattr(batch, "terminals", np.zeros_like(rewards)), dtype=np.float32)
        terminals = np.clip(terminals + done_her, 0.0, 1.0)

        obs = _to_tensor(getattr(batch, "observations")).to(self.device)
        next_obs = _to_tensor(getattr(batch, "next_observations")).to(self.device)
        actions = _to_tensor(getattr(batch, "actions")).to(self.device)
        goals = _to_tensor(goals_np["goals"]).to(self.device)
        r = torch.as_tensor(rewards, dtype=torch.float32, device=self.device)
        d = torch.as_tensor(terminals, dtype=torch.float32, device=self.device)

        stats: Dict[str, float] = {}

        # (1) value: expectile regression of V(s, g) onto min-Q(s, a, g)
        with torch.no_grad():
            q_target = self.q.min_q(obs, actions, goals)
        v_pred = self.v(obs, goals)
        value_loss = expectile_loss(v_pred, q_target, expectile=self.config.expectile)
        self.optimizer.zero_grad(set_to_none=True)
        value_loss.backward()
        self._clip_grads()
        self.optimizer.step()

        # (2) critic: TD regression onto r + gamma (1 - done) V_target(s', g)
        with torch.no_grad():
            next_v = self.target_v(next_obs, goals)
            td_target = r + float(self.config.discount) * (1.0 - d) * next_v
        q_all = self.q.q_all(obs, actions, goals)
        q_loss = 0.5 * (q_all - td_target.unsqueeze(-1)).pow(2).mean()
        self.optimizer.zero_grad(set_to_none=True)
        q_loss.backward()
        self._clip_grads()
        self.optimizer.step()

        # (3) policy: AWR with weights exp(temperature * (Q - V))
        with torch.no_grad():
            q_for_adv = self.q.min_q(obs, actions, goals)
            v_for_adv = self.v(obs, goals)
            advantage = q_for_adv - v_for_adv
            weights = awr_weights(
                advantage,
                temperature=self.config.awr_temperature,
                clamp_max=self.config.adv_weight_clamp,
            )
        log_prob = self.policy.log_prob(obs, goals, actions)
        policy_loss = -(weights * log_prob).mean()
        self.optimizer.zero_grad(set_to_none=True)
        policy_loss.backward()
        self._clip_grads()
        self.optimizer.step()

        soft_update(self.target_v, self.v, tau=float(self.config.tau))
        self.train_step_count += 1

        with torch.no_grad():
            stats.update(
                {
                    "value_loss": float(value_loss.detach().cpu()),
                    "q_loss": float(q_loss.detach().cpu()),
                    "policy_loss": float(policy_loss.detach().cpu()),
                    "total_loss": float(
                        (value_loss + q_loss + policy_loss).detach().cpu()
                    ),
                    "mean_q": float(q_all.min(dim=-1).values.mean().detach().cpu()),
                    "mean_v": float(v_pred.mean().detach().cpu()),
                    "mean_advantage": float(advantage.mean().detach().cpu()),
                    "mean_weight": float(weights.mean().detach().cpu()),
                    "mean_td_target": float(td_target.mean().detach().cpu()),
                    "mean_reward": float(r.mean().detach().cpu()),
                    "goal_reached_rate": float(done_her.mean()),
                    "train_step": float(self.train_step_count),
                }
            )
        return stats

    def _clip_grads(self) -> None:
        max_norm = float(self.config.max_grad_norm or 0.0)
        if max_norm > 0:
            torch.nn.utils.clip_grad_norm_(self.parameters(), max_norm)

    def train_step(self, batch: Any = None) -> Dict[str, float]:
        return self.update(batch)

    def train(
        self,
        num_steps: Optional[int] = None,
        callback: Optional[Callable[[int, Dict[str, float]], None]] = None,
        log_interval: Optional[int] = None,
    ) -> List[Dict[str, float]]:
        steps = int(num_steps if num_steps is not None else self.config.num_steps)
        history: List[Dict[str, float]] = []
        for i in range(steps):
            stats = self.update()
            history.append(stats)
            if callback is not None:
                callback(i, stats)
            if log_interval and (i + 1) % int(log_interval) == 0:
                print(f"[GC-IQL] step {i + 1}/{steps} q_loss={stats['q_loss']:.4f}")
        return history

    #: alias matching the reference codebase's naming
    fit = train

    # -- evaluation interface ---------------------------------------------
    def goal_for_task(self, task: Any, reference_state: Any = None) -> np.ndarray:
        """Ground-truth goal of an evaluation task, in the (discretized) obs space."""
        key = str(getattr(task, "name", id(task)))
        if key in self._goal_cache:
            return self._goal_cache[key]
        goal = task_goal_state(
            task,
            obs_dim=self.obs_dim,
            reference_state=self.reference_state() if reference_state is None else reference_state,
        )
        self._goal_cache[key] = goal
        return goal

    def condition(self, task: Any, context: Any = None, rng: Optional[np.random.Generator] = None) -> np.ndarray:
        return self.goal_for_task(task)

    def condition_many(
        self,
        task: Any,
        num_skills: int = 1,
        context: Any = None,
        rng: Optional[np.random.Generator] = None,
    ) -> np.ndarray:
        goal = self.condition(task, context=context, rng=rng)
        return np.repeat(goal.reshape(1, -1), int(num_skills), axis=0)

    def act(self, observation: Any, conditioning: Any, deterministic: bool = True) -> np.ndarray:
        obs = _to_tensor(observation).to(self.device)
        if obs.dim() == 1:
            obs = obs.unsqueeze(0)
        goal = _to_tensor(conditioning).to(self.device)
        if goal.dim() == 1:
            goal = goal.unsqueeze(0)
        if goal.shape[0] != obs.shape[0]:
            goal = goal.expand(obs.shape[0], -1)
        with torch.no_grad():
            _, _, action, _ = self.policy(obs, goal, deterministic=deterministic)
        return action.detach().cpu().numpy()

    def act_batch(self, observations: Any, conditioning: Any, deterministic: bool = True) -> np.ndarray:
        return self.act(as_2d(observations), np.asarray(conditioning, dtype=np.float32), deterministic=deterministic)

    # -- persistence -------------------------------------------------------
    def state_dict(self) -> Dict[str, Any]:
        return {
            "q": self.q.state_dict(),
            "v": self.v.state_dict(),
            "target_v": self.target_v.state_dict(),
            "policy": self.policy.state_dict(),
            "optimizer": self.optimizer.state_dict(),
            "config": self.config.to_dict(),
            "train_step_count": self.train_step_count,
            "obs_dim": self.obs_dim,
            "act_dim": self.act_dim,
            "goal_dim": self.goal_dim,
        }

    def load_state_dict(self, state: Dict[str, Any], load_optimizer: bool = True) -> None:
        self.q.load_state_dict(state["q"])
        self.v.load_state_dict(state["v"])
        self.target_v.load_state_dict(state["target_v"])
        self.policy.load_state_dict(state["policy"])
        if load_optimizer and "optimizer" in state:
            try:
                self.optimizer.load_state_dict(state["optimizer"])
            except Exception:
                pass
        self.train_step_count = int(state.get("train_step_count", 0))

    def save(self, path: str) -> str:
        os.makedirs(os.path.dirname(os.path.abspath(path)) or ".", exist_ok=True)
        torch.save(self.state_dict(), path)
        return path

    def load(self, path: str, load_optimizer: bool = True) -> Dict[str, Any]:
        state = torch.load(path, map_location=self.device)
        self.load_state_dict(state, load_optimizer=load_optimizer)
        return state

    def describe(self) -> Dict[str, Any]:
        return {
            "name": self.name,
            "method": "GC-IQL",
            "obs_dim": self.obs_dim,
            "act_dim": self.act_dim,
            "goal_dim": self.goal_dim,
            "hidden_dims": list(self.config.hidden_dims),
            "expectile": self.config.expectile,
            "awr_temperature": self.config.awr_temperature,
            "discount": self.config.discount,
            "tau": self.config.tau,
            "her": {
                "p_random_goal": self.config.p_random_goal,
                "p_geometric_goal": self.config.p_geometric_goal,
                "p_current_goal": self.config.p_current_goal,
                "reward_at_goal": self.config.reward_at_goal,
                "reward_otherwise": self.config.reward_otherwise,
            },
            "train_steps": self.train_step_count,
        }


