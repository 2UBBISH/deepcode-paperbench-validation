def as_2d(observations: Any) -> np.ndarray:
    """Coerce observations (tensor / array / list) to a 2-D float64 array."""
    if observations is None:
        return np.zeros((0, 0), dtype=np.float64)
    if isinstance(observations, np.ndarray):
        arr = np.asarray(observations, dtype=np.float64)
    elif _HAS_TORCH and isinstance(observations, torch.Tensor):  # pragma: no cover
        arr = observations.detach().cpu().numpy().astype(np.float64)
    else:
        arr = np.asarray(observations, dtype=np.float64)
    if arr.size == 0:
        return arr.reshape(0, -1)
    if arr.ndim == 1:
        arr = arr.reshape(1, -1)
    return arr


def episode_length_for(task: Any, default: int = 1000) -> int:
    fn = _resolve("episode_length_for", None)
    if callable(fn):
        try:
            return int(fn(task, default=default))
        except TypeError:
            try:
                return int(fn(task))
            except Exception:
                pass
        except Exception:
            pass
    return int(getattr(task, "eval_episode_length", default) or default)


def task_reward(task: Any, observations: Any) -> np.ndarray:
    fn = _resolve("task_reward", None)
    if callable(fn):
        try:
            return np.asarray(fn(task, observations), dtype=np.float64).reshape(-1)
        except Exception:
            pass
    obs = as_2d(observations)
    reward_fn = getattr(task, "reward_fn", None)
    if reward_fn is not None:
        return np.asarray(reward_fn(obs), dtype=np.float64).reshape(-1)
    reward = getattr(task, "reward", None)
    if callable(reward):
        return np.asarray(reward(obs), dtype=np.float64).reshape(-1)
    raise AttributeError("task does not expose a usable reward function")


def task_succeeded(task: Any, observations: Any, threshold: Optional[float] = None) -> np.ndarray:
    fn = _resolve("task_succeeded", None)
    if callable(fn):
        try:
            return np.asarray(fn(task, observations, threshold), dtype=bool).reshape(-1)
        except Exception:
            pass
    success = getattr(task, "success", None)
    if callable(success):
        try:
            return np.asarray(success(observations, threshold), dtype=bool).reshape(-1)
        except TypeError:
            return np.asarray(success(observations), dtype=bool).reshape(-1)
    rewards = task_reward(task, observations)
    reward_max = float(getattr(task, "reward_max", 0.0) or 0.0)
    return rewards >= reward_max - 1e-8


def normalize_score(
    task: Any,
    episode_return: float,
    succeeded: bool = False,
    episode_length: Optional[int] = None,
    clip: bool = False,
) -> float:
    fn = _resolve("normalize_score", None)
    if callable(fn):
        try:
            return float(
                fn(
                    task,
                    episode_return,
                    succeeded=succeeded,
                    episode_length=episode_length,
                    clip=clip,
                )
            )
        except Exception:
            pass
    reward_min = float(getattr(task, "reward_min", -1.0) or -1.0)
    reward_max = float(getattr(task, "reward_max", 0.0) or 0.0)
    length = float(episode_length or episode_length_for(task))
    lo, hi = reward_min * length, reward_max * length
    if hi <= lo:
        return float(100.0 * episode_return)
    score = 100.0 * (float(episode_return) - lo) / (hi - lo)
    return float(np.clip(score, 0.0, 100.0)) if clip else float(score)


