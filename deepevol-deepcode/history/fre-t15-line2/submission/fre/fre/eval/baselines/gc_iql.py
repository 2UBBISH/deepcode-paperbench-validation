def expectile_loss(
    prediction: Any, target: Any, expectile: float = DEFAULT_EXPECTILE, reduction: str = "mean"
):
    """Expectile regression loss ``L = |tau - 1{u < 0}| * u^2``."""
    fn = None
    try:
        from fre.training.iql import expectile_loss as _fn  # type: ignore

        fn = _fn
    except Exception:
        fn = None
    if callable(fn):
        return fn(prediction, target, expectile=expectile, reduction=reduction)
    diff = target - prediction
    weight = torch.where(diff > 0, float(expectile), 1.0 - float(expectile))
    loss = weight * diff.pow(2)
    if reduction == "none":
        return loss
    if reduction == "sum":
        return loss.sum()
    return loss.mean()


def awr_weights(
    advantage: Any,
    temperature: float = DEFAULT_AWR_TEMPERATURE,
    clamp_max: float = DEFAULT_ADV_WEIGHT_CLAMP,
    normalize: bool = False,
):
    """AWR weights ``exp(temperature * advantage)`` with an upper clamp."""
    fn = None
    try:
        from fre.training.iql import awr_weights as _fn  # type: ignore

        fn = _fn
    except Exception:
        fn = None
    if callable(fn):
        try:
            return fn(advantage, temperature=temperature, clamp_max=clamp_max, normalize=normalize)
        except TypeError:
            pass
    weights = torch.exp(float(temperature) * advantage)
    return torch.clamp(weights, max=float(clamp_max))


def soft_update(target: Any, source: Any, tau: float = DEFAULT_TAU) -> None:
    """Polyak update ``theta_target <- tau * theta + (1 - tau) * theta_target``."""
    fn = None
    try:
        from fre.training.iql import soft_update as _fn  # type: ignore

        fn = _fn
    except Exception:
        fn = None
    if callable(fn):
        try:
            fn(target, source, tau=tau)
            return
        except TypeError:
            pass
    with torch.no_grad():
        for tp, sp in zip(target.parameters(), source.parameters()):
            tp.data.mul_(1.0 - float(tau)).add_(sp.data, alpha=float(tau))


# ----------------------------------------------------------------------------
# Goal-conditioned rewards / HER goal sampling (Addendum, verbatim ratios)
# ----------------------------------------------------------------------------
def goal_distance(
    observations: Any,
    goals: Any,
    dims: Optional[Sequence[int]] = None,
    weights: Optional[Sequence[float]] = None,
    eps: float = 1e-8,
) -> np.ndarray:
    """Euclidean distance between each observation and each goal (broadcast)."""
    obs = as_2d(observations)
    goal = as_2d(goals)
    if obs.shape[0] == 0 or goal.shape[0] == 0:
        return np.zeros((obs.shape[0], goal.shape[0]), dtype=np.float64)
    if dims is not None:
        idx = np.asarray(list(dims), dtype=int)
        obs = obs[:, idx]
        goal = goal[:, idx]
    diff = obs[:, None, :] - goal[None, :, :]
    if weights is not None:
        w = np.asarray(list(weights), dtype=np.float64).reshape(1, 1, -1)
        diff = diff * w
    return np.sqrt(np.sum(diff * diff, axis=-1) + float(eps) ** 2)


def goal_reward(
    observations: Any,
    goals: Any,
    tolerance: float = DEFAULT_GOAL_TOLERANCE,
    dims: Optional[Sequence[int]] = None,
    weights: Optional[Sequence[float]] = None,
    reward_at_goal: float = REWARD_AT_GOAL,
    reward_otherwise: float = REWARD_OTHERWISE,
) -> Tuple[np.ndarray, np.ndarray]:
    """Goal-conditioned reward: ``0`` at the goal (within ``tolerance``), else ``-1``.

    Returns ``(rewards, dones)`` where ``dones`` is the terminal flag that is
    ``True`` exactly when the goal is reached (the addendum sets the terminal
    flag to ``True`` whenever the reward is ``0``).
    """
    obs = as_2d(observations)
    goal = as_2d(goals)
    if goal.shape[0] == 1 and obs.shape[0] > 1:
        goal = np.repeat(goal, obs.shape[0], axis=0)
    if obs.shape[0] != goal.shape[0]:
        raise ValueError(
            "observations and goals must have the same number of rows, got "
            f"{obs.shape[0]} and {goal.shape[0]}"
        )
    dist = np.sqrt(np.sum((obs - goal) ** 2, axis=-1) + 1e-12)
    reached = dist <= float(tolerance) + 1e-9
    rewards = np.where(reached, float(reward_at_goal), float(reward_otherwise)).astype(np.float64)
    return rewards, reached.astype(bool)


def _geometric_lookahead(rng: np.random.Generator, p: float, size: int, max_len: np.ndarray) -> np.ndarray:
    """Number of steps ahead sampled from a geometric distribution, clipped."""
    draws = rng.geometric(p=float(p), size=int(size)).astype(np.int64)
    return np.minimum(draws, np.maximum(max_len.astype(np.int64), 1))


def sample_her_goals(
    observations: Any,
    traj_index: Any,
    step_index: Any,
    replay_buffer: Any = None,
    trajectory_lengths: Optional[Sequence[int]] = None,
    rng: Optional[np.random.Generator] = None,
    p_random_goal: float = DEFAULT_P_RANDOM_GOAL,
    p_geometric_goal: float = DEFAULT_P_GEOMETRIC_GOAL,
    p_current_goal: float = DEFAULT_P_CURRENT_GOAL,
    geometric_p: float = DEFAULT_GEOMETRIC_P,
    tolerance: float = DEFAULT_GOAL_TOLERANCE,
    reward_at_goal: float = REWARD_AT_GOAL,
    reward_otherwise: float = REWARD_OTHERWISE,
    goal_dims: Optional[Sequence[int]] = None,
    goal_weights: Optional[Sequence[float]] = None,
) -> Dict[str, np.ndarray]:
    """Sample hindsight goals with the addendum's 0.3 / 0.5 / 0.2 mixture.

    Branch 1 (``p_random_goal = 0.3``): a completely random goal state taken from
    the dataset.  Branch 2 (``p_geometric_goal = 0.5``): a *future* state in the
    same trajectory, sampled with a geometric distribution.  Branch 3
    (``p_current_goal = 0.2``): the current state is the goal, giving reward ``0``
    and a terminal flag of ``True``.

    Returns a dict with ``goals``, ``rewards``, ``terminals`` and ``branch`` (an
    integer code per row: 0 = random, 1 = geometric/future, 2 = current).
    """
    rng = rng if rng is not None else np.random.default_rng()
    obs = as_2d(observations)
    n = obs.shape[0]
    if n == 0:
        return {
            "goals": np.zeros((0, obs.shape[1] if obs.ndim == 2 else 0), dtype=np.float64),
            "rewards": np.zeros(0, dtype=np.float64),
            "terminals": np.zeros(0, dtype=bool),
            "branch": np.zeros(0, dtype=np.int64),
        }

    traj = np.asarray(traj_index, dtype=np.int64).reshape(-1) if traj_index is not None else np.zeros(n, dtype=np.int64)
    step = np.asarray(step_index, dtype=np.int64).reshape(-1) if step_index is not None else np.zeros(n, dtype=np.int64)

    if trajectory_lengths is not None:
        lengths = np.asarray(trajectory_lengths, dtype=np.int64).reshape(-1)
    elif replay_buffer is not None and hasattr(replay_buffer, "num_trajectories"):
        lengths = np.array(
            [int(replay_buffer.trajectory_length(i)) for i in range(int(replay_buffer.num_trajectories))],
            dtype=np.int64,
        )
    else:
        lengths = np.array([int(traj.max()) + 1 if n else 0], dtype=np.int64)

    # ---- branch assignment -------------------------------------------------
    probs = np.asarray([p_random_goal, p_geometric_goal, p_current_goal], dtype=np.float64)
    if probs.sum() <= 0:
        probs = np.asarray([0.3, 0.5, 0.2], dtype=np.float64)
    probs = probs / probs.sum()
    branch = rng.choice(3, size=n, p=probs).astype(np.int64)

    goals = np.array(obs, dtype=np.float64)

    # branch 1: future state within the same trajectory (geometric look-ahead)
    geo_rows = np.flatnonzero(branch == 1)
    if geo_rows.size:
        t_len = lengths[np.clip(traj[geo_rows], 0, max(len(lengths) - 1, 0))] if lengths.size else np.zeros(geo_rows.size)
        remaining = np.maximum(t_len - step[geo_rows], 1)
        offsets = _geometric_lookahead(rng, geometric_p, geo_rows.size, remaining)
        future_steps = np.minimum(step[geo_rows] + offsets, np.maximum(t_len - 1, 0))
        if replay_buffer is not None and hasattr(replay_buffer, "state_at"):
            for row, (t, s) in enumerate(zip(traj[geo_rows], future_steps)):
                try:
                    goals[geo_rows[row]] = as_2d(replay_buffer.state_at(int(t), int(s)))[0]
                except Exception:
                    goals[geo_rows[row]] = obs[geo_rows[row]]
        else:
            # fall back to grouping: nearest later observation in the same traj
            for row, (t, s) in enumerate(zip(traj[geo_rows], future_steps)):
                same = np.flatnonzero((traj == t) & (step >= s))
                if same.size:
                    goals[geo_rows[row]] = obs[int(same[0])]

    # branch 0: completely random goal taken from the dataset
    rand_rows = np.flatnonzero(branch == 0)
    if rand_rows.size:
        if replay_buffer is not None and hasattr(replay_buffer, "sample_states"):
            try:
                sampled = as_2d(replay_buffer.sample_states(int(rand_rows.size), rng=rng))
                if sampled.shape[0] == rand_rows.size:
                    goals[rand_rows] = sampled
            except Exception:
                pass
        if not np.all(goals[rand_rows] != obs[rand_rows]):
            # deterministic fallback: exchange goals among the random branch
            perm = rng.permutation(rand_rows.size)
            goals[rand_rows] = obs[rand_rows][perm]

    # branch 2: the current state is the goal (reward 0, terminal True)
    goals[branch == 2] = obs[branch == 2]

    rewards, reached = goal_reward(
        obs,
        goals,
        tolerance=float(tolerance),
        dims=goal_dims,
        weights=goal_weights,
        reward_at_goal=reward_at_goal,
        reward_otherwise=reward_otherwise,
    )
    # "the current state is the goal, in which case the reward is 0 and the
    # mask/terminal flag is True"
    terminals = reached | (branch == 2)
    rewards = np.where(branch == 2, float(reward_at_goal), rewards)
    return {
        "goals": np.asarray(goals, dtype=np.float64),
        "rewards": np.asarray(rewards, dtype=np.float64),
        "terminals": np.asarray(terminals, dtype=bool),
        "branch": branch,
    }


def sample_geometric_goal_steps(
    step_index: Any,
    trajectory_lengths: Any,
    p: float = DEFAULT_GEOMETRIC_P,
    rng: Optional[np.random.Generator] = None,
) -> np.ndarray:
    """Sample future goal steps with a geometric look-ahead distribution."""
    rng = rng if rng is not None else np.random.default_rng()
    steps = np.asarray(step_index, dtype=np.int64).reshape(-1)
    lengths = np.asarray(trajectory_lengths, dtype=np.int64).reshape(-1)
    if lengths.size == 1:
        lengths = np.repeat(lengths, steps.size)
    remaining = np.maximum(lengths - steps, 1)
    offsets = _geometric_lookahead(rng, p, steps.size, remaining)
    return np.minimum(steps + offsets, np.maximum(lengths - 1, 0))


# ----------------------------------------------------------------------------
# Networks: goal concatenated to the observation (Addendum), Table 3 widths.
# ----------------------------------------------------------------------------
def _build_mlp(
    input_dim: int,
    hidden_dims: Sequence[int],
    output_dim: int,
    activation: str = DEFAULT_ACTIVATION,
    layer_norm: bool = False,
) -> Any:
    """Small MLP builder (reuses ``fre.models.rl_networks.build_mlp`` if present)."""
    try:
        from fre.models.rl_networks import build_mlp as _fn  # type: ignore

        return _fn(input_dim, tuple(hidden_dims), output_dim, activation=activation, layer_norm=layer_norm)
    except Exception:
        pass
    act = {"relu": nn.ReLU, "gelu": nn.GELU, "tanh": nn.Tanh, "silu": nn.SiLU}.get(
        str(activation).lower(), nn.ReLU
    )
    layers: List[Any] = []
    last = int(input_dim)
    for width in hidden_dims:
        layers.append(nn.Linear(last, int(width)))
        if layer_norm:
            layers.append(nn.LayerNorm(int(width)))
        layers.append(act())
        last = int(width)
    layers.append(nn.Linear(last, int(output_dim)))
    return nn.Sequential(*layers)


class GCQNetwork(_ModuleBase):
    """Twin goal-conditioned action-value network ``Q(s, a, g)``."""

    def __init__(
        self,
        obs_dim: int,
        act_dim: int,
        goal_dim: Optional[int] = None,
        hidden_dims: Sequence[int] = DEFAULT_HIDDEN_DIMS,
        activation: str = DEFAULT_ACTIVATION,
        layer_norm: bool = False,
        num_qs: int = DEFAULT_NUM_QS,
        name: str = "gc_q_network",
    ) -> None:
        super().__init__()
        self.obs_dim = int(obs_dim)
        self.act_dim = int(act_dim)
        self.goal_dim = int(goal_dim) if goal_dim else int(obs_dim)
        self.num_qs = int(num_qs)
        self.name = name
        input_dim = self.obs_dim + self.goal_dim + self.act_dim
        self.qs = nn.ModuleList(
            [
                _build_mlp(input_dim, hidden_dims, 1, activation=activation, layer_norm=layer_norm)
                for _ in range(self.num_qs)
            ]
        )

    def forward(self, observation: Any, action: Any, goal: Any, return_all: bool = False):
        x = torch.cat([observation, goal, action], dim=-1)
        values = torch.cat([q(x) for q in self.qs], dim=-1)  # (B, num_qs)
        if return_all:
            return values
        return values.min(dim=-1).values

    def q_all(self, observation: Any, action: Any, goal: Any):
        return self.forward(observation, action, goal, return_all=True)

    def min_q(self, observation: Any, action: Any, goal: Any):
        return self.forward(observation, action, goal, return_all=False)


class GCValueNetwork(_ModuleBase):
    """Goal-conditioned value network ``V(s, g)``."""

    def __init__(
        self,
        obs_dim: int,
        goal_dim: Optional[int] = None,
        hidden_dims: Sequence[int] = DEFAULT_HIDDEN_DIMS,
        activation: str = DEFAULT_ACTIVATION,
        layer_norm: bool = False,
        name: str = "gc_value_network",
    ) -> None:
        super().__init__()
        self.obs_dim = int(obs_dim)
        self.goal_dim = int(goal_dim) if goal_dim else int(obs_dim)
        self.name = name
        self.net = _build_mlp(
            self.obs_dim + self.goal_dim, hidden_dims, 1, activation=activation, layer_norm=layer_norm
        )

    def forward(self, observation: Any, goal: Any):
        return self.net(torch.cat([observation, goal], dim=-1)).squeeze(-1)


class GCPolicyNetwork(_ModuleBase):
    """Goal-conditioned Gaussian policy ``pi(a | s, g)`` (tanh-squashed)."""

    def __init__(
        self,
        obs_dim: int,
        act_dim: int,
        goal_dim: Optional[int] = None,
        hidden_dims: Sequence[int] = DEFAULT_HIDDEN_DIMS,
        activation: str = DEFAULT_ACTIVATION,
        layer_norm: bool = False,
        tanh_squash: bool = True,
        log_std_min: float = DEFAULT_LOG_STD_MIN,
        log_std_max: float = DEFAULT_LOG_STD_MAX,
        name: str = "gc_policy_network",
    ) -> None:
        super().__init__()
        self.obs_dim = int(obs_dim)
        self.act_dim = int(act_dim)
        self.goal_dim = int(goal_dim) if goal_dim else int(obs_dim)
        self.tanh_squash = bool(tanh_squash)
        self.log_std_min = float(log_std_min)
        self.log_std_max = float(log_std_max)
        self.name = name
        self.trunk = _build_mlp(
            self.obs_dim + self.goal_dim, hidden_dims, int(hidden_dims[-1]) if len(hidden_dims) else 256,
            activation=activation, layer_norm=layer_norm,
        )
        last = int(hidden_dims[-1]) if len(hidden_dims) else 256
        self.mean_layer = nn.Linear(last, self.act_dim)
        self.log_std_layer = nn.Linear(last, self.act_dim)

    def distribution_params(self, observation: Any, goal: Any):
        h = self.trunk(torch.cat([observation, goal], dim=-1))
        mean = self.mean_layer(h)
        log_std = torch.clamp(self.log_std_layer(h), self.log_std_min, self.log_std_max)
        return mean, log_std

    def forward(
        self,
        observation: Any,
        goal: Any,
        sample: bool = True,
        deterministic: bool = False,
        action: Any = None,
        return_log_prob: bool = True,
    ):
        mean, log_std = self.distribution_params(observation, goal)
        std = log_std.exp()
        if action is None:
            if deterministic:
                pre_tanh = mean
            else:
                pre_tanh = mean + std * torch.randn_like(std)
            act = torch.tanh(pre_tanh) if self.tanh_squash else pre_tanh
            log_prob = self._log_prob(pre_tanh, mean, log_std) if return_log_prob else None
        else:
            pre_tanh = action
            if self.tanh_squash:
                pre_tanh = torch.clamp(action, -1.0 + 1e-6, 1.0 - 1e-6).atanh()
            act = action
            log_prob = self._log_prob(pre_tanh, mean, log_std) if return_log_prob else None
        return mean, log_std, act, log_prob

    def _log_prob(self, pre_tanh: Any, mean: Any, log_std: Any):
        var = (2.0 * log_std).exp()
        log_prob = -0.5 * (((pre_tanh - mean) ** 2) / var + 2.0 * log_std + math.log(2.0 * math.pi))
        log_prob = log_prob.sum(dim=-1)
        if self.tanh_squash:
            correction = torch.log(torch.clamp(1.0 - torch.tanh(pre_tanh) ** 2, min=1e-6))
            log_prob = log_prob - correction.sum(dim=-1)
        return log_prob

    def log_prob(self, observation: Any, goal: Any, action: Any):
        _, _, _, log_prob = self.forward(observation, goal, action=action, return_log_prob=True)
        return log_prob

    def act_numpy(self, observation: Any, goal: Any, deterministic: bool = True) -> np.ndarray:
        with torch.no_grad():
            _, _, act, _ = self.forward(
                _to_tensor(observation), _to_tensor(goal), deterministic=deterministic
            )
        return act.detach().cpu().numpy()


def _to_tensor(value: Any) -> Any:
    if value is None:
        return None
    if _HAS_TORCH and isinstance(value, torch.Tensor):
        return value
    return torch.as_tensor(np.asarray(value, dtype=np.float32))


