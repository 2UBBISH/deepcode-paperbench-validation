def _mask_net_for_refiner(handle: ExplanationHandle) -> Any:
    """Return the mask network the refiner should use (None => random scoring)."""
    if handle.mask_net is not None:
        return handle.mask_net
    # Random / IG / AIRS do not expose a `MaskNetwork`; prefer their shim if provided.
    explainer = handle.explainer
    if explainer is not None:
        shim = getattr(explainer, "mask_net", None)
        if shim is not None:
            return shim
        as_mask = getattr(explainer, "as_mask_network", None)
        if callable(as_mask):
            try:
                return as_mask()
            except Exception:  # pragma: no cover
                return None
    return None


def _refine_once(env: Any, policy: Any, handle: ExplanationHandle, env_id: str,
                 cfg: Optional[Dict[str, Any]] = None, seed: int = 0, device: str = "cpu",
                 logger: Any = None, total_timesteps: Optional[int] = None,
                 eval_episodes: int = DEFAULT_EVAL_EPISODES, **kwargs: Any
                 ) -> Tuple[Any, Any, Dict[str, Any]]:
    """Run RICE's Algorithm 2 refiner with the explanation's critical states.

    The refiner is identical for every explanation method (the paper's "fix the refining
    method" protocol); only the mask network / importance signal changes.
    """
    refine_cfg = dict((cfg or {}).get("refine", {}) or {})
    p = float(kwargs.pop("p", refine_cfg.get("p", DEFAULT_P)))
    lam = float(kwargs.pop("lam", refine_cfg.get("lam", DEFAULT_LAMBDA)))
    timesteps = int(total_timesteps or refine_cfg.get("total_timesteps", DEFAULT_REFINE_TIMESTEPS))
    K = refine_cfg.get("K", None)

    start = time.time()
    try:
        refined, refiner = refine_policy(
            env,
            policy=policy,
            mask_net=_mask_net_for_refiner(handle),
            total_timesteps=timesteps,
            p=p,
            lam=lam,
            K=K,
            env_id=env_id,
            seed=seed,
            device=device,
            logger=logger,
            progress=False,
            use_mixed_init=bool(refine_cfg.get("use_mixed_init", True)),
            use_rnd=bool(refine_cfg.get("use_rnd", True)),
            **kwargs,
        )
    except Exception as exc:  # pragma: no cover - surfaced to the caller
        raise RuntimeError(f"refining with explanation '{handle.method}' failed: {exc}") from exc
    wall = time.time() - start
    info = {"wall_time": wall, "timesteps": timesteps, "p": p, "lam": lam}
    return refined, refiner, info


def evaluate_policy_return(env: Any, policy: Any, env_id: str, n_episodes: int = DEFAULT_EVAL_EPISODES,
                           deterministic: bool = True, max_steps: Optional[int] = None,
                           device: str = "cpu", logger: Any = None, **kwargs: Any
                           ) -> Dict[str, float]:
    """Evaluate the (possibly refined) policy's final reward."""
    if policy is None:
        return {"mean_reward": float("nan"), "std_reward": float("nan"), "n_episodes": 0}
    try:
        stats = evaluate_refined_policy(env, policy, env_id=env_id, n_episodes=int(n_episodes),
                                        max_steps=max_steps, deterministic=deterministic,
                                        device=device)
    except Exception:  # pragma: no cover
        stats = {"mean_reward": float("nan"), "std_reward": float("nan"), "n_episodes": 0}
    return {
        "mean_reward": float(stats.get("mean_reward", stats.get("mean", float("nan")))),
        "std_reward": float(stats.get("std_reward", stats.get("std", 0.0))),
        "n_episodes": int(stats.get("n_episodes", n_episodes)),
        "rewards": stats.get("rewards", stats.get("episode_rewards", [])),
    }


def refine_with_explanation(explanation: str, env: Any, policy: Any,
                            handle: ExplanationHandle, env_id: str,
                            cfg: Optional[Dict[str, Any]] = None, seed: int = 0,
                            device: str = "cpu", logger: Any = None,
                            total_timesteps: Optional[int] = None,
                            no_refine_reward: Optional[float] = None,
                            eval_episodes: int = DEFAULT_EVAL_EPISODES,
                            checkpoint: Optional[str] = None,
                            **kwargs: Any) -> ExplanationQualityResult:
    """Refine with one explanation + the fixed RICE refiner and package the result."""
    result = ExplanationQualityResult(
        explanation=str(explanation),
        env_id=env_id,
        no_refine_reward=no_refine_reward,
        seed=int(seed),
        samples=int(handle.samples),
        explanation_time=float(handle.train_time),
        checkpoint=str(checkpoint) if checkpoint else None,
    )
    try:
        refined, refiner, info = _refine_once(
            env, policy, handle, env_id, cfg=cfg, seed=seed, device=device, logger=logger,
            total_timesteps=total_timesteps, eval_episodes=eval_episodes, **kwargs,
        )
    except Exception as exc:
        result.extra.setdefault("errors", []).append(str(exc))
        result.extra["failed"] = True
        return result

    stats = evaluate_policy_return(env, refined, env_id, n_episodes=eval_episodes,
                                   device=device, logger=logger)
    result.final_reward = float(stats.get("mean_reward", float("nan")))
    result.std = float(stats.get("std_reward", float("nan")))
    result.eval_rewards = list(stats.get("rewards", []) or [])
    result.wall_time = float(info.get("wall_time", 0.0))
    result.policy = refined
    result.refiner = refiner
    try:
        result.history = list(getattr(refiner, "train_history", None)
                              or getattr(refiner, "history", []) or [])
    except Exception:  # pragma: no cover
        result.history = []
    try:
        result.summary = dict(refiner.summary())
    except Exception:  # pragma: no cover
        result.summary = {}
    result.extra.update({"refine_info": _jsonable(info), "reference": reference_for(explanation, env_id)})
    _fill_improvement(result, no_refine_reward)
    return result


def _fill_improvement(result: ExplanationQualityResult,
                      no_refine_reward: Optional[float]) -> None:
    """Compute improvement (higher-is-better for both positive and negative rewards)."""
    baseline = _safe_float(no_refine_reward)
    current = _safe_float(result.final_reward)
    if baseline is None or current is None:
        result.improvement = None
        return
    if is_negative_env(result.env_id):
        # For negative rewards, higher means closer to zero; keep the signed difference.
        result.improvement = current - baseline
    else:
        result.improvement = current - baseline


