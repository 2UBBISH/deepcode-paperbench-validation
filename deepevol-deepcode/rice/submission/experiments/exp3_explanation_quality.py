def run_experiment3(env_id: str, cfg: Optional[Dict[str, Any]] = None,
                    explanations: Sequence[str] = EXPLANATION_METHODS,
                    seeds: Sequence[int] = DEFAULT_SEEDS,
                    refine_timesteps: Optional[int] = None,
                    mask_timesteps: Optional[int] = None,
                    pretrain_timesteps: Optional[int] = None,
                    device: str = "cpu", out_dir: Optional[str] = None,
                    logger: Any = None, progress: bool = False,
                    checkpoint: Optional[str] = None,
                    checkpoint_dir: Optional[str] = None,
                    eval_episodes: int = DEFAULT_EVAL_EPISODES,
                    **kwargs: Any) -> Dict[str, Any]:
    """Run Experiment III on a single application.

    Fixes the refining method to RICE (ours) and varies the explanation method across
    ``explanations`` (default the paper's Random/StateMask/Ours).  Reports the final
    reward before/after refining and the qualitative ordering per seed.
    """
    cfg = cfg if cfg is not None else get_config(normalize_env_key(env_id), None)
    out_dir = ensure_dir(out_dir or os.path.join("results", "exp3"))
    log = logger or get_logger("rice.exp3", out_dir)

    report: Dict[str, Any] = {
        "experiment": "III",
        "env_id": env_id,
        "explanations": list(explanations),
        "seeds": list(seeds),
        "refining_method": "ours",
        "results": {},
        "references": {},
        "no_refine_reward": None,
        "config": _jsonable(cfg),
        "errors": [],
    }
    log.info("Experiment III | env=%s | explanations=%s | seeds=%s",
             env_id, list(explanations), list(seeds))

    for seed in seeds:
        set_seed(seed_from(0, int(seed), 3))
        log.info("--- seed %d ---", seed)
        try:
            env = build_experiment_env(env_id, cfg=cfg, seed=seed, mode="train")
        except Exception as exc:
            report["errors"].append(f"env build failed: {exc}")
            log.warning("env build failed: %s", exc)
            continue

        try:
            policy = build_or_load_policy(env, env_id, cfg=cfg, device=device,
                                          checkpoint=checkpoint, logger=log)
            if policy is None:
                policy = pretrain_target_policy(
                    env, env_id,
                    total_timesteps=int(pretrain_timesteps
                                        or ((cfg or {}).get("target", {}) or {}).get(
                                            "total_timesteps", DEFAULT_PRETRAIN_TIMESTEPS)),
                    seed=seed, device=device, logger=log, cfg=cfg,
                )
        except Exception as exc:
            report["errors"].append(f"target policy unavailable: {exc}")
            log.warning("target policy unavailable: %s", exc)
            continue

        # ---------------- "No Refine" baseline (once per seed) ----------------
        no_refine = None
        try:
            stats = evaluate_policy_return(env, policy, env_id, n_episodes=eval_episodes,
                                           device=device, logger=log)
            no_refine = float(stats.get("mean_reward", float("nan")))
        except Exception as exc:  # pragma: no cover
            log.warning("no-refine evaluation failed: %s", exc)
        if report["no_refine_reward"] is None:
            report["no_refine_reward"] = _safe_float(no_refine)
        report.setdefault("no_refine_per_seed", {})[seed] = _safe_float(no_refine)
        log.info("No Refine reward: %s", format_mean_std([no_refine]))

        # -------- Stage 1: one explanation per method, then Stage 2: refine --------
        for method in explanations:
            log.info("training explanation '%s' (seed %d)", method, seed)
            try:
                handle = train_explanation(
                    method, env, policy, env_id, cfg=cfg, seed=seed, device=device,
                    logger=log, mask_timesteps=mask_timesteps, checkpoint_dir=checkpoint_dir,
                )
            except Exception as exc:
                report["errors"].append(f"{method} explanation failed: {exc}")
                log.warning("explanation '%s' failed: %s", method, exc)
                continue

            ckpt = None
            if checkpoint_dir:
                ckpt = os.path.join(str(checkpoint_dir),
                                    f"{normalize_env_key(env_id)}_{method}_refined.zip")

            result = refine_with_explanation(
                method, env, policy, handle, env_id, cfg=cfg, seed=seed, device=device,
                logger=log, total_timesteps=refine_timesteps,
                no_refine_reward=no_refine, eval_episodes=eval_episodes,
                checkpoint=ckpt, **kwargs,
            )
            if ckpt and result.policy is not None:
                try:
                    ensure_dir(os.path.dirname(ckpt) or ".")
                    save_policy(result.policy, ckpt, env_id=env_id)
                except Exception:  # pragma: no cover
                    pass

            entry = report["results"].setdefault(str(method), {"seeds": {}, "values": []})
            entry["seeds"][seed] = result.to_dict(include_history=False)
            if _safe_float(result.final_reward) is not None:
                entry["values"].append(float(result.final_reward))
            if _safe_float(handle.train_time) is not None:
                entry.setdefault("explanation_time", []).append(float(handle.train_time))
            log.info("  refined reward [%s]: %s", method, format_mean_std(entry["values"]))

        try:
            env.close()
        except Exception:  # pragma: no cover
            pass

    # ---------------- aggregation + trend validation ----------------
    for method, entry in report["results"].items():
        values = entry.get("values", [])
        entry["mean"] = _safe_float(np.mean(values)) if values else None
        entry["std"] = _safe_float(np.std(values)) if values else None
        entry["formatted"] = format_mean_std(values)
        entry["reference"] = reference_for(method, env_id)
        report["references"][method] = entry["reference"]

    report["ranking"] = _rank_methods(report["results"])
    report["trend_check"] = check_trends(report)
    report["report"] = format_report(report)

    save_json(_jsonable(report), os.path.join(out_dir, f"exp3_{normalize_env_key(env_id)}.json"))
    try:
        with open(os.path.join(out_dir, f"exp3_{normalize_env_key(env_id)}.txt"), "w",
                  encoding="utf-8") as fh:
            fh.write(report["report"])
    except Exception:  # pragma: no cover
        pass
    log.info("\n%s", report["report"])
    return report


def _rank_methods(results: Dict[str, Dict[str, Any]]) -> List[str]:
    """Rank explanation methods by mean refined reward (higher is better)."""
    pairs = [(name, entry.get("mean")) for name, entry in results.items()
             if _safe_float(entry.get("mean")) is not None]
    pairs.sort(key=lambda kv: kv[1], reverse=True)
    return [name for name, _ in pairs]


