def train_ours_explanation(env: Any, policy: Any, env_id: str, total_timesteps: int,
                           alpha: float = DEFAULT_ALPHA, seed: int = 0, device: str = "cpu",
                           checkpoint: Optional[str] = None, logger: Any = None,
                           cfg: Optional[Dict[str, Any]] = None) -> ExplanationHandle:
    """Stage 1 for RICE: Algorithm 1 (vanilla PPO + blinding bonus alpha * a_t^m)."""
    start = time.time()
    mask_net, trainer = train_mask_network(
        env,
        policy,
        total_timesteps=int(total_timesteps),
        alpha=float(alpha),
        env_id=env_id,
        seed=seed,
        device=device,
        logger=logger,
        progress=False,
    )
    elapsed = time.time() - start
    if checkpoint:
        try:
            ensure_dir(os.path.dirname(str(checkpoint)) or ".")
            save_mask_network(mask_net, str(checkpoint), env_id=env_id)
        except Exception:  # pragma: no cover
            pass
    return ExplanationHandle(
        method="ours",
        env_id=env_id,
        mask_net=mask_net,
        trainer=trainer,
        train_time=elapsed,
        samples=int(total_timesteps),
        checkpoint=str(checkpoint) if checkpoint else None,
        extra={"alpha": float(alpha)},
    )


