def check_trends(report: Dict[str, Any]) -> Dict[str, Any]:
    """Validate the qualitative ordering of Table 1's right block.

    Required by the reproduction plan:
      * Ours and StateMask are comparable (both may beat Random);
      * both beat Random;
      * Ours is not worse than Random.
    The claim "Ours strictly beats StateMask" is intentionally NOT enforced.
    """
    results = report.get("results", {}) or {}
    env_id = report.get("env_id")
    checks: Dict[str, Any] = {"env_id": env_id, "checks": {}, "passed": None, "notes": []}

    means = {name: _safe_float(entry.get("mean")) for name, entry in results.items()}
    checks["means"] = means
    checks["ranking"] = report.get("ranking", [])

    ours = means.get("ours")
    statemask = means.get("statemask")
    random_ = means.get("random")

    def _cmp(a: Optional[float], b: Optional[float]) -> Optional[bool]:
        if a is None or b is None:
            return None
        return a >= b - ORDER_TOLERANCE

    if ours is not None and random_ is not None:
        checks["checks"]["ours_beats_random"] = _cmp(ours, random_)
    if statemask is not None and random_ is not None:
        checks["checks"]["statemask_beats_random"] = _cmp(statemask, random_)
    if ours is not None and statemask is not None:
        # Comparable, not strictly better: allow a small deficit.
        tol = max(0.02 * abs(statemask), 1e-6)
        checks["checks"]["ours_comparable_to_statemask"] = bool(ours >= statemask - tol)
        checks["checks"]["ours_strictly_beats_statemask"] = bool(ours > statemask)

    # Optional Table-6 explanations.
    for extra in OTHER_EXPLANATION_METHODS:
        value = means.get(extra)
        if value is not None and random_ is not None:
            checks["checks"][f"{extra}_beats_random"] = _cmp(value, random_)

    applicable = [v for v in checks["checks"].values() if v is not None]
    checks["passed"] = bool(applicable) and all(applicable)
    if not applicable:
        checks["notes"].append("no comparable methods produced finite rewards")

    # Reference comparison (trend only, never exact).
    for name, mean in means.items():
        ref = reference_for(name, env_id) if env_id else None
        if mean is not None and ref is not None and abs(ref) > 1e-9:
            rel = abs(mean - ref) / abs(ref)
            checks["notes"].append(
                f"{name}: mean={mean:.2f} vs paper {ref:.2f} (rel. diff {rel:.1%})"
            )
    return checks


def format_report(report: Dict[str, Any], decimals: int = 2) -> str:
    """Render a human-readable Experiment-III table."""
    lines: List[str] = []
    env_id = report.get("env_id", "?")
    lines.append("=" * 78)
    lines.append(f"Experiment III - explanation quality effect ({env_id})")
    lines.append("Fix refining method = Ours (RICE); vary explanation methods")
    lines.append("=" * 78)
    no_refine = report.get("no_refine_reward")
    if no_refine is not None:
        lines.append(f"No Refine (pre-trained pi): {no_refine:.{decimals}f}")
    lines.append("")
    header = f"{'Explanation':<24}{'Refined reward (mean +- std)':<34}{'Paper (Table 1)':<18}"
    lines.append(header)
    lines.append("-" * len(header))
    ranking = report.get("ranking", []) or list((report.get("results") or {}).keys())
    for name in ranking:
        entry = report["results"][name]
        mean = entry.get("mean")
        std = entry.get("std")
        if mean is None:
            cell = "n/a"
        elif std is None:
            cell = f"{mean:.{decimals}f}"
        else:
            cell = f"{mean:.{decimals}f} +- {std:.{decimals}f}"
        ref = entry.get("reference")
        ref_cell = f"{ref:.{decimals}f}" if ref is not None else "-"
        lines.append(f"{name:<24}{cell:<34}{ref_cell:<18}")
    lines.append("")

    trend = report.get("trend_check", {}) or {}
    lines.append("Trend validation:")
    for key, value in (trend.get("checks", {}) or {}).items():
        mark = "OK " if value else "FAIL"
        lines.append(f"  [{mark}] {key}")
    for note in trend.get("notes", []) or []:
        lines.append(f"  note: {note}")
    lines.append(f"  overall: {'PASS' if trend.get('passed') else 'FAIL'}")
    errors = report.get("errors") or []
    if errors:
        lines.append("")
        lines.append("Errors:")
        for err in errors:
            lines.append(f"  - {err}")
    lines.append("=" * 78)
    return "\n".join(lines)


