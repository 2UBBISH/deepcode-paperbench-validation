def build_target_policy(env: Any, env_id: str, cfg: Optional[Dict[str, Any]] = None,
                        device: str = "cpu", **kwargs: Any) -> Any:
    """Instantiate the (per-application) target policy architecture."""
    target_cfg = (cfg or {}).get("target", {}) or {}
    hidden = target_cfg.get("hidden_sizes")
    activation = target_cfg.get("activation")
    try:
        return build_policy(
            env_id,
            observation_space=getattr(env, "observation_space", None),
            action_space=getattr(env, "action_space", None),
            hidden_sizes=hidden,
            activation=activation,
            device=device,
            **kwargs,
        )
    except Exception as exc:  # pragma: no cover - only on bare installs
        try:
            return build_policy(
                env_id,
                obs_dim=getattr(getattr(env, "observation_space", None), "shape", [None])[0],
                action_dim=int(np.prod(getattr(getattr(env, "action_space", None), "shape", [1]))),
                hidden_sizes=hidden,
                device=device,
            )
        except Exception:
            raise RuntimeError(f"unable to build target policy for {env_id}: {exc}") from exc


def build_or_load_policy(env: Any, env_id: str, cfg: Optional[Dict[str, Any]] = None,
                         device: str = "cpu", checkpoint: Optional[str] = None,
                         logger: Any = None, **kwargs: Any) -> Any:
    """Load a pre-trained / frozen target policy pi, else build a fresh one."""
    target_cfg = (cfg or {}).get("target", {}) or {}
    ckpt = checkpoint or target_cfg.get("checkpoint")
    if ckpt and os.path.exists(str(ckpt)):
        try:
            policy = load_policy(
                str(ckpt),
                env_id=env_id,
                observation_space=getattr(env, "observation_space", None),
                action_space=getattr(env, "action_space", None),
                device=device,
            )
            if policy is not None:
                return policy
        except Exception as exc:  # pragma: no cover
            if logger is not None:
                logger.warning("failed to load policy checkpoint %s: %s", ckpt, exc)
    return build_target_policy(env, env_id, cfg=cfg, device=device, **kwargs)


def pretrain_target_policy(env: Any, env_id: str, total_timesteps: int = DEFAULT_PRETRAIN_TIMESTEPS,
                           seed: int = 0, device: str = "cpu", logger: Any = None,
                           cfg: Optional[Dict[str, Any]] = None, **kwargs: Any) -> Any:
    """Pre-train the frozen pi with plain PPO (no mixed init, no RND).

    This reproduces the "No Refine" (bottlenecked) regime of Table 1.  Only used when no
    checkpoint is supplied.
    """
    policy = build_target_policy(env, env_id, cfg=cfg, device=device)
    try:
        _, refiner = refine_policy(
            env,
            policy=policy,
            total_timesteps=int(total_timesteps),
            env_id=env_id,
            use_mixed_init=False,
            use_rnd=False,
            p=0.0,
            lam=0.0,
            seed=seed,
            device=device,
            logger=logger,
            progress=False,
            **kwargs,
        )
        return getattr(refiner, "policy", policy)
    except Exception as exc:  # pragma: no cover
        if logger is not None:
            logger.warning("target pre-training failed (%s); using fresh policy", exc)
        return policy


