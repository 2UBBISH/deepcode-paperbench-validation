@dataclass
class ExplanationHandle:
    """A trained (or trivially constructed) Stage-1 explanation."""

    method: str
    env_id: str
    mask_net: Any = None
    trainer: Any = None
    explainer: Any = None
    train_time: float = 0.0
    samples: int = 0
    checkpoint: Optional[str] = None
    extra: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "method": self.method,
            "env_id": self.env_id,
            "has_mask_net": self.mask_net is not None,
            "has_explainer": self.explainer is not None,
            "train_time": self.train_time,
            "samples": self.samples,
            "checkpoint": self.checkpoint,
            "extra": _jsonable(self.extra),
        }


@dataclass
class ExplanationQualityResult:
    """Outcome of refining with one explanation method (one env, one seed)."""

    explanation: str
    env_id: str
    final_reward: float = float("nan")
    std: float = float("nan")
    eval_rewards: List[float] = field(default_factory=list)
    no_refine_reward: Optional[float] = None
    improvement: Optional[float] = None
    history: List[Dict[str, float]] = field(default_factory=list)
    summary: Dict[str, Any] = field(default_factory=dict)
    wall_time: float = 0.0
    explanation_time: float = 0.0
    samples: int = 0
    seed: int = 0
    policy: Any = None
    refiner: Any = None
    checkpoint: Optional[str] = None
    extra: Dict[str, Any] = field(default_factory=dict)

    def format(self, decimals: int = 2) -> str:
        return (
            f"{self.env_id:<16} {self.explanation:<22} "
            f"{self.final_reward:.{decimals}f} (std {self.std:.{decimals}f})"
        )

    def to_dict(self, include_history: bool = False) -> Dict[str, Any]:
        payload = {
            "explanation": self.explanation,
            "env_id": self.env_id,
            "final_reward": _safe_float(self.final_reward),
            "std": _safe_float(self.std),
            "eval_rewards": [_safe_float(v) for v in self.eval_rewards],
            "no_refine_reward": _safe_float(self.no_refine_reward),
            "improvement": _safe_float(self.improvement),
            "wall_time": self.wall_time,
            "explanation_time": self.explanation_time,
            "samples": self.samples,
            "seed": self.seed,
            "checkpoint": self.checkpoint,
            "summary": _jsonable(self.summary),
            "extra": _jsonable(self.extra),
        }
        if include_history:
            payload["history"] = _jsonable(self.history)
        return payload


