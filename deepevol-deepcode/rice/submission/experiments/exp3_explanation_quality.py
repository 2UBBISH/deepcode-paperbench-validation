"""Experiment III of RICE (Cheng et al., ICML 2024, PMLR 235).

Paper specification
-------------------
Sec. 4.2 -- "Experiment III. To investigate how the quality of explanation affects
the downstream refining process, we run our proposed refining method based on the
critical steps identified by different explanation methods (Random, StateMask, and
our method) and compare the agent's performance after refining."

Sec. 4.3 -- "Refining based on Different Explanations. ... We run our proposed
refining method based on the critical steps identified by ours and Random. We have
two main observations.  First, using the explanation generated by our mask network,
the refining achieves the best outcome across all applications.  Second, using the
explanation generated by our explanation significantly outperforms the random
baseline."

The corresponding paper numbers live in the *right* block of Table 1
("Fix Refine; Vary Explanation Methods"), e.g. Hopper
Random 3648.98 / StateMask 3661.86 / Ours 3663.91 and Cage
-25.94 / -20.07 / -20.02.  Appendix C.3 additionally studies
"Impact of Other Explanation Methods" (Integrated Gradients and AIRS) on four
MuJoCo games and concludes "Using other explanation methods (Integrated Gradients
and AIRS), our framework still achieves better results than the random baseline"
(Table 6).  Per the reproduction plan, the claim that "Ours strictly beats
StateMask" is explicitly *not* required -- the two are comparable -- so the trend
checker only enforces (a) Ours/StateMask both beat Random and (b) Ours is at the
top of the ranking.

This driver therefore:
  1. trains the frozen target policy pi (or loads a checkpoint),
  2. trains/loads each requested Stage-1 explanation method,
  3. refines with the *same* refiner (RICE's Algorithm 2 by default) for every
     explanation, so the only varying factor is the explanation quality,
  4. aggregates final refined reward over seeds (mean +/- std),
  5. validates the qualitative ordering against the paper's Table-1 right block
     and (optionally) Table 6, and
  6. writes JSON/text reports to ``results/exp3/``.

Everything heavy is delegated to the already implemented ``rice`` modules; all
project imports are defensive so the CLI stays introspectable on a bare install.
"""

