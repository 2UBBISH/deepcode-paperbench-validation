def _safe_float(value: Any) -> Optional[float]:
    try:
        out = float(value)
    except (TypeError, ValueError):
        return None
    return out if np.isfinite(out) else None


def _jsonable(value: Any) -> Any:
    """Best-effort JSON conversion of nested result payloads."""
    if value is None or isinstance(value, (bool, int, float, str)):
        return value if not isinstance(value, float) or np.isfinite(value) else None
    if isinstance(value, np.generic):
        return _jsonable(value.item())
    if isinstance(value, np.ndarray):
        return value.tolist()
    if isinstance(value, dict):
        return {str(k): _jsonable(v) for k, v in value.items()}
    if isinstance(value, (list, tuple, set)):
        return [_jsonable(v) for v in value]
    return str(value)


def reference_for(explanation: str, env_id: str) -> Optional[float]:
    """Paper reference (Table 1 right block / Table 6) for a method+env pair."""
    key = normalize_env_key(env_id)
    table = REFERENCE_FIX_REFINE.get(key) or REFERENCE_TABLE6.get(key)
    if not table:
        return None
    return _safe_float(table.get(str(explanation).strip().lower()))


def mask_budget_for(env_id: str, cfg: Optional[Dict[str, Any]] = None) -> int:
    """Fixed mask-net sample budget (Table 4), overridable through the config."""
    key = normalize_env_key(env_id)
    explanation_cfg = (cfg or {}).get("explanation", {}) or {}
    if explanation_cfg.get("total_timesteps"):
        return int(explanation_cfg["total_timesteps"])
    if key in TABLE4_SAMPLES:
        return int(TABLE4_SAMPLES[key])
    try:
        return int(statemask_samples_for(env_id))
    except Exception:  # pragma: no cover
        return DEFAULT_MASK_TIMESTEPS


