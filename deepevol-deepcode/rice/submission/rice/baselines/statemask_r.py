def statemask_r_baseline(
    env: Any,
    target_policy: Any,
    env_id: str = "default",
    mask_samples: Optional[int] = None,
    refine_timesteps: Optional[int] = None,
    refine_iterations: Optional[int] = None,
    config: Optional[Any] = None,
    seed: Optional[int] = None,
    device: str = "cpu",
    progress: bool = False,
    evaluate: bool = False,
    eval_episodes: int = 10,
    save_dir: Optional[str] = None,
    **kwargs: Any,
) -> Dict[str, Any]:
    """Run the full StateMask-R baseline (StateMask explanation + reset-to-critical refine)."""
    baseline = StateMaskR(
        env_id=env_id,
        config=config,
        seed=seed,
        device=device,
        mask_samples=mask_samples,
        **kwargs,
    )
    return baseline.run(
        env=env,
        target_policy=target_policy,
        mask_samples=mask_samples,
        refine_timesteps=refine_timesteps,
        refine_iterations=refine_iterations,
        progress=progress,
        evaluate=evaluate,
        eval_episodes=eval_episodes,
        save_dir=save_dir,
    )


