class StateMaskTrainer(MaskTrainer):  # type: ignore[misc]
    """StateMask explanation trainer: vanilla PPO inner loop + dual update on ``alpha``.

    This reproduces the *primal-dual* scheme the paper attributes to StateMask
    (``min |eta(pi) - eta(pi_bar)|``) as opposed to RICE's ``max eta(pi_bar)``
    reformulation (Sec. 3.3 / Theorem 3.3).  The mask-network parameters are
    optimized with vanilla PPO on the augmented reward
    ``R'_t = R(s_t, a_t) + alpha * a_t^m`` exactly like
    :class:`rice.explanation.mask_trainer.MaskTrainer`; the difference is that
    ``alpha`` is a *Lagrangian multiplier* recomputed after every iteration from
    the measured performance gap between the original policy and the perturbed
    (masked) policy — this extra dual optimisation is what makes StateMask
    slower than RICE for a fixed sample budget (Table 4: 16.8% on average).

    Parameters mirror :class:`MaskTrainer`; ``config`` may be a
    :class:`StateMaskConfig`, a dict, or a :class:`MaskPPOConfig`.
    """

    def __init__(
        self,
        env: Any,
        target_policy: Any,
        mask_net: Any = None,
        critic: Any = None,
        config: Optional[Any] = None,
        env_id: str = "default",
        device: str = "cpu",
        logger: Any = None,
        observation_space: Any = None,
        action_space: Any = None,
        discrete: Optional[bool] = None,
        seed: Optional[int] = None,
        store_dataset: bool = True,
        **kwargs: Any,
    ) -> None:
        if not _HAS_MASK_TRAINER:
            raise ImportError(
                "StateMaskTrainer requires rice.explanation.mask_trainer "
                "(PyTorch + the RICE explanation package)."
            )

        sm_cfg = (
            config
            if isinstance(config, StateMaskConfig)
            else StateMaskConfig.from_dict(config if config is not None else kwargs)
        )
        inner = (
            MaskPPOConfig.from_dict(sm_cfg.to_dict())
            if MaskPPOConfig is not None
            else sm_cfg
        )
        try:
            inner.alpha = float(sm_cfg.alpha_init)  # type: ignore[attr-defined]
        except Exception:
            pass

        super().__init__(  # type: ignore[misc]
            env=env,
            target_policy=target_policy,
            mask_net=mask_net,
            critic=critic,
            config=inner,
            env_id=env_id,
            device=device,
            logger=logger,
            observation_space=observation_space,
            action_space=action_space,
            discrete=discrete,
            seed=seed,
            store_dataset=store_dataset,
            **kwargs,
        )

        self.sm_config = sm_cfg
        self.delta = float(sm_cfg.delta)
        self.dual_lr = float(sm_cfg.dual_lr)
        self.alpha_min = float(sm_cfg.alpha_min)
        self.alpha_max = float(sm_cfg.alpha_max)
        self.dual_mode = str(sm_cfg.dual_mode)

        self.original_return: Optional[float] = None
        self.gap_history: List[float] = []
        self.alpha_history: List[float] = []
        self._gap_measurements = 0

        self._apply_alpha(float(sm_cfg.alpha_init))

    # ------------------------------------------------------------------ utils
    def _mask_env(self) -> Any:
        for attr in ("mask_env", "masked_env", "train_env"):
            env = getattr(self, attr, None)
            if env is not None:
                return env
        env = getattr(self, "env", None)
        if env is not None and MaskEnv is not None and isinstance(env, MaskEnv):
            return env
        return None

    def _apply_alpha(self, alpha: float) -> float:
        """Push the current multiplier into the trainer/config/mask-env."""
        self.alpha = float(np.clip(alpha, self.alpha_min, self.alpha_max))
        cfg = getattr(self, "config", None)
        if cfg is not None:
            try:
                cfg.alpha = self.alpha
            except Exception:
                pass
        env = self._mask_env()
        if env is not None:
            if hasattr(env, "set_alpha"):
                try:
                    env.set_alpha(self.alpha)
                except Exception:
                    env.alpha = self.alpha  # type: ignore[attr-defined]
            else:
                env.alpha = self.alpha  # type: ignore[attr-defined]
        self.alpha_history.append(self.alpha)
        return self.alpha

    # ------------------------------------------------- policy return estimates
    def measure_original_return(
        self,
        n_episodes: Optional[int] = None,
        max_steps: Optional[int] = None,
        deterministic: bool = False,
    ) -> float:
        """Estimate ``eta(pi)`` by rolling the frozen policy with mask = keep.

        Equivalent to evaluating the pre-trained policy: with ``a_t^m = 0`` the
        masked action equals the target action and the blinding bonus vanishes.
        """
        env = self._mask_env()
        if env is None:
            return float("nan")
        n_episodes = int(n_episodes or self.sm_config.eval_episodes)
        if max_steps is None:
            max_steps = int(getattr(self.config, "n_steps", None) or 1000)

        rewards: List[float] = []
        for ep in range(max(1, n_episodes)):
            try:
                if hasattr(env, "seed"):
                    env.seed(int(getattr(self, "seed", 0) or 0) + ep)
            except Exception:
                pass
            try:
                obs, _ = _unpack_reset(env.reset())
            except Exception:
                break
            ep_ret, steps, done = 0.0, 0, False
            while not done and steps < max_steps:
                obs, reward, terminated, truncated, info = _unpack_step(
                    env.step(MASK_KEEP)
                )
                ep_ret += float(info.get("task_reward", reward))
                done = bool(terminated or truncated)
                steps += 1
            rewards.append(ep_ret)

        self._gap_measurements += 1
        value = _mean(rewards)
        if np.isfinite(value):
            self.original_return = value
        return float(self.original_return if self.original_return is not None else value)

    def perturbed_return(self, batch: Any = None) -> float:
        """Estimate ``eta(pi_bar)`` from the freshly collected perturbed rollout."""
        if batch is not None:
            for attr in ("episode_task_returns", "episode_returns", "episode_augmented_returns"):
                values = getattr(batch, attr, None)
                if values is not None and len(values) > 0:
                    return _mean(values)
            task_rewards = getattr(batch, "task_rewards", None)
            if task_rewards is not None and len(task_rewards) > 0:
                n_steps = float(getattr(self.config, "n_steps", None) or 1000)
                n_ep = max(1.0, len(task_rewards) / n_steps)
                return float(np.sum(task_rewards) / n_ep)
        return float("nan")

    # ------------------------------------------------------------ dual update
    def dual_update(self, gap: float) -> float:
        """Projected (dual) update of the blinding multiplier ``alpha``.

        ``gap = eta(pi) - eta(pi_bar)`` (positive when perturbing hurts).
        Stored as a *relative* gap ``gap / |eta(pi)|`` so ``delta`` is
        scale-free across applications.
        """
        if not np.isfinite(gap):
            return self.alpha

        ref = self.original_return
        if ref is not None and np.isfinite(ref) and abs(float(ref)) > 1e-8:
            rel_gap = float(gap) / abs(float(ref))
        else:
            rel_gap = float(gap)

        violation = abs(rel_gap) - self.delta
        if self.dual_mode == "classic":
            new_alpha = self.alpha + self.dual_lr * violation
        else:  # "enforce" (default): blinding only pays while performance holds
            new_alpha = self.alpha - self.dual_lr * violation

        self.gap_history.append(float(rel_gap))
        self._apply_alpha(float(new_alpha))
        return self.alpha

    # -------------------------------------------------------------- main loop
    def train(  # type: ignore[override]
        self,
        total_timesteps: Optional[int] = None,
        total_iterations: Optional[int] = None,
        logger: Any = None,
        progress: bool = False,
        **kwargs: Any,
    ) -> List[Dict[str, Any]]:
        """StateMask training loop = RICE loop + per-iteration dual update."""
        log = logger or getattr(self, "logger", None) or globals()["logger"]
        steps_target = int(
            total_timesteps
            or getattr(self.config, "total_timesteps", DEFAULT_SAMPLES)
            or DEFAULT_SAMPLES
        )
        n_steps = int(getattr(self.config, "n_steps", None) or kwargs.get("n_steps") or 1000)
        if total_iterations is None:
            total_iterations = max(1, int(math.ceil(steps_target / max(1, n_steps))))

        # eta(pi) is a property of the frozen pre-trained policy: estimate once.
        self.measure_original_return()

        history: List[Dict[str, Any]] = []
        for iteration in range(int(total_iterations)):
            batch = self.collect_rollout()
            stats = dict(self.update(batch) or {})

            perturbed = self.perturbed_return(batch)
            if self.original_return is not None and np.isfinite(perturbed):
                gap: float = float(self.original_return) - float(perturbed)
            else:
                gap = float("nan")
            alpha_before = self.alpha
            self.dual_update(gap)

            stats.update(
                {
                    "statemask/iteration": iteration,
                    "statemask/alpha": float(self.alpha),
                    "statemask/alpha_before": float(alpha_before),
                    "statemask/dual_gap": float(gap),
                    "statemask/original_return": float(self.original_return or float("nan")),
                    "statemask/perturbed_return": float(perturbed),
                    "statemask/dual_step": float(self.alpha - alpha_before),
                }
            )
            history.append(stats)

            if self.sm_config.refresh_every and (iteration + 1) % int(self.sm_config.refresh_every) == 0:
                self.measure_original_return()

            if progress and self.sm_config.log_interval:
                try:
                    log.info(
                        "[StateMask] iter %d/%d alpha=%.5f gap=%.4f",
                        iteration + 1,
                        int(total_iterations),
                        self.alpha,
                        gap,
                    )
                except Exception:
                    pass

        return history

    # ------------------------------------------------------------- reporting
    def dual_report(self) -> Dict[str, Any]:
        return {
            "alpha_final": float(self.alpha),
            "alpha_init": float(self.sm_config.alpha_init),
            "alpha_history": [float(a) for a in self.alpha_history],
            "gap_history": [float(g) for g in self.gap_history],
            "mean_gap": _mean(self.gap_history),
            "original_return": (
                float(self.original_return) if self.original_return is not None else float("nan")
            ),
            "dual_mode": self.dual_mode,
            "delta": float(self.delta),
            "dual_lr": float(self.dual_lr),
            "n_dual_updates": len(self.gap_history),
        }

    def summary(self) -> Dict[str, Any]:  # type: ignore[override]
        try:
            base: Dict[str, Any] = dict(super().summary() or {})
        except Exception:
            base = {}
        base.update(self.dual_report())
        if hasattr(self, "time_report"):
            try:
                base.update(self.time_report())
            except Exception:
                pass
        return base


