"""StateMask-R baseline (explanation + refining) for RICE.

Paper reference
---------------
Cheng et al., *RICE: A Refining Scheme for Reinforcement Learning with
Explanation*, ICML 2024 (PMLR 235).

* **Baseline explanation method** (Sec. 4.1, "Baseline Explanation Methods"):
  "Since our explanation method proposes an alternative design of StateMask, the
  first baseline is StateMask. We compare our explanation method with StateMask
  to show the equivalence and efficiency of our method."  Appendix C.1:
  "as for StateMask, we use their released opensourced code from
  https://github.com/nuwuxian/RL-state_mask".

* **Baseline refining method** (Sec. 4.1, "Baseline Refining Methods"):
  "The second baseline is a refining method introduced by StateMask
  (Cheng et al., 2023), i.e., resetting to the critical state and continuing
  training from the critical state."

So ``StateMask-R`` is the union of the two:

1. ``StateMaskExplainer`` / ``StateMaskTrainer`` — an explanation stage that
   reproduces the *primal-dual* StateMask formulation
   (``min |eta(pi) - eta(pi_bar)|`` solved with a Lagrangian multiplier on the
   blinding reward, as opposed to RICE's vanilla-PPO reformulation
   ``max eta(pi_bar)``, see Sec. 3.3 / Theorem 3.3).  This is the reference for
   Experiment I / Table 4 (fidelity ~= RICE, but 16.8% slower to train).

2. ``StateMaskRefiner`` — a refinement stage that **always** resets to the
   identified critical state (``p = 1`` in the mixed-initial-state rule, i.e. no
   ``rho`` component, no RND bonus) before continuing PPO training.  Per
   Sec. 4.2 Experiment II, "all the refining methods use the same explanation
   generated by our explanation method if needed, to ensure a fair comparison" —
   so when used as a *refining* baseline, this class is fed RICE's mask net.

Only *trends* matter for reproduction (see the plan's validation approach):
StateMask fidelity ~= RICE fidelity > Random; StateMask-R "does not always help
(overfits)" relative to RICE's mixed-initial-distribution refinement.

Everything is written defensively: the module stays importable (and usable for
the Random / RICE branches) even when torch, the mask trainer or the refiner are
unavailable.
"""

