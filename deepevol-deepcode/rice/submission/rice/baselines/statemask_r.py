@dataclass
class StateMaskConfig:
    """Configuration of the StateMask explanation trainer (primal-dual).

    Mirrors the hyper-parameters of the released StateMask code
    (``nuwuxian/RL-state_mask``): a vanilla PPO inner loop over the binary mask
    actions with reward ``R + alpha * a_t^m``, plus an *adaptive* multiplier
    ``alpha`` that enforces the constraint ``|eta(pi) - eta(pi_bar)| <= delta``
    (the primal-dual reformulation StateMask uses instead of RICE's
    ``max eta(pi_bar)``).

    Fields
    ------
    alpha_init : float
        Initial blinding coefficient (Sec. C.3 uses 0.01).
    dual_lr : float
        Step size of the projected dual update on ``alpha``.
    delta : float
        Tolerated *relative* performance gap ``|eta(pi) - eta(pi_bar)| / |eta(pi)|``.
    alpha_min / alpha_max : float
        Box constraints for the multiplier (dual feasibility ``alpha >= 0``).
    dual_mode : str
        ``"enforce"`` (default): decrease ``alpha`` when the gap exceeds
        ``delta`` (blinding is over-rewarded), increase it when the gap is
        comfortably inside the tolerance.  ``"classic"``: textbook dual ascent
        ``alpha <- alpha + dual_lr * (gap - delta)`` clipped to the box.  Both
        are exposed because the released code does not document its schedule;
        only trends are compared.
    eval_episodes : int
        Number of mask-keep rollouts used to estimate ``eta(pi)`` (cached).
    refresh_every : int
        Re-estimate ``eta(pi)`` every N iterations (0 = never after the first).
    """

    # inner PPO (vanilla) -- inherits RICE/SB3 defaults
    lr: float = 3e-4
    gamma: float = 0.99
    gae_lambda: float = 0.95
    clip_range: float = 0.2
    clip_range_vf: Optional[float] = None
    n_epochs: int = 10
    batch_size: int = 64
    vf_coef: float = 0.5
    ent_coef: float = 0.01
    max_grad_norm: float = 0.5
    normalize_advantage: bool = True
    target_kl: Optional[float] = None
    n_steps: Optional[int] = None
    total_timesteps: int = DEFAULT_SAMPLES
    device: str = "cpu"
    seed: Optional[int] = None
    deterministic_policy: bool = False
    log_interval: int = 1

    # Stage-1 (StateMask specific) hyper-parameters
    alpha_init: float = 0.01
    dual_lr: float = DEFAULT_DUAL_LR
    delta: float = DEFAULT_DELTA
    alpha_min: float = DEFAULT_ALPHA_MIN
    alpha_max: float = DEFAULT_ALPHA_MAX
    dual_mode: str = "enforce"
    use_blinding_bonus: bool = True
    eval_episodes: int = 3
    refresh_every: int = 0
    reward_mode: str = "augmented"

    @classmethod
    def from_dict(cls, cfg: Optional[Any] = None, **overrides: Any) -> "StateMaskConfig":
        """Build from a (possibly nested) YAML/dict config.

        Accepts the sections ``statemask`` / ``state_mask`` / ``mask_trainer`` /
        ``explanation`` / ``mask`` and the aliases ``alpha``/``lambda``,
        ``lr``/``learning_rate``, ``clip``, and ``dual_learning_rate``.
        """
        data: Dict[str, Any] = {}
        if cfg is not None:
            if isinstance(cfg, StateMaskConfig):
                data.update(cfg.to_dict())
            elif hasattr(cfg, "to_dict"):
                try:
                    nested = cfg.to_dict()
                    if isinstance(nested, dict):
                        data.update(nested)
                except Exception:
                    pass
            if isinstance(cfg, dict):
                data.update(cfg)
                for sect in ("statemask", "state_mask", "mask_trainer", "explanation", "mask"):
                    inner = cfg.get(sect)
                    if isinstance(inner, dict):
                        data.update(inner)
        data.update({k: v for k, v in overrides.items() if v is not None})

        # aliases
        alias = {
            "learning_rate": "lr",
            "lr_mask": "lr",
            "clip": "clip_range",
            "alpha": "alpha_init",
            "lambda": "alpha_init",
            "lambda_": "alpha_init",
            "dual_learning_rate": "dual_lr",
            "tolerance": "delta",
            "budget": "delta",
        }
        for src, dst in alias.items():
            if src in data and dst not in data:
                data[dst] = data[src]

        valid = set(getattr(cls, "__dataclass_fields__", {}).keys())
        kwargs = {k: v for k, v in data.items() if k in valid}
        return cls(**kwargs)

    def to_dict(self) -> Dict[str, Any]:
        return {f: getattr(self, f) for f in getattr(self, "__dataclass_fields__", {})}

    # ---- convenience aliases -------------------------------------------------
    @property
    def alpha(self) -> float:
        """Current multiplier (kept for API symmetry with ``MaskPPOConfig``)."""
        return float(getattr(self, "_alpha", self.alpha_init))

    @alpha.setter
    def alpha(self, value: float) -> None:
        self._alpha = float(value)

    @property
    def samples(self) -> int:
        return int(self.total_timesteps)


