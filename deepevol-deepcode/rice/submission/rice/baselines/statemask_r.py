def train_statemask_network(
    env: Any,
    target_policy: Any,
    total_timesteps: Optional[int] = None,
    alpha: float = 0.01,
    env_id: str = "default",
    config: Optional[Any] = None,
    logger: Any = None,
    save_path: Optional[str] = None,
    seed: Optional[int] = None,
    device: str = "cpu",
    store_dataset: bool = False,
    progress: bool = False,
    mask_net: Any = None,
    critic: Any = None,
    **kwargs: Any,
) -> Tuple[Any, "StateMaskTrainer"]:
    """Train a StateMask-style mask network (primal-dual) and return ``(net, trainer)``.

    ``total_timesteps`` defaults to the Table-4 sample budget for ``env_id``
    (3x10^5 for the MuJoCo games).  ``alpha`` is the *initial* multiplier.
    """
    if not _HAS_MASK_TRAINER:
        raise ImportError("train_statemask_network requires rice.explanation.mask_trainer")

    cfg = StateMaskConfig.from_dict(config, **kwargs)
    cfg.alpha_init = float(alpha)
    if total_timesteps is None:
        total_timesteps = samples_for(env_id, int(cfg.total_timesteps or DEFAULT_SAMPLES))
    cfg.total_timesteps = int(total_timesteps)

    trainer = StateMaskTrainer(
        env=env,
        target_policy=target_policy,
        mask_net=mask_net,
        critic=critic,
        config=cfg,
        env_id=env_id,
        device=device,
        logger=logger,
        seed=seed,
        store_dataset=store_dataset,
    )
    trainer.train(total_timesteps=total_timesteps, progress=progress)

    if save_path:
        try:
            trainer.save(save_path)  # type: ignore[attr-defined]
        except Exception as exc:  # pragma: no cover
            (logger or globals()["logger"]).warning(
                "could not save StateMask checkpoint: %s", exc
            )

    return trainer.mask_net, trainer  # type: ignore[attr-defined]


