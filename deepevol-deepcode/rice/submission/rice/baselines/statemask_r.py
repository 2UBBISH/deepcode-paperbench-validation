# Explanation facade (drop-in for the RICE explanation in the exp drivers)
# --------------------------------------------------------------------------- #


class StateMaskExplainer:
    """Explanation-method facade backed by a StateMask-trained mask network.

    Exposes the same surface as the RICE explanation
    (:class:`rice.explanation.importance.ImportanceScorer` +
    :class:`rice.explanation.critical_state.CriticalStateSelector`) so experiment
    drivers can swap ``{Random, StateMask, Ours}`` transparently
    (Sec. 4.2 Experiment III / Table 6).
    """

    name = "StateMask"

    def __init__(
        self,
        mask_net: Any = None,
        env: Any = None,
        policy: Any = None,
        env_id: str = "default",
        K: Optional[int] = None,
        deterministic_policy: bool = False,
        rng: Any = None,
        seed: Optional[int] = None,
        attach_scores: bool = True,
        batch_size: int = 4096,
        trainer: Any = None,
    ) -> None:
        self.mask_net = mask_net
        self.env = env
        self.policy = policy
        self.env_id = env_id
        self.K = K
        self.deterministic_policy = bool(deterministic_policy)
        self.rng = rng
        self.seed = seed
        self.trainer = trainer

        self.scorer: Any = None
        if _HAS_IMPORTANCE and mask_net is not None and ImportanceScorer is not None:
            try:
                self.scorer = ImportanceScorer(mask_net=mask_net, batch_size=batch_size)
            except Exception:
                self.scorer = None

        self.selector: Any = None
        if _HAS_CRITICAL and env is not None and CriticalStateSelector is not None:
            try:
                self.selector = CriticalStateSelector(  # type: ignore[misc]
                    env=env,
                    mask_net=mask_net,
                    K=K,
                    scorer=self.scorer,
                    deterministic_policy=self.deterministic_policy,
                    rng=rng,
                    attach_scores=attach_scores,
                )
            except Exception:
                self.selector = None

        self._history: List[Dict[str, Any]] = []

    # ------------------------------------------------------------------ scores
    def score(self, observations: Any) -> np.ndarray:
        """Step-level importance ``P(a_t^m = 0 | s_t)`` for each observation."""
        if self.mask_net is None:
            arr = np.asarray(observations)
            n = arr.shape[0] if arr.ndim > 1 else 1
            return np.ones(int(n), dtype=np.float64)
        if self.scorer is not None:
            try:
                return np.asarray(self.scorer.score(observations), dtype=np.float64)
            except Exception:
                pass
        try:
            from ..explanation.mask_network import state_importance  # type: ignore

            return np.asarray(state_importance(self.mask_net, observations), dtype=np.float64)
        except Exception:
            return np.ones(1, dtype=np.float64)

    def score_trajectory(self, trajectory: Any) -> np.ndarray:
        if _HAS_IMPORTANCE and score_trajectory is not None and self.mask_net is not None:
            try:
                return np.asarray(score_trajectory(self.mask_net, trajectory), dtype=np.float64)
            except Exception:
                pass
        obs = getattr(trajectory, "observations", trajectory)
        return self.score(obs)

    def importance_scores(self, trajectory: Any) -> np.ndarray:
        return self.score_trajectory(trajectory)

    def rank(self, trajectory: Any) -> np.ndarray:
        return np.argsort(-self.score_trajectory(trajectory), kind="mergesort")

    def top_k_states(self, trajectory: Any, k: int = 10) -> List[Any]:
        scores = self.score_trajectory(trajectory)
        order = np.argsort(-scores, kind="mergesort")[: max(1, int(k))]
        obs = getattr(trajectory, "observations", np.asarray(trajectory))
        return [np.asarray(obs[int(i)]) for i in order]

    # -------------------------------------------------------------- selection
    def rollout(self, policy: Any = None, K: Optional[int] = None, **kwargs: Any) -> Any:
        if self.selector is not None:
            return self.selector.rollout(policy=policy or self.policy, K=K or self.K, **kwargs)
        if _HAS_CRITICAL and roll_trajectory is not None and self.env is not None:
            return roll_trajectory(
                self.env,
                policy or self.policy,
                length=K or self.K,
                deterministic=self.deterministic_policy,
                **kwargs,
            )
        raise RuntimeError("StateMaskExplainer.rollout requires an environment")

    def select(
        self,
        policy: Any = None,
        K: Optional[int] = None,
        reset: bool = True,
        seed: Optional[int] = None,
        rollout: Any = None,
        **kwargs: Any,
    ) -> Any:
        """Critical state = argmax-importance state of a length-K ``pi`` rollout."""
        if self.selector is not None:
            critical = self.selector.select(
                policy=policy or self.policy,
                K=K or self.K,
                reset=reset,
                seed=seed,
                rollout=rollout,
            )
        elif _HAS_CRITICAL and identify_critical_state is not None and self.env is not None:
            critical = identify_critical_state(  # type: ignore[misc]
                self.env,
                policy or self.policy,
                mask_net=self.mask_net,
                K=K or self.K,
                deterministic=self.deterministic_policy,
                reset=reset,
                seed=seed,
            )
        else:
            raise RuntimeError("StateMaskExplainer.select requires an environment")
        self._history.append(
            {
                "env_id": self.env_id,
                "K": K or self.K,
                "impact": float(getattr(critical, "score", float("nan"))),
            }
        )
        return critical

    def select_top_k(
        self, k: int = 10, policy: Any = None, K: Optional[int] = None, **kwargs: Any
    ) -> List[Any]:
        rollout = self.rollout(policy=policy, K=K, **kwargs)
        if _HAS_CRITICAL and top_k_critical_states is not None:
            return top_k_critical_states(rollout, mask_net=self.mask_net, k=k)
        scores = self.score_trajectory(rollout)
        order = np.argsort(-scores, kind="mergesort")[: max(1, int(k))]
        obs = getattr(rollout, "observations", np.asarray(rollout))
        return [np.asarray(obs[int(i)]) for i in order]

    def identify(
        self, env: Any = None, policy: Any = None, K: Optional[int] = None, **kwargs: Any
    ) -> Any:
        self.env = env or self.env
        self.policy = policy or self.policy
        self.K = K or self.K
        if (
            self.selector is None
            and _HAS_CRITICAL
            and CriticalStateSelector is not None
            and self.env is not None
        ):
            try:
                self.selector = CriticalStateSelector(  # type: ignore[misc]
                    env=self.env,
                    mask_net=self.mask_net,
                    K=self.K,
                    scorer=self.scorer,
                    deterministic_policy=self.deterministic_policy,
                    rng=self.rng,
                )
            except Exception:
                self.selector = None
        return self.select(policy=self.policy, K=self.K, **kwargs)

    identify_critical_state = identify

    def reset_to(self, env: Any = None, critical: Any = None, **kwargs: Any) -> Any:
        if self.selector is not None and hasattr(self.selector, "reset_to"):
            return self.selector.reset_to(env or self.env, critical, **kwargs)
        target = env or self.env
        if target is not None and hasattr(target, "reset_to"):
            return target.reset_to(critical, **kwargs)
        if target is not None:
            return _unpack_reset(target.reset())
        raise RuntimeError("StateMaskExplainer.reset_to requires a resettable env")

    def statistics(self) -> Dict[str, Any]:
        stats: Dict[str, Any] = {
            "name": self.name,
            "env_id": self.env_id,
            "n_selections": len(self._history),
        }
        if self.selector is not None and hasattr(self.selector, "summary"):
            try:
                stats["selector"] = self.selector.summary()
            except Exception:
                pass
        if self.trainer is not None and hasattr(self.trainer, "dual_report"):
            try:
                stats["dual"] = self.trainer.dual_report()
            except Exception:
                pass
        return stats

    stats = statistics

    def describe(self) -> str:
        return (
            f"StateMask explanation (env={self.env_id}, "
            f"mask={'trained' if self.mask_net is not None else 'none'})"
        )


def make_statemask_explainer(
    env: Any = None,
    policy: Any = None,
    mask_net: Any = None,
    env_id: str = "default",
    K: Optional[int] = None,
    seed: Optional[int] = None,
    **kwargs: Any,
) -> StateMaskExplainer:
    return StateMaskExplainer(
        mask_net=mask_net, env=env, policy=policy, env_id=env_id, K=K, seed=seed, **kwargs
    )


# --------------------------------------------------------------------------- #
# Refining facade (reset-to-critical-state + continue PPO)
# --------------------------------------------------------------------------- #


class StateMaskRefiner:
    """StateMask refining baseline: **always** reset to the critical state.

    Paper (Sec. 4.1): "The second baseline is a refining method introduced by
    StateMask (Cheng et al., 2023), i.e., resetting to the critical state and
    continuing training from the critical state."  In the mixed-initial-state
    rule ``mu(s) = beta * d_rho^pihat(s) + (1 - beta) * rho(s)`` this is
    ``beta = 1`` (here ``p = 1``), with no RND exploration bonus and no ``rho``
    component (Sec. 4.2 Exp. IV: RICE's PPO switch with mixed init "breaks the
    bottleneck" whereas this baseline overfits and "does not always help").

    Per Sec. 4.2 (Experiment II) the *explanation* used here is the same as for
    every other refiner (RICE's mask net), which is why ``mask_net`` is the
    primary input.
    """

    name = "StateMask-R"

    def __init__(
        self,
        env: Any = None,
        policy: Any = None,
        mask_net: Any = None,
        config: Optional[Any] = None,
        env_id: str = "default",
        device: str = "cpu",
        logger: Any = None,
        sampler: Any = None,
        explainer: Any = None,
        use_rnd: bool = False,
        seed: Optional[int] = None,
        **kwargs: Any,
    ) -> None:
        if not _HAS_REFINER:
            raise ImportError("StateMaskRefiner requires rice.refining.ppo_refine (PPORefiner)")

        cfg = (
            RefinePPOConfig.from_dict(config, **kwargs)
            if (RefinePPOConfig is not None and not isinstance(config, RefinePPOConfig))
            else (config if config is not None else (RefinePPOConfig() if RefinePPOConfig else None))
        )
        # beta = 1  ->  always start from the critical state
        for attr, value in (
            ("p", 1.0),
            ("beta", 1.0),
            ("use_mixed_init", True),
            ("use_rnd", bool(use_rnd)),
            ("copy_policy", True),
        ):
            try:
                setattr(cfg, attr, value)
            except Exception:
                pass

        self.mask_net = mask_net
        self.explainer = explainer or (
            make_statemask_explainer(
                env=env, policy=policy, mask_net=mask_net, env_id=env_id, seed=seed
            )
            if env is not None
            else None
        )
        self.refiner = PPORefiner(  # type: ignore[misc]
            env=env,
            policy=policy,
            mask_net=mask_net,
            config=cfg,
            env_id=env_id,
            device=device,
            logger=logger,
            sampler=sampler,
            seed=seed,
            **kwargs,
        )
        try:
            self.refiner.set_p(1.0)
        except Exception:
            pass
        self.env_id = env_id

    # --------------------------------------------------------------- training
    def train(self, *args: Any, **kwargs: Any) -> Any:
        return self.refiner.train(*args, **kwargs)  # type: ignore[attr-defined]

    fit = train

    def evaluate(self, *args: Any, **kwargs: Any) -> Dict[str, float]:
        return self.refiner.evaluate(*args, **kwargs)  # type: ignore[attr-defined]

    @property
    def policy(self) -> Any:
        return getattr(self.refiner, "policy", None)

    def summary(self) -> Dict[str, Any]:
        out: Dict[str, Any] = {"name": self.name, "env_id": self.env_id, "p": 1.0}
        try:
            out.update(self.refiner.summary())  # type: ignore[attr-defined]
        except Exception:
            pass
        return out

    def save(self, path: str, extra: Optional[Dict[str, Any]] = None) -> str:
        return self.refiner.save(path, extra=extra)  # type: ignore[attr-defined]


def refine_from_critical_state(
    env: Any,
    policy: Any = None,
    mask_net: Any = None,
    total_timesteps: Optional[int] = None,
    total_iterations: Optional[int] = None,
    env_id: str = "default",
    config: Optional[Any] = None,
    logger: Any = None,
    save_path: Optional[str] = None,
    seed: Optional[int] = None,
    device: str = "cpu",
    progress: bool = False,
    evaluate: bool = False,
    eval_episodes: int = 10,
    use_rnd: bool = False,
    **kwargs: Any,
) -> Tuple[Any, "StateMaskRefiner"]:
    """StateMask-R refining: reset to the critical state and keep training PPO."""
    refiner = StateMaskRefiner(
        env=env,
        policy=policy,
        mask_net=mask_net,
        config=config,
        env_id=env_id,
        device=device,
        logger=logger,
        use_rnd=use_rnd,
        seed=seed,
        **kwargs,
    )
    train_kwargs: Dict[str, Any] = {"progress": progress}
    if total_timesteps is not None:
        train_kwargs["total_timesteps"] = int(total_timesteps)
    if total_iterations is not None:
        train_kwargs["total_iterations"] = int(total_iterations)
    refiner.train(**train_kwargs)

    if evaluate:
        try:
            refiner.evaluate(n_episodes=eval_episodes)
        except Exception as exc:  # pragma: no cover
            (logger or globals()["logger"]).warning("StateMask-R evaluation failed: %s", exc)

    if save_path:
        try:
            refiner.save(save_path)
        except Exception as exc:  # pragma: no cover
            (logger or globals()["logger"]).warning(
                "could not save StateMask-R checkpoint: %s", exc
            )

    return refiner.policy, refiner


# --------------------------------------------------------------------------- #
# Umbrella baseline (explanation + refining), mirroring the RICE pipeline
# --------------------------------------------------------------------------- #


class StateMaskR:
    """End-to-end StateMask-R baseline: StateMask explanation + reset-to-critical refining.

    Usage::

        baseline = StateMaskR(env_id="hopper")
        mask_net, trainer = baseline.train_explanation(env, target_policy)   # Stage 1
        policy, refiner = baseline.refine(env, target_policy, mask_net)      # Stage 2
    """

    name = "StateMask-R"

    def __init__(
        self,
        env_id: str = "default",
        config: Optional[Any] = None,
        seed: Optional[int] = None,
        device: str = "cpu",
        logger: Any = None,
        mask_samples: Optional[int] = None,
        alpha: float = 0.01,
        use_rnd: bool = False,
        **kwargs: Any,
    ) -> None:
        self.env_id = env_id
        self.config = config
        self.seed = seed
        self.device = device
        self.logger = logger
        self.alpha = float(alpha)
        self.use_rnd = bool(use_rnd)
        self.mask_samples = int(mask_samples if mask_samples is not None else samples_for(env_id))

        self.mask_net: Any = None
        self.trainer: Optional[StateMaskTrainer] = None
        self.explainer: Optional[StateMaskExplainer] = None
        self.refiner: Optional[StateMaskRefiner] = None
        self.refined_policy: Any = None
        self.history: List[Dict[str, Any]] = []

    # --------------------------------------------------------------- stage 1
    def train_explanation(
        self,
        env: Any,
        target_policy: Any,
        total_timesteps: Optional[int] = None,
        progress: bool = False,
        save_path: Optional[str] = None,
        **kwargs: Any,
    ) -> Tuple[Any, "StateMaskTrainer"]:
        self.mask_net, self.trainer = train_statemask_network(
            env=env,
            target_policy=target_policy,
            total_timesteps=total_timesteps or self.mask_samples,
            alpha=self.alpha,
            env_id=self.env_id,
            config=self.config,
            logger=self.logger,
            save_path=save_path,
            seed=self.seed,
            device=self.device,
            progress=progress,
            **kwargs,
        )
        # frozen pi identifies critical states for the explainer
        self.explainer = make_statemask_explainer(
            env=env,
            policy=getattr(self.trainer, "target_policy", target_policy),
            mask_net=self.mask_net,
            env_id=self.env_id,
            seed=self.seed,
            trainer=self.trainer,
        )
        self.history.append(self.trainer.dual_report())
        return self.mask_net, self.trainer

    # --------------------------------------------------------------- stage 2
    def refine(
        self,
        env: Any,
        target_policy: Any,
        mask_net: Any = None,
        total_timesteps: Optional[int] = None,
        total_iterations: Optional[int] = None,
        progress: bool = False,
        evaluate: bool = False,
        eval_episodes: int = 10,
        save_path: Optional[str] = None,
        **kwargs: Any,
    ) -> Tuple[Any, "StateMaskRefiner"]:
        self.refined_policy, self.refiner = refine_from_critical_state(
            env=env,
            policy=target_policy,
            mask_net=mask_net if mask_net is not None else self.mask_net,
            total_timesteps=total_timesteps,
            total_iterations=total_iterations,
            env_id=self.env_id,
            config=self.config,
            logger=self.logger,
            save_path=save_path,
            seed=self.seed,
            device=self.device,
            progress=progress,
            evaluate=evaluate,
            eval_episodes=eval_episodes,
            use_rnd=self.use_rnd,
            **kwargs,
        )
        return self.refined_policy, self.refiner

    # ----------------------------------------------------------- end to end
    def run(
        self,
        env: Any,
        target_policy: Any,
        mask_samples: Optional[int] = None,
        refine_timesteps: Optional[int] = None,
        refine_iterations: Optional[int] = None,
        progress: bool = False,
        evaluate: bool = True,
        eval_episodes: int = 10,
        save_dir: Optional[str] = None,
        **kwargs: Any,
    ) -> Dict[str, Any]:
        """Run both stages and report the before/after reward (Table 1 style)."""
        self.train_explanation(
            env=env,
            target_policy=target_policy,
            total_timesteps=mask_samples or self.mask_samples,
            progress=progress,
            save_path=(f"{ensure_dir(save_dir)}/statemask_mask.pt" if save_dir else None),
            **kwargs,
        )
        self.refine(
            env=env,
            target_policy=target_policy,
            total_timesteps=refine_timesteps,
            total_iterations=refine_iterations,
            progress=progress,
            evaluate=evaluate,
            eval_episodes=eval_episodes,
            save_path=(f"{ensure_dir(save_dir)}/statemask_r.pt" if save_dir else None),
        )

        result: Dict[str, Any] = {
            "method": self.name,
            "env_id": self.env_id,
            "mask_samples": self.mask_samples,
            "alpha_final": float(getattr(self.trainer, "alpha", float("nan"))),
        }
        try:
            result.update(self.trainer.time_report())  # type: ignore[union-attr]
        except Exception:
            pass
        try:
            result["refine"] = self.refiner.summary()  # type: ignore[union-attr]
        except Exception:
            pass
        return result

    def summary(self) -> Dict[str, Any]:
        return {
            "name": self.name,
            "env_id": self.env_id,
            "mask_samples": self.mask_samples,
            "alpha": self.alpha,
            "use_rnd": self.use_rnd,
            "history": self.history,
        }


