def samples_for(env_id: Optional[str], default: int = DEFAULT_SAMPLES) -> int:
    """Table-4 sample budget for the mask-network training of a given env."""
    key = str(env_id or "").split("-")[0].split("/")[-1].replace(".yaml", "").strip().lower()
    for name, value in DEFAULT_MASK_SAMPLES.items():
        if name in key:
            return int(value)
    return int(default)


def _mean(values: Sequence[float]) -> float:
    vals = [float(v) for v in values if v is not None and np.isfinite(v)]
    return float(np.mean(vals)) if vals else float("nan")


def _unpack_step(result: Any) -> Tuple[Any, float, bool, bool, Dict[str, Any]]:
    """Normalise 4-tuple / 5-tuple gym step outputs."""
    if unpack_step is not None:
        try:
            return unpack_step(result)  # type: ignore[misc]
        except Exception:
            pass
    if not isinstance(result, (tuple, list)):
        return result, 0.0, False, False, {}
    if len(result) == 5:
        obs, reward, terminated, truncated, info = result
        return obs, float(reward), bool(terminated), bool(truncated), dict(info or {})
    if len(result) == 4:
        obs, reward, done, info = result
        return obs, float(reward), bool(done), False, dict(info or {})
    raise ValueError(f"Unsupported step tuple of length {len(result)}")


def _unpack_reset(result: Any) -> Tuple[Any, Dict[str, Any]]:
    if isinstance(result, (tuple, list)) and len(result) == 2:
        obs, info = result
        return obs, dict(info or {})
    return result, {}


def _flat(obs: Any) -> np.ndarray:
    try:
        from ..explanation.mask_network import flatten_observation  # type: ignore

        return flatten_observation(obs)
    except Exception:
        arr = np.asarray(obs, dtype=np.float32)
        return arr.reshape(-1) if arr.ndim > 1 else arr


