# --------------------------------------------------------------------------------------
# JSRL trainer
# --------------------------------------------------------------------------------------
class JSRLTrainer:
    """Curriculum-based refiner: guided policy pi_g jump-starts pi_e.

    The guided policy is the frozen pre-trained RICE target policy; the
    exploration policy is initialised from it (``pi_e <- pi_g``) and trained
    with PPO while the guided horizon anneals to zero.
    """

    name = "JSRL"

    def __init__(
        self,
        env: Any,
        guided_policy: Any = None,
        policy: Any = None,
        config: Optional[Any] = None,
        env_id: str = "default",
        device: str = "cpu",
        logger: Any = None,
        observation_space: Any = None,
        action_space: Any = None,
        discrete: Optional[bool] = None,
        rng: Any = None,
        seed: Optional[int] = None,
        copy_policy: bool = True,
        verbose: bool = True,
        **kwargs: Any,
    ) -> None:
        self.env = env
        cfg = config if config is not None else kwargs.pop("cfg", None)
        self.config = JSRLConfig.from_dict(
            cfg, **{k: v for k, v in kwargs.items() if k in JSRLConfig.__dataclass_fields__}
        )
        if env_id and self.config.env_id in ("default", "", None):
            self.config.env_id = str(env_id)
        self.env_id = str(self.config.env_id or env_id or "default")
        self.device = str(device or self.config.device)
        self.logger = logger or _LOGGER
        self.verbose = bool(verbose)

        self.seed = seed if seed is not None else self.config.seed
        if _HAS_SEEDING and self.seed is not None:
            try:
                set_seed(int(self.seed))
            except Exception:
                pass
        self.rng = rng if rng is not None else get_rng(self.seed)

        # pi_g: frozen pre-trained policy that sets up the curriculum
        self.guided_policy = guided_policy if guided_policy is not None else policy
        if self.guided_policy is None:
            raise ValueError("JSRLTrainer requires the pre-trained guided policy (pi_g)")
        # pi_e: trainable exploration policy, initialised from pi_g
        self.policy = ensure_trainable_policy(
            policy=policy if policy is not None else self.guided_policy,
            env=env,
            env_id=self.env_id,
            device=self.device,
            copy_policy=copy_policy if copy_policy is not None else self.config.copy_policy,
        )

        self.observation_space = (
            observation_space if observation_space is not None else getattr(env, "observation_space", None)
        )
        self.action_space = action_space if action_space is not None else getattr(env, "action_space", None)
        self.obs_dim, self.action_dim, inferred_discrete = resolve_obs_act_dims(env, self.policy)
        self.discrete = bool(inferred_discrete if discrete is None else discrete)

        self.horizon = _resolve_horizon(env if env is not None else self.policy, DEFAULT_HORIZON)
        max_h = self.config.max_guided_horizon
        self.max_guided_horizon = int(max_h) if max_h is not None else int(self.horizon)
        self._current_horizon = float(self.max_guided_horizon)
        self.iteration = 0

        self.optimizer = None
        if _HAS_TORCH and isinstance(self.policy, torch.nn.Module):
            self.optimizer = torch.optim.Adam(
                [p for p in self.policy.parameters() if p.requires_grad], lr=float(self.config.lr)
            )

        # Running state
        self._obs: Any = None
        self._episode_steps = 0
        self._episode_guided_steps = 0
        self._episode_task_return = 0.0
        self._episode_horizon = int(self.max_guided_horizon)
        self.history: List[Dict[str, Any]] = []
        self.eval_history: List[Dict[str, Any]] = []
        self.stats: Dict[str, Any] = {
            "iterations": 0,
            "timesteps": 0,
            "episodes": 0,
            "guided_steps": 0,
            "trainable_steps": 0,
        }
        self._timers: Dict[str, float] = {}
        self._timer_starts: Dict[str, float] = {}

    # -- properties -------------------------------------------------------------------
    @property
    def policy_network(self) -> Any:
        return self.policy

    @property
    def exploration_policy(self) -> Any:
        return self.policy

    @property
    def guided_horizon(self) -> int:
        return int(round(self._current_horizon))

    @property
    def total_time(self) -> float:
        return float(self._timers.get("total", 0.0))

    @property
    def seconds_per_sample(self) -> float:
        n = max(1, int(self.stats.get("timesteps", 0)))
        return float(self._timers.get("total", 0.0)) / n

    @property
    def guided_fraction(self) -> float:
        total = int(self.stats.get("guided_steps", 0)) + int(self.stats.get("trainable_steps", 0))
        if not total:
            return 0.0
        return float(self.stats.get("guided_steps", 0)) / float(total)

    # -- timers -----------------------------------------------------------------------
    def timer_start(self, name: str = "total") -> float:
        self._timer_starts[name] = time.time()
        return self._timer_starts[name]

    def timer_end(self, name: str = "total", accumulate: bool = True) -> float:
        start = self._timer_starts.get(name)
        if start is None:
            return 0.0
        elapsed = time.time() - start
        self._timers[name] = self._timers.get(name, 0.0) + elapsed if accumulate else elapsed
        return elapsed

    def time_report(self) -> Dict[str, float]:
        return dict(self._timers)

    # -- curriculum -------------------------------------------------------------------
    def current_horizon(self, iteration: Optional[int] = None) -> int:
        """Guided horizon scheduled for ``iteration``."""
        it = self.iteration if iteration is None else int(iteration)
        return jsrl_guided_horizon(
            it,
            max(1, self.config.iterations),
            max_horizon=self.max_guided_horizon,
            min_horizon=self.config.min_guided_horizon,
            schedule=self.config.horizon_schedule,
            decay=self.config.horizon_decay,
            warmup_iterations=self.config.warmup_iterations,
        )

    def set_iteration(self, iteration: int) -> int:
        self.iteration = int(iteration)
        self._current_horizon = float(self.current_horizon(iteration))
        return self.guided_horizon

    def set_guided_policy(self, policy: Any) -> None:
        self.guided_policy = policy

    def _draw_episode_horizon(self) -> int:
        return sample_horizon(
            self._current_horizon,
            sampling=self.config.horizon_sampling,
            sigma_frac=self.config.horizon_sigma_frac,
            rng=self.rng,
            max_horizon=self.max_guided_horizon,
        )

    # -- rollout ----------------------------------------------------------------------
    def _reset_env(self, **reset_kwargs: Any) -> Tuple[Any, Dict[str, Any]]:
        kwargs = dict(reset_kwargs)
        if self.seed is not None and "seed" not in kwargs:
            kwargs["seed"] = int(self.seed)
        try:
            result = self.env.reset(**kwargs)
        except TypeError:
            result = self.env.reset()
        obs, info = unpack_reset(result)
        self._obs = obs
        self._episode_steps = 0
        self._episode_guided_steps = 0
        self._episode_task_return = 0.0
        self._episode_horizon = self._draw_episode_horizon()
        return obs, info

    def collect_rollout(
        self,
        n_steps: Optional[int] = None,
        reset: bool = False,
        reset_kwargs: Optional[Dict[str, Any]] = None,
        horizon: Optional[int] = None,
    ) -> JSRLRollout:
        """Collect ``n_steps`` transitions with the JSRL curriculum applied.

        For every episode the guided policy pi_g acts for the first ``d_i``
        steps (``d_i`` drawn from the scheduled horizon); pi_e then takes over.
        ``trainable`` records which steps belong to pi_e.
        """
        n_steps = int(n_steps or self.config.n_steps or DEFAULT_N_STEPS)
        if horizon is not None:
            self._current_horizon = float(horizon)

        if self._obs is None or reset:
            self._reset_env(**(reset_kwargs or {}))

        rollout = JSRLRollout(iteration=self.iteration, guided_horizon=self.guided_horizon)
        for step_i in range(n_steps):
            obs = self._obs
            if self._episode_steps >= self.horizon:  # pragma: no cover - env time limit
                obs, _ = self._reset_env(**(reset_kwargs or {}))

            guided = False
            if self.config.use_guiding:
                if self.config.guidance_mode == "probabilistic":
                    guided = bool(self.rng.rand() < (1.0 - self.config.guidance_prob))
                else:
                    guided = self._episode_steps < int(self._episode_horizon)

            if guided:
                raw_action = policy_action(self.guided_policy, obs, deterministic=False)
                log_prob, value = 0.0, 0.0
                # Value of the task objective at guided states (critic bootstrap)
                if _HAS_TORCH:
                    try:
                        _, value_t = policy_distribution_and_values(
                            self.policy, np.asarray(_flat(obs), dtype=np.float32)
                        )
                        if value_t is not None:
                            value = float(value_t.reshape(-1)[0].detach().cpu().item())
                    except Exception:
                        value = 0.0
            else:
                raw_action, log_prob, value = _sample_action_and_logprob(self.policy, obs)

            action = prepare_action_for_env(raw_action, self.action_space, self.discrete)
            next_obs, reward, terminated, truncated, info = unpack_step(self.env.step(action))

            task_reward = float(reward)
            if self.config.guided_reward_scale != 1.0 and guided:
                task_reward *= float(self.config.guided_reward_scale)

            rollout.observations.append(obs)
            rollout.next_observations.append(next_obs)
            rollout.actions.append(raw_action)
            rollout.rewards.append(task_reward)
            rollout.task_rewards.append(float(reward))
            rollout.log_probs.append(float(log_prob))
            rollout.values.append(float(value))
            done = bool(terminated or truncated)
            rollout.dones.append(float(terminated))
            rollout.truncated.append(float(truncated))
            rollout.trainable.append(bool(not guided))
            rollout.guided_steps.append(int(self._episode_guided_steps))
            rollout.horizons.append(int(self._episode_horizon))

            key = "guided_steps" if guided else "trainable_steps"
            self.stats["timesteps"] = int(self.stats.get("timesteps", 0)) + 1
            self.stats[key] = int(self.stats.get(key, 0)) + 1
            self._episode_steps += 1
            self._episode_guided_steps += int(guided)
            self._episode_task_return += float(reward)

            if done:
                rollout.episode_task_returns.append(float(self._episode_task_return))
                rollout.episode_guided_fraction.append(
                    float(self._episode_guided_steps) / max(1, self._episode_steps)
                )
                self.stats["episodes"] = int(self.stats.get("episodes", 0)) + 1
                self._obs = None
                if step_i == n_steps - 1:
                    break
                self._reset_env(**(reset_kwargs or {}))
            else:
                self._obs = next_obs

        # Bootstrap value for the (possibly time-limit truncated) final state
        last_value = 0.0
        if self._obs is not None:
            try:
                _, value_t = policy_distribution_and_values(
                    self.policy, np.asarray(_flat(self._obs), dtype=np.float32)
                )
                if value_t is not None:
                    last_value = float(value_t.reshape(-1)[0].detach().cpu().item())
            except Exception:
                last_value = 0.0

        rollout.advantages, rollout.returns = compute_gae(
            np.asarray(rollout.rewards, dtype=np.float64),
            np.asarray(rollout.values, dtype=np.float64),
            np.asarray(rollout.dones, dtype=np.float64),
            last_value=last_value,
            gamma=float(self.config.gamma),
            gae_lambda=float(self.config.gae_lambda),
        )
        return rollout

    # -- optimisation -----------------------------------------------------------------
    def update(self, rollout: Optional[JSRLRollout] = None, n_steps: Optional[int] = None) -> Dict[str, float]:
        """One PPO update on the exploration policy's transitions."""
        if not _HAS_TORCH:
            raise RuntimeError("JSRLTrainer.update requires PyTorch")
        if rollout is None:
            rollout = self.collect_rollout(n_steps=n_steps)
        if len(rollout) == 0:
            return {"policy_loss": 0.0, "value_loss": 0.0, "entropy": 0.0, "approx_kl": 0.0}

        obs = torch.as_tensor(
            np.asarray([_flat(o) for o in rollout.observations], dtype=np.float32), device=self.device
        )
        actions = np.asarray([np.asarray(a, dtype=np.float32).reshape(-1) for a in rollout.actions], dtype=np.float32)
        actions_t = torch.as_tensor(actions, device=self.device)
        if self.discrete:
            actions_t = actions_t.reshape(-1).long()
        old_log_probs = torch.as_tensor(np.asarray(rollout.log_probs, dtype=np.float32), device=self.device)
        advantages = torch.as_tensor(np.asarray(rollout.advantages, dtype=np.float32), device=self.device)
        returns = torch.as_tensor(np.asarray(rollout.returns, dtype=np.float32), device=self.device)
        weights = torch.as_tensor(
            np.asarray(rollout.trainable, dtype=np.float32)
            if self.config.exclude_guided_transitions
            else np.ones(len(rollout), dtype=np.float32),
            device=self.device,
        )
        weight_sum = float(weights.sum().item())
        if weight_sum <= 0:  # no pi_e transitions collected -> nothing to learn
            return {"policy_loss": 0.0, "value_loss": 0.0, "entropy": 0.0, "approx_kl": 0.0, "n_trainable": 0.0}

        if self.config.normalize_advantage and weight_sum > 1:
            masked = advantages[weights > 0]
            advantages = (advantages - masked.mean()) / masked.std(unbiased=False).clamp_min(1e-8)

        batch_size = int(min(self.config.batch_size, max(1, int(weight_sum))))
        indices = np.arange(len(rollout))
        metrics_accum: Dict[str, List[float]] = {
            "policy_loss": [],
            "value_loss": [],
            "entropy": [],
            "approx_kl": [],
        }

        for _epoch in range(int(self.config.n_epochs)):
            self.rng.shuffle(indices)
            for start in range(0, len(rollout), batch_size):
                batch_idx = indices[start:start + batch_size]
                idx_t = torch.as_tensor(batch_idx, dtype=torch.long, device=self.device)
                b_obs = obs[idx_t]
                b_actions = actions_t[idx_t]
                b_old_log_probs = old_log_probs[idx_t]
                b_advantages = advantages[idx_t]
                b_returns = returns[idx_t]
                b_weights = weights[idx_t]
                b_wsum = float(b_weights.sum().item())
                if b_wsum <= 0:
                    continue

                dist, values = policy_distribution_and_values(self.policy, b_obs)
                if dist is None or values is None:
                    raise RuntimeError("JSRL requires a policy exposing get_distribution/predict_values")
                values = values.reshape(-1)

                if self.discrete:
                    log_probs = dist.log_prob(b_actions.reshape(-1))
                else:
                    log_probs = dist.log_prob(b_actions)
                    if log_probs.dim() > 1:
                        log_probs = log_probs.sum(dim=-1)
                entropy = dist.entropy()
                if entropy.dim() > 1:
                    entropy = entropy.sum(dim=-1)
                entropy = entropy.mean()

                ratio = torch.exp(log_probs - b_old_log_probs)
                clip = float(self.config.clip_range)
                unclipped = ratio * b_advantages
                clipped = torch.clamp(ratio, 1.0 - clip, 1.0 + clip) * b_advantages
                policy_loss = -(torch.min(unclipped, clipped) * b_weights).sum() / max(b_wsum, 1e-8)
                value_loss = ((values - b_returns) ** 2 * b_weights).sum() / max(b_wsum, 1e-8)
                loss = policy_loss + float(self.config.vf_coef) * value_loss - float(self.config.ent_coef) * entropy

                if self.optimizer is not None:
                    self.optimizer.zero_grad()
                    loss.backward()
                    torch.nn.utils.clip_grad_norm_(
                        [p for p in self.policy.parameters() if p.requires_grad],
                        float(self.config.max_grad_norm),
                    )
                    self.optimizer.step()

                with torch.no_grad():
                    approx_kl = ((ratio - 1.0) - (log_probs - b_old_log_probs)).mean()
                metrics_accum["policy_loss"].append(float(policy_loss.detach().cpu().item()))
                metrics_accum["value_loss"].append(float(value_loss.detach().cpu().item()))
                metrics_accum["entropy"].append(float(entropy.detach().cpu().item()))
                metrics_accum["approx_kl"].append(float(approx_kl.detach().cpu().item()))

        out = {key: float(np.mean(vals)) if vals else 0.0 for key, vals in metrics_accum.items()}
        out["n_trainable"] = float(weight_sum)
        out["guided_fraction"] = float(rollout.guided_fraction)
        out["guided_horizon"] = float(rollout.guided_horizon)
        out["mean_reward"] = float(np.mean(rollout.task_rewards)) if rollout.task_rewards else 0.0
        if rollout.episode_task_returns:
            out["episode_return"] = float(np.mean(rollout.episode_task_returns))
        return out

    def train(
        self,
        total_timesteps: Optional[int] = None,
        total_iterations: Optional[int] = None,
        logger: Any = None,
        progress: bool = False,
        callback: Optional[Callable[[int, Dict[str, Any]], None]] = None,
    ) -> List[Dict[str, Any]]:
        """Run the JSRL curriculum + PPO for the requested budget."""
        logger = logger or self.logger
        n_steps = int(self.config.n_steps)
        if total_iterations is not None and total_iterations > 0:
            n_iterations = int(total_iterations)
        elif total_timesteps is not None and total_timesteps > 0:
            n_iterations = max(1, int(total_timesteps) // max(1, n_steps))
        else:
            n_iterations = max(1, int(self.config.iterations))
        # Keep curriculum annealing consistent with the executed budget.
        self.config.total_iterations = n_iterations

        self.timer_start("total")
        for iteration in range(n_iterations):
            self.set_iteration(iteration)
            rollout = self.collect_rollout(n_steps=n_steps)
            metrics = self.update(rollout)
            metrics["iteration"] = iteration
            metrics["timesteps"] = int(self.stats.get("timesteps", 0))
            metrics["scheduled_horizon"] = int(self.guided_horizon)
            metrics["guided_fraction_total"] = self.guided_fraction
            self.stats["iterations"] = iteration + 1
            self.history.append(metrics)
            if progress and (iteration % max(1, int(self.config.log_interval)) == 0):
                logger.info(
                    f"[JSRL] it={iteration} steps={metrics['timesteps']} "
                    f"horizon={metrics['scheduled_horizon']} guided_frac={metrics['guided_fraction']:.2f} "
                    f"reward={metrics.get('mean_reward', 0.0):.2f} pi_loss={metrics['policy_loss']:.4f}"
                )
            if callback is not None:
                callback(iteration, metrics)
        self.timer_end("total")
        return self.history

    fit = train

    # -- evaluation -------------------------------------------------------------------
    def evaluate(
        self,
        n_episodes: int = 10,
        deterministic: bool = True,
        policy: Any = None,
        max_steps: Optional[int] = None,
        reset_kwargs: Optional[Dict[str, Any]] = None,
        guided: bool = False,
    ) -> Dict[str, Any]:
        """Episode returns from the default initial distribution rho.

        ``guided=True`` evaluates the frozen pre-trained policy instead of the
        refined one (i.e. the "No-Refine" reference of Table 1).
        """
        policy = policy if policy is not None else self.policy
        max_steps = int(max_steps or self.horizon)
        returns: List[float] = []
        lengths: List[int] = []
        for episode in range(int(n_episodes)):
            kwargs = dict(reset_kwargs or {})
            if self.seed is not None and "seed" not in kwargs:
                kwargs["seed"] = int(self.seed) + episode
            try:
                result = self.env.reset(**kwargs)
            except TypeError:
                result = self.env.reset()
            obs, _ = unpack_reset(result)
            done = False
            ep_return = 0.0
            steps = 0
            while not done and steps < max_steps:
                if guided and self.guided_policy is not None:
                    action = policy_action(self.guided_policy, obs, deterministic=deterministic)
                else:
                    action = policy_action(policy, obs, deterministic=deterministic)
                action = prepare_action_for_env(action, self.action_space, self.discrete)
                obs, reward, terminated, truncated, _ = unpack_step(self.env.step(action))
                ep_return += float(reward)
                steps += 1
                done = bool(terminated or truncated)
            returns.append(ep_return)
            lengths.append(steps)
        arr = np.asarray(returns, dtype=np.float64)
        result = {
            "mean_reward": float(arr.mean()) if arr.size else float("nan"),
            "std_reward": float(arr.std()) if arr.size else float("nan"),
            "mean_episode_length": float(np.mean(lengths)) if lengths else 0.0,
            "n_episodes": int(arr.size),
            "rewards": returns,
        }
        self.eval_history.append(result)
        return result

    # -- bookkeeping ------------------------------------------------------------------
    def summary(self) -> Dict[str, Any]:
        def _last(key: str) -> Optional[float]:
            for entry in reversed(self.history):
                if key in entry and np.isfinite(entry[key]):
                    return float(entry[key])
            return None

        return {
            "baseline": self.name,
            "env_id": self.env_id,
            "timesteps": int(self.stats.get("timesteps", 0)),
            "iterations": int(self.stats.get("iterations", 0)),
            "episodes": int(self.stats.get("episodes", 0)),
            "guided_fraction": self.guided_fraction,
            "final_horizon": int(self.guided_horizon),
            "max_horizon": int(self.max_guided_horizon),
            "horizon_schedule": self.config.horizon_schedule,
            "last_policy_loss": _last("policy_loss"),
            "last_mean_reward": _last("mean_reward"),
            "total_time": self.total_time,
            "eval": self.eval_history[-1] if self.eval_history else None,
        }

    def save(self, path: str, extra: Optional[Dict[str, Any]] = None) -> str:
        """Persist trainer state (policy weights included)."""
        if not _HAS_TORCH:
            raise RuntimeError("JSRLTrainer.save requires PyTorch")
        payload = {
            "algorithm": "JSRL",
            "env_id": self.env_id,
            "obs_dim": self.obs_dim,
            "action_dim": self.action_dim,
            "discrete": self.discrete,
            "config": self.config.to_dict(),
            "stats": self.stats,
            "summary": self.summary(),
            "policy_state_dict": self.policy.state_dict() if hasattr(self.policy, "state_dict") else None,
            "history": self.history,
        }
        if extra:
            payload["extra"] = extra
        parent = os.path.dirname(os.path.abspath(path))
        if parent:
            ensure_dir(parent)
        torch.save(payload, path)
        return path

    def save_policy(self, path: str, extra: Optional[Dict[str, Any]] = None) -> str:
        if _HAS_POLICIES and save_policy is not None:
            try:
                return save_policy(self.policy, path, env_id=self.env_id, kind="policy", extra=extra)  # type: ignore[misc]
            except Exception:
                pass
        return self.save(path, extra=extra)

    @classmethod
    def load(cls, path: str, env: Any = None, **kwargs: Any) -> "JSRLTrainer":
        if not _HAS_TORCH:
            raise RuntimeError("JSRLTrainer.load requires PyTorch")
        device = kwargs.pop("device", "cpu")
        payload = torch.load(path, map_location=device)
        config = JSRLConfig.from_dict(payload.get("config"))
        trained_policy = None
        if _HAS_POLICIES and build_policy is not None:
            trained_policy = build_policy(  # type: ignore[misc]
                env_id=payload.get("env_id", config.env_id),
                obs_dim=payload.get("obs_dim"),
                action_dim=payload.get("action_dim"),
                discrete=payload.get("discrete"),
                device=device,
            )
            if payload.get("policy_state_dict") is not None:
                trained_policy.load_state_dict(payload["policy_state_dict"], strict=False)
        trainer = cls(env=env, guided_policy=trained_policy, policy=trained_policy, config=config, device=device, **kwargs)
        trainer.history = payload.get("history", [])
        trainer.stats.update(payload.get("stats", {}))
        return trainer


