def train_jsrl(
    env: Any,
    guided_policy: Any = None,
    policy: Any = None,
    total_timesteps: Optional[int] = None,
    total_iterations: Optional[int] = None,
    env_id: str = "default",
    config: Optional[Any] = None,
    logger: Any = None,
    save_path: Optional[str] = None,
    seed: Optional[int] = None,
    device: str = "cpu",
    progress: bool = False,
    evaluate: bool = False,
    eval_episodes: int = 10,
    refiner_cls: Any = JSRLRefiner,
    **kwargs: Any,
) -> Tuple[Any, JSRLTrainer]:
    """Train the JSRL refining baseline end-to-end.

    Returns ``(policy, trainer)`` where ``policy`` is the refined exploration
    policy pi_e (initialised from the guided policy pi_g).
    """
    logger = logger or _LOGGER
    trainer = refiner_cls(
        env=env,
        guided_policy=guided_policy if guided_policy is not None else policy,
        policy=policy,
        config=config,
        env_id=env_id,
        device=device,
        logger=logger,
        seed=seed,
        **kwargs,
    )
    trainer.train(total_timesteps=total_timesteps, total_iterations=total_iterations, progress=progress)
    if evaluate:
        trainer.evaluate(n_episodes=eval_episodes, deterministic=trainer.config.deterministic_eval)
    if save_path:
        try:
            trainer.save_policy(save_path, extra={"baseline": "JSRL"})
        except Exception as exc:  # pragma: no cover
            logger.warning(f"[JSRL] could not save policy to {save_path}: {exc}")
    return trainer.policy, trainer


def make_jsrl(
    env: Any = None,
    guided_policy: Any = None,
    policy: Any = None,
    env_id: str = "default",
    config: Optional[Any] = None,
    seed: Optional[int] = None,
    device: str = "cpu",
    logger: Any = None,
    **kwargs: Any,
) -> JSRLRefiner:
    """Factory used by the baseline registry / CLI dispatcher."""
    if isinstance(env, str) and env_id in ("default", "", None):
        env_id = env
        env = None
    if isinstance(config, str) and env_id in ("default", "", None):
        env_id = config
        config = None
    return JSRLRefiner(
        env=env,
        guided_policy=guided_policy if guided_policy is not None else policy,
        policy=policy,
        config=config,
        env_id=env_id,
        device=device,
        logger=logger,
        seed=seed,
        **kwargs,
    )


build_jsrl = make_jsrl


def jsrl(
    env: Any,
    guided_policy: Any = None,
    policy: Any = None,
    total_timesteps: Optional[int] = None,
    **kwargs: Any,
) -> Dict[str, Any]:
    """Plain-dict JSRL pipeline helper (mirrors ``sil``/``gail``)."""
    evaluate = bool(kwargs.pop("evaluate", True))
    eval_episodes = int(kwargs.pop("eval_episodes", 10))
    progress = bool(kwargs.pop("progress", False))
    refiner = make_jsrl(env=env, guided_policy=guided_policy, policy=policy, **kwargs)
    return refiner.run(
        total_timesteps=total_timesteps,
        evaluate=evaluate,
        eval_episodes=eval_episodes,
        progress=progress,
    )


jsrl_baseline = jsrl
run_jsrl = jsrl


def jsrl_for(env_id: str, **kwargs: Any) -> JSRLConfig:
    """Config bundle pre-set for an application id."""
    config = JSRLConfig.from_dict(kwargs.pop("config", None), **kwargs)
    config.env_id = str(env_id)
    return config


def describe_jsrl(trainer: Any = None) -> str:
    """One-line human-readable summary for logging / tables."""
    if trainer is None:
        return "JSRL (guided policy pi_g + exploration policy pi_e, decaying guided-horizon curriculum)"
    try:
        summary = trainer.summary()
    except Exception:
        return "JSRL refining baseline"
    return (
        f"JSRL[{summary.get('env_id')}] guided_frac={summary.get('guided_fraction', 0.0):.2f} "
        f"final_horizon={summary.get('final_horizon')}/{summary.get('max_horizon')} "
        f"schedule={summary.get('horizon_schedule')} steps={summary.get('timesteps')}"
    )
