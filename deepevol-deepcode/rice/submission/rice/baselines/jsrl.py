"""Jump-Start Reinforcement Learning (JSRL) refining baseline for RICE.

Paper reference
---------------
Cheng et al., *RICE: A Refining Scheme for Reinforcement Learning with
Explanation*, ICML 2024 (PMLR 235).

Section 4.1 (Baseline Refining Methods)::

    The third baseline is Jump-Start Reinforcement Learning (referred to as
    "JSRL") (Uchendu et al., 2023). JSRL introduces a guided policy pi_g to
    set up a curriculum to train an exploration policy pi_e. Through
    initializing pi_e = pi_g, we can transform JSRL to be a refining method
    that can further improve the performance of the guided policy.

Section 4.2 (Experiment II): all refining methods use the same explanation
generated by RICE's explanation method *if needed*; JSRL does not need one.
Appendix C.1: "Regarding Jump-Start Reinforcement Learning, we use the
implementation from https://github.com/steventango/jumpstart-rl."

Implementation summary
----------------------
The pre-trained (bottlenecked) RICE target policy plays both roles:

* ``guided_policy = pi_g`` -- the frozen pre-trained policy.  It sets up the
  curriculum by acting for the first ``d_i`` steps of every episode and
  handing the resulting state over to
* ``policy = pi_e`` -- the *trainable* exploration policy, initialised from
  ``pi_g`` (``pi_e <- pi_g``) and optimised with PPO on its own transitions.

The guided horizon ``d_i`` anneals from the episode horizon ``T`` (or a
configured start) down to zero over training iterations, so ``pi_e``
progressively takes over the whole episode.  Because RICE's explanation
(mask network / critical states) is *not* part of JSRL, this baseline needs
neither a reset to a critical state nor an RND bonus: only the curriculum and
plain PPO.

This is the "curriculum" counterpart of RICE's mixed initial state
distribution, letting Experiment II compare refining mechanisms (PPO
fine-tuning, StateMask-R, JSRL) against RICE on top of the same frozen
pre-trained policy.

Defensive imports keep the module importable without torch / SB3 / the rest of
the ``rice`` package.
"""

