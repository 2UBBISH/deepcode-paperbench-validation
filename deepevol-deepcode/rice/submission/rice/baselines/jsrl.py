def _flat(observation: Any) -> np.ndarray:
    """Flatten dict/tuple/array observations to a 1-D float64 vector."""
    if observation is None:
        return np.zeros(1, dtype=np.float64)
    if isinstance(observation, dict):
        keys = sorted(observation.keys())
        parts = [_flat(observation[k]) for k in keys]
        return np.concatenate(parts) if parts else np.zeros(1, dtype=np.float64)
    if isinstance(observation, (list, tuple)):
        parts = [_flat(o) for o in observation]
        return np.concatenate(parts) if parts else np.zeros(1, dtype=np.float64)
    arr = np.asarray(observation, dtype=np.float64)
    return arr.reshape(-1)


def unpack_reset(result: Any) -> Tuple[Any, Dict[str, Any]]:
    """Normalise the many ``env.reset`` return conventions to ``(obs, info)``."""
    if isinstance(result, tuple):
        if len(result) >= 2:
            obs, info = result[0], result[1]
            return obs, info if isinstance(info, dict) else {"info": info}
        if len(result) == 1:
            return result[0], {}
    return result, {}


def unpack_step(result: Any) -> Tuple[Any, float, bool, bool, Dict[str, Any]]:
    """Normalise ``env.step`` to ``(obs, reward, terminated, truncated, info)``."""
    if not isinstance(result, tuple):
        return result, 0.0, True, False, {}
    if len(result) == 5:
        obs, reward, terminated, truncated, info = result
        return obs, float(reward), bool(terminated), bool(truncated), info or {}
    if len(result) == 4:
        obs, reward, done, info = result
        return obs, float(reward), bool(done), False, info or {}
    if len(result) == 3:
        obs, reward, done = result
        return obs, float(reward), bool(done), False, {}
    if len(result) == 2:
        return result[0], float(result[1]), False, False, {}
    return result[0], 0.0, False, False, {}


def _policy_observation(observation: Any):
    """Convert an observation to the representation the policy expects."""
    if _HAS_TORCH:
        if isinstance(observation, torch.Tensor):
            return observation
        flat = _flat(observation)
        return torch.as_tensor(flat, dtype=torch.float32).unsqueeze(0)
    return np.asarray(_flat(observation), dtype=np.float32)


def policy_action(policy: Any, observation: Any, deterministic: bool = False) -> np.ndarray:
    """Interface-agnostic ``policy(observation) -> action`` (SB3 or native)."""
    if policy is None:
        raise ValueError("policy_action requires a policy")
    # Preferred: torch distribution path (works for native ActorCritic and SB3)
    if _HAS_TORCH and hasattr(policy, "get_distribution"):
        try:
            with torch.no_grad():
                obs_t = _policy_observation(observation)
                if obs_t.dim() == 1:
                    obs_t = obs_t.unsqueeze(0)
                dist = policy.get_distribution(obs_t)
                if deterministic:
                    action = dist.mean if hasattr(dist, "mean") else dist.probs.argmax(dim=-1)
                else:
                    action = dist.sample()
            return action.detach().cpu().numpy().reshape(-1)
        except Exception:
            pass
    # SB3 ``predict``
    if hasattr(policy, "predict"):
        try:
            action, _ = policy.predict(observation, deterministic=deterministic)
            return np.asarray(action, dtype=np.float32).reshape(-1)
        except Exception:
            pass
    # Native ``act``
    if hasattr(policy, "act"):
        try:
            return np.asarray(policy.act(observation, deterministic=deterministic), dtype=np.float32).reshape(-1)
        except Exception:
            pass
    if callable(policy):
        try:
            return np.asarray(policy(observation), dtype=np.float32).reshape(-1)
        except Exception:
            pass
    raise TypeError("Unsupported policy interface for action selection")


def prepare_action_for_env(action: Any, action_space: Any = None, discrete: Optional[bool] = None) -> Any:
    """Clip / cast an action so ``env.step`` accepts it."""
    if isinstance(discrete, bool) and discrete:
        if isinstance(action, np.ndarray):
            if action.size == 1 or action.ndim == 0:
                return int(action.reshape(-1)[0])
            return int(np.argmax(action))
        return int(action)

    arr = np.asarray(action, dtype=np.float32).reshape(-1)
    if action_space is not None:
        low = getattr(action_space, "low", None)
        high = getattr(action_space, "high", None)
        if low is not None and high is not None:
            try:
                low = np.asarray(low, dtype=np.float32).reshape(-1)
                high = np.asarray(high, dtype=np.float32).reshape(-1)
                if low.shape == arr.shape:
                    arr = np.clip(arr, low, high)
            except Exception:
                pass
        shape = tuple(getattr(action_space, "shape", ()) or ())
        if shape and arr.shape != shape and arr.size == int(np.prod(shape)):
            arr = arr.reshape(shape)
    return arr


def resolve_obs_act_dims(env: Any, policy: Any = None) -> Tuple[int, int, bool]:
    """Return ``(obs_dim, action_dim, discrete)``."""
    obs_dim = action_dim = None
    discrete = False
    if policy is not None:
        obs_space = getattr(policy, "observation_space", None)
        act_space = getattr(policy, "action_space", None)
        if obs_space is not None:
            shape = getattr(obs_space, "shape", None)
            if shape:
                obs_dim = int(np.prod(shape))
        if act_space is not None:
            shape = getattr(act_space, "shape", None)
            if shape:
                action_dim = int(np.prod(shape))
            elif hasattr(act_space, "n"):
                action_dim = int(act_space.n)
                discrete = True
    if obs_dim is None and env is not None:
        space = getattr(env, "observation_space", None)
        shape = getattr(space, "shape", None)
        if shape:
            obs_dim = int(np.prod(shape))
    if action_dim is None and env is not None:
        space = getattr(env, "action_space", None)
        shape = getattr(space, "shape", None)
        if shape:
            action_dim = int(np.prod(shape))
        elif hasattr(space, "n"):
            action_dim = int(space.n)
            discrete = True
    return int(obs_dim or 1), int(action_dim or 1), bool(discrete)


def _resolve_horizon(env: Any, default: int = DEFAULT_HORIZON) -> int:
    """Resolve the episode horizon T from the (possibly wrapped) environment."""
    node = env
    for _ in range(12):
        if node is None:
            break
        value = getattr(node, "rice_max_episode_steps", None)
        if isinstance(value, (int, float)) and value > 0:
            return int(value)
        spec = getattr(node, "rice_env_spec", None)
        value = getattr(spec, "max_episode_steps", None)
        if isinstance(value, (int, float)) and value > 0:
            return int(value)
        value = getattr(node, "_max_episode_steps", None)
        if isinstance(value, (int, float)) and value > 0:
            return int(value)
        node = getattr(node, "env", None)
    return int(default)


def policy_distribution_and_values(policy: Any, observations: Any):
    """Return ``(dist, values_tensor)`` for a batch of observations."""
    if not _HAS_TORCH or policy is None:
        return None, None
    obs_t = observations if isinstance(observations, torch.Tensor) else torch.as_tensor(
        np.asarray(observations, dtype=np.float32)
    )
    if obs_t.dim() == 1:
        obs_t = obs_t.unsqueeze(0)
    dist = None
    values = None
    get_dist = getattr(policy, "get_distribution", None)
    if callable(get_dist):
        try:
            dist = get_dist(obs_t)
        except Exception:
            dist = None
    if dist is None and hasattr(policy, "_distribution"):  # pragma: no cover
        try:
            dist = policy._distribution(obs_t)
        except Exception:
            dist = None
    if hasattr(policy, "predict_values"):
        try:
            values = policy.predict_values(obs_t)
        except Exception:
            values = None
    if values is None and hasattr(policy, "value_net"):  # native ActorCritic fallback
        try:
            values = policy.value_net(policy.extract_features(obs_t))  # type: ignore[attr-defined]
        except Exception:
            values = None
    return dist, values


def ensure_trainable_policy(
    policy: Any = None,
    env: Any = None,
    env_id: str = "default",
    device: str = "cpu",
    copy_policy: bool = True,
    **kwargs: Any,
) -> Any:
    """Return a *trainable* policy initialised from ``policy`` (JSRL: pi_e <- pi_g)."""
    if policy is None:
        if not (_HAS_POLICIES and build_policy is not None):
            raise RuntimeError("No policy supplied and rice.models.policies is unavailable")
        obs_dim, action_dim, discrete = resolve_obs_act_dims(env)
        policy = build_policy(  # type: ignore[misc]
            env_id=env_id,
            obs_dim=obs_dim,
            action_dim=action_dim,
            discrete=discrete,
            device=device,
        )
    trainable = policy
    if copy_policy:
        try:
            trainable = copy.deepcopy(policy)
        except Exception:
            trainable = policy
    if _HAS_TORCH and isinstance(trainable, torch.nn.Module):
        for param in trainable.parameters():
            param.requires_grad_(True)
        try:
            trainable.train()
        except Exception:
            pass
        for attr in ("action_space", "observation_space"):
            if getattr(trainable, attr, None) is None and policy is not None:
                setattr(trainable, attr, getattr(policy, attr, None))
    return trainable


def _sample_action_and_logprob(policy: Any, observation: Any) -> Tuple[np.ndarray, float, float]:
    """Sample an action from the trainable policy -> ``(action, log_prob, value)``."""
    obs_t = _policy_observation(observation)
    if _HAS_TORCH and hasattr(policy, "get_distribution"):
        with torch.no_grad():
            dist = policy.get_distribution(obs_t)
            action = dist.sample()
            log_prob = dist.log_prob(action)
            if log_prob.dim() > 1:
                log_prob = log_prob.sum(dim=-1)
            value = None
            if hasattr(policy, "predict_values"):
                try:
                    value = policy.predict_values(obs_t)
                except Exception:
                    value = None
        action_np = action.detach().cpu().numpy().reshape(-1)
        return (
            action_np,
            float(log_prob.reshape(-1)[0].item()),
            float(value.reshape(-1)[0].item()) if value is not None else 0.0,
        )
    action_np = policy_action(policy, observation, deterministic=False)
    return action_np, 0.0, 0.0


