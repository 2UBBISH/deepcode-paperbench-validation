def horizon_schedule(
    iteration: int,
    total_iterations: int,
    max_horizon: int = DEFAULT_MAX_HORIZON,
    min_horizon: int = DEFAULT_MIN_HORIZON,
    schedule: str = "linear",
    decay: float = 0.5,
    warmup_iterations: int = 0,
    **kwargs: Any,
) -> float:
    """Return the guided horizon ``d_i`` for training iteration ``i``.

    JSRL (Uchendu et al., 2023) anneals the number of steps executed by the
    *guided* policy from the full horizon down to zero, so the exploration
    policy gradually takes over responsibility for the episode.

    Parameters
    ----------
    iteration, total_iterations : int
        Current (0-based) training iteration and the annealing budget.
    max_horizon, min_horizon : int
        Guided horizon at the start (typically the episode horizon ``T``) and
        at the end (0 = pure exploration policy).
    schedule : {"linear", "exponential", "cosine", "step", "constant"}
        Annealing shape.
    decay : float
        Per-iteration multiplicative factor for ``"exponential"`` / step count
        hint for ``"step"``.
    warmup_iterations : int
        Iterations spent at ``max_horizon`` before annealing starts.
    """
    max_h = float(max(0, max_horizon))
    min_h = float(max(0, min_horizon))
    if max_h < min_h:
        max_h, min_h = min_h, max_h

    warm = int(max(0, warmup_iterations))
    it = max(0, int(iteration) - warm)
    total = max(1, int(total_iterations) - warm)
    progress = min(1.0, it / float(total))

    name = str(schedule or "linear").strip().lower()
    if name in ("constant", "none", "fixed") or max_h == min_h:
        value = max_h
    elif name in ("linear", "anneal"):
        value = max_h - (max_h - min_h) * progress
    elif name in ("exponential", "exp", "geometric"):
        factor = float(decay) ** max(0.0, progress * total)
        value = min_h + (max_h - min_h) * float(np.clip(factor, 0.0, 1.0))
    elif name in ("cosine", "cos"):
        value = min_h + 0.5 * (max_h - min_h) * (1.0 + math.cos(math.pi * progress))
    elif name in ("step", "staircase"):
        n_levels = max(1, int(round(1.0 / max(1e-6, float(decay))))) if decay else 10
        level = min(n_levels, int(progress * n_levels) + 1)
        value = max_h - (max_h - min_h) * (level / float(n_levels))
    else:
        raise ValueError(f"Unknown horizon schedule '{schedule}'. Options: {HORIZON_SCHEDULES}")
    return float(np.clip(value, min_h, max_h))


def jsrl_guided_horizon(
    iteration: int,
    total_iterations: int,
    max_horizon: int = DEFAULT_MAX_HORIZON,
    min_horizon: int = DEFAULT_MIN_HORIZON,
    schedule: str = "linear",
    **kwargs: Any,
) -> int:
    """Integer wrapper around :func:`horizon_schedule`."""
    return int(round(horizon_schedule(iteration, total_iterations, max_horizon, min_horizon, schedule, **kwargs)))


def sample_horizon(
    horizon: float,
    sampling: str = "deterministic",
    sigma_frac: float = 0.1,
    rng: Any = None,
    max_horizon: Optional[int] = None,
) -> int:
    """Draw a (possibly stochastic) guided horizon at an episode start.

    JSRL samples horizon lengths from a truncated Gaussian to smooth the
    curriculum; ``sampling="deterministic"`` simply rounds the scheduled value.
    """
    name = str(sampling or "deterministic").strip().lower()
    h = float(max(0.0, horizon))
    if name not in ("gaussian", "truncated_gaussian", "normal"):
        return int(round(h))
    if rng is None:
        rng = np.random.RandomState()
    sigma = max(1e-6, float(sigma_frac) * max(1.0, h))
    drawn = float(rng.normal(loc=h, scale=sigma))
    upper = float(max_horizon) if max_horizon is not None else max(h, 1.0)
    return int(round(float(np.clip(drawn, 0.0, upper))))


def guidance_mask(
    episode_steps: Sequence[int],
    horizon: int,
    n_steps: Optional[int] = None,
    guidance_mode: str = "prefix",
    guidance_prob: float = 0.5,
    rng: Any = None,
) -> np.ndarray:
    """Boolean mask: ``True`` where the *trainable* policy pi_e was executed.

    ``guidance_mode="prefix"`` implements the JSRL curriculum literally (pi_g
    acts for the first ``horizon`` steps of each episode).  ``"probabilistic"``
    keeps the JSRL start-state-distribution intent while randomising when pi_e
    takes over.
    """
    steps = np.asarray(list(episode_steps), dtype=np.int64).reshape(-1)
    mode = str(guidance_mode or "prefix").strip().lower()
    if mode in ("probabilistic", "random", "prob"):
        if rng is None:
            rng = np.random.RandomState()
        probs = float(np.clip(float(guidance_prob), 0.0, 1.0))
        guided = rng.rand(steps.size) < (1.0 - probs)
        trainable = ~guided
    else:
        trainable = steps >= int(max(0, horizon))
    if n_steps is not None and trainable.size < int(n_steps):
        trainable = np.concatenate([trainable, np.ones(int(n_steps) - trainable.size, dtype=bool)])
    return trainable.astype(bool)


def compute_gae(
    rewards: Sequence[float],
    values: Sequence[float],
    dones: Sequence[Any],
    last_value: float = 0.0,
    gamma: float = DEFAULT_GAMMA,
    gae_lambda: float = DEFAULT_GAE_LAMBDA,
) -> Tuple[np.ndarray, np.ndarray]:
    """Generalized Advantage Estimation (identical convention to the refiner)."""
    rewards = np.asarray(rewards, dtype=np.float64).reshape(-1)
    values = np.asarray(values, dtype=np.float64).reshape(-1)
    dones = np.asarray(dones, dtype=np.float64).reshape(-1)
    n = rewards.shape[0]
    advantages = np.zeros(n, dtype=np.float64)
    last_gae = 0.0
    for t in reversed(range(n)):
        next_value = last_value if t == n - 1 else values[t + 1]
        non_terminal = 1.0 - float(dones[t])
        delta = rewards[t] + gamma * next_value * non_terminal - values[t]
        last_gae = delta + gamma * gae_lambda * non_terminal * last_gae
        advantages[t] = last_gae
    return advantages, advantages + values


