class JSRLRefiner(JSRLTrainer):
    """JSRL as a *refining* baseline, mirroring the RICE/StateMask-R surface."""

    name = "JSRL"

    def approximate_policy(self, total_timesteps: Optional[int] = None, progress: bool = False, **kwargs: Any):
        """Run the JSRL curriculum and return the resulting pi_e."""
        self.train(total_timesteps=total_timesteps, progress=progress, **kwargs)
        return self.policy

    @property
    def approximated_policy(self) -> Any:
        return self.policy

    def refine(
        self,
        env: Any = None,
        mask_net: Any = None,
        total_timesteps: Optional[int] = None,
        total_iterations: Optional[int] = None,
        config: Optional[Any] = None,
        logger: Any = None,
        seed: Optional[int] = None,
        **kwargs: Any,
    ) -> Tuple[Any, Any]:
        """Optional: feed the JSRL policy into RICE's Stage-2 refinement.

        Experiment II uses RICE's explanation for every refining method "if
        needed"; JSRL itself needs none, but this hook keeps the API uniform.
        """
        if not _HAS_REFINER or refine_policy is None:
            raise RuntimeError("rice.refining.ppo_refine is required to refine the JSRL policy")
        return refine_policy(  # type: ignore[misc]
            env if env is not None else self.env,
            policy=self.policy,
            mask_net=mask_net,
            total_timesteps=total_timesteps,
            total_iterations=total_iterations,
            env_id=self.env_id,
            config=config,
            logger=logger or self.logger,
            seed=self.seed if seed is None else seed,
            device=self.device,
            **kwargs,
        )

    def run(
        self,
        env: Any = None,
        guided_policy: Any = None,
        total_timesteps: Optional[int] = None,
        total_iterations: Optional[int] = None,
        mask_net: Any = None,
        refine: bool = False,
        refine_timesteps: Optional[int] = None,
        refine_iterations: Optional[int] = None,
        refine_config: Optional[Any] = None,
        evaluate: bool = True,
        eval_episodes: int = 10,
        save_dir: Optional[str] = None,
        progress: bool = False,
        **kwargs: Any,
    ) -> Dict[str, Any]:
        """Full baseline run: JSRL training (+ optional RICE refinement)."""
        if env is not None:
            self.env = env
        if guided_policy is not None:
            self.guided_policy = guided_policy
        baseline_eval = self.evaluate(n_episodes=eval_episodes) if evaluate else None
        history = self.train(
            total_timesteps=total_timesteps, total_iterations=total_iterations, progress=progress
        )
        result: Dict[str, Any] = {
            "baseline": self.name,
            "env_id": self.env_id,
            "no_refine": baseline_eval,
            "history": history,
            "summary": self.summary(),
        }
        if save_dir:
            ensure_dir(save_dir)
            try:
                result["checkpoint"] = self.save(os.path.join(save_dir, "jsrl_checkpoint.pt"))
            except Exception:
                pass
        if refine:
            refined_policy, refiner = self.refine(
                env=self.env,
                mask_net=mask_net,
                total_timesteps=refine_timesteps,
                total_iterations=refine_iterations,
                config=refine_config,
            )
            result["refined_policy"] = refined_policy
            result["refiner"] = refiner
            if evaluate and _HAS_REFINER and evaluate_refined_policy is not None:
                result["eval"] = evaluate_refined_policy(  # type: ignore[misc]
                    self.env,
                    refined_policy,
                    env_id=self.env_id,
                    n_episodes=eval_episodes,
                    device=self.device,
                )
                result["final_reward"] = result["eval"].get("mean_reward")
        elif evaluate:
            final = self.evaluate(n_episodes=eval_episodes)
            result["eval"] = final
            result["final_reward"] = final.get("mean_reward")
        return result


