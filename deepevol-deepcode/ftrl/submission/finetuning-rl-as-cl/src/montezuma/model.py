def main(argv: Optional[Sequence[str]] = None) -> int:
    """Print a short parameter report and run a forward-pass smoke test."""
    import argparse

    parser = argparse.ArgumentParser(description="Montezuma PPO + RND model utilities")
    parser.add_argument("--config", type=str, default=None, help="optional YAML config")
    parser.add_argument("--set", nargs="*", default=[], help="config overrides key=value")
    parser.add_argument("--device", type=str, default="cpu")
    parser.add_argument("--batch-size", type=int, default=4)
    parser.add_argument("--no-smoke-test", action="store_true")
    args = parser.parse_args(argv)

    cfg = None
    if args.config:
        try:
            from src.common.config import load_config

            cfg = load_config(args.config, args.set)
        except Exception as exc:  # pragma: no cover - CLI convenience
            print(f"Could not load config ({exc}); continuing with defaults.")

    if not _HAS_TORCH:
        print("PyTorch is not installed: reporting default hyperparameters only.")
        print(MontezumaModelConfig.from_config(cfg).to_dict())
        return 0

    built = build_models(cfg, device=args.device)
    policy, rnd, model_cfg = built["policy"], built["rnd"], built["config"]
    print("Policy:", policy.describe())
    if rnd is not None:
        print("RND:   ", rnd.describe())

    if not args.no_smoke_test:
        obs = torch.zeros(args.batch_size, *model_cfg.obs_shape)  # type: ignore[union-attr]
        obs = (obs + torch.rand_like(obs) * 255.0).to(built["device"])  # type: ignore[union-attr]
        logits, value = policy(obs)
        print("policy forward:", tuple(logits.shape), tuple(value.shape))
        actions = logits.argmax(dim=-1)
        log_prob, entropy, value2 = policy.pi_value(obs, actions)
        print("log_prob/entropy/value:", tuple(log_prob.shape), tuple(entropy.shape), tuple(value2.shape))
        if rnd is not None:
            intrinsic = rnd.intrinsic_reward(obs)
            loss = rnd.loss(obs)
            print("rnd error/loss:", tuple(intrinsic.shape), float(loss.detach().cpu()))
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
