def build_policy(
    cfg: Any = None,
    obs_shape: Optional[Tuple[int, int, int]] = None,
    num_actions: Optional[int] = None,
    device: Optional[Union[str, Any]] = None,
    **overrides: Any,
) -> "PolicyNetwork":
    """Build a :class:`PolicyNetwork` from a config (mapping/dataclass) or defaults."""
    model_cfg = _coerce_config(cfg, **overrides)
    obs_shape = tuple(obs_shape or model_cfg.obs_shape)
    num_actions = int(num_actions or model_cfg.num_actions)
    policy = PolicyNetwork(
        obs_shape=obs_shape,
        num_actions=num_actions,
        feature_dim=model_cfg.feature_dim,
        shared_backbone=model_cfg.shared_backbone,
        normalize_obs=model_cfg.normalize_obs,
    )
    dev = device if device is not None else model_cfg.device
    if dev is not None:
        policy = policy.to(_resolve_device(dev))
    return policy


def build_rnd(
    cfg: Any = None,
    obs_shape: Optional[Tuple[int, int, int]] = None,
    device: Optional[Union[str, Any]] = None,
    **overrides: Any,
) -> "RNDModel":
    """Build an :class:`RNDModel` (target + predictor) from a config or defaults."""
    model_cfg = _coerce_config(cfg, **overrides)
    obs_shape = tuple(obs_shape or model_cfg.obs_shape)
    rnd = RNDModel(
        obs_shape=obs_shape,
        output_size=model_cfg.rnd_feature_dim,
        normalize_obs=model_cfg.normalize_obs,
    )
    dev = device if device is not None else model_cfg.device
    if dev is not None:
        rnd = rnd.to(_resolve_device(dev))
    return rnd


def build_models(
    cfg: Any = None,
    obs_shape: Optional[Tuple[int, int, int]] = None,
    num_actions: Optional[int] = None,
    device: Optional[Union[str, Any]] = None,
    **overrides: Any,
) -> Dict[str, Any]:
    """Convenience factory returning ``{"policy", "rnd", "config", "device"}``."""
    model_cfg = _coerce_config(cfg, **overrides)
    policy = build_policy(model_cfg, obs_shape=obs_shape, num_actions=num_actions, device=device)
    rnd = None
    if model_cfg.use_rnd:
        rnd = build_rnd(model_cfg, obs_shape=obs_shape, device=device)
    return {
        "policy": policy,
        "rnd": rnd,
        "config": model_cfg,
        "device": _resolve_device(device if device is not None else model_cfg.device),
    }


def count_parameters(module: Any) -> int:
    """Number of trainable parameters of a module."""
    if module is None or not _HAS_TORCH:
        return 0
    return int(sum(p.numel() for p in module.parameters() if p.requires_grad))


def save_model_state(path: str, policy: Any = None, rnd: Any = None, extra: Optional[Mapping[str, Any]] = None) -> str:
    """Save policy / RND weights (plus any extra payload) to ``path``."""
    _require_torch()
    import os

    state: Dict[str, Any] = dict(extra or {})
    if policy is not None:
        state["policy"] = policy.state_dict()
    if rnd is not None:
        state["rnd"] = rnd.state_dict()
    directory = os.path.dirname(os.path.abspath(path))
    if directory:
        os.makedirs(directory, exist_ok=True)
    torch.save(state, path)  # type: ignore[union-attr]
    return path


def load_model_state(path: str, policy: Any = None, rnd: Any = None, map_location: str = "cpu") -> Dict[str, Any]:
    """Load weights saved by :func:`save_model_state` into ``policy`` / ``rnd``."""
    _require_torch()
    state = torch.load(path, map_location=map_location)  # type: ignore[union-attr]
    if policy is not None and isinstance(state, Mapping) and state.get("policy") is not None:
        policy.load_state_dict(state["policy"])
    if rnd is not None and isinstance(state, Mapping) and state.get("rnd") is not None:
        rnd.load_state_dict(state["rnd"])
    return state if isinstance(state, Mapping) else {"state": state}


