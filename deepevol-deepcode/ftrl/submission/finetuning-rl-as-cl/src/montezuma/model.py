def _require_torch() -> None:
    if not _HAS_TORCH:
        raise RuntimeError(
            "PyTorch is required to build the Montezuma networks. Install torch "
            "(>= 2.1) to use src.montezuma.model."
        )


def _make_activation(name: str) -> Any:
    name = (name or "relu").lower()
    if name in ("relu",):
        return nn.ReLU(inplace=False)
    if name in ("leaky_relu", "leakyrelu", "lrelu"):
        return nn.LeakyReLU(negative_slope=0.01, inplace=False)
    if name == "elu":
        return nn.ELU(inplace=False)
    if name == "tanh":
        return nn.Tanh()
    raise ValueError(f"Unsupported activation: {name!r}")


def _prepare_obs(obs: Any, in_channels: int = FRAME_STACK, normalize: bool = True) -> Any:
    """Coerce a batch of observations into a float ``(B, C, H, W)`` tensor."""
    _require_torch()
    if isinstance(obs, Mapping):  # Meta-World-style dict (not used for Atari)
        obs = next(iter(obs.values()))
    if not isinstance(obs, torch.Tensor):  # type: ignore[union-attr]
        obs = torch.as_tensor(_as_array(obs))  # type: ignore[union-attr]
    if obs.dim() == 3:
        obs = obs.unsqueeze(0)
    if obs.dim() != 4:
        raise ValueError(f"Expected a 3-D or 4-D observation, got shape {tuple(obs.shape)}")
    # (B, H, W, C) -> (B, C, H, W) when the channels are last and obviously so.
    if obs.shape[-1] == in_channels and obs.shape[1] != in_channels:
        obs = obs.permute(0, 3, 1, 2)
    obs = obs.float()
    if normalize and float(obs.max()) > 1.5:
        obs = obs / 255.0
    return obs


def _is_single_obs(obs: Any) -> bool:
    if obs is None:
        return False
    shape = getattr(obs, "shape", None)
    if shape is None:
        return True
    return len(tuple(shape)) == 3


def _batchify(obs: Any) -> Any:
    if isinstance(obs, Mapping):
        obs = next(iter(obs.values()))
    if not isinstance(obs, torch.Tensor):  # type: ignore[union-attr]
        obs = torch.as_tensor(_as_array(obs))  # type: ignore[union-attr]
    if obs.dim() == 3:
        obs = obs.unsqueeze(0)
    return obs


def _as_long(actions: Any) -> Any:
    if isinstance(actions, torch.Tensor):  # type: ignore[union-attr]
        return actions.long().reshape(-1)
    return torch.as_tensor(_as_array(actions)).long().reshape(-1)  # type: ignore[union-attr]


def _resolve_device(device: Any) -> Any:
    if not _HAS_TORCH:
        return device
    if device is None:
        return torch.device("cpu")  # type: ignore[union-attr]
    if isinstance(device, torch.device):  # type: ignore[union-attr]
        return device
    device_str = str(device)
    if device_str.startswith("cuda") and not torch.cuda.is_available():  # type: ignore[union-attr]
        return torch.device("cpu")  # type: ignore[union-attr]
    return torch.device(device_str)  # type: ignore[union-attr]


def _as_array(x: Any) -> Any:
    if x is None:
        return _zeros((0,))
    if isinstance(x, torch.Tensor):  # type: ignore[union-attr]
        x = x.detach().cpu().numpy()
    if np is not None:
        return np.asarray(x)
    return x  # pragma: no cover


def _zeros(shape: Sequence[int]) -> Any:
    if np is not None:
        return np.zeros(tuple(shape), dtype=np.float64)
    return [0.0 for _ in range(int(shape[0]))]


def _concat(a: Any, b: Any) -> Any:
    if np is not None:
        return np.concatenate([np.asarray(a).reshape(-1), np.asarray(b).reshape(-1)])
    return list(a) + list(b)  # pragma: no cover


def _tolist(value: Any) -> Any:
    if np is not None and isinstance(value, np.ndarray):
        return value.tolist()
    if isinstance(value, (list, tuple)):
        return [float(v) for v in value]
    try:
        return float(value)
    except Exception:  # pragma: no cover
        return value


def _fromlist(value: Any, shape: Tuple[int, ...]) -> Any:
    if value is None:
        return RunningMeanStd._zeros(shape)
    if np is not None:
        return np.array(value, dtype=np.float64).reshape(shape) if shape else np.asarray(value, dtype=np.float64)
    return float(value)  # pragma: no cover


def _coerce_config(cfg: Any, **overrides: Any) -> MontezumaModelConfig:
    """Accept a :class:`MontezumaModelConfig`, a config mapping, or ``None``."""
    if isinstance(cfg, MontezumaModelConfig):
        return cfg.with_overrides(**overrides) if overrides else cfg
    return MontezumaModelConfig.from_config(cfg, **overrides)


def _get_block(cfg: Any, key: str) -> Optional[Any]:
    if cfg is None:
        return None
    if isinstance(cfg, Mapping):
        value = cfg.get(key)
    else:
        value = getattr(cfg, key, None)
    if value is None:
        return None
    if isinstance(value, Mapping):
        return value
    to_dict = getattr(value, "to_dict", None)
    if callable(to_dict):
        return to_dict()
    return value


def _first(block: Any, *keys: str) -> Any:
    """First present key of ``block`` (mapping or object), else ``None``."""
    if not block:
        return None
    for key in keys:
        if isinstance(block, Mapping):
            if key in block and block[key] is not None:
                return block[key]
        else:
            value = getattr(block, key, None)
            if value is not None:
                return value
    return None


def _filter_fields(cls: Any, values: Mapping[str, Any]) -> Dict[str, Any]:
    """Keep only keys that correspond to dataclass fields (and are not ``None``)."""
    names = set(getattr(cls, "__dataclass_fields__", {}).keys())
    out: Dict[str, Any] = {}
    for key, value in values.items():
        if key in names and value is not None:
            out[key] = value
    return out


