class NatureCNN(nn.Module):
    """Nature-DQN style convolutional trunk (Mnih et al., 2015).

    ``(C, 84, 84)`` uint8 observation -> ``feature_dim`` features (512 by default, as
    used for both the PPO trunk and the RND target/predictor in Appendix B.2).

    Architecture: ``Conv(8x8, s4, 32) - Conv(4x4, s2, 64) - Conv(3x3, s1, 64) - FC``.
    The Montezuma implementation used by the paper (jcwleo's RND repository, cited in
    Table 2) uses ``LeakyReLU`` inside the RND networks; the PPO trunk uses ``ReLU``.
    """

    def __init__(
        self,
        in_channels: int = FRAME_STACK,
        feature_dim: int = FEATURE_DIM,
        activation: str = "relu",
        width_scale: float = 1.0,
    ):
        _require_torch()
        super().__init__()
        c1 = max(1, int(round(32 * width_scale)))
        c2 = max(1, int(round(64 * width_scale)))
        c3 = max(1, int(round(64 * width_scale)))

        self.in_channels = int(in_channels)
        self.feature_dim = int(feature_dim)
        self.activation_name = activation
        self.activation = _make_activation(activation)

        self.conv1 = nn.Conv2d(self.in_channels, c1, kernel_size=8, stride=4)
        self.conv2 = nn.Conv2d(c1, c2, kernel_size=4, stride=2)
        self.conv3 = nn.Conv2d(c2, c3, kernel_size=3, stride=1)

        self._conv_out_dim = self._infer_conv_out_dim()
        self.fc = nn.Linear(self._conv_out_dim, self.feature_dim)
        self._init_weights()

    # ---------------------------------------------------------------- helpers
    def _infer_conv_out_dim(self, size: int = FRAME_SIZE) -> int:
        """Shape of the flattened convolution output for an ``size x size`` input."""
        with torch.no_grad():  # type: ignore[union-attr]
            dummy = torch.zeros(1, self.in_channels, size, size)  # type: ignore[union-attr]
            out = self.activation(self.conv3(self.activation(self.conv2(self.activation(self.conv1(dummy))))))
        return int(out.numel())

    def _init_weights(self) -> None:
        for module in self.modules():
            if isinstance(module, (nn.Conv2d, nn.Linear)):
                nn.init.orthogonal_(module.weight, gain=math.sqrt(2.0))
                if module.bias is not None:
                    nn.init.constant_(module.bias, 0.0)

    @property
    def conv_out_dim(self) -> int:
        return self._conv_out_dim

    # ---------------------------------------------------------------- forward
    def conv_features(self, obs: Any) -> Any:
        x = _prepare_obs(obs, in_channels=self.in_channels)
        x = self.activation(self.conv1(x))
        x = self.activation(self.conv2(x))
        x = self.activation(self.conv3(x))
        return x.flatten(1)

    def forward(self, obs: Any) -> Any:
        features = self.conv_features(obs)
        return self.activation(self.fc(features))

    def extra_repr(self) -> str:  # pragma: no cover
        return f"in_channels={self.in_channels}, feature_dim={self.feature_dim}, conv_out={self._conv_out_dim}"


class PolicyNetwork(nn.Module):
    """PPO actor-critic for Montezuma's Revenge (18 discrete actions).

    The convolutional trunk is shared between the policy and value heads (the standard
    setup for Atari PPO, and what the reference RND implementation uses).  Setting
    ``shared_backbone=False`` instantiates two independent trunks.
    """

    def __init__(
        self,
        obs_shape: Tuple[int, int, int] = OBS_SHAPE,
        num_actions: int = NUM_ACTIONS,
        feature_dim: int = FEATURE_DIM,
        activation: str = "relu",
        shared_backbone: bool = True,
        normalize_obs: bool = True,
        init_log_std: float = 0.0,
    ):
        _require_torch()
        super().__init__()
        in_channels = int(obs_shape[0])
        self.obs_shape = tuple(obs_shape)
        self.num_actions = int(num_actions)
        self.feature_dim = int(feature_dim)
        self.normalize_obs = bool(normalize_obs)
        self.shared_backbone = bool(shared_backbone)

        self.backbone = NatureCNN(in_channels=in_channels, feature_dim=feature_dim, activation=activation)
        self.value_backbone = (
            None
            if self.shared_backbone
            else NatureCNN(in_channels=in_channels, feature_dim=feature_dim, activation=activation)
        )

        self.policy_head = nn.Linear(feature_dim, self.num_actions)
        self.value_head = nn.Linear(feature_dim, 1)

        # Fixed log-standard-deviation for optional Gaussian-style parameterisation of
        # the discrete policy.  The PPO objective itself uses Categorical, but the
        # analysis utilities (expert log-likelihood) can consume `logits` directly.
        self.log_std = nn.Parameter(torch.full((self.num_actions,), float(init_log_std)))

        self._init_weights()

    # ---------------------------------------------------------------- helpers
    def _init_weights(self) -> None:
        for module in (self.policy_head, self.value_head):
            nn.init.orthogonal_(module.weight, gain=0.01)
            nn.init.constant_(module.bias, 0.0)

    def encode(self, obs: Any) -> Any:
        """Shared trunk features (used by CKA/analysis utilities)."""
        x = _prepare_obs(obs, in_channels=self.obs_shape[0], normalize=self.normalize_obs)
        return self.backbone(x)

    # ---------------------------------------------------------------- core API
    def forward(self, obs: Any) -> Tuple[Any, Any]:
        """Return ``(logits, value)`` with ``value`` shaped ``(batch,)``."""
        features = self.encode(obs)
        logits = self.policy_head(features)
        value_source = features if self.shared_backbone else self.value_backbone(
            _prepare_obs(obs, in_channels=self.obs_shape[0], normalize=self.normalize_obs)
        )
        value = self.value_head(value_source).squeeze(-1)
        return logits, value

    def distribution(self, obs: Any) -> Any:
        """Categorical action distribution ``pi(a|s)``."""
        logits, _ = self.forward(obs)
        return Categorical(logits=logits)

    def log_prob(self, obs: Any, actions: Any) -> Any:
        dist = self.distribution(obs)
        return dist.log_prob(_as_long(actions))

    def entropy(self, obs: Any) -> Any:
        return self.distribution(obs).entropy()

    def pi_value(self, obs: Any, actions: Any, detach: bool = False) -> Tuple[Any, Any, Any]:
        """Evaluate ``(log pi(a|s), entropy, V(s))`` for a batch (PPO update step)."""
        logits, value = self.forward(obs)
        dist = Categorical(logits=logits)
        actions_long = _as_long(actions)
        log_prob = dist.log_prob(actions_long)
        entropy = dist.entropy()
        if detach:
            log_prob = log_prob.detach()
            entropy = entropy.detach()
        return log_prob, entropy, value

    # ---------------------------------------------------------------- acting
    @torch.no_grad() if _HAS_TORCH else (lambda f: f)  # type: ignore[misc]
    def act(
        self,
        obs: Any,
        deterministic: bool = False,
        return_log_prob: bool = False,
        return_value: bool = False,
    ) -> Any:
        """Sample an action for a *single* observation (or batch of observations).

        Returns the action (``int`` for a single observation, tensor for a batch), or a
        dict with additional ``log_prob`` / ``value`` / ``logits`` entries when
        requested.  This mirrors the duck-typed ``.act`` interface used by
        ``src.montezuma.env`` and the RoboticSequence SAC policy.
        """
        single = _is_single_obs(obs)
        batch = _batchify(obs) if single else obs
        logits, value = self.forward(batch)
        dist = Categorical(logits=logits)
        action = logits.argmax(dim=-1) if deterministic else dist.sample()

        if not (return_log_prob or return_value):
            return int(action.item()) if single else action

        out: Dict[str, Any] = {"action": action}
        if return_log_prob:
            out["log_prob"] = dist.log_prob(action)
        if return_value:
            out["value"] = value
        out["logits"] = logits
        if single:
            out["action"] = int(action.item())
            out["log_prob"] = out["log_prob"].item()
            out["value"] = out["value"].item()
        return out

    def greedy_action(self, obs: Any) -> Any:
        result = self.act(obs, deterministic=True)
        return result

    def sample_action(self, obs: Any, deterministic: bool = False, **kwargs: Any) -> Any:
        return self.act(obs, deterministic=deterministic, **kwargs)

    # ---------------------------------------------------------------- persistence
    def state_dict(self, *args: Any, **kwargs: Any) -> Dict[str, Any]:  # type: ignore[override]
        return super().state_dict(*args, **kwargs)

    def describe(self) -> Dict[str, Any]:
        return {
            "obs_shape": list(self.obs_shape),
            "num_actions": self.num_actions,
            "feature_dim": self.feature_dim,
            "shared_backbone": self.shared_backbone,
            "parameters": count_parameters(self),
        }


class RNDModel(nn.Module):
    """Random Network Distillation (Burda et al., 2018) as used in Appendix B.2.

    * ``target`` – randomly initialised and *frozen* network.
    * ``predictor`` – trainable network regressing onto the target's outputs.

    Both networks "receive observation as an input and return a vector with size 512"
    (Appendix B.2).  The intrinsic reward is the (optionally normalised) prediction
    error ``||target(s) - predictor(s)||^2``.
    """

    def __init__(
        self,
        obs_shape: Tuple[int, int, int] = OBS_SHAPE,
        output_size: int = RND_FEATURE_DIM,
        predictor_extra_layers: int = 0,
        activation: str = "leaky_relu",
        normalize_obs: bool = True,
        hidden_dim: Optional[int] = None,
    ):
        _require_torch()
        super().__init__()
        in_channels = int(obs_shape[0])
        self.obs_shape = tuple(obs_shape)
        self.output_size = int(output_size)
        self.normalize_obs = bool(normalize_obs)

        self.target = NatureCNN(in_channels=in_channels, feature_dim=output_size, activation=activation)
        self.predictor = NatureCNN(in_channels=in_channels, feature_dim=output_size, activation=activation)

        extra = int(predictor_extra_layers or 0)
        self.predictor_extra = None
        if extra > 0:
            layers = []
            prev = output_size
            hidden = int(hidden_dim or output_size)
            for _ in range(extra):
                layers.append(nn.Linear(prev, hidden))
                layers.append(_make_activation(activation))
                prev = hidden
            self.predictor_extra = nn.Sequential(*layers)

        # The target is never optimised.
        for param in self.target.parameters():
            param.requires_grad_(False)
        self.target.eval()

    # ---------------------------------------------------------------- forward
    def target_features(self, obs: Any) -> Any:
        return self.target(_prepare_obs(obs, in_channels=self.obs_shape[0], normalize=self.normalize_obs))

    def predictor_features(self, obs: Any) -> Any:
        features = self.predictor(_prepare_obs(obs, in_channels=self.obs_shape[0], normalize=self.normalize_obs))
        if self.predictor_extra is not None:
            features = self.predictor_extra(features)
        return features

    def forward(self, obs: Any) -> Tuple[Any, Any]:
        """Return ``(prediction, target)`` feature vectors."""
        with torch.no_grad():  # type: ignore[union-attr]
            target = self.target_features(obs)
        prediction = self.predictor_features(obs)
        return prediction, target

    def prediction_error(self, obs: Any) -> Any:
        """Per-sample squared prediction error (the raw intrinsic reward)."""
        prediction, target = self(obs)
        return ((prediction - target) ** 2).mean(dim=-1)

    def intrinsic_reward(self, obs: Any) -> Any:
        return self.prediction_error(obs)

    def loss(self, obs: Any, weights: Any = None, reduction: str = "mean") -> Any:
        """RND regression loss ``||target(s) - predictor(s)||^2``.

        ``weights`` implements the paper's ``UpdateProportion=0.25`` behaviour: only a
        random quarter of each mini-batch contributes to the gradient (this is the
        convention of the reference implementation).
        """
        prediction, target = self(obs)
        loss = ((prediction - target) ** 2).mean(dim=-1)
        if weights is not None:
            weights = weights.reshape(-1).to(loss.dtype)
            loss = loss * weights
            denom = weights.sum().clamp(min=1e-8)
            if reduction == "sum":
                return loss.sum()
            return loss.sum() / denom
        if reduction == "none":
            return loss
        if reduction == "sum":
            return loss.sum()
        return loss.mean()

    def update_proportion_mask(self, batch_size: int, proportion: float, device: Any = None) -> Any:
        """Bernoulli mask enforcing ``UpdateProportion`` (Table 2: 0.25)."""
        proportion = float(proportion)
        if proportion >= 1.0:
            return torch.ones(batch_size, device=device)  # type: ignore[union-attr]
        return (torch.rand(batch_size, device=device) < proportion).float()  # type: ignore[union-attr]

    # ---------------------------------------------------------------- persistence
    def state_dict(self, *args: Any, **kwargs: Any) -> Dict[str, Any]:  # type: ignore[override]
        return super().state_dict(*args, **kwargs)

    def describe(self) -> Dict[str, Any]:
        return {
            "obs_shape": list(self.obs_shape),
            "output_size": self.output_size,
            "parameters": count_parameters(self),
            "predictor_parameters": count_parameters(self.predictor),
            "target_parameters": count_parameters(self.target),
        }


