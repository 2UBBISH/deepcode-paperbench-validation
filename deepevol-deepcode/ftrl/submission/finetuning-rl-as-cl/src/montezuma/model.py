class RunningMeanStd:
    """Welford-style running mean/variance, matching the RND reference implementation.

    Works with scalars or NumPy arrays.  ``update`` accepts either a single value or a
    batch; NumPy is optional so this remains usable (with pure-Python maths) in
    dependency-light tests.
    """

    def __init__(self, shape: Union[int, Sequence[int]] = (), epsilon: float = 1e-4, name: str = "rms"):
        self.shape = tuple(shape) if not isinstance(shape, int) else (shape,)
        self.epsilon = float(epsilon)
        self.name = name
        self.mean = self._zeros(self.shape)
        self.var = self._ones(self.shape)
        self.count = float(self.epsilon)

    # ---------------------------------------------------------------- helpers
    @staticmethod
    def _zeros(shape: Tuple[int, ...]) -> Any:
        if np is not None:
            return np.zeros(shape, dtype=np.float64)
        return 0.0 if shape == () else [0.0 for _ in range(int(shape[0]))]

    @staticmethod
    def _ones(shape: Tuple[int, ...]) -> Any:
        if np is not None:
            return np.ones(shape, dtype=np.float64)
        return 1.0 if shape == () else [1.0 for _ in range(int(shape[0]))]

    def update(self, x: Any) -> None:
        """Incorporate a new sample (array-like) into the running statistics."""
        if x is None:
            return
        if np is None:  # pragma: no cover - pure-Python fallback
            value = float(x)
            self.count += 1.0
            delta = value - self.mean
            self.mean = self.mean + delta / self.count
            self.var = self.var + delta * (value - self.mean)
            return

        batch = np.asarray(x, dtype=np.float64)
        if batch.ndim == 0:
            batch = batch.reshape(1)
        elif self.shape and batch.shape[0] == self.shape[0] and batch.ndim > len(self.shape):
            # (T, *shape) -> fold the leading time axis into the batch dimension
            batch = batch.reshape(-1, *batch.shape[-len(self.shape):])

        batch_mean = batch.mean(axis=0)
        batch_var = batch.var(axis=0)
        batch_count = batch.shape[0] if batch.ndim else 1

        self._update_from_moments(batch_mean, batch_var, batch_count)

    def _update_from_moments(self, batch_mean: Any, batch_var: Any, batch_count: float) -> None:
        delta = batch_mean - self.mean
        tot_count = self.count + batch_count
        new_mean = self.mean + delta * batch_count / tot_count
        m_a = self.var * self.count
        m_b = batch_var * batch_count
        m2 = m_a + m_b + (delta ** 2) * self.count * batch_count / tot_count
        self.mean = new_mean
        self.var = m2 / tot_count
        self.count = float(tot_count)

    # ---------------------------------------------------------------- usage
    @property
    def std(self) -> Any:
        if np is not None:
            return np.sqrt(np.maximum(self.var, 1e-12))
        return math.sqrt(max(self.var, 1e-12))

    def normalize(self, x: Any, clip: Optional[float] = 10.0) -> Any:
        value = (x - self.mean) / (self.std + 1e-8)
        if clip is not None:
            if np is not None:
                value = np.clip(value, -clip, clip)
            else:  # pragma: no cover
                value = max(-clip, min(clip, value))
        return value

    def state_dict(self) -> Dict[str, Any]:
        return {
            "mean": _tolist(self.mean),
            "var": _tolist(self.var),
            "count": self.count,
            "shape": list(self.shape),
            "epsilon": self.epsilon,
        }

    def load_state_dict(self, state: Mapping[str, Any]) -> None:
        if not state:
            return
        self.mean = _fromlist(state.get("mean"), self.shape)
        self.var = _fromlist(state.get("var"), self.shape)
        self.count = float(state.get("count", self.count))

    def __repr__(self) -> str:  # pragma: no cover - debugging aid
        return f"RunningMeanStd(name={self.name!r}, count={self.count:.1f})"


class ObsNormalizer:
    """Optional observation normalisation (``UseNorm`` / ``ObsNormStep`` in Table 2).

    The paper follows Burda et al. (2018) and *disables* it (``UseNorm=False``), but
    the mechanism is provided because the reference implementation supports it and the
    M1/M2 runs may enable it.  When ``normalize_obs`` is used the network simply sees
    frames scaled to ``[0, 1]``.
    """

    def __init__(
        self,
        shape: Union[int, Sequence[int]] = (FRAME_STACK, FRAME_SIZE, FRAME_SIZE),
        enabled: bool = False,
        update_steps: int = TABLE2_DEFAULTS["obs_norm_step"],
        clip: float = 10.0,
    ):
        self.shape = tuple(shape) if not isinstance(shape, int) else (shape,)
        self.enabled = bool(enabled)
        self.update_steps = int(update_steps)
        self.clip = float(clip)
        self.rms = RunningMeanStd(self.shape, name="obs")
        self.steps = 0

    def update(self, obs: Any) -> None:
        if not self.enabled:
            return
        if self.update_steps and self.steps >= self.update_steps:
            return
        self.rms.update(obs)
        self.steps += 1

    def __call__(self, obs: Any) -> Any:
        if not self.enabled:
            return obs
        return self.rms.normalize(obs, clip=self.clip)

    def state_dict(self) -> Dict[str, Any]:
        return {"rms": self.rms.state_dict(), "steps": self.steps, "enabled": self.enabled}

    def load_state_dict(self, state: Mapping[str, Any]) -> None:
        if not state:
            return
        self.rms.load_state_dict(state.get("rms") or {})
        self.steps = int(state.get("steps", self.steps))
        self.enabled = bool(state.get("enabled", self.enabled))


class RewardForwardFilter:
    """Discounted running average of the intrinsic reward stream.

    Implements the ``RewardForwardFilter`` used by RND reference implementations:

    ``rff_t = gamma_int * rff_{t-1} + r_t``

    The normalised intrinsic reward is then ``r_t / sqrt(Var(RFF))`` applied by
    :class:`IntrinsicRewardNormalizer`.
    """

    def __init__(self, num_env: int = TABLE2_DEFAULTS["num_env"], int_gamma: float = TABLE2_DEFAULTS["int_gamma"]):
        self.num_env = int(num_env)
        self.int_gamma = float(int_gamma)
        self.rewems = _zeros([self.num_env])

    def update(self, rewards: Any) -> Any:
        """``rewards`` shape ``(num_env,)`` -> updated accumulators (same shape)."""
        rewards_arr = _as_array(rewards).reshape(-1)
        if rewards_arr.size < self.num_env:
            pad = self.num_env - rewards_arr.size
            rewards_arr = _concat(rewards_arr, _zeros([pad]))
        self.rewems = self.rewems * self.int_gamma + rewards_arr[: self.num_env]
        return self.rewems

    def reset(self) -> None:
        self.rewems = _zeros([self.num_env])

    def state_dict(self) -> Dict[str, Any]:
        return {"rewems": _tolist(self.rewems), "num_env": self.num_env, "int_gamma": self.int_gamma}

    def load_state_dict(self, state: Mapping[str, Any]) -> None:
        if not state:
            return
        if state.get("rewems") is not None:
            self.rewems = _fromlist(state["rewems"], (self.num_env,))


class IntrinsicRewardNormalizer:
    """Normalise the RND prediction error by its running standard deviation.

    This is the standard "intrinsic reward normalization" from Burda et al. (2018):
    ``r_int <- r_int / std(RFF)`` where RFF is a discounted running average of the raw
    prediction errors.
    """

    def __init__(
        self,
        num_env: int = TABLE2_DEFAULTS["num_env"],
        int_gamma: float = TABLE2_DEFAULTS["int_gamma"],
        enabled: bool = True,
    ):
        self.enabled = bool(enabled)
        self.num_env = int(num_env)
        self.filter = RewardForwardFilter(num_env=num_env, int_gamma=int_gamma)
        self.rms = RunningMeanStd((), name="int_reward")
        self.discounted_rms = RunningMeanStd((), name="int_reward_discounted")

    def update(self, intrinsic_rewards: Any) -> None:
        rewards = _as_array(intrinsic_rewards).reshape(-1)
        if rewards.size == 0:
            return
        self.rms.update(rewards)
        if self.enabled:
            disc = self.filter.update(rewards)
            self.discounted_rms.update(_as_array(disc).reshape(-1))

    def __call__(self, intrinsic_rewards: Any) -> Any:
        rewards = _as_array(intrinsic_rewards)
        if not self.enabled or self.discounted_rms.count <= 1.0:
            return intrinsic_rewards
        return rewards / (self.discounted_rms.std + 1e-8)

    def state_dict(self) -> Dict[str, Any]:
        return {
            "enabled": self.enabled,
            "rms": self.rms.state_dict(),
            "discounted_rms": self.discounted_rms.state_dict(),
            "filter": self.filter.state_dict(),
        }

    def load_state_dict(self, state: Mapping[str, Any]) -> None:
        if not state:
            return
        self.enabled = bool(state.get("enabled", self.enabled))
        self.rms.load_state_dict(state.get("rms") or {})
        self.discounted_rms.load_state_dict(state.get("discounted_rms") or {})
        self.filter.load_state_dict(state.get("filter") or {})


