"""Kickstarting (KS) knowledge-retention loss.

Paper: "Fine-tuning Reinforcement Learning Models is Secretly a Forgetting
Mitigation Problem".

Section 2 (Knowledge retention)::

    L_KS(theta) = E_{s ~ pi_theta}[ D_KL( pi_*(s) || pi_theta(s) ) ]

Appendix C.2 ("Distillation-based methods") defines the per-state divergence

    D_KL^s(p || q) = E_{a ~ p(.|s)} [ log( p(a|s) / q(a|s) ) ]

and the kickstarting objective

    L_KS(theta) = E_{s ~ B_theta}[ D_KL^s( pi_*(.|s) || pi_theta(.|s) ) ]

where ``B_theta`` is a buffer of data gathered by the *online* policy
``pi_theta`` (in contrast to behavioral cloning, whose expectation is over a
buffer of pre-training states).  Note that the KL direction is
``KL(teacher || student)`` -- the teacher ``pi_*`` samples the actions and the
student's log-probability of those actions is maximised (an advantage-weighted
cross-entropy / "kickstarting" distillation objective).

Appendix B.1 (NetHack fine-tuning), *Fine-tuning + KS*:

    "we compute the auxiliary loss on data generated by the online policy.  We
    scaled the loss by a factor of 0.5 and used exponential decay 0.99998,
    where the coefficient was decayed every train step."

Following Wołczyk et al. (2022) knowledge retention is applied to the **actor
only**; the critic coefficient is always 0.

This module provides

* :class:`RolloutBuffer` (alias :data:`OnlineBuffer`) -- a ring buffer of states
  visited by the current policy, optionally storing teacher log-probabilities
  computed at collection time (cheap: no teacher forward pass at update time);
* :class:`Kickstarting` -- the actor-only auxiliary loss with a per-step
  multiplicative coefficient decay (0.5 * 0.99998^t for NetHack);
* :func:`kickstarting_loss` / :func:`ks_loss` -- the functional objective;
* :func:`ks_coef_for` / :func:`ks_config_for` -- the paper's per-environment
  scale (and decay) constants.
"""

