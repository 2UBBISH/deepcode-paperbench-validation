# The regulariser
# ---------------------------------------------------------------------------
class Kickstarting:
    """Actor-only kickstarting retention loss for RL fine-tuning.

    Args:
        actor: the (student) policy whose parameters receive the auxiliary loss.
        teacher: the pre-trained policy ``pi_*`` (used for the KL target).
            Optional if the online buffer stores teacher log-probabilities.
        buffer: an :class:`RolloutBuffer` of online-policy states (``B_theta``).
        coef: initial scale of the auxiliary loss (NetHack: ``0.5``).
        schedule: optional schedule object exposing ``value_at``/``step`` (e.g.
            the shared ``CoefficientSchedule``).  Overrides ``coef``/``decay``.
        decay: per-step multiplicative decay factor (NetHack: ``0.99998``).
            ``None`` means a constant coefficient.
        direction: KL direction; ``"reverse"`` = ``D_KL^s(pi_* || pi_theta)``
            (the paper's kickstarting loss).
        batch_size: number of online states per update.
        use_exact_kl: use analytic KL when both distributions are available.
        temperature: softmax temperature applied to discovered logits.
        log_prob_fn: optional ``fn(module, obs, actions) -> log_prob``.
        forward_fn: optional ``fn(module, obs) -> output``.
        min_coef: lower bound on the (decaying) coefficient.
        name: label used in reprs / logs.
    """

    kind = "kickstarting"

    def __init__(
        self,
        actor: Any,
        teacher: Any = None,
        buffer: Optional[RolloutBuffer] = None,
        coef: float = 1.0,
        schedule: Optional[Any] = None,
        decay: Optional[float] = None,
        decay_type: str = "exponential",
        direction: str = "reverse",
        batch_size: int = 128,
        use_exact_kl: bool = True,
        temperature: float = 1.0,
        loss_type: str = "kl",
        log_prob_fn: Optional[Callable[..., Any]] = None,
        forward_fn: Optional[Callable[..., Any]] = None,
        min_coef: float = 0.0,
        device: Optional[Any] = None,
        name: str = "ks",
    ) -> None:
        if torch is None:  # pragma: no cover
            raise RuntimeError("Kickstarting requires torch to be installed")
        if direction not in ("forward", "reverse"):
            raise ValueError("direction must be 'forward' or 'reverse'")
        self.actor = actor
        self.teacher = teacher
        self.buffer = buffer if buffer is not None else RolloutBuffer(device=device)
        self.name = name
        self.direction = direction
        self.batch_size = int(batch_size)
        self.use_exact_kl = bool(use_exact_kl)
        self.temperature = float(temperature)
        self.loss_type = str(loss_type)
        self.log_prob_fn = log_prob_fn
        self.forward_fn = forward_fn
        self.min_coef = float(min_coef)
        self.device = device
        self.schedule = _as_schedule(schedule, coef=coef, decay=decay,
                                     decay_type=decay_type, min_coef=min_coef)
        # Initial coefficient as declared (used by config-driven reporting).
        self.coef = float(getattr(self.schedule, "value", coef))
        self._schedule_backend = getattr(self.schedule, "kind", type(self.schedule).__name__)
        if teacher is not None:
            freeze_teacher(teacher, device=device)

    # -- construction helpers --------------------------------------------
    @classmethod
    def for_env(cls, env_name: str, actor: Any, teacher: Any = None,
                buffer: Optional[RolloutBuffer] = None, **kwargs: Any) -> "Kickstarting":
        """Build a Kickstarting loss with the paper's per-environment constants."""
        settings = ks_config_for(env_name)
        settings.update(kwargs)
        if buffer is not None:
            settings.setdefault("buffer", buffer)
        return cls(actor, teacher=teacher, **settings)

    def configure(self, cfg: Any) -> "Kickstarting":
        """Apply configuration keys (``coef``/``scale``/``decay``/``batch_size``)."""
        get = _cfg_getter(cfg)

        def _get(*names: str, default: Any = None) -> Any:
            for n in names:
                v = get(n, None)
                if v is not None:
                    return v
            return default

        scale = _get("coef", "scale", "ks_coef", "lambda_ks")
        decay = _get("decay", "decay_factor")
        min_coef = _get("min_coef", "coef_min")
        direction = _get("direction")
        batch_size = _get("batch_size")
        use_exact_kl = _get("use_exact_kl", "exact_kl")
        if scale is not None or decay is not None or min_coef is not None:
            value = self.coef if scale is None else float(scale)
            if min_coef is not None:
                self.min_coef = float(min_coef)
            self.schedule = PerStepDecay(
                value=value,
                decay=None if decay is None else float(decay),
                min_value=self.min_coef,
            )
            self.coef = value
            self._schedule_backend = "per_step"
        if direction is not None:
            self.direction = str(direction)
        if batch_size is not None:
            self.batch_size = int(batch_size)
        if use_exact_kl is not None:
            self.use_exact_kl = bool(use_exact_kl)
        return self

    # -- state ------------------------------------------------------------
    @property
    def enabled(self) -> bool:
        """``False`` when the (current) coefficient is zero -> loss skipped."""
        return self.coef > 0.0 and self.schedule.value_at(self.step_count) > 0.0

    @property
    def coefficient(self) -> float:
        return float(self.schedule.value_at(self.step_count))

    @property
    def step_count(self) -> int:
        return int(getattr(self.schedule, "_step", 0))

    def value_at(self, step: int) -> float:
        return float(self.schedule.value_at(step))

    def step(self, n: int = 1) -> float:
        """Advance the decay schedule (called once per train step)."""
        self.schedule.step(n)
        return self.coefficient

    def reset(self) -> None:
        self.schedule.reset()

    # -- buffers / teacher -------------------------------------------------
    def attach_buffer(self, buffer: RolloutBuffer) -> "Kickstarting":
        self.buffer = buffer
        return self

    set_buffer = attach_buffer

    def add_rollout(self, obs: Any, **kwargs: Any) -> None:
        """Feed online policy observations into ``B_theta``.

        If the teacher is available and ``log_prob_fn`` is provided, teacher
        log-probabilities are precomputed on the fly, which keeps the update
        step free of teacher forward passes.
        """
        if "teacher_log_prob" not in kwargs and self.teacher is not None and self.log_prob_fn is not None:
            actions = kwargs.get("action", kwargs.get("teacher_action"))
            if actions is not None:
                with torch.no_grad():
                    kwargs["teacher_log_prob"] = self.teacher_log_prob(obs, actions)
        self.buffer.add(obs, **kwargs)

    def set_teacher_dist_fn(self, fn: Optional[Callable[..., Any]]) -> "Kickstarting":
        """Provide ``fn(obs) -> distribution`` (or ``-> module output``) for the teacher."""
        self._teacher_dist_fn = fn
        return self

    def teacher_log_prob(self, obs: Any, actions: Any) -> Any:
        """``log pi_*(a|s)`` for the given observations/actions (no grad)."""
        if self.teacher is None:
            raise RuntimeError("no teacher policy was provided to Kickstarting")
        if self.log_prob_fn is not None:
            return self.log_prob_fn(self.teacher, obs, actions)
        dist = self._distribution(self.teacher, obs, teacher=True)
        if hasattr(dist, "log_prob"):
            log_prob = dist.log_prob(actions)
        else:  # pragma: no cover - logits without a distribution wrapper
            from torch.distributions import Categorical  # local import

            log_prob = Categorical(logits=dist / max(self.temperature, 1e-8)).log_prob(actions)
        if log_prob.dim() > 1:
            log_prob = log_prob.sum(dim=-1)
        return log_prob.detach()

    # -- loss -------------------------------------------------------------
    def _distribution(self, module: Any, obs: Any, teacher: bool = False) -> Any:
        fn = self._teacher_dist_fn if (teacher and getattr(self, "_teacher_dist_fn", None)) else None
        output = fn(obs) if fn is not None else _forward_actor(module, obs, self.forward_fn)
        dist = _find_distribution(output, obs=obs, forward_fn=None,
                                  prefer_logits=(self.temperature != 1.0))
        return _apply_temperature(dist, self.temperature)

    def student_distribution(self, obs: Any) -> Any:
        return self._distribution(self.actor, obs, teacher=False)

    def penalty(self, batch: Optional[Mapping[str, Any]] = None,
                batch_size: Optional[int] = None) -> Any:
        """Scaled ``L_KS`` for one batch of online states.

        Returns a scalar tensor carrying gradients w.r.t. the actor's
        parameters; the teacher term is detached.
        """
        if self.coef <= 0.0:
            return _zero_tensor(self.actor)

        if batch is None:
            batch = self.buffer.sample(batch_size or self.batch_size)
        obs = _get_obs(batch)
        weight = batch.get("weights")
        if weight is None:
            weight = batch.get("weight")
        reduction = "mean" if weight is None else "none"

        teacher_lp = batch.get("teacher_log_prob")
        if teacher_lp is not None:
            actions = batch.get("teacher_action", batch.get("action"))
            if self.log_prob_fn is not None:
                student_lp = self.log_prob_fn(self.actor, obs, actions)
            else:
                dist = self.student_distribution(obs)
                student_lp = dist.log_prob(actions)
            if student_lp.dim() > 1:
                student_lp = student_lp.sum(dim=-1)
            if teacher_lp.dim() > 1:
                teacher_lp = teacher_lp.sum(dim=-1)
            per_state = kl_s_divergence(teacher_lp.detach(), student_lp)
            loss = _reduce(per_state, reduction, weight)
            return loss * self.coefficient

        if self.teacher is None:
            raise RuntimeError(
                "Kickstarting requires either a teacher policy or pre-computed "
                "teacher_log_prob entries in the online buffer"
            )
        if not hasattr(self.actor, "parameters") and not hasattr(self.actor, "__call__"):
            raise RuntimeError("actor must be callable or an nn.Module")

        student_dist = self.student_distribution(obs)
        if batch.get("teacher_output") is not None:
            teacher_dist = _apply_temperature(
                _find_distribution(batch["teacher_output"], obs=obs), self.temperature
            )
        else:
            teacher_dist = self._distribution(self.teacher, obs, teacher=True)

        loss = kickstarting_loss(
            student_dist,
            teacher_dist,
            direction=self.direction,
            use_exact_kl=self.use_exact_kl,
            reduction=reduction,
            weight=weight,
            actions=batch.get("teacher_action", batch.get("action")),
        )
        return loss * self.coefficient

    # Aliases matching the naming used across the code base.
    penalty_loss = penalty
    loss = penalty
    auxiliary_loss = penalty

    def __call__(self, batch: Optional[Mapping[str, Any]] = None,
                 batch_size: Optional[int] = None) -> Any:
        return self.penalty(batch, batch_size)

    # For convenience when a runner only keeps the auxiliary objects around.
    def done_adjusting(self) -> None:  # pragma: no cover - API parity with BC
        """No-op kept for API parity: KS decay is applied every train step."""
        return None

    # -- persistence ------------------------------------------------------
    def state_dict(self) -> Dict[str, Any]:
        return {
            "coef": self.coef,
            "direction": self.direction,
            "batch_size": self.batch_size,
            "schedule": self.schedule.state_dict(),
            "backend": self._schedule_backend,
        }

    def load_state_dict(self, state: Mapping[str, Any]) -> None:
        if not state:
            return
        self.coef = float(state.get("coef", self.coef))
        self.direction = state.get("direction", self.direction)
        self.batch_size = int(state.get("batch_size", self.batch_size))
        if state.get("schedule"):
            self.schedule.load_state_dict(state["schedule"])

    def extra_repr(self) -> str:
        return (
            f"name={self.name}, coef={self.coef}, coefficient={self.coefficient:.6g}, "
            f"decay={getattr(self.schedule, 'decay', None)}, direction={self.direction}, "
            f"batch_size={self.batch_size}, buffer={len(self.buffer)}"
        )

    def __repr__(self) -> str:  # pragma: no cover - cosmetic
        return f"Kickstarting({self.extra_repr()})"


