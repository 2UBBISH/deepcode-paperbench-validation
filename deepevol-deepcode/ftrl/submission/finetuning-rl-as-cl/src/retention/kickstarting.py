# ---------------------------------------------------------------------------
# Functional objective
# ---------------------------------------------------------------------------
def kickstarting_loss(
    student_dist: Any,
    teacher_dist: Any = None,
    direction: str = "reverse",
    use_exact_kl: bool = True,
    reduction: str = "mean",
    weight: Any = None,
    student_log_prob: Any = None,
    teacher_log_prob: Any = None,
    actions: Any = None,
) -> Any:
    """Unscaled ``E_{s ~ B_theta}[ D_KL^s ]`` for kickstarting.

    The paper's KS loss uses ``D_KL^s(pi_* || pi_theta)`` (Appendix C.2), i.e.
    actions are drawn from the **teacher**; this corresponds to
    ``direction="reverse"``.  Either

    * both distributions are given (analytic ``torch.distributions.kl_divergence``
      when available, otherwise Monte-Carlo with teacher-sampled actions), or
    * pre-computed log-probabilities of teacher-sampled actions are given, in
      which case the exact per-state estimate ``log pi_* - log pi_theta`` is
      used (gradients flow through the student term only).
    """
    if torch is None:  # pragma: no cover
        raise RuntimeError("torch is required to compute the kickstarting loss")

    if student_log_prob is not None and teacher_log_prob is not None:
        per_state = kl_s_divergence(teacher_log_prob.detach(), student_log_prob)
        return _reduce(per_state, reduction, weight)

    if teacher_dist is None:
        raise ValueError("kickstarting_loss requires either teacher_dist or teacher_log_prob")

    # For the reverse direction the teacher is the sampling distribution.
    sample_dist = teacher_dist if direction == "reverse" else student_dist
    if user_actions_needed := (actions is None):
        try:
            actions = sample_dist.sample()
        except Exception:  # pragma: no cover - exotic distributions
            pass
    del user_actions_needed

    if use_exact_kl:
        try:
            kl = torch.distributions.kl_divergence(teacher_dist, student_dist)
            if kl.dim() > 1:
                kl = kl.sum(dim=-1)
            return _reduce(kl, reduction, weight)
        except (NotImplementedError, AttributeError, TypeError):  # pragma: no cover
            pass

    teacher_lp = teacher_dist.log_prob(actions)
    student_lp = student_dist.log_prob(actions)
    if student_lp.dim() > 1:
        student_lp = student_lp.sum(dim=-1)
        teacher_lp = teacher_lp.sum(dim=-1)
    per_state = kl_s_divergence(teacher_lp.detach(), student_lp)
    return _reduce(per_state, reduction, weight)


