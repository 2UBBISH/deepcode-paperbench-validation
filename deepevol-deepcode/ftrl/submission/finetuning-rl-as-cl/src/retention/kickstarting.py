def freeze_teacher(module: Any, device: Optional[Any] = None) -> Any:
    """Put the teacher in eval mode and disable its gradients."""
    if module is None:
        return module
    if hasattr(module, "eval"):
        module.eval()
    if hasattr(module, "parameters"):
        for p in module.parameters():
            p.requires_grad_(False)
    if device is not None and hasattr(module, "to"):
        try:
            module.to(device)
        except Exception:  # pragma: no cover - already on device
            pass
    return module


def _cfg_getter(cfg: Any) -> Callable[[str, Any], Any]:
    if cfg is None:
        return lambda key, default=None: default
    if hasattr(cfg, "get"):
        return lambda key, default=None: cfg.get(key, default)
    return lambda key, default=None: getattr(cfg, key, default)


def _apply_temperature(dist: Any, temperature: float) -> Any:
    """Rescale an (unwrapped) distribution or logits by ``1/T``."""
    if temperature == 1.0:
        return dist
    try:
        from torch.distributions import Categorical

        if isinstance(dist, Categorical):
            logits = dist.logits / max(temperature, 1e-8)
            return Categorical(logits=logits)
    except Exception:  # pragma: no cover
        return dist
    return dist


def _get_obs(batch: Mapping[str, Any]) -> Any:
    for key in ("obs", "observations", "states", "state"):
        if isinstance(batch, Mapping) and batch.get(key) is not None:
            return batch[key]
    raise KeyError("batch does not contain observations under 'obs'/'states'")


def _reduce(per_sample: Any, reduction: str, weight: Any = None) -> Any:
    if reduction == "none":
        return per_sample
    if weight is not None:
        if isinstance(weight, (int, float)):
            norm = weight if reduction == "mean" else 1.0
            return (per_sample * float(weight)).sum() / max(float(norm), 1e-8)
        weight = weight.to(per_sample.device).float().reshape(-1)
        if weight.shape[0] != per_sample.shape[0]:  # pragma: no cover - broadcast
            weight = weight.expand_as(per_sample)
        weighted = per_sample.reshape(-1) * weight
        denom = weight.sum().clamp_min(1e-8)
        return weighted.sum() / denom
    if reduction == "sum":
        return per_sample.sum()
    return per_sample.mean()


def _to_tensor(value: Any) -> Any:
    if value is None or torch is None:
        return value
    if isinstance(value, torch.Tensor):
        return value.detach()
    try:
        return torch.as_tensor(value)
    except Exception:  # pragma: no cover - non-numeric payloads
        return value


def _concat(store: Sequence[Any]) -> Any:
    items = [x for x in store if x is not None]
    if not items:
        return torch.zeros(0) if torch is not None else None
    if len(items) == 1:
        return items[0]
    try:
        return torch.cat([x.reshape(-1, *x.shape[1:]) for x in items], dim=0)
    except Exception:  # pragma: no cover - mismatched shapes
        return items


def _lead_dim(value: Any) -> int:
    if torch is not None and isinstance(value, torch.Tensor):
        return int(value.shape[0]) if value.dim() > 0 else 1
    shape = getattr(value, "shape", None)
    if shape:
        return int(shape[0])
    try:
        return len(value)  # type: ignore[arg-type]
    except TypeError:  # pragma: no cover
        return 1


def _zeros_like(value: Any) -> Any:
    if torch is not None and isinstance(value, torch.Tensor):
        return torch.zeros(_lead_dim(value), dtype=torch.bool)
    return torch.zeros(_lead_dim(value))  # pragma: no cover


def _constant_like(value: Any, constant: float) -> Any:
    n = _lead_dim(value)
    if torch is None:  # pragma: no cover
        return [constant] * n
    dtype = torch.float32
    return torch.full((n,), float(constant), dtype=dtype)


def _move(value: Any, device: Optional[Any]) -> Any:
    if device is None or torch is None or not isinstance(value, torch.Tensor):
        return value
    return value.to(device)


def _zero_tensor(actor: Any) -> Any:
    """A differentiable-by-construction zero scalar (keeps ``.backward()`` valid)."""
    if torch is None:  # pragma: no cover
        return 0.0
    params = list(actor.parameters()) if hasattr(actor, "parameters") else []
    if params:
        return params[0].sum() * 0.0
    return torch.zeros((), requires_grad=True)


