# ---------------------------------------------------------------------------
# Per-environment constants (paper Appendix B.1 / Section 3)
# ---------------------------------------------------------------------------
# NetHack: scale 0.5 with exponential decay 0.99998 applied every train step.
# The paper only reports KS for NetHack; other environments fall back to a
# constant coefficient of 1.0 (Montezuma/RoboticSequence use BC/EWC/EM).
DEFAULT_KS_COEF: Dict[str, float] = {
    "nethack": 0.5,
    "montezuma": 1.0,
    "robotic_sequence": 1.0,
    "metaworld": 1.0,
}

DEFAULT_KS_DECAY: Dict[str, Optional[float]] = {
    "nethack": 0.99998,
    "montezuma": None,
    "robotic_sequence": None,
    "metaworld": None,
}


def _normalise_env_name(env_name: str) -> str:
    name = str(env_name or "").strip().lower().replace("-", "_").replace(" ", "_")
    if "nethack" in name or name in ("nle", "nld"):
        return "nethack"
    if "montezuma" in name:
        return "montezuma"
    if "robot" in name or "meta" in name:
        return "robotic_sequence"
    return name


def ks_coef_for(env_name: str) -> float:
    """The paper's kickstarting scale for a given environment (NetHack: 0.5)."""
    return float(DEFAULT_KS_COEF.get(_normalise_env_name(env_name), 1.0))


def ks_decay_for(env_name: str) -> Optional[float]:
    """Per-step exponential decay for kickstarting (NetHack: 0.99998)."""
    return DEFAULT_KS_DECAY.get(_normalise_env_name(env_name), None)


def ks_config_for(env_name: str) -> Dict[str, Any]:
    """Kickstarting keyword arguments for a given environment (Appendix B.1)."""
    env = _normalise_env_name(env_name)
    return {
        "coef": ks_coef_for(env),
        "decay": ks_decay_for(env),
        "decay_type": "exponential" if ks_decay_for(env) is not None else "none",
        "min_coef": 0.0,
    }


