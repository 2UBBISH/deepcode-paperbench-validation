class CoefficientSchedule:
    """Multiplicative schedule for an auxiliary-loss coefficient.

    The paper's NetHack Kickstarting run "scaled the loss by a factor of 0.5 and used
    exponential decay 0.99998, where the coefficient was decayed every train step"
    (Appendix B.1); BC uses *no decay* in NetHack.  This class covers both cases::

        CoefficientSchedule(kind="none", value=2.0)                 # BC (NetHack)
        CoefficientSchedule(kind="exponential", value=0.99998, start=0.5, per_step=True)

    Parameters
    ----------
    kind : {"none", "constant", "exponential", "linear", "inverse", "cosine"}
        ``"none"``/``"constant"`` keep the coefficient fixed.
    value : float
        For ``"exponential"`` this is the per-unit *decay factor* (e.g. ``0.99998``);
        for the other kinds it is simply the coefficient.
    start : float, optional
        Initial coefficient (defaults to ``value`` for non-exponential kinds and to
        ``1.0`` for exponential decay, i.e. the decay multiplies ``start``).
    decay_steps : int, optional
        Total number of steps for ``"linear"``/``"cosine"`` (required for those kinds).
    min_value : float
        Lower bound on the coefficient (default 0.0, i.e. no auxiliary loss).
    per_step : bool
        If True the decay is applied on every call to :meth:`step` (the paper decays the
        KS coefficient every train step); otherwise the *caller* passes env-step counts.
    """

    def __init__(
        self,
        kind: str = "none",
        value: float = 1.0,
        start: Optional[float] = None,
        decay_steps: Optional[int] = None,
        min_value: float = 0.0,
        per_step: bool = True,
    ) -> None:
        kind = str(kind).lower()
        if kind in ("constant", "fixed", "off"):
            kind = "none"
        if kind not in ("none", "exponential", "linear", "inverse", "cosine"):
            raise ValueError(f"Unsupported schedule kind: {kind!r}")
        self.kind = kind
        self.value = float(value)
        self.decay_steps = int(decay_steps) if decay_steps else None
        self.min_value = float(min_value)
        self.per_step = bool(per_step)
        if start is not None:
            self.base = float(start)
        elif kind == "exponential":
            self.base = 1.0  # `value` is the per-step factor
        else:
            self.base = float(value)
        self.step_count = 0

    # -- API ---------------------------------------------------------------------------
    @property
    def factor(self) -> float:
        """Current multiplicative factor (1.0 for ``kind='none'``)."""
        if self.kind == "none":
            return 1.0
        n = self.step_count
        if self.kind == "exponential":
            f = self.value ** n
        elif self.kind == "linear":
            if not self.decay_steps:
                return 1.0
            f = max(0.0, 1.0 - n / float(self.decay_steps))
        elif self.kind == "inverse":
            f = 1.0 / (1.0 + self.value * n)
        else:  # cosine
            if not self.decay_steps:
                return 1.0
            f = 0.5 * (1.0 + math.cos(math.pi * min(1.0, n / float(self.decay_steps))))
        return f

    def value_at(self, step: int) -> float:
        """Coefficient value at an explicit step counter."""
        saved, self.step_count = self.step_count, int(step)
        try:
            return max(self.min_value, self.base * self.factor)
        finally:
            self.step_count = saved

    @property
    def coefficient(self) -> float:
        """Current (decayed) coefficient value."""
        return max(self.min_value, self.base * self.factor)

    def step(self, n: int = 1) -> float:
        """Advance the schedule by ``n`` units and return the new coefficient."""
        self.step_count += int(n)
        return self.coefficient

    def reset(self) -> None:
        self.step_count = 0

    def state_dict(self) -> Dict[str, Any]:
        return {
            "kind": self.kind,
            "value": self.value,
            "base": self.base,
            "min_value": self.min_value,
            "decay_steps": self.decay_steps,
            "per_step": self.per_step,
            "step_count": self.step_count,
        }

    def load_state_dict(self, state: Mapping[str, Any]) -> "CoefficientSchedule":
        for key in ("kind", "value", "base", "min_value", "decay_steps", "per_step", "step_count"):
            if key in state and state[key] is not None:
                setattr(self, key, state[key])
        self.value = float(self.value)
        self.base = float(self.base)
        self.min_value = float(self.min_value)
        self.step_count = int(self.step_count)
        return self

    def configure(self, cfg: Any) -> "CoefficientSchedule":
        """Update from a config mapping / object (keys: kind, value, start, ...)."""
        get = cfg.get if hasattr(cfg, "get") else lambda k, d=None: getattr(cfg, k, d)
        kind = get("kind", get("schedule", self.kind))
        value = get("value", get("decay", self.value))
        start = get("start", get("initial", None))
        decay_steps = get("decay_steps", get("steps", self.decay_steps))
        min_value = get("min_value", get("floor", self.min_value))
        per_step = get("per_step", self.per_step)
        self.__init__(kind=kind, value=value, start=start, decay_steps=decay_steps,
                      min_value=min_value, per_step=per_step)
        return self

    def __repr__(self) -> str:  # pragma: no cover - cosmetic
        return (f"CoefficientSchedule(kind={self.kind!r}, value={self.value}, base={self.base}, "
                f"step={self.step_count}, coef={self.coefficient:.6g})")


