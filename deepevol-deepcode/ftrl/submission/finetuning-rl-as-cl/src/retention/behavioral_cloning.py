def kl_s_divergence(p_log_prob: Any, q_log_prob: Any) -> Any:
    """Per-state ``D_KL^s(p || q)`` from sampled log-probabilities.

    Appendix C.2: ``D_KL^s(p||q) = E_{a ~ p(.|s)}[ log p(a|s) - log q(a|s) ]``.
    This is the plain difference estimator; it is unbiased for the divergence itself
    (the sample mean over states), and equals 0 exactly when ``p == q``.
    """
    return (p_log_prob - q_log_prob)


def sampled_kl(
    student_dist: Any,
    teacher_dist: Any,
    direction: str = "forward",
    actions: Any = None,
    reparameterize: bool = True,
) -> Any:
    """Monte-Carlo estimate of ``D_KL^s`` between two action distributions.

    ``direction="forward"`` = ``KL(student || teacher)`` (Appendix C.2 eq. 1) where the
    expectation is taken over actions from the *student*; ``direction="reverse"`` =
    ``KL(teacher || student)`` (the ordering written in Section 2), sampling from the
    teacher.  ``actions`` may supply the sampled actions explicitly (e.g. expert actions
    stored in the buffer), in which case no sampling is performed.

    If ``reparameterize`` is True and the sampled distribution supports ``rsample`` the
    gradient is a reparameterized estimate of the KL gradient; otherwise the sample is
    treated as constant (score-function estimate of ``E_p[log p - log q]``, i.e. the
    gradient of the negative entropy term, still a valid descent direction and exactly
    zero when the two distributions coincide).
    """
    if str(direction).lower() in ("reverse", "teacher_student", "backward", "t_s"):
        src, dst, sign = teacher_dist, student_dist, -1.0
    else:
        src, dst, sign = student_dist, teacher_dist, 1.0

    if actions is None:
        if reparameterize and hasattr(src, "rsample"):
            actions = src.rsample()
        else:
            actions = src.sample()
        actions = actions.detach() if not (reparameterize and hasattr(src, "rsample")) else actions

    log_src = src.log_prob(actions)
    log_dst = dst.log_prob(actions)
    return sign * (log_src - log_dst)


def _exact_kl(student_dist: Any, teacher_dist: Any, direction: str) -> Any:
    """Analytic ``torch.distributions.kl_divergence`` when available, else ``None``."""
    if torch is None:
        return None
    fn = getattr(getattr(torch, "distributions", None), "kl_divergence", None)
    if fn is None:
        return None
    p, q = (student_dist, teacher_dist)
    if str(direction).lower() in ("reverse", "teacher_student", "backward", "t_s"):
        p, q = q, p
    try:
        return fn(p, q)
    except Exception:
        try:  # some distributions only support one direction
            return fn(q, p)
        except Exception:
            return None


def bc_loss(
    student_dist: Any,
    teacher_dist: Any,
    direction: str = "forward",
    actions: Any = None,
    use_exact_kl: bool = True,
    reduction: str = "mean",
    weight: Any = None,
) -> Any:
    """Per-batch behavioral-cloning divergence ``E_{s ~ B}[ D_KL^s(...) ]``.

    The result is the *unscaled* auxiliary loss; the coefficient (NetHack 2.0, Meta-World
    1.0) is applied by :class:`BehavioralCloning`.

    ``reduction`` is applied over the batch of states: ``"mean"`` (paper's expectation),
    ``"sum"`` or ``"none"`` (per-state values).
    """
    if torch is None:
        raise RuntimeError("bc_loss requires PyTorch to be installed")

    value = None
    if use_exact_kl and actions is None:
        value = _exact_kl(student_dist, teacher_dist, direction)
        if value is not None:
            value = value.reshape(value.shape[0] if value.dim() else 1)

    if value is None:
        value = sampled_kl(student_dist, teacher_dist, direction=direction, actions=actions)
        if value.dim() > 1:
            value = value.sum(dim=-1)

    value = value.reshape(-1)
    if weight is not None:
        w = torch.as_tensor(weight).reshape(-1).to(value.device).float()
        if reduction == "mean" and w.numel() == value.numel():
            denom = w.sum().clamp(min=1e-8)
            value = (value * w).sum() / denom
        else:
            value = value * w
            if reduction == "sum":
                value = value.sum()
            elif reduction == "mean":
                value = value.mean()
        return value

    if reduction == "mean":
        return value.mean()
    if reduction == "sum":
        return value.sum()
    if reduction == "none":
        return value
    raise ValueError(f"Unknown reduction: {reduction!r}")


