"""Behavioral cloning (BC / replay-by-distillation) knowledge-retention loss.

Paper specification
-------------------
Section 2 (Knowledge retention):

    "We implement BC in the following way. Before the training, we gather a subset
     of states S_BC on which the pre-trained model pi_* was trained, and we construct
     a buffer B_BC := {(s, pi_*(s)) : s in S_BC}. ... we apply an auxiliary loss of the
     form L_BC(theta) = E_{s ~ B_BC}[ D_KL( pi_*(s) || pi_theta(s) ) ] alongside the RL
     objective."

Appendix C.2 (Distillation-based methods) gives the precise definition of the
per-state KL divergence::

    D_KL^s(p || q) = E_{a ~ p(.|s)}[ log( p(a|s) / q(a|s) ) ]

and the BC loss used in this work::

    L_BC(theta) = E_{s ~ B}[ D_KL^s( pi_theta || pi_* ) ]        (Appendix, eq. 1)

where B is a buffer of data containing states from pre-training.  Note the two
directions (Section 2 writes ``pi_* || pi_theta`` while Appendix C.2 writes
``pi_theta || pi_*``); both are supported through the ``direction`` argument, the
default follows the Appendix equation because it is the one stated verbatim with the
KL definition (``forward`` = KL(student || teacher)).

Appendix B.1 (NetHack) — hyperparameters::

    "In Fine-tuning + BC we compute the auxiliary loss by utilizing the trajectories
     generated by the expert (i.e. the AutoAscend algorithm), note that no decay was
     used here. We scaled the auxiliary loss by a factor of 2.0."

Appendix B.3 (Meta-World) — Table 3 lists ``BC: actor reg. coef. = 1,
critic reg. coef. = 0, memory = 10000``; following (Wolczyk et al., 2022) the critic is
never regularized.

Consequences implemented here
-----------------------------
* The loss is *actor-only*; the critic coefficient is always 0.
* The expectation is over a buffer of **pre-training states** (not online data; the
  online-data variant is Kickstarting, see :mod:`src.retention.kickstarting`).
* The coefficient supports an optional decay schedule (none for BC, per the paper),
  and NetHack uses scale 2.0 in the main experiments.
* The teacher ``pi_*`` is a frozen copy of the pre-trained policy.  Where a teacher
  distribution has been pre-computed (e.g. stored alongside the states in the buffer)
  it is used directly, which lets BC be evaluated without keeping the teacher in
  memory.

Also provided here: :class:`BCBuffer`, a replay buffer of ``(state, teacher output)``
pairs (used by NetHack with NLD-AA states, by Meta-World with 10k states from the
pre-trained stages and by Montezuma with 500 cloned trajectories from Room 7 onward),
plus :class:`CoefficientSchedule`, the shared per-train-step decay used by both BC and
Kickstarting (NetHack KS: 0.5 with exponential decay 0.99998 per train step).
"""

