def _attr_or_key(obj: Any, names: Sequence[str]) -> Any:
    """Return the first present attribute/key from ``names`` (``None`` if absent)."""
    if obj is None:
        return None
    for name in names:
        if isinstance(obj, Mapping):
            if name in obj:
                return obj[name]
        elif hasattr(obj, name):
            value = getattr(obj, name)
            if value is not None:
                return value
    return None


def _is_distribution(obj: Any) -> bool:
    return obj is not None and hasattr(obj, "log_prob")


def _find_distribution(out: Any) -> Any:
    """Locate a torch distribution in an arbitrary model output."""
    if _is_distribution(out):
        return out
    dist = _attr_or_key(out, _DIST_KEYS)
    if _is_distribution(dist):
        return dist
    # Sample-Factory style ModelOutput / namedtuples expose ``.action_distribution``
    if isinstance(out, (tuple, list)):
        for item in out:
            dist = _find_distribution(item)
            if dist is not None:
                return dist
    return None


def _find_logits(out: Any) -> Any:
    """Locate policy logits (or distribution parameters) in an arbitrary output."""
    logits = _attr_or_key(out, _LOGITS_KEYS)
    if logits is not None:
        return logits
    if isinstance(out, (tuple, list)):
        for item in out:
            logits = _find_logits(item)
            if logits is not None:
                return logits
    return None


def _to_tensor(value: Any, device: Any = None) -> Any:
    if isinstance(value, (tuple, list)):
        return type(value)(_to_tensor(v, device) for v in value)
    if isinstance(value, Mapping):
        return {k: _to_tensor(v, device) for k, v in value.items()}
    if torch is not None and not isinstance(value, Tensor):
        value = torch.as_tensor(value)
    if torch is not None and device is not None and isinstance(value, Tensor):
        value = value.to(device)
    return value


def freeze_teacher(module: Any, device: Any = None) -> Any:
    """Put ``module`` in eval mode with gradients disabled (teacher ``pi_*``)."""
    if module is None:
        return module
    if hasattr(module, "eval"):
        module.eval()
    for p in getattr(module, "parameters", lambda: [])():
        p.requires_grad_(False)
    if device is not None and hasattr(module, "to"):
        module.to(device)
    return module


