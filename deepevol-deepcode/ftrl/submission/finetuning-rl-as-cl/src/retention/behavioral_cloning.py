def _stack(items: Sequence[Any]) -> Any:
    """Stack a list of observations into a batch (fallback to a list of tensors)."""
    if torch is None or not items:
        return items
    first = items[0]
    if isinstance(first, Mapping):
        return {k: _stack([it[k] for it in items]) for k in first}
    if isinstance(first, (tuple, list)):
        return tuple(_stack([it[i] for it in items]) for i in range(len(first)))
    if isinstance(first, Tensor):
        try:
            return torch.stack(items, dim=0)
        except Exception:
            return list(items)
    try:
        return torch.as_tensor(items)
    except Exception:
        return list(items)


class BCBuffer:
    """Buffer ``B_BC = {(s, pi_*(s)) : s in S_BC}`` of pre-training states.

    Stores states collected while the pre-trained policy ``pi_*`` was trained (Appendix
    Section 2 / B.1) together with the teacher's actions and/or action distributions.
    Following Appendix B.3 / Table 3 the Meta-World buffer holds 10000 samples, and 10%
    of SAC's 100k replay buffer is reserved for prior-stage data in the episodic-memory
    variant (see :mod:`src.retention.episodic_memory`).

    Teacher outputs are optional: if ``teacher`` is available at loss time the buffer only
    needs states, but pre-computing ``pi_*(s)`` (``store_teacher=True`` or an explicit
    :meth:`precompute`) removes the need to keep the teacher model in memory.
    """

    def __init__(
        self,
        capacity: Optional[int] = None,
        store_teacher: bool = False,
        device: Any = None,
        seed: Optional[int] = None,
    ) -> None:
        self.capacity = int(capacity) if capacity else None
        self.store_teacher = bool(store_teacher)
        self.device = device
        self._gen = None
        if torch is not None:
            self._gen = torch.Generator(device="cpu")
            if seed is not None:
                self._gen.manual_seed(int(seed))
        self.states: List[Any] = []
        self.actions: List[Any] = []
        self.teacher_outputs: List[Any] = []
        self.weights: List[float] = []
        self._cursor = 0

    # -- construction ------------------------------------------------------------------
    def add(
        self,
        obs: Any,
        actions: Any = None,
        teacher_output: Any = None,
        weight: Optional[float] = None,
    ) -> None:
        """Append one (or a batch of) transitions to the buffer."""
        obs = _to_tensor(obs, self.device)
        n = None
        if torch is not None and isinstance(obs, Tensor) and obs.dim() > 1:
            n = obs.shape[0]

        if n is None:
            self.states.append(obs)
            if actions is not None:
                self.actions.append(_to_tensor(actions, self.device))
            if teacher_output is not None:
                self.teacher_outputs.append(_to_tensor(teacher_output, self.device))
            self.weights.append(1.0 if weight is None else float(weight))
        else:
            for i in range(n):
                self.states.append(obs[i])
                if actions is not None:
                    a = _to_tensor(actions, self.device)
                    self.actions.append(a[i])
                if teacher_output is not None:
                    t = _to_tensor(teacher_output, self.device)
                    self.teacher_outputs.append(t[i] if (isinstance(t, Tensor) and t.shape[0] == n) else t)
                self.weights.append(1.0 if weight is None else float(weight))
        self._trim()

    def extend(self, transitions: Iterable[Any]) -> None:
        """Add an iterable of transitions (tuples or dicts)."""
        for item in transitions:
            if isinstance(item, Mapping):
                self.add(item.get("obs", item.get("state", item.get("states"))),
                         item.get("actions", item.get("action")),
                         item.get("teacher_output", item.get("teacher_logits")),
                         item.get("weight"))
            elif isinstance(item, (tuple, list)):
                if len(item) >= 3:
                    self.add(item[0], item[1], item[2])
                elif len(item) == 2:
                    self.add(item[0], item[1])
                else:
                    self.add(item[0])
            else:
                self.add(item)

    def _trim(self) -> None:
        if self.capacity is not None and len(self.states) > self.capacity:
            overflow = len(self.states) - self.capacity
            del self.states[:overflow]
            if self.actions:
                del self.actions[:overflow]
            if self.teacher_outputs:
                del self.teacher_outputs[:overflow]
            if self.weights:
                del self.weights[:overflow]

    # -- sampling ----------------------------------------------------------------------
    def __len__(self) -> int:
        return len(self.states)

    def sample(self, batch_size: int, generator: Any = None) -> Dict[str, Any]:
        """Uniformly sample a batch of pre-training states (and teacher outputs)."""
        if len(self.states) == 0:
            raise ValueError("BCBuffer is empty; collect pre-training states first")
        bs = min(int(batch_size), len(self.states))
        if torch is not None:
            gen = generator if generator is not None else self._gen
            idx = torch.randint(0, len(self.states), (bs,), generator=gen).tolist()
        else:  # pragma: no cover
            import random
            idx = [random.randrange(len(self.states)) for _ in range(bs)]
        batch: Dict[str, Any] = {"obs": _stack([self.states[i] for i in idx])}
        if self.actions:
            batch["actions"] = _stack([self.actions[i] for i in idx])
        if self.teacher_outputs:
            t = [self.teacher_outputs[i] for i in idx]
            batch["teacher_output"] = _stack(t) if all(x is not None for x in t) else t
        if self.weights:
            batch["weights"] = [self.weights[i] for i in idx]
        batch["indices"] = idx
        return batch

    def all_states(self) -> Any:
        return _stack(self.states)

    def clear(self) -> None:
        self.states.clear()
        self.actions.clear()
        self.teacher_outputs.clear()
        self.weights.clear()

    def state_dict(self) -> Dict[str, Any]:
        return {
            "states": [s.detach().cpu() if (torch is not None and isinstance(s, Tensor)) else s
                       for s in self.states],
            "actions": [a.detach().cpu() if (torch is not None and isinstance(a, Tensor)) else a
                        for a in self.actions],
            "capacity": self.capacity,
            "store_teacher": self.store_teacher,
        }

    def load_state_dict(self, state: Mapping[str, Any]) -> "BCBuffer":
        self.states = list(state.get("states", []))
        self.actions = list(state.get("actions", []))
        self.capacity = state.get("capacity", self.capacity)
        return self

    # -- teacher pre-computation -------------------------------------------------------
    def precompute(
        self,
        teacher: Any,
        batch_size: int = 128,
        forward_fn: Optional[Callable[[Any, Any], Any]] = None,
    ) -> "BCBuffer":
        """Fill ``teacher_outputs`` with ``pi_*(s)`` for all stored states."""
        if torch is None:
            raise RuntimeError("precompute requires PyTorch")
        if teacher is None:
            raise ValueError("precompute requires a teacher policy pi_*")
        out: List[Any] = []
        with torch.no_grad():
            for start in range(0, len(self.states), batch_size):
                chunk = _stack(self.states[start:start + batch_size])
                pred = forward_fn(teacher, chunk) if forward_fn else teacher(chunk)
                dist = _find_distribution(pred)
                if dist is not None:
                    item: Any = {"dist": dist}
                else:
                    logits = _find_logits(pred)
                    item = {"logits": logits if logits is not None else pred}
                if torch is not None and isinstance(item.get("logits", None), Tensor) and item["logits"].dim() > 1:
                    item = {"logits": item["logits"]}
                    for i in range(item["logits"].shape[0]):
                        out.append({"logits": item["logits"][i].detach().cpu()})
                else:
                    out.append({k: (v.detach().cpu() if isinstance(v, Tensor) else v)
                                for k, v in item.items()})
        self.teacher_outputs = out
        self.store_teacher = True
        return self


def build_bc_buffer(
    states: Iterable[Any],
    teacher: Any = None,
    actions: Any = None,
    capacity: Optional[int] = None,
    batch_size: int = 128,
    device: Any = None,
    seed: Optional[int] = None,
    forward_fn: Optional[Callable[[Any, Any], Any]] = None,
) -> BCBuffer:
    """Construct ``B_BC`` from an iterable of pre-training states.

    If ``teacher`` is given, ``pi_*(s)`` is evaluated (in eval mode, no gradients) and
    stored in the buffer.  ``actions`` may be the expert actions recorded in the dataset
    (e.g. NLD-AA for NetHack); they are only used when ``teacher`` is ``None`` or when a
    cross-entropy style objective is selected.
    """
    buffer = BCBuffer(capacity=capacity, store_teacher=teacher is not None,
                      device=device, seed=seed)
    states = list(states)
    if actions is not None:
        actions = list(actions)
        for i, s in enumerate(states):
            buffer.add(s, actions[i] if i < len(actions) else None)
    else:
        for s in states:
            buffer.add(s)
    if teacher is not None and len(buffer) > 0:
        buffer.precompute(freeze_teacher(teacher, device), batch_size=batch_size, forward_fn=forward_fn)
    return buffer


# --------------------------------------------------------------------------------------
# Behavioral cloning regularizer
# --------------------------------------------------------------------------------------

class BehavioralCloning:
    """Actor-only behavioral-cloning retention loss ``L_BC`` (Appendix C.2 eq. 1).

    The RL objective is modified additively::

        total_loss = rl_loss + bc.penalty_loss()

    with ``penalty_loss() = coef * E_{s ~ B_BC}[ D_KL^s(pi_theta || pi_*) ]``.

    Parameters
    ----------
    actor : nn.Module
        Current (fine-tuned) policy ``pi_theta``.
    teacher : nn.Module, optional
        Pre-trained policy ``pi_*``; frozen automatically.  May be ``None`` when the
        buffer stores teacher distributions (or when ``teacher_dist_fn`` is given).
    buffer : BCBuffer, optional
        Buffer of pre-training states (``B_BC``); can be attached later via
        :meth:`attach_buffer`.
    coef : float
        Loss scale.  NetHack: 2.0 (Appendix B.1).  Meta-World actor coef: 1 (Table 3).
    schedule / decay : optional
        Coefficient schedule; BC uses **no decay**, so by default the coefficient is
        constant.
    direction : {"forward", "reverse"}
        ``"forward"`` = ``KL(pi_theta || pi_*)`` (Appendix C.2, default);
        ``"reverse"`` = ``KL(pi_* || pi_theta)`` (the ordering written in Section 2).
    batch_size : int
        Mini-batch of pre-training states drawn from the buffer (NetHack NLD-AA batch
        size 128; Meta-World buffer 10000 samples).
    """

    def __init__(
        self,
        actor: Any,
        teacher: Any = None,
        buffer: Optional[BCBuffer] = None,
        coef: float = 1.0,
        schedule: Optional[CoefficientSchedule] = None,
        decay: Optional[Union[str, float]] = None,
        direction: str = "forward",
        batch_size: int = 128,
        use_exact_kl: bool = True,
        weight_decay: Optional[str] = None,
        temperature: float = 1.0,
        loss_type: str = "kl",
        log_prob_fn: Optional[Callable[[Any, Any], Any]] = None,
        forward_fn: Optional[Callable[[Any, Any], Any]] = None,
        device: Any = None,
        name: str = "bc",
    ) -> None:
        self.name = name
        self.actor = actor
        self.teacher = freeze_teacher(teacher, device) if teacher is not None else None
        self.buffer = buffer
        self.coef = float(coef)
        self.batch_size = int(batch_size)
        self.use_exact_kl = bool(use_exact_kl)
        self.direction = str(direction)
        self.loss_type = str(loss_type).lower()
        self.temperature = float(temperature)
        self.log_prob_fn = log_prob_fn
        self.forward_fn = forward_fn
        self.device = device
        self._teacher_dist_fn: Optional[Callable[[Any], Any]] = None
        if schedule is not None:
            self.schedule = schedule
        elif decay is None:
            self.schedule = CoefficientSchedule(kind="none", value=self.coef)
        elif isinstance(decay, (int, float)):
            self.schedule = CoefficientSchedule(kind="exponential", value=float(decay),
                                                start=self.coef, per_step=True)
        else:
            self.schedule = CoefficientSchedule(kind=str(decay), value=self.coef, start=self.coef)
        # running statistics for logging
        self.last_value: Optional[float] = None
        self.steps = 0

    # -- configuration -----------------------------------------------------------------
    @property
    def enabled(self) -> bool:
        """Whether the BC term contributes to the objective right now."""
        return self.coef > 0.0 and self.schedule.coefficient > 0.0 and self.buffer is not None

    @property
    def coefficient(self) -> float:
        """Current ``coef`` including the schedule multiplier."""
        return self.coef * self.schedule.coefficient

    def attach_buffer(self, buffer: BCBuffer) -> "BehavioralCloning":
        self.buffer = buffer
        return self

    set_buffer = attach_buffer

    def set_teacher_dist_fn(self, fn: Callable[[Any], Any]) -> "BehavioralCloning":
        """Provide a function returning the teacher distribution for a batch of states."""
        self._teacher_dist_fn = fn
        return self

    def configure(self, cfg: Any) -> "BehavioralCloning":
        """Update hyperparameters from a config mapping / object."""
        get = cfg.get if hasattr(cfg, "get") else lambda k, d=None: getattr(cfg, k, d)
        if get("coef", get("scale", get("coefficient", None))) is not None:
            self.coef = float(get("coef", get("scale", get("coefficient", self.coef))))
        for key, attr, cast in (
            ("batch_size", "batch_size", int),
            ("direction", "direction", str),
            ("loss_type", "loss_type", str),
            ("use_exact_kl", "use_exact_kl", bool),
            ("temperature", "temperature", float),
        ):
            value = get(key, None)
            if value is not None:
                setattr(self, attr, cast(value))
        decay = get("decay", None)
        kind = get("decay_type", get("schedule", None))
        if decay is not None:
            # NetHack BC: no decay.  KS keeps a per-step exponential factor.
            if isinstance(decay, dict) or (kind is not None and kind not in ("none", "constant")):
                self.schedule = CoefficientSchedule(**(decay if isinstance(decay, dict) else
                                                       {"kind": kind, "value": 1.0}))
            elif float(decay) < 1.0 and float(decay) > 0.0:
                self.schedule = CoefficientSchedule(kind="exponential", value=float(decay),
                                                    start=self.coef, per_step=True)
            else:
                self.schedule = CoefficientSchedule(kind="none", value=self.coef)
        return self

    def step(self, n: int = 1) -> float:
        """Advance the coefficient schedule (called once per train step)."""
        self.steps += int(n)
        self.schedule.step(n)
        return self.coefficient

    def done_adjusting(self) -> float:
        """Alias of :meth:`step` (``step`` name clashes conceptually with env steps)."""
        return self.step()

    # -- forward helpers ----------------------------------------------------------------
    def _forward(self, module: Any, obs: Any) -> Any:
        if module is None:
            return None
        fn = self.forward_fn
        if fn is not None:
            return fn(module, obs)
        return module(obs)

    def teacher_log_prob(self, obs: Any, actions: Any) -> Any:
        """``log pi_*(a|s)`` for the stored actions (teacher pre-computation path)."""
        if self.log_prob_fn is not None:
            return self.log_prob_fn(self.teacher, obs, actions)
        out = self._forward(self.teacher, obs)
        dist = _find_distribution(out)
        if dist is None:
            raise RuntimeError("Could not locate a distribution in the teacher output; "
                               "pass forward_fn/log_prob_fn")
        return dist.log_prob(actions)

    def _teacher_distribution(self, obs: Any, stored: Any = None) -> Any:
        """Teacher distribution for ``obs`` (rebuilt from stored outputs when possible)."""
        if stored is not None:
            if isinstance(stored, Mapping) and "dist" in stored and _is_distribution(stored["dist"]):
                return stored["dist"]
            logits = stored.get("logits") if isinstance(stored, Mapping) else stored
            if logits is not None and torch is not None and hasattr(torch, "distributions"):
                logits = _to_tensor(logits, self.device)
                if logits.dim() == 1:
                    logits = logits.unsqueeze(0)
                return torch.distributions.Categorical(logits=logits)
            if _is_distribution(stored):
                return stored
        if self._teacher_dist_fn is not None:
            return self._teacher_dist_fn(obs)
        out = self._forward(self.teacher, obs)
        dist = _find_distribution(out)
        if dist is not None:
            return dist
        logits = _find_logits(out)
        if logits is not None and torch is not None:
            return torch.distributions.Categorical(logits=logits)
        if _is_distribution(out):
            return out
        raise RuntimeError("Unable to obtain the teacher distribution; pass teacher, "
                           "teacher_dist_fn or store teacher outputs in the buffer")

    def _student_distribution(self, obs: Any) -> Any:
        out = self._forward(self.actor, obs)
        dist = _find_distribution(out)
        if dist is not None:
            return dist
        logits = _find_logits(out)
        if logits is not None and torch is not None:
            return torch.distributions.Categorical(logits=logits / self.temperature)
        if _is_distribution(out):
            return out
        raise RuntimeError("Unable to obtain the student distribution from the actor output")

    # -- loss --------------------------------------------------------------------------
    def penalty(self, batch: Optional[Mapping[str, Any]] = None,
                batch_size: Optional[int] = None) -> Any:
        """Unscaled ``E_{s ~ B_BC}[ D_KL^s ]`` for a mini-batch of pre-training states."""
        if torch is None:
            raise RuntimeError("BehavioralCloning requires PyTorch")
        if batch is None:
            if self.buffer is None:
                raise ValueError("No BC buffer attached and no batch provided")
            batch = self.buffer.sample(batch_size or self.batch_size)

        obs = batch.get("obs", batch.get("states"))
        obs = _to_tensor(obs, self.device)
        weights = batch.get("weights", None)

        student_dist = self._student_distribution(obs)
        teacher_dist = self._teacher_distribution(obs, batch.get("teacher_output", None))

        if teacher_dist is None:
            raise RuntimeError("No teacher distribution available for the BC loss")

        if self.loss_type in ("ce", "cross_entropy", "crossentropy"):
            actions = batch.get("actions", None)
            if actions is None:
                raise ValueError("loss_type='cross_entropy' requires actions in the batch")
            return -teacher_dist.log_prob(_to_tensor(actions, self.device)).reshape(-1).mean()

        return bc_loss(student_dist, teacher_dist, direction=self.direction,
                       actions=batch.get("actions", None), use_exact_kl=self.use_exact_kl,
                       reduction="mean", weight=weights)

    def penalty_loss(self, batch: Optional[Mapping[str, Any]] = None,
                     batch_size: Optional[int] = None) -> Any:
        """Scaled BC penalty ``coef * L_BC`` to be added to the RL objective."""
        value = self.penalty(batch=batch, batch_size=batch_size)
        self.last_value = float(value.detach()) if hasattr(value, "detach") else float(value)
        return value * self.coefficient

    # aliases
    loss = penalty_loss
    auxiliary_loss = penalty_loss

    def __call__(self, batch: Optional[Mapping[str, Any]] = None,
                 batch_size: Optional[int] = None) -> Any:
        return self.penalty_loss(batch=batch, batch_size=batch_size)

    # -- persistence -------------------------------------------------------------------
    def state_dict(self) -> Dict[str, Any]:
        return {
            "coef": self.coef,
            "batch_size": self.batch_size,
            "direction": self.direction,
            "loss_type": self.loss_type,
            "use_exact_kl": self.use_exact_kl,
            "schedule": self.schedule.state_dict(),
            "steps": self.steps,
            "buffer_size": len(self.buffer) if self.buffer is not None else 0,
        }

    def load_state_dict(self, state: Mapping[str, Any]) -> "BehavioralCloning":
        for key in ("coef", "batch_size", "direction", "loss_type", "use_exact_kl", "steps"):
            if key in state and state[key] is not None:
                setattr(self, key, state[key])
        if state.get("schedule"):
            self.schedule.load_state_dict(state["schedule"])
        return self

    def extra_repr(self) -> str:
        teacher = "frozen" if self.teacher is not None else "from-buffer"
        return (f"coef={self.coef}, schedule={self.schedule.kind}, "
                f"coef_now={self.coefficient:.6g}, direction={self.direction}, "
                f"batch_size={self.batch_size}, teacher={teacher}, "
                f"buffer={len(self.buffer) if self.buffer is not None else 0}")

    def __repr__(self) -> str:  # pragma: no cover - cosmetic
        return f"BehavioralCloning({self.extra_repr()})"


def bc_coef_for(env_name: str) -> float:
    """Paper's BC loss scale for an environment name.

    NetHack -> 2.0 (Appendix B.1), Meta-World / RoboticSequence -> 1 (Table 3),
    Montezuma -> 1.0 (weight tuned via the Figure 13 sweep; not stated in the paper).
    """
    key = str(env_name).lower().replace("-", "_").replace(" ", "_")
    if "nethack" in key or "nle" in key:
        return DEFAULT_BC_COEF["nethack"]
    if "montezuma" in key:
        return DEFAULT_BC_COEF["montezuma"]
    if "robot" in key or "meta" in key or "mw" in key:
        return DEFAULT_BC_COEF["robotic_sequence"]
    return 1.0
