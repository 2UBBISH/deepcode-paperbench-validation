# Backbone resolution (mirrors adapter/energy_model.py, kept local to avoid a hard import)
# --------------------------------------------------------------------------------------


def resolve_mlm_backbone(
    dataset: Optional[str] = None,
    size: Optional[str] = None,
    backbone: Optional[str] = None,
) -> str:
    """Resolve the MLM backbone checkpoint (explicit > size alias > per-dataset)."""
    if backbone:
        return backbone
    try:  # reuse the canonical maps from the energy adapter when available
        from ..adapter.energy_model import ADAPTER_BACKBONES, SIZE_BACKBONES

        key_size = str(size or "").lower().replace("-", "").replace("_", "")
        if key_size and key_size in SIZE_BACKBONES:
            return SIZE_BACKBONES[key_size]
        key_ds = str(dataset or "").lower().replace("-", "").replace("_", "")
        if key_ds in ADAPTER_BACKBONES:
            return ADAPTER_BACKBONES[key_ds]
    except Exception:  # pragma: no cover - optional import
        pass
    if str(size or "").lower().replace("-", "").replace("_", "") in {"0.3b", "304m", "large"}:
        return "microsoft/deberta-v3-large"
    return "microsoft/deberta-v3-base"


def _hf_classes():
    """Lazily import transformers helpers (heavy dependency)."""
    try:
        from transformers import AutoModelForMaskedLM, AutoTokenizer
    except Exception as exc:  # pragma: no cover - dependency guard
        raise ImportError(
            "The MLM ablation requires `transformers`. Install with "
            "`pip install transformers` (see requirements.txt)."
        ) from exc
    return AutoModelForMaskedLM, AutoTokenizer


# --------------------------------------------------------------------------------------
# Word-level text utilities (§4.5: "generate text chunks ... randomly masking words")
# --------------------------------------------------------------------------------------


def word_spans(text: str) -> List[Tuple[int, int]]:
    """Character spans of whitespace-delimited words (including attached punctuation)."""
    spans: List[Tuple[int, int]] = []
    start = None
    for i, ch in enumerate(text):
        if ch.isspace():
            if start is not None:
                spans.append((start, i))
                start = None
        elif start is None:
            start = i
    if start is not None:
        spans.append((start, len(text)))
    return spans


def split_text_chunks(text: str, max_words: int = 128) -> List[str]:
    """Split a text into word chunks (used to build the ground-truth training chunks)."""
    words = text.split()
    if max_words <= 0 or len(words) <= max_words:
        return [text] if text.strip() else []
    return [" ".join(words[i : i + max_words]) for i in range(0, len(words), max_words)]


def select_mask_word_indices(
    word_ids: Sequence[Optional[int]],
    *,
    mask_prob: float = 0.15,
    max_masks: int = 5,
    rng: Optional[random.Random] = None,
    forced_word: Optional[int] = None,
) -> List[int]:
    """Choose token positions to mask, operating on *words* rather than tokens.

    ``word_ids`` maps each token position to a word id (``None`` for special tokens),
    exactly what a fast tokenizer's ``word_ids()`` returns.
    """
    rng = rng or random.Random()
    groups: Dict[int, List[int]] = {}
    for pos, wid in enumerate(word_ids):
        if wid is None:
            continue
        groups.setdefault(int(wid), []).append(pos)
    n_words = len(groups)
    if n_words == 0:
        return []
    if forced_word is not None:
        return list(groups.get(int(forced_word), []))
    n_mask = max(1, int(math.ceil(mask_prob * n_words)))
    n_mask = min(n_mask, max_masks, n_words)
    chosen = rng.sample(sorted(groups.keys()), n_mask)
    positions: List[int] = []
    for wid in chosen:
        positions.extend(groups[wid])
    return sorted(positions)


def _special_token_positions(tokenizer: Any, input_ids: Sequence[int]) -> List[int]:
    """Best-effort identification of special tokens in ``input_ids``."""
    try:
        mask = tokenizer.get_special_tokens_mask(list(input_ids), already_has_special_tokens=True)
        return [i for i, m in enumerate(mask) if m]
    except Exception:
        specials = set(getattr(tokenizer, "all_special_ids", []) or [])
        return [i for i, tid in enumerate(input_ids) if tid in specials]


def _word_ids(tokenizer: Any, text: str) -> Tuple[List[int], List[Optional[int]]]:
    """Tokenize ``text`` and return ``(token_ids, word_ids)`` without special tokens."""
    enc = tokenizer(text, add_special_tokens=False, truncation=False)["input_ids"]
    ids = list(enc) if not (enc and isinstance(enc[0], list)) else list(enc[0])
    wid: List[Optional[int]] = list(range(len(ids)))
    return ids, wid


# --------------------------------------------------------------------------------------
# Masked-token probability and loss
# --------------------------------------------------------------------------------------


def compute_mlm_loss(
    logits: torch.Tensor,
    labels: torch.Tensor,
    attention_mask: Optional[torch.Tensor] = None,
    *,
    reduction: str = "mean",
    ignore_index: int = -100,
    label_smoothing: float = 0.0,
) -> torch.Tensor:
    """Masked-token cross entropy.

    Args:
        logits: ``[B, L, V]`` LM head outputs.
        labels: ``[B, L]`` target ids with ``ignore_index`` at unmasked positions.
        attention_mask: optional ``[B, L]`` mask (unused positions must already be
            ``ignore_index`` in ``labels``; the mask only guards against garbage).
    """
    if labels is None:
        raise ValueError("labels are required for the MLM loss")
    if attention_mask is not None:
        labels = labels.masked_fill(attention_mask == 0, ignore_index)
    vocab = logits.shape[-1]
    loss = F.cross_entropy(
        logits.reshape(-1, vocab),
        labels.reshape(-1),
        ignore_index=ignore_index,
        reduction=reduction,
        label_smoothing=float(label_smoothing),
    )
    return loss


def mlm_objective(
    logits: torch.Tensor,
    labels: torch.Tensor,
    attention_mask: Optional[torch.Tensor] = None,
    **kwargs: Any,
) -> torch.Tensor:
    """Alias of :func:`compute_mlm_loss` (paper-facing name)."""
    return compute_mlm_loss(logits, labels, attention_mask, **kwargs)


def masked_word_log_prob(
    logits: torch.Tensor,
    labels: torch.Tensor,
    mask_positions: Optional[torch.Tensor] = None,
    *,
    ignore_index: int = -100,
) -> Tuple[torch.Tensor, torch.Tensor]:
    """Log-probability of the *true* masked word.

    Returns ``(log_probs, counts)`` where ``log_probs`` is ``[B]`` (sum over the masked
    positions of each sequence) and ``counts`` is ``[B]`` (number of masked positions).
    """
    log_probs = F.log_softmax(logits.float(), dim=-1)  # [B, L, V]
    if mask_positions is None:
        mask_positions = labels != ignore_index
    else:
        mask_positions = mask_positions.bool()
    safe_labels = labels.clamp(min=0)
    gathered = log_probs.gather(-1, safe_labels.unsqueeze(-1)).squeeze(-1)  # [B, L]
    gathered = gathered * mask_positions.to(gathered.dtype)
    return gathered.sum(dim=-1), mask_positions.sum(dim=-1).to(gathered.dtype)


def masked_word_probability(
    logits: torch.Tensor,
    labels: torch.Tensor,
    mask_positions: Optional[torch.Tensor] = None,
    *,
    ignore_index: int = -100,
    reduction: str = "mean",
) -> torch.Tensor:
    """Probability ``p(true masked word)`` averaged over masked positions.

    This is the inference-time scoring quantity of §4.5 ("scoring the sequence based on
    the probability of the masked word").
    """
    log_p, counts = masked_word_log_prob(logits, labels, mask_positions, ignore_index=ignore_index)
    probs = torch.exp(log_p)
    if reduction == "none":
        return probs
    if reduction == "sum":
        return probs.sum()
    denom = counts.clamp(min=1.0)
    return (probs / denom).mean()


def sentence_masked_word_score(
    logits: torch.Tensor,
    labels: torch.Tensor,
    mask_positions: Optional[torch.Tensor] = None,
    *,
    mode: str = "logprob",
    reduction: str = "mean",
    ignore_index: int = -100,
) -> torch.Tensor:
    """Per-sequence score used to rank beam-search candidates with the MLM ablation.

    Higher is better (log-probability or probability of the masked word).
    """
    log_p, counts = masked_word_log_prob(logits, labels, mask_positions, ignore_index=ignore_index)
    if mode == "logprob":
        scores = log_p
    elif mode == "prob":
        scores = torch.exp(log_p)
    else:
        raise ValueError(f"unknown scoring mode {mode!r}")
    if reduction == "mean":
        scores = scores / counts.clamp(min=1.0)
    return scores


