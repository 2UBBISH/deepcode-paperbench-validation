def build_mlm_batch(
    texts: Sequence[str],
    tokenizer: Any,
    config: Optional[MLMLossConfig] = None,
    *,
    rng: Optional[random.Random] = None,
    device: Optional[torch.device] = None,
) -> Dict[str, torch.Tensor]:
    """Tokenize ``texts`` and apply random-word masking plus labels.

    Returns a dict with ``input_ids``, ``attention_mask``, ``labels`` and
    ``mask_positions`` (bool ``[B, L]``).
    """
    cfg = config or MLMLossConfig()
    rng = rng or random.Random(cfg.seed)
    mask_token_id = getattr(tokenizer, "mask_token_id", None)
    if mask_token_id is None:
        raise ValueError("tokenizer has no mask token; a masked-LM tokenizer is required")
    vocab_size = int(getattr(tokenizer, "vocab_size", 0) or 0)

    all_ids: List[List[int]] = []
    all_labels: List[List[int]] = []
    for text in texts:
        enc = tokenizer(
            str(text),
            add_special_tokens=True,
            truncation=True,
            max_length=cfg.max_length,
            return_tensors=None,
        )
        ids = list(enc["input_ids"])
        if hasattr(tokenizer, "word_ids") and hasattr(tokenizer, "__call__"):
            try:
                fast = tokenizer(str(text), add_special_tokens=True, truncation=True,
                                 max_length=cfg.max_length)
                word_ids = list(fast.word_ids()) if hasattr(fast, "word_ids") else None
            except Exception:
                word_ids = None
        else:
            word_ids = None
        if word_ids is None or len(word_ids) != len(ids):
            special = set(_special_token_positions(tokenizer, ids)) if ids else set()
            word_ids = [None if i in special else i for i in range(len(ids))]
        if not cfg.mask_whole_words:
            word_ids = [None if w is None else i for i, w in enumerate(word_ids)]

        positions = select_mask_word_indices(
            word_ids,
            mask_prob=cfg.mask_prob,
            max_masks=cfg.max_masks_per_sequence,
            rng=rng,
        )
        labels = [cfg.ignore_index] * len(ids)
        for pos in positions:
            original = ids[pos]
            labels[pos] = original
            r = rng.random()
            if r < cfg.prob_replace_mask:
                ids[pos] = int(mask_token_id)
            elif r < cfg.prob_replace_mask + cfg.prob_replace_random and vocab_size > 0:
                ids[pos] = rng.randrange(vocab_size)
            # else: keep the original token (10% branch)
        all_ids.append(ids)
        all_labels.append(labels)

    max_len = max((len(x) for x in all_ids), default=0) or 1
    pad_id = int(getattr(tokenizer, "pad_token_id", 0) or 0)
    input_ids = torch.full((len(all_ids), max_len), pad_id, dtype=torch.long)
    attention_mask = torch.zeros((len(all_ids), max_len), dtype=torch.long)
    labels = torch.full((len(all_labels), max_len), cfg.ignore_index, dtype=torch.long)
    for i, (ids, labs) in enumerate(zip(all_ids, all_labels)):
        input_ids[i, : len(ids)] = torch.tensor(ids, dtype=torch.long)
        attention_mask[i, : len(ids)] = 1
        labels[i, : len(labs)] = torch.tensor(labs, dtype=torch.long)
    batch = {
        "input_ids": input_ids,
        "attention_mask": attention_mask,
        "labels": labels,
        "mask_positions": labels != cfg.ignore_index,
    }
    if device is not None:
        batch = {k: v.to(device) for k, v in batch.items()}
    return batch


def apply_random_mask(
    text: str,
    tokenizer: Optional[Any] = None,
    config: Optional[MLMLossConfig] = None,
    *,
    rng: Optional[random.Random] = None,
) -> Tuple[str, List[str]]:
    """Replace a random word of ``text`` with the mask token (§4.5, training/inference).

    Returns ``(masked_text, removed_words)``. Purely string based, so it works with any
    tokenizer and is handy for building "text chunks from the groundtruth data".
    """
    cfg = config or MLMLossConfig()
    rng = rng or random.Random(cfg.seed)
    spans = word_spans(text)
    if not spans:
        return text, []
    n_mask = max(1, int(math.ceil(cfg.mask_prob * len(spans))))
    n_mask = min(n_mask, cfg.max_masks_per_sequence, len(spans))
    chosen = sorted(rng.sample(range(len(spans)), n_mask), reverse=True)
    mask_str = getattr(tokenizer, "mask_token", None) or "[MASK]"
    masked = text
    removed: List[str] = []
    for idx in chosen:
        s, e = spans[idx]
        removed.append(text[s:e])
        masked = masked[:s] + mask_str + masked[e:]
    removed.reverse()
    return masked, removed


# --------------------------------------------------------------------------------------
# Masked-LM adapter (the ablation's learnable module)
# --------------------------------------------------------------------------------------


class MLMAdapter(nn.Module):
    """Small masked-LM adapter used for the MLM ablation of Table 5.

    It is structurally the same tiny encoder as the energy adapter, but with a
    vocabulary-sized MLM head instead of a scalar energy head, trained with masked-word
    cross entropy on ground-truth text chunks (§4.5).
    """

    def __init__(
        self,
        config: Optional[MLMLossConfig] = None,
        tokenizer: Optional[Any] = None,
        *,
        backbone: Optional[str] = None,
    ) -> None:
        super().__init__()
        cfg = config or MLMLossConfig()
        if isinstance(cfg, dict):
            cfg = MLMLossConfig.from_dict(cfg)
        self.config = cfg
        AutoModelForMaskedLM, AutoTokenizer = _hf_classes()
        resolved = resolve_mlm_backbone(cfg.dataset, cfg.size, backbone or cfg.backbone)
        self.backbone_name = resolved
        if tokenizer is None:
            try:
                tokenizer = AutoTokenizer.from_pretrained(resolved)
            except Exception as exc:  # pragma: no cover - network guard
                raise RuntimeError(f"could not load tokenizer for {resolved!r}: {exc}") from exc
        self.tokenizer = tokenizer
        try:
            self.model = AutoModelForMaskedLM.from_pretrained(resolved)
        except Exception as exc:  # pragma: no cover - network guard
            raise RuntimeError(f"could not load MLM backbone {resolved!r}: {exc}") from exc

    # -- io ---------------------------------------------------------------------
    @classmethod
    def from_pretrained(
        cls,
        path_or_dir: str,
        config: Optional[MLMLossConfig] = None,
        tokenizer: Optional[Any] = None,
        map_location: str = "cpu",
    ) -> "MLMAdapter":
        cfg_path = os.path.join(path_or_dir, "mlm_config.pt")
        weights = os.path.join(path_or_dir, "mlm_adapter.pt")
        if config is None and os.path.isfile(cfg_path):
            blob = torch.load(cfg_path, map_location="cpu")
            config = MLMLossConfig.from_dict(blob if isinstance(blob, dict) else None)
        obj = cls(config=config, tokenizer=tokenizer)
        if os.path.isfile(weights):
            state = torch.load(weights, map_location=map_location)
            missing, unexpected = obj.load_state_dict(state, strict=False)
            obj._missing_keys, obj._unexpected_keys = list(missing), list(unexpected)
        return obj

    def save_pretrained(self, path_or_dir: str) -> None:
        os.makedirs(path_or_dir, exist_ok=True)
        torch.save(self.state_dict(), os.path.join(path_or_dir, "mlm_adapter.pt"))
        torch.save(self.config.to_dict(), os.path.join(path_or_dir, "mlm_config.pt"))
        tok_dir = os.path.join(path_or_dir, "tokenizer")
        try:
            self.tokenizer.save_pretrained(tok_dir)
        except Exception:  # pragma: no cover - optional
            pass

    # -- core -------------------------------------------------------------------
    @property
    def device(self) -> torch.device:
        try:
            return next(self.parameters()).device
        except StopIteration:  # pragma: no cover
            return torch.device("cpu")

    def num_parameters(self, trainable_only: bool = False) -> int:
        params = [p for p in self.parameters() if (p.requires_grad or not trainable_only)]
        return int(sum(p.numel() for p in params))

    def forward(
        self,
        input_ids: torch.Tensor,
        attention_mask: Optional[torch.Tensor] = None,
        **kwargs: Any,
    ) -> torch.Tensor:
        """Return vocabulary logits ``[B, L, V]``."""
        out = self.model(input_ids=input_ids, attention_mask=attention_mask, **kwargs)
        return out.logits if hasattr(out, "logits") else out[0]

    def tokenize(
        self,
        texts: Sequence[str],
        max_length: Optional[int] = None,
    ) -> Dict[str, torch.Tensor]:
        enc = self.tokenizer(
            list(texts),
            add_special_tokens=True,
            truncation=True,
            max_length=int(max_length or self.config.max_length),
            padding=True,
            return_tensors="pt",
        )
        return {k: v for k, v in dict(enc).items() if k in {"input_ids", "attention_mask", "token_type_ids"}}

    # -- training ---------------------------------------------------------------
    def batch(
        self,
        texts: Sequence[str],
        *,
        rng: Optional[random.Random] = None,
        device: Optional[torch.device] = None,
    ) -> Dict[str, torch.Tensor]:
        return build_mlm_batch(texts, self.tokenizer, self.config, rng=rng, device=device)

    def loss(
        self,
        texts: Optional[Sequence[str]] = None,
        *,
        batch: Optional[Dict[str, torch.Tensor]] = None,
        rng: Optional[random.Random] = None,
    ) -> torch.Tensor:
        """Masked-word cross entropy over ground-truth text chunks (§4.5 training)."""
        if batch is None:
            if texts is None:
                raise ValueError("provide either `texts` or `batch`")
            batch = self.batch(texts, rng=rng, device=self.device)
        logits = self.forward(batch["input_ids"], batch.get("attention_mask"))
        return compute_mlm_loss(
            logits,
            batch["labels"],
            batch.get("attention_mask"),
            reduction=self.config.reduction,
            ignore_index=self.config.ignore_index,
            label_smoothing=self.config.label_smoothing,
        )

    # -- inference --------------------------------------------------------------
    @torch.no_grad()
    def score_sequences(
        self,
        texts: Sequence[str],
        *,
        n_masks: Optional[int] = None,
        rng: Optional[random.Random] = None,
    ) -> torch.Tensor:
        """Score each sequence by the probability of a randomly masked word (§4.5)."""
        cfg = self.config
        rng = rng or random.Random(cfg.seed)
        n_masks = int(n_masks or cfg.n_inference_masks)
        scores: List[float] = []
        for text in texts:
            acc = 0.0
            used = 0
            for _ in range(max(1, n_masks)):
                batch = build_mlm_batch([str(text)], self.tokenizer, cfg,
                                        rng=rng, device=self.device)
                if not bool(batch["mask_positions"].any()):
                    continue
                logits = self.forward(batch["input_ids"], batch.get("attention_mask"))
                s = sentence_masked_word_score(
                    logits, batch["labels"], batch["mask_positions"],
                    mode=cfg.inference_score, reduction=cfg.inference_reduction,
                    ignore_index=cfg.ignore_index,
                )
                acc += float(s.mean().item())
                used += 1
            scores.append(acc / used if used else 0.0)
        return torch.tensor(scores, dtype=torch.float32)

    @torch.no_grad()
    def score_pairs(
        self,
        questions: Sequence[str],
        answers: Sequence[str],
        *,
        n_masks: Optional[int] = None,
        rng: Optional[random.Random] = None,
        batch_size: int = 32,
        **_: Any,
    ) -> torch.Tensor:
        """Energy-model-compatible interface: scalar score per ``(question, answer)``."""
        if len(questions) != len(answers):
            raise ValueError("questions and answers must have the same length")
        pairs = [f"Question: {q}\nAnswer: {a}" for q, a in zip(questions, answers)]
        chunks = [pairs[i : i + batch_size] for i in range(0, len(pairs), batch_size)] or [[]]
        out: List[torch.Tensor] = []
        for chunk in chunks:
            if chunk:
                out.append(self.score_sequences(chunk, n_masks=n_masks, rng=rng))
        if not out:
            return torch.zeros(0, dtype=torch.float32)
        return torch.cat(out, dim=0)


class MaskedLMScorer:
    """Thin ``EnergyModel``-shaped wrapper around :class:`MLMAdapter` for beam search."""

    def __init__(self, model: MLMAdapter, n_masks: Optional[int] = None, seed: int = 0) -> None:
        self.model = model
        self.n_masks = n_masks
        self.rng = random.Random(seed)

    def score_pairs(self, questions: Sequence[str], answers: Sequence[str], **kwargs: Any) -> torch.Tensor:
        return self.model.score_pairs(questions, answers, n_masks=self.n_masks,
                                      rng=self.rng, **kwargs)

    __call__ = score_pairs

    def energy(self, questions: Sequence[str], answers: Sequence[str], **kwargs: Any) -> torch.Tensor:
        # For the ablation the "energy" is a negated log-probability so that lower is
        # better, matching the EnergyModel convention used by beam search.
        return -self.score_pairs(questions, answers, **kwargs)


