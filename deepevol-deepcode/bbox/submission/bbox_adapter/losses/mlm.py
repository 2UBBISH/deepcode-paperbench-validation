class MaskedLMLoss(nn.Module):
    """``nn.Module`` wrapper exposing the MLM ablation through a loss-like interface.

    Usage::

        loss_fn = MaskedLMLoss(model=my_mlm_adapter)      # or MaskedLMLoss(config=...)
        loss = loss_fn(positive_texts)                    # ground-truth chunks
        loss = loss_fn(questions=qs, positive_answers=ys) # text pairs

    The signature accepts the same keyword names as
    :class:`~bbox_adapter.losses.nce.RankingNCELoss` (``questions``,
    ``positive_answers``) so the online-adaptation loop can swap objectives via
    ``get_loss("mlm")`` without further changes; negatives are ignored, as the paper's
    MLM ablation uses ground-truth masked-word supervision only.
    """

    def __init__(
        self,
        config: Optional[MLMLossConfig] = None,
        *,
        model: Optional[MLMAdapter] = None,
        tokenizer: Optional[Any] = None,
        **kwargs: Any,
    ) -> None:
        super().__init__()
        cfg = config if isinstance(config, MLMLossConfig) else MLMLossConfig.from_dict(config or {})
        for k, v in kwargs.items():
            if hasattr(cfg, k):
                setattr(cfg, k, v)
        self.config = cfg
        self.model = model if model is not None else MLMAdapter(cfg, tokenizer=tokenizer)
        self.rng = random.Random(int(cfg.seed))
        self._last_stats: Dict[str, float] = {}

    # -- helpers ----------------------------------------------------------------
    @property
    def tokenizer(self) -> Any:
        return self.model.tokenizer

    def _texts_from_inputs(
        self,
        texts: Optional[Sequence[str]] = None,
        questions: Optional[Sequence[str]] = None,
        positive_answers: Optional[Sequence[str]] = None,
    ) -> List[str]:
        if texts is not None:
            return [str(t) for t in texts]
        if questions is not None and positive_answers is not None:
            return [f"Question: {q}\nAnswer: {a}" for q, a in zip(questions, positive_answers)]
        if positive_answers is not None:
            return [str(t) for t in positive_answers]
        raise ValueError("no text supplied to the MLM loss")

    def forward(
        self,
        texts: Optional[Sequence[str]] = None,
        *,
        questions: Optional[Sequence[str]] = None,
        positive_answers: Optional[Sequence[str]] = None,
        negative_answers: Optional[Sequence[Any]] = None,  # ignored (ablation)
        batch: Optional[Dict[str, torch.Tensor]] = None,
        return_stats: bool = False,
        **_: Any,
    ) -> Union[torch.Tensor, Tuple[torch.Tensor, Dict[str, float]]]:
        chunks: List[str] = []
        if batch is None:
            raw = self._texts_from_inputs(texts, questions, positive_answers)
            for t in raw:
                chunks.extend(split_text_chunks(t, self.config.extra.get("chunk_max_words", 128)) or [t])
            batch = self.model.batch(chunks, rng=self.rng, device=self.model.device)
        logits = self.model.forward(batch["input_ids"], batch.get("attention_mask"))
        loss = compute_mlm_loss(
            logits,
            batch["labels"],
            batch.get("attention_mask"),
            reduction=self.config.reduction,
            ignore_index=self.config.ignore_index,
            label_smoothing=self.config.label_smoothing,
        )
        if not return_stats:
            return loss
        with torch.no_grad():
            prob = masked_word_probability(
                logits.detach(), batch["labels"], batch["mask_positions"],
                ignore_index=self.config.ignore_index, reduction="mean",
            )
        stats = {
            "loss": float(loss.detach().item()),
            "masked_word_prob": float(prob.item()),
            "n_masked": float(batch["mask_positions"].sum().item()),
            "n_sequences": float(batch["labels"].shape[0]),
        }
        self._last_stats = stats
        return loss, stats

    def score_pairs(self, questions: Sequence[str], answers: Sequence[str], **kw: Any) -> torch.Tensor:
        return self.model.score_pairs(questions, answers, **kw)


