def _self_test() -> None:
    """Dependency-free checks of masking + objective math (no transformers needed)."""
    rng = random.Random(0)
    text = "The answer is 21 because three times seven equals twenty one."
    spans = word_spans(text)
    assert len(spans) == 10, spans
    masked, removed = apply_random_mask(text, tokenizer=None, config=MLMLossConfig(seed=3), rng=rng)
    assert "[MASK]" in masked and removed, (masked, removed)
    assert "The answer is" in masked

    # word-level selection
    word_ids = [None, 0, 0, 1, 2, 3, None]
    pos = select_mask_word_indices(word_ids, mask_prob=1.0, max_masks=10, rng=random.Random(0))
    assert pos == [1, 2, 3, 4, 5], pos
    pos_forced = select_mask_word_indices(word_ids, forced_word=2)
    assert pos_forced == [4], pos_forced

    # objective: loss decreases as the true masked word probability rises
    B, L, V = 2, 4, 7
    labels = torch.full((B, L), -100, dtype=torch.long)
    labels[0, 1] = 3
    labels[1, 2] = 5
    good = torch.zeros(B, L, V)
    good[0, 1, 3] = 20.0
    good[1, 2, 5] = 20.0
    bad = torch.zeros(B, L, V)
    bad[0, 1, 3] = -20.0
    bad[1, 2, 5] = -20.0
    l_good = compute_mlm_loss(good, labels)
    l_bad = compute_mlm_loss(bad, labels)
    assert float(l_good) < float(l_bad), (l_good, l_bad)
    p_good = masked_word_probability(good, labels)
    assert float(p_good) > 0.9, p_good
    scores = sentence_masked_word_score(good, labels, mode="logprob")
    assert scores.shape == (B,)
    assert float(scores[0]) > 0.0

    # gradient flows into the logits
    logits = torch.zeros(B, L, V, requires_grad=True)
    compute_mlm_loss(logits, labels).backward()
    assert logits.grad is not None and float(logits.grad.abs().sum()) > 0.0

    # chunking
    chunks = split_text_chunks("a b c d e", max_words=2)
    assert chunks == ["a b", "c d", "e"], chunks


if __name__ == "__main__":  # pragma: no cover
    _self_test()
    print("mlm.py self-test passed")
