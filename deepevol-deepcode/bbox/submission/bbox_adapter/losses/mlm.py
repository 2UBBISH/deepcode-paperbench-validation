# --------------------------------------------------------------------------------------
# Configuration
# --------------------------------------------------------------------------------------


@dataclass
class MLMLossConfig:
    """Configuration for the masked-LM ablation.

    Defaults mirror the BBox-Adapter setup (§H.2): max length 512 and the same small
    encoder backbone used by the energy adapter (DeBERTa-v3-base/large, BERT-base-cased).
    """

    backbone: Optional[str] = None
    dataset: Optional[str] = None
    size: str = "0.1b"
    max_length: int = 512
    # --- masking ---------------------------------------------------------------
    mask_prob: float = 0.15          # fraction of *words* masked
    max_masks_per_sequence: int = 5  # cap on masked words per sequence
    mask_whole_words: bool = True    # §4.5: "randomly masking words" (word level)
    prob_replace_mask: float = 0.8   # BERT-style 80/10/10 corruption
    prob_replace_random: float = 0.1
    # --- objective -------------------------------------------------------------
    reduction: str = "mean"          # {"mean", "sum", "none"}
    ignore_index: int = -100
    label_smoothing: float = 0.0
    # --- inference scoring -----------------------------------------------------
    n_inference_masks: int = 1       # "masking a random word in each sequence"
    inference_score: str = "logprob"  # {"logprob", "prob"}
    inference_reduction: str = "mean"
    seed: int = 0
    extra: Dict[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if self.reduction not in {"mean", "sum", "none"}:
            raise ValueError(f"unknown reduction {self.reduction!r}")
        if self.inference_score not in {"logprob", "prob"}:
            raise ValueError(f"unknown inference_score {self.inference_score!r}")
        if not 0.0 < self.mask_prob <= 1.0:
            raise ValueError("mask_prob must be in (0, 1]")
        s = self.prob_replace_mask + self.prob_replace_random
        if s > 1.0 + 1e-9:
            raise ValueError("prob_replace_mask + prob_replace_random must be <= 1")

    def to_dict(self) -> Dict[str, Any]:
        return {
            "backbone": self.backbone,
            "dataset": self.dataset,
            "size": self.size,
            "max_length": self.max_length,
            "mask_prob": self.mask_prob,
            "max_masks_per_sequence": self.max_masks_per_sequence,
            "mask_whole_words": self.mask_whole_words,
            "prob_replace_mask": self.prob_replace_mask,
            "prob_replace_random": self.prob_replace_random,
            "reduction": self.reduction,
            "ignore_index": self.ignore_index,
            "label_smoothing": self.label_smoothing,
            "n_inference_masks": self.n_inference_masks,
            "inference_score": self.inference_score,
            "inference_reduction": self.inference_reduction,
            "seed": self.seed,
            "extra": dict(self.extra),
        }

    @classmethod
    def from_dict(cls, d: Optional[Dict[str, Any]]) -> "MLMLossConfig":
        if not d:
            return cls()
        known = {f for f in cls.__dataclass_fields__}  # type: ignore[attr-defined]
        return cls(**{k: v for k, v in d.items() if k in known})


