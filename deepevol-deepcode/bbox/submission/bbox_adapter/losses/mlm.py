def mlm_loss_from_model(
    model: Any,
    texts: Optional[Sequence[str]] = None,
    positive_answers: Optional[Sequence[str]] = None,
    *,
    questions: Optional[Sequence[str]] = None,
    config: Optional[MLMLossConfig] = None,
    rng: Optional[random.Random] = None,
    return_stats: bool = False,
):
    """Compute the MLM ablation loss through an ``MLMAdapter`` / ``MaskedLMLoss``."""
    cfg = config or getattr(model, "config", None) or MLMLossConfig()
    if hasattr(model, "loss"):
        batch = None
        if isinstance(model, MaskedLMLoss):
            return model(
                texts=texts,
                questions=questions,
                positive_answers=positive_answers,
                return_stats=return_stats,
            )
        if texts is None:
            if questions is not None and positive_answers is not None:
                texts = [f"Question: {q}\nAnswer: {a}" for q, a in zip(questions, positive_answers)]
            elif positive_answers is not None:
                texts = list(positive_answers)
        if texts is None:
            raise ValueError("no text supplied to the MLM loss")
        chunks: List[str] = []
        for t in texts:
            chunks.extend(split_text_chunks(t, cfg.extra.get("chunk_max_words", 128)) or [t])
        batch = model.batch(chunks, rng=rng, device=getattr(model, "device", None))
        logits = model.forward(batch["input_ids"], batch.get("attention_mask"))
        loss = compute_mlm_loss(
            logits, batch["labels"], batch.get("attention_mask"),
            reduction=cfg.reduction, ignore_index=cfg.ignore_index,
            label_smoothing=cfg.label_smoothing,
        )
        if not return_stats:
            return loss
        with torch.no_grad():
            prob = masked_word_probability(
                logits.detach(), batch["labels"], batch["mask_positions"],
                ignore_index=cfg.ignore_index, reduction="mean",
            )
        return loss, {
            "loss": float(loss.detach().item()),
            "masked_word_prob": float(prob.item()),
            "n_masked": float(batch["mask_positions"].sum().item()),
        }
    raise TypeError("model must expose a `.loss(...)` method (MLMAdapter / MaskedLMLoss)")


