"""Masked Language Modeling (MLM) ablation loss for BBox-Adapter.

Paper (§4.5, verbatim):
    "We compare the efficacy of ranking-based NCE loss against the Masked Language
     Modeling (MLM) loss. For the MLM-based approach, we generate text chunks from the
     groundtruth data, randomly masking words, and then train the adapter using the
     masked word as supervision. During inference, we apply a similar process: masking a
     random word in each sequence generated by beam search and scoring the sequence
     based on the probability of the masked word."

Reference numbers (Table 5, accuracy %):

    =====  ============  ============  ========  ========
    Loss   StratQA 0.1B  StratQA 0.3B  GSM 0.1B  GSM 0.3B
    =====  ============  ============  ========  ========
    MLM    61.52         60.41         70.56     70.81
    NCE    71.62         71.18         72.06     73.86
    =====  ============  ============  ========  ========

The ablation intentionally mirrors the NCE pipeline in :mod:`bbox_adapter.losses.nce`:

* training: one scalar objective term (masked-token cross entropy) on text chunks
  built from the *ground-truth* answers (positives);
* inference: a scalar *score per candidate sequence* obtained by masking a random word
  and reading off the probability the model assigns to the true (removed) word.

Both entry points are exposed through the ``EnergyModel``-compatible surface
``score_pairs(questions, answers) -> Tensor[N]`` so that ``inference/beam_search.py``
can swap the evaluator without any other change.

NOTE (paper, §3.2 + Addendum): the ``alpha * E[g^2]`` regularization applies to the
ranking-based NCE objective only; the MLM ablation is trained with plain cross entropy.
"""

