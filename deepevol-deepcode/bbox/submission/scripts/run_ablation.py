@dataclass
class AblationRun:
    """One (dataset x size x loss x analysis-value) run."""

    dataset: str
    setting: str = "ground_truth"
    size: str = "0.1b"
    loss: str = "nce"
    beam_size: int = 3
    iterations: int = 4
    alpha: float = DEFAULT_ALPHA
    metric: str = "accuracy"
    accuracy: float = 0.0
    delta: float = 0.0
    base_accuracy: Optional[float] = None
    n_eval: int = 0
    seed: int = 0
    history: List[Dict[str, Any]] = field(default_factory=list)
    curve: Dict[str, List[float]] = field(default_factory=dict)
    energy_scales: Dict[str, float] = field(default_factory=dict)
    paper_value: Optional[float] = None
    error: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        d = asdict(self)
        d.pop("curve", None)
        return d

    def row(self) -> Dict[str, Any]:
        return {
            "dataset": self.dataset,
            "loss": self.loss.upper(),
            "size": self.size,
            "beam_size": self.beam_size,
            "iterations": self.iterations,
            "alpha": self.alpha,
            "accuracy": round(self.accuracy, 2),
            "delta": round(self.delta, 2),
            "paper": self.paper_value,
            "n_eval": self.n_eval,
        }


