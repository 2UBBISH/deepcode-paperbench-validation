def aggregate_runs(runs: Sequence[AblationRun]) -> List[Dict[str, Any]]:
    """Group runs by (dataset, size, loss, beam, iterations, alpha) and average seeds."""
    groups: Dict[Tuple, List[AblationRun]] = {}
    for r in runs:
        key = (r.dataset, r.size, r.loss, r.beam_size, r.iterations, r.alpha)
        groups.setdefault(key, []).append(r)

    rows: List[Dict[str, Any]] = []
    for key, members in sorted(groups.items(), key=lambda kv: [str(x) for x in kv[0]]):
        ds, size, loss, beam, iters, alpha = key
        accs = [m.accuracy for m in members if m.error is None]
        deltas = [m.delta for m in members if m.error is None]
        row = dict(
            dataset=ds,
            size=size,
            loss=loss,
            beam_size=beam,
            iterations=iters,
            alpha=alpha,
            n_seeds=len(members),
            n_ok=len(accs),
            accuracy=round(average(accs) or 0.0, 2),
            std=round(population_std(accs), 2),
            delta=round(average(deltas) or 0.0, 2),
            base_accuracy=BASE_ACCURACY.get(ds),
            paper=paper_ablation_reference(ds, loss, size),
            errors=[m.error for m in members if m.error],
        )
        row["paper_gap"] = (
            None if row["paper"] is None else round(row["accuracy"] - float(row["paper"]), 2)
        )
        rows.append(row)
    return rows


def format_table5(rows: Sequence[Dict[str, Any]]) -> str:
    """Render the NCE-vs-MLM ablation in the paper's Table-5 layout."""
    lines: List[str] = []
    datasets = []
    for row in rows:
        if row["dataset"] not in datasets:
            datasets.append(row["dataset"])
    for ds in datasets:
        sub = [r for r in rows if r["dataset"] == ds]
        if not sub:
            continue
        sizes = []
        for r in sub:
            if r["size"] not in sizes:
                sizes.append(r["size"])
        lines.append("")
        lines.append("Dataset: %s   (base model %.2f)" % (ds, BASE_ACCURACY.get(ds, 0.0)))
        header = ["Loss"] + ["%s (paper)" % s for s in sizes]
        lines.append("  ".join(header))
        lines.append("-" * len("  ".join(header)))
        for loss in ("mlm", "nce"):
            cells = []
            for size in sizes:
                matches = [r for r in sub if r["loss"] == loss and r["size"] == size]
                if not matches:
                    cells.append("-")
                    continue
                m = matches[0]
                rep = m["paper"]
                cells.append(
                    "%.2f (%s)" % (m["accuracy"], "-" if rep is None else "%.2f" % rep)
                )
            if any(c != "-" for c in cells):
                lines.append("  ".join([loss.upper().ljust(4)] + cells))
    return "\n".join(lines)


def format_sweep_table(rows: Sequence[Dict[str, Any]], column: str) -> str:
    """Render a beam / iteration / alpha sweep as an aligned table."""
    fields = [
        ("dataset", "dataset"),
        ("size", "size"),
        (column, column),
        ("accuracy", "acc(%)"),
        ("std", "std"),
        ("delta", "delta(%)"),
    ]
    try:
        return render_table([{k: r.get(k) for k, _ in fields} for r in rows],
                            fields=[f[1] for f in fields])
    except Exception:  # pragma: no cover - fallback rendering
        out = ["  ".join(f[1] for f in fields)]
        for r in rows:
            out.append("  ".join(str(r.get(k, "")) for k, _ in fields))
        return "\n".join(out)


def beam_gain_analysis(rows: Sequence[Dict[str, Any]]) -> Dict[str, Any]:
    """Reproduce the '+2.41% average' claim of Sec. 4.6 (k=1 -> k=5 per size)."""
    out: Dict[str, Any] = {"per_size": {}, "average_gain": None, "paper_gain": PAPER_BEAM_AVERAGE_GAIN}
    gains: List[float] = []
    for r in rows:
        key = (r["dataset"], r["size"])
        out["per_size"].setdefault(str(key), {})[str(r["beam_size"])] = r["accuracy"]
    for key, beams in out["per_size"].items():
        if "1" in beams and "5" in beams:
            gains.append(float(beams["5"]) - float(beams["1"]))
    if gains:
        out["average_gain"] = round(sum(gains) / len(gains), 2)
    return out


def iteration_analysis(rows: Sequence[Dict[str, Any]]) -> Dict[str, Any]:
    """Check the Fig-3(b) story: T=0 worse than base, improving afterwards."""
    out: Dict[str, Any] = {"per_dataset": {}}
    for r in rows:
        key = str(r["dataset"])
        base = r.get("base_accuracy")
        entry = out["per_dataset"].setdefault(key, {"base": base, "curve": {}})
        entry["curve"][str(r["iterations"])] = r["accuracy"]
    for key, entry in out["per_dataset"].items():
        curve = entry["curve"]
        base = entry["base"]
        t0 = curve.get("0")
        later = [v for k, v in curve.items() if k != "0"]
        entry["t0_below_base"] = None if (t0 is None or base is None) else bool(t0 < base)
        entry["max_after_zero"] = max(later) if later else None
        if base is not None and entry["max_after_zero"] is not None:
            entry["gain_after_adaptation"] = round(entry["max_after_zero"] - base, 2)
    return out


def alpha_analysis(runs: Sequence[AblationRun]) -> List[Dict[str, Any]]:
    """Summarise the regularization-coefficient sweep with energy diagnostics."""
    rows: List[Dict[str, Any]] = []
    for a in sorted({r.alpha for r in runs}):
        sub = [r for r in runs if r.alpha == a and r.error is None]
        if not sub:
            continue
        row = {
            "alpha": a,
            "accuracy": round(average([r.accuracy for r in sub]) or 0.0, 2),
            "loss_mean": round(average([r.energy_scales.get("loss_mean") for r in sub]) or 0.0, 4),
            "pos_energy_mean": round(
                average([r.energy_scales.get("pos_energy_mean") for r in sub]) or 0.0, 4
            ),
            "neg_energy_mean": round(
                average([r.energy_scales.get("neg_energy_mean") for r in sub]) or 0.0, 4
            ),
            "finite": check_energy_scales(
                [r.energy_scales.get("pos_energy_mean", 0.0) for r in sub],
                [r.energy_scales.get("neg_energy_mean", 0.0) for r in sub],
                alpha=a,
            ).get("finite", True),
        }
        rows.append(row)
    return rows


def compare_table5(rows: Sequence[Dict[str, Any]], tolerance: float = 3.0) -> Dict[str, Any]:
    """Validate the reproduced NCE-vs-MLM numbers against Table 5."""
    out: Dict[str, Any] = {"tolerance": tolerance, "cells": {}, "n_within": 0, "n_cells": 0}
    for r in rows:
        if r.get("paper") is None:
            continue
        key = "%s/%s/%s" % (r["dataset"], r["loss"], r["size"])
        gap = float(r["accuracy"]) - float(r["paper"])
        out["cells"][key] = {
            "reproduced": r["accuracy"],
            "paper": r["paper"],
            "gap": round(gap, 2),
            "within_tolerance": abs(gap) <= tolerance,
        }
        out["n_cells"] += 1
        if abs(gap) <= tolerance:
            out["n_within"] += 1
    return out


def write_reports(
    logger: RunLogger,
    args: argparse.Namespace,
    mode: str,
    runs: Sequence[AblationRun],
    rows: Sequence[Dict[str, Any]],
    extra: Optional[Dict[str, Any]] = None,
) -> Dict[str, str]:
    """Persist raw runs, aggregated rows, curves and a markdown report."""
    paths: Dict[str, str] = {}
    os.makedirs(logger.output_dir, exist_ok=True)

    payload = {
        "mode": mode,
        "args": {k: v for k, v in vars(args).items() if k != "argv"},
        "runs": [r.to_dict() for r in runs],
        "rows": list(rows),
        "paper_table5": PAPER_TABLE5,
        "generated_at": time.strftime("%Y-%m-%d %H:%M:%S"),
    }
    if extra:
        payload.update(extra)

    paths["results"] = logger.path("ablation_results.json")
    with open(paths["results"], "w") as fh:
        json.dump(payload, fh, indent=2, default=str)

    # curves (Appendix K) -- one CSV per (dataset, size)
    curve_dir = os.path.join(logger.curve_dir, "ablation")
    os.makedirs(curve_dir, exist_ok=True)
    for r in runs:
        if not r.curve:
            continue
        import csv

        path = os.path.join(curve_dir, "%s_%s_%s.csv" % (r.dataset, r.size, r.loss))
        names = sorted(r.curve)
        n = max(len(r.curve[k]) for k in names)
        with open(path, "w", newline="") as fh:
            writer = csv.writer(fh)
            writer.writerow(["step"] + names)
            for i in range(n):
                writer.writerow(
                    [i] + [(r.curve[k][i] if i < len(r.curve[k]) else "") for k in names]
                )
        paths.setdefault("curves", curve_dir)

    # report
    lines: List[str] = []
    lines.append("# BBox-Adapter ablation report")
    lines.append("")
    lines.append("- mode: `%s`" % mode)
    lines.append("- datasets: %s" % ", ".join(dict.fromkeys(r["dataset"] for r in rows)))
    lines.append("- sizes: %s" % ", ".join(dict.fromkeys(r["size"] for r in rows)))
    lines.append("- seeds: %s" % ", ".join(str(s) for s in args.seeds))
    lines.append("")
    if mode == "ablation":
        lines.append("## Table 5 -- MLM vs ranking-based NCE loss (Sec. 4.5)")
        lines.append("")
        lines.append("```")
        lines.append(format_table5(rows))
        lines.append("```")
        lines.append("")
        cmp_paths = compare_table5(rows)
        lines.append(
            "Cells within +/-3.0 of the paper: %d / %d"
            % (cmp_paths["n_within"], cmp_paths["n_cells"])
        )
        if extra and extra.get("table5_comparison"):
            lines.append("")
            for key, info in extra["table5_comparison"].get("cells", {}).items():
                lines.append(
                    "- `%s`: reproduced %.2f vs paper %.2f (gap %+.2f)"
                    % (key, info["reproduced"], info["paper"], info["gap"])
                )
    elif mode == "beams":
        lines.append("## Figure 3(a) -- number of beams (Sec. 4.6)")
        lines.append("")
        lines.append("```")
        lines.append(format_sweep_table(rows, "beam_size"))
        lines.append("```")
        if extra and extra.get("beam_analysis"):
            ba = extra["beam_analysis"]
            lines.append("")
            lines.append("Average k=1 -> k=5 gain: %s%% (paper %s%%)"
                         % (ba.get("average_gain"), ba.get("paper_gain")))
    elif mode == "iterations":
        lines.append("## Figure 3(b) -- number of adaptation iterations (Sec. 4.6)")
        lines.append("")
        lines.append("```")
        lines.append(format_sweep_table(rows, "iterations"))
        lines.append("```")
        if extra and extra.get("iteration_analysis"):
            for ds, info in extra["iteration_analysis"]["per_dataset"].items():
                lines.append("")
                lines.append(
                    "- `%s`: base %.2f; T=0 below base: %s; best after adaptation: %s "
                    "(gain %s)"
                    % (
                        ds,
                        info.get("base") if info.get("base") is not None else float("nan"),
                        info.get("t0_below_base"),
                        info.get("max_after_zero"),
                        info.get("gain_after_adaptation"),
                    )
                )
    elif mode == "alphas":
        lines.append("## Regularization coefficient sweep `alpha` (paper-silent)")
        lines.append("")
        lines.append("```")
        lines.append(
            format_sweep_table(
                [
                    {
                        "dataset": r["dataset"],
                        "size": r["size"],
                        "alpha": r["alpha"],
                        "accuracy": r["accuracy"],
                        "std": r["std"],
                        "delta": r["delta"],
                    }
                    for r in rows
                ],
                "alpha",
            )
        )
        lines.append("```")
        if extra and extra.get("alpha_analysis"):
            lines.append("")
            lines.append("| alpha | acc(%) | loss | pos. energy | neg. energy | finite |")
            lines.append("|---|---|---|---|---|---|")
            for a in extra["alpha_analysis"]:
                lines.append(
                    "| %g | %.2f | %.4f | %.4f | %.4f | %s |"
                    % (
                        a["alpha"],
                        a["accuracy"],
                        a["loss_mean"],
                        a["pos_energy_mean"],
                        a["neg_energy_mean"],
                        a["finite"],
                    )
                )
    else:
        lines.append("## Learning curves (Appendix K)")
        lines.append("")
        for r in runs:
            if r.error:
                lines.append("- `%s/%s/%s`: ERROR %s" % (r.dataset, r.size, r.loss, r.error))
                continue
            lines.append(
                "- `%s/%s/%s`: loss_final=%.4f, pos_energy=%.4f, neg_energy=%.4f"
                % (
                    r.dataset,
                    r.size,
                    r.loss,
                    r.energy_scales.get("loss_final", 0.0),
                    r.energy_scales.get("pos_energy_mean", 0.0),
                    r.energy_scales.get("neg_energy_mean", 0.0),
                )
            )
        lines.append("")
        lines.append("Curves written to `%s`" % curve_dir)
    lines.append("")
    lines.append("Raw results: `%s`" % paths["results"])

    paths["report"] = logger.path("ABLATION.md")
    with open(paths["report"], "w") as fh:
        fh.write("\n".join(lines))
    return paths


