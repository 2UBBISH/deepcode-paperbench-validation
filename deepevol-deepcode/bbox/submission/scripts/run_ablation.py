def choose_mode(args: argparse.Namespace, argv: Optional[Sequence[str]]) -> str:
    """Infer the analysis mode from explicit flags when ``--mode auto``."""
    if args.mode != "auto":
        return args.mode
    argv = list(argv) if argv is not None else sys.argv[1:]
    if any(a == "--beams" or a.startswith("--beams=") for a in argv):
        return "beams"
    if any(a == "--iterations" or a.startswith("--iterations=") for a in argv):
        return "iterations"
    if any(a == "--alphas" or a.startswith("--alphas=") for a in argv):
        return "alphas"
    if any(a == "--curves" for a in argv):
        return "curves"
    return "ablation"


