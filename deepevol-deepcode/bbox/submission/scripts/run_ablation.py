def run_cell(
    cell: Dict[str, Any],
    args: argparse.Namespace,
    seed: int,
    logger: Optional[RunLogger] = None,
) -> AblationRun:
    """Execute a single ablation cell (dataset x size x loss x knobs)."""
    dataset = str(cell["dataset"])
    size = str(cell["size"])
    loss_name = str(cell["loss"])
    run = AblationRun(
        dataset=dataset,
        size=size,
        loss=loss_name,
        beam_size=int(cell.get("beam_size") or 3),
        iterations=int(cell.get("iterations") or 4),
        alpha=float(cell.get("alpha", DEFAULT_ALPHA)),
        seed=seed,
        base_accuracy=BASE_ACCURACY.get(dataset),
    )

    if RX is None:
        run.error = "run_experiment module unavailable; cannot execute cells"
        return run

    try:
        config = RX.build_config(dataset, args)
    except Exception as exc:  # pragma: no cover - config problems are fatal
        run.error = "config error: %s" % exc
        return run

    # ---- apply the cell's overrides onto the merged config ----
    training = config.setdefault("training", {})
    training["max_train_steps"] = int(
        args.train_steps if args.train_steps is not None else training.get("max_train_steps", 6000)
    )
    training["n_iterations"] = int(run.iterations)
    training["loss_name"] = loss_name
    training["sel_mode"] = run.setting
    if args.lr is not None:
        training["lr"] = float(args.lr)
    if args.batch_size is not None:
        training["batch_size"] = int(args.batch_size)
    beam_cfg = config.setdefault("beam_search", {})
    beam_cfg["beam_size"] = int(run.beam_size)
    beam_cfg["n_samples"] = int(beam_cfg.get("n_samples", 2))
    loss_cfg = config.setdefault("loss", {})
    loss_cfg["name"] = loss_name
    loss_cfg["alpha"] = float(run.alpha)
    config.setdefault("dataset", dataset)
    config["size"] = size

    generator = ledger = None
    try:
        generator, ledger = RX.build_generator_and_ledger(config, args)
    except Exception as exc:
        run.error = "generator error: %s" % exc
        return run

    try:
        adapter = RX.build_adapter(config, dataset, size, seed=seed)
    except Exception as exc:
        run.error = "adapter error: %s" % exc
        return run

    try:
        train = RX.prepare_data(
            dataset, config, split="train", limit=args.limit, seed=seed, model=args.blackbox
        )
        test = RX.prepare_data(
            dataset,
            config,
            split="test",
            limit=args.test_limit if args.test_limit is not None else args.limit,
            seed=seed,
            model=args.blackbox,
        )
    except Exception as exc:
        run.error = "data error: %s" % exc
        return run

    # ---- evaluation closure (also records the T=0 / per-iteration score curve) ----
    metric = getattr(test, "metric", "accuracy")

    def eval_fn(current_adapter, t=None, _test=test, _cfg=config):
        try:
            gens, stats = RX.generate_adapted(
                _test,
                current_adapter,
                generator,
                _cfg,
                mode="single" if run.beam_size <= 1 else "full",
                ledger=ledger,
            )
        except Exception as exc:  # pragma: no cover - evaluation robustness
            if logger:
                logger.warning("eval at t=%s failed: %s", t, exc)
            return 0.0
        return float(RX.compute_metric(gens, _test, _cfg))

    # ---- online adaptation (Algorithm 1) ----
    try:
        _, history = RX.run_adaptation(
            adapter,
            generator,
            train,
            config,
            setting=run.setting,
            size=size,
            eval_fn=eval_fn,
            ledger=ledger,
        )
    except Exception as exc:
        run.error = "adaptation error: %s" % exc
        return run

    run.history = list(history or [])

    # Appendix-K style curves: loss / mean positive energy / mean negative energy.
    run.curve = extract_curves(run.history)
    run.energy_scales = energy_diagnostics(run.history)

    # final adapted accuracy (last evaluation in the history, else a fresh run)
    run.accuracy = float(history[-1].get("score", 0.0)) if history else 0.0
    if not history:
        run.accuracy = float(eval_fn(adapter))
    run.delta = run.accuracy - (run.base_accuracy or 0.0)

    try:
        gens, stats = RX.generate_adapted(
            test,
            adapter,
            generator,
            config,
            mode="single" if run.beam_size <= 1 else "full",
            ledger=ledger,
        )
        run.n_eval = len(gens)
        run.metric = metric
    except Exception:
        run.n_eval = len(getattr(test, "questions", []) or [])

    run.paper_value = paper_ablation_reference(dataset, loss_name, size)
    if logger:
        logger.info(
            "[%s|%s|%s k=%d T=%d alpha=%g] acc=%.2f (paper=%s, delta=%+.2f)",
            dataset,
            size,
            loss_name,
            run.beam_size,
            run.iterations,
            run.alpha,
            run.accuracy,
            run.paper_value,
            run.delta,
        )
    return run


# --------------------------------------------------------------------------- #
# curve / diagnostic extraction
# --------------------------------------------------------------------------- #
def extract_curves(history: Sequence[Dict[str, Any]]) -> Dict[str, List[float]]:
    """Pull loss / positive-energy / negative-energy series out of a history."""
    curves: Dict[str, List[float]] = {"loss": [], "pos_energy": [], "neg_energy": []}
    aliases = {
        "loss": ("loss", "nce_loss", "train_loss", "mean_loss"),
        "pos_energy": ("pos_energy", "positive_energy", "mean_pos_energy", "pos"),
        "neg_energy": ("neg_energy", "negative_energy", "mean_neg_energy", "neg"),
    }
    for rec in history or []:
        if not isinstance(rec, dict):
            continue
        for key, names in aliases.items():
            for name in names:
                if name in rec and rec[name] is not None:
                    try:
                        curves[key].append(float(rec[name]))
                    except (TypeError, ValueError):
                        pass
                    break
    return curves


def energy_diagnostics(history: Sequence[Dict[str, Any]]) -> Dict[str, float]:
    """Mean / final loss and energies, plus the alpha-scale check."""
    out: Dict[str, float] = {}
    curves = extract_curves(history)

    def _mean(xs: List[float]) -> float:
        return float(sum(xs) / len(xs)) if xs else 0.0

    out["loss_mean"] = _mean(curves["loss"])
    out["loss_final"] = curves["loss"][-1] if curves["loss"] else 0.0
    out["pos_energy_mean"] = _mean(curves["pos_energy"])
    out["neg_energy_mean"] = _mean(curves["neg_energy"])

    # Appendix-K sanity: positives should sit above negatives once adapted.
    if curves["pos_energy"] and curves["neg_energy"]:
        out["energy_gap"] = out["pos_energy_mean"] - out["neg_energy_mean"]
    return out


