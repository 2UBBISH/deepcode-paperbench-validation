# main
# --------------------------------------------------------------------------- #
def main(argv: Optional[Sequence[str]] = None) -> int:
    args = parse_args(argv)
    mode = choose_mode(args, argv)

    logger = RunLogger(
        output_dir=args.output_dir,
        name="bbox_adapter_ablation",
        dataset=",".join(args.datasets),
        size=",".join(args.sizes),
        blackbox=args.blackbox or "gpt-3.5-turbo",
        level="DEBUG" if args.verbose else "INFO",
    )
    log = logger.logger
    log.info("BBox-Adapter ablation driver | mode=%s", mode)

    cells = build_grid(mode, args)
    log.info("planned cells: %d (seeds=%s)", len(cells), args.seeds)

    if args.dry_run:
        for c in cells:
            log.info(
                "  %s size=%s loss=%s beams=%s T=%s alpha=%s",
                c["dataset"], c["size"], c["loss"], c["beam_size"], c["iterations"], c["alpha"],
            )
        print(json.dumps({"mode": mode, "cells": cells}, indent=2, default=str))
        return 0

    runs: List[AblationRun] = []
    t_start = time.time()
    for seed in args.seeds:
        set_seed(seed)
        seeds = derive_component_seeds(seed)
        for cell in cells:
            try:
                run = run_cell(cell, args, seed, logger=logger)
            except KeyboardInterrupt:  # pragma: no cover
                log.warning("interrupted; stopping early")
                run = AblationRun(
                    dataset=str(cell["dataset"]),
                    size=str(cell["size"]),
                    loss=str(cell["loss"]),
                    seed=seed,
                    error="interrupted",
                )
                runs.append(run)
                raise
            except Exception as exc:  # pragma: no cover - keep going on errors
                run = AblationRun(
                    dataset=str(cell["dataset"]),
                    size=str(cell["size"]),
                    loss=str(cell["loss"]),
                    beam_size=int(cell.get("beam_size") or 3),
                    iterations=int(cell.get("iterations") or 4),
                    alpha=float(cell.get("alpha", DEFAULT_ALPHA)),
                    seed=seed,
                    error=str(exc),
                )
                log.error("cell failed: %s", exc)
            runs.append(run)
            runs[-1].seed = seed
            _ = seeds  # component seeds available for future wiring

    log.info("finished %d runs in %.1fs", len(runs), time.time() - t_start)

    rows = aggregate_runs(runs)
    extra: Dict[str, Any] = {}
    if mode == "ablation":
        extra["table5_comparison"] = compare_table5(rows)
    elif mode == "beams":
        extra["beam_analysis"] = beam_gain_analysis(rows)
    elif mode == "iterations":
        extra["iteration_analysis"] = iteration_analysis(rows)
    elif mode == "alphas":
        extra["alpha_analysis"] = alpha_analysis(runs)

    paths = write_reports(logger, args, mode, runs, rows, extra=extra)
    log.info("report -> %s", paths.get("report"))

    # console summary
    print("")
    if mode == "ablation":
        print(format_table5(rows))
        cmp_paths = extra.get("table5_comparison", {})
        print("")
        print("paper-parity: %s/%s cells within tolerance" % (
            cmp_paths.get("n_within"), cmp_paths.get("n_cells")))
    elif mode == "beams":
        print(format_sweep_table(rows, "beam_size"))
        print("")
        print("average k=1->k=5 gain: %s%% (paper %.2f%%)" % (
            extra["beam_analysis"].get("average_gain"), PAPER_BEAM_AVERAGE_GAIN))
    elif mode == "iterations":
        print(format_sweep_table(rows, "iterations"))
    elif mode == "alphas":
        print(format_sweep_table(
            [{"dataset": r["dataset"], "size": r["size"], "alpha": r["alpha"],
              "accuracy": r["accuracy"], "std": r["std"], "delta": r["delta"]} for r in rows],
            "alpha"))
    else:
        print("%d runs logged; see %s" % (len(runs), paths.get("report")))
    print("")
    print("artifacts: %s" % json.dumps(paths, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
