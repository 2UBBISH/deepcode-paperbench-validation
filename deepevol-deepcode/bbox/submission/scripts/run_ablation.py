#!/usr/bin/env python
"""Ablation / analysis driver for the BBox-Adapter reproduction.

Reproduces the paper's ablation and scale-analysis experiments:

* **Table 5** -- ranking-based NCE loss vs. the Masked-Language-Modelling (MLM)
  ablation (Sec. 4.5).  The MLM variant trains on ground-truth text chunks with
  randomly masked words, and at inference masks a random word of every candidate
  generated by beam search and scores the sequence by the probability of the
  masked word.
  Paper numbers (accuracy %)::

      dataset     loss    0.1B    0.3B
      StrategyQA  MLM    61.52   60.41
      StrategyQA  NCE    71.62   71.18
      GSM8K       MLM    70.56   70.81
      GSM8K       NCE    72.06   73.86

* **Figure 3(a)** -- number of beams ``k in {1, 3, 5}`` for gpt-3.5-turbo
  adaptation on StrategyQA; increasing the beam size yields an average
  ``+2.41%`` across the 0.1B and 0.3B adapters (Sec. 4.6).

* **Figure 3(b)** -- number of online-adaptation iterations ``T in {0..4}`` on
  StrategyQA.  ``T = 0`` (un-tuned adapter) scores *below* the base model; after
  a single round the adapted LLM surpasses the base model and keeps improving
  (Sec. 4.6).

* **Appendix K** -- learning curves (loss, mean positive energy, mean negative
  energy) for StrategyQA / GSM8K / TruthfulQA / ScienceQA.

* **Regularization coefficient** ``alpha in {1e-3, 1e-2, 1e-1}`` sweep, whose
  outcome is judged with the energy-scale diagnostics (the paper is silent about
  ``alpha``; the sweep range comes from the reproduction plan).

Usage
-----
``python scripts/run_ablation.py --dry-run`` prints the planned grid only.
``python scripts/run_ablation.py --datasets strategyqa gsm8k --losses nce mlm``
runs the Table-5 ablation.  ``--beams`` / ``--iterations`` / ``--alphas`` switch
to the scale / sensitivity analyses.  Everything degrades gracefully to the
offline mock black-box client so the script can be smoke-tested without Azure
credentials.

The script never talks to the black-box LLM's internals: only prompts go in and
raw text comes out (see ``llm/blackbox_client.py``).
"""

