def build_grid(mode: str, args: argparse.Namespace) -> List[Dict[str, Any]]:
    """Enumerate the (dataset, size, loss, analysis-value) cells to evaluate."""
    cells: List[Dict[str, Any]] = []
    datasets = list(args.datasets)
    sizes = list(args.sizes)
    losses = list(args.losses)

    if mode == "ablation":
        for ds in datasets:
            for size in sizes:
                for loss in losses:
                    cells.append(
                        dict(
                            dataset=ds,
                            size=size,
                            loss=loss,
                            beam_size=args.beam_size or 3,
                            iterations=args.n_iterations or 4,
                            alpha=args.alpha if args.alpha is not None else DEFAULT_ALPHA,
                        )
                    )
    elif mode == "beams":
        for ds in datasets:
            for size in sizes:
                for k in args.beams:
                    cells.append(
                        dict(
                            dataset=ds,
                            size=size,
                            loss="nce",
                            beam_size=int(k),
                            iterations=args.n_iterations or 4,
                            alpha=args.alpha if args.alpha is not None else DEFAULT_ALPHA,
                        )
                    )
    elif mode == "iterations":
        for ds in datasets:
            for size in sizes:
                for t in args.iterations:
                    cells.append(
                        dict(
                            dataset=ds,
                            size=size,
                            loss="nce",
                            beam_size=args.beam_size or 3,
                            iterations=int(t),
                            alpha=args.alpha if args.alpha is not None else DEFAULT_ALPHA,
                        )
                    )
    elif mode == "alphas":
        for ds in datasets:
            for size in sizes:
                for a in args.alphas:
                    cells.append(
                        dict(
                            dataset=ds,
                            size=size,
                            loss="nce",
                            beam_size=args.beam_size or 3,
                            iterations=args.n_iterations or 4,
                            alpha=float(a),
                        )
                    )
    elif mode == "curves":
        for ds in datasets:
            for size in sizes:
                cells.append(
                    dict(
                        dataset=ds,
                        size=size,
                        loss="nce",
                        beam_size=args.beam_size or 3,
                        iterations=args.n_iterations or 4,
                        alpha=args.alpha if args.alpha is not None else DEFAULT_ALPHA,
                    )
                )
    else:  # pragma: no cover - argparse restricts the choices
        raise ValueError("unknown mode %r" % mode)
    return cells


