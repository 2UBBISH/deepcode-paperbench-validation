class GoalConditionedPolicy(nn.Module):
    """Tanh-squashed Gaussian policy ``pi(a | s, g)`` with an MLP trunk."""

    def __init__(
        self,
        input_dim: int,
        action_dim: int,
        hidden_dims: Sequence[int] = DEFAULT_GC_HIDDEN_DIMS,
        activation: str = "relu",
        use_layer_norm: bool = False,
        action_low: Union[float, Sequence[float]] = -1.0,
        action_high: Union[float, Sequence[float]] = 1.0,
        log_std_min: float = DEFAULT_GC_LOG_STD_MIN,
        log_std_max: float = DEFAULT_GC_LOG_STD_MAX,
        init_gain: Optional[float] = None,
    ) -> None:
        super().__init__()
        if not _HAS_TORCH:
            raise RuntimeError("torch is required for GoalConditionedPolicy")
        self.input_dim = int(input_dim)
        self.action_dim = int(action_dim)
        self.log_std_min = float(log_std_min)
        self.log_std_max = float(log_std_max)

        gain = math.sqrt(2.0) if init_gain is None else float(init_gain)
        self.net = build_gc_mlp(
            self.input_dim,
            hidden_dims=tuple(hidden_dims),
            output_dim=2 * self.action_dim,
            activation=activation,
            output_activation=None,
            use_layer_norm=use_layer_norm,
            init_gain=gain,
        )

        low = np.broadcast_to(np.asarray(action_low, dtype=np.float32), (self.action_dim,)).copy()
        high = np.broadcast_to(np.asarray(action_high, dtype=np.float32), (self.action_dim,)).copy()
        self.register_buffer("action_scale", torch.as_tensor((high - low) / 2.0, dtype=torch.float32))
        self.register_buffer("action_bias", torch.as_tensor((high + low) / 2.0, dtype=torch.float32))

    # -- distribution -------------------------------------------------------
    def distribution(self, x: "torch.Tensor") -> "torch.distributions.Normal":
        out = self.net(x)
        mean, log_std = torch.split(out, self.action_dim, dim=-1)
        log_std = torch.clamp(log_std, self.log_std_min, self.log_std_max)
        return torch.distributions.Normal(mean, log_std.exp())

    def forward(self, x: "torch.Tensor") -> "torch.distributions.Normal":
        return self.distribution(x)

    def log_prob(self, x: "torch.Tensor", actions: "torch.Tensor") -> "torch.Tensor":
        dist = self.distribution(x)
        y = torch.clamp(actions, -1.0 + 1e-6, 1.0 - 1e-6)
        pre = torch.atanh(y)
        log_prob = dist.log_prob(pre)
        # tanh change-of-variables correction
        log_prob = log_prob - torch.log(1.0 - actions.pow(2) + 1e-6)
        return log_prob.sum(dim=-1)

    def sample(self, x: "torch.Tensor", deterministic: bool = False) -> "torch.Tensor":
        dist = self.distribution(x)
        raw = dist.mean if deterministic else dist.rsample()
        return torch.tanh(raw) * self.action_scale + self.action_bias


class GCIQLAgent(nn.Module):
    """Goal-conditioned IQL agent: ``Q(s,g,a)``, ``V(s,g)``, ``pi(a|s,g)``.

    Goals and observations are concatenated (addendum).  Rewards are *not* taken
    from the environment: they are generated by the goal-conditioned
    preprocessor (0 at the goal, -1 otherwise).
    """

    def __init__(
        self,
        state_dim: int,
        action_dim: int,
        goal_dim: Optional[int] = None,
        hidden_dims: Sequence[int] = DEFAULT_GC_HIDDEN_DIMS,
        expectile: float = DEFAULT_EXPECTILE,
        awr_temperature: float = DEFAULT_AWR_TEMPERATURE,
        discount: float = DEFAULT_GC_DISCOUNT,
        target_update_rate: float = DEFAULT_TARGET_UPDATE_RATE,
        learning_rate: float = DEFAULT_GC_LEARNING_RATE,
        activation: str = "relu",
        use_layer_norm: bool = False,
        action_low: Union[float, Sequence[float]] = -1.0,
        action_high: Union[float, Sequence[float]] = 1.0,
        log_std_min: float = DEFAULT_GC_LOG_STD_MIN,
        log_std_max: float = DEFAULT_GC_LOG_STD_MAX,
        exp_adv_clamp: float = DEFAULT_GC_EXP_ADV_CLAMP,
        update_policy: bool = True,
        tau: Optional[float] = None,
        device: Optional[Union[str, "torch.device"]] = None,
        name: str = "gc-iql",
    ) -> None:
        super().__init__()
        if not _HAS_TORCH:
            raise RuntimeError("torch is required for GCIQLAgent")

        self.name = name
        self.state_dim = int(state_dim)
        self.action_dim = int(action_dim)
        self.goal_dim = int(goal_dim if goal_dim is not None else state_dim)
        self.goal_input_dim = self.state_dim + self.goal_dim

        self.hidden_dims = tuple(hidden_dims)
        self.expectile = float(expectile)
        self.awr_temperature = float(awr_temperature)
        self.discount = float(discount)
        self.target_update_rate = float(tau if tau is not None else target_update_rate)
        self.exp_adv_clamp = float(exp_adv_clamp)
        self.update_policy = bool(update_policy)
        self.activation = activation
        self.use_layer_norm = use_layer_norm
        self.log_std_min = float(log_std_min)
        self.log_std_max = float(log_std_max)
        gain = math.sqrt(2.0)

        self.q1 = build_gc_mlp(
            self.goal_input_dim + self.action_dim,
            hidden_dims=self.hidden_dims,
            output_dim=1,
            activation=activation,
            use_layer_norm=use_layer_norm,
            init_gain=gain,
        )
        self.q2 = build_gc_mlp(
            self.goal_input_dim + self.action_dim,
            hidden_dims=self.hidden_dims,
            output_dim=1,
            activation=activation,
            use_layer_norm=use_layer_norm,
            init_gain=gain,
        )
        self.q1_target = copy.deepcopy(self.q1)
        self.q2_target = copy.deepcopy(self.q2)
        self.q1_target.requires_grad_(False)
        self.q2_target.requires_grad_(False)

        self.v = build_gc_mlp(
            self.goal_input_dim,
            hidden_dims=self.hidden_dims,
            output_dim=1,
            activation=activation,
            use_layer_norm=use_layer_norm,
            init_gain=gain,
        )
        self.policy = GoalConditionedPolicy(
            self.goal_input_dim,
            self.action_dim,
            hidden_dims=self.hidden_dims,
            activation=activation,
            use_layer_norm=use_layer_norm,
            action_low=action_low,
            action_high=action_high,
            log_std_min=log_std_min,
            log_std_max=log_std_max,
            init_gain=gain,
        )

        self.learning_rate = float(learning_rate)
        self.q_optimizer = torch.optim.Adam(
            list(self.q1.parameters()) + list(self.q2.parameters()), lr=self.learning_rate
        )
        self.v_optimizer = torch.optim.Adam(self.v.parameters(), lr=self.learning_rate)
        self.policy_optimizer = torch.optim.Adam(self.policy.parameters(), lr=self.learning_rate)
        self.train_steps = 0

        if device is not None:
            self.to(device)

    # -- helpers ------------------------------------------------------------
    @staticmethod
    def compose(states: "torch.Tensor", goals: "torch.Tensor") -> "torch.Tensor":
        """Concatenate observation and goal (addendum: "goals and observations are concatenated")."""
        states = torch.as_tensor(states, dtype=torch.float32)
        goals = torch.as_tensor(goals, dtype=torch.float32)
        if states.ndim == 1:
            states = states.unsqueeze(0)
        if goals.ndim == 1:
            goals = goals.unsqueeze(0)
        if goals.shape[0] != states.shape[0]:
            if goals.shape[0] == 1:
                goals = goals.expand(states.shape[0], -1)
            else:
                raise ValueError(f"goal batch {tuple(goals.shape)} incompatible with states {tuple(states.shape)}")
        return torch.cat([states, goals], dim=-1)

    def _as_tensor(self, x: Any) -> "torch.Tensor":
        if isinstance(x, torch.Tensor):
            return x.to(next(self.parameters()).device).float()
        return torch.as_tensor(np.asarray(x), dtype=torch.float32, device=next(self.parameters()).device)

    # -- losses -------------------------------------------------------------
    def q_loss_fn(
        self,
        states: "torch.Tensor",
        actions: "torch.Tensor",
        rewards: "torch.Tensor",
        next_states: "torch.Tensor",
        goals: "torch.Tensor",
        next_goals: Optional["torch.Tensor"] = None,
        dones: Optional["torch.Tensor"] = None,
    ) -> Tuple["torch.Tensor", Dict[str, float]]:
        if next_goals is None:
            next_goals = goals
        if dones is None:
            dones = torch.zeros_like(rewards)
        x = self.compose(states, goals)
        xn = self.compose(next_states, next_goals)

        with torch.no_grad():
            # paper's Bellman target: eta(s) + gamma * E[max_a' Q_target(s', a', z)]
            a_next = self.policy.sample(xn, deterministic=False)
            q_next = torch.minimum(self.q1_target(xn, a_next), self.q2_target(xn, a_next))
            target_q = rewards + self.discount * (1.0 - dones) * q_next

        q1 = self.q1(x, actions)
        q2 = self.q2(x, actions)
        loss = F.mse_loss(q1, target_q) + F.mse_loss(q2, target_q)
        metrics = {
            "q_loss": float(loss.detach().cpu()),
            "q_mean": float(((q1 + q2) / 2.0).mean().detach().cpu()),
            "target_q_mean": float(target_q.mean().detach().cpu()),
            "reward_mean": float(rewards.mean().detach().cpu()),
        }
        return loss, metrics

    def value_loss_fn(self, states: "torch.Tensor", goals: "torch.Tensor", actions: "torch.Tensor") -> Tuple["torch.Tensor", Dict[str, float]]:
        x = self.compose(states, goals)
        with torch.no_grad():
            q = torch.minimum(self.q1(x, actions), self.q2(x, actions))
        v = self.v(x)
        loss = expectile_loss(q - v, expectile=self.expectile)
        metrics = {"v_loss": float(loss.detach().cpu()), "v_mean": float(v.mean().detach().cpu())}
        return loss, metrics

    def policy_loss_fn(self, states: "torch.Tensor", goals: "torch.Tensor", actions: "torch.Tensor") -> Tuple["torch.Tensor", Dict[str, float]]:
        x = self.compose(states, goals)
        with torch.no_grad():
            q = torch.minimum(self.q1(x, actions), self.q2(x, actions))
            v = self.v(x)
            adv = q - v
        log_probs = self.policy.log_prob(x, actions)
        loss = awr_loss(log_probs, adv, temperature=self.awr_temperature, clamp=self.exp_adv_clamp)
        metrics = {
            "policy_loss": float(loss.detach().cpu()),
            "log_prob_mean": float(log_probs.mean().detach().cpu()),
            "advantage_mean": float(adv.mean().detach().cpu()),
        }
        return loss, metrics

    # -- update -------------------------------------------------------------
    def update(self, batch: Mapping[str, Any]) -> Dict[str, float]:
        """One GC-IQL update: Q -> V -> pi -> Polyak."""
        states = self._as_tensor(batch["observations"])
        actions = self._as_tensor(batch["actions"])
        rewards = self._as_tensor(batch["rewards"]).reshape(-1, 1)
        next_states = self._as_tensor(batch.get("next_observations", batch["observations"]))
        goals = self._as_tensor(batch["goals"])
        next_goals = self._as_tensor(batch["next_goals"]) if "next_goals" in batch and batch["next_goals"] is not None else None
        dones = self._as_tensor(batch["dones"]).reshape(-1, 1) if batch.get("dones") is not None else None

        q_loss, metrics = self.q_loss_fn(states, actions, rewards, next_states, goals, next_goals, dones)
        self.q_optimizer.zero_grad(set_to_none=True)
        q_loss.backward()
        self.q_optimizer.step()

        v_loss, v_metrics = self.value_loss_fn(states, goals, actions)
        self.v_optimizer.zero_grad(set_to_none=True)
        v_loss.backward()
        self.v_optimizer.step()

        metrics.update(v_metrics)

        if self.update_policy:
            pi_loss, pi_metrics = self.policy_loss_fn(states, goals, actions)
            self.policy_optimizer.zero_grad(set_to_none=True)
            pi_loss.backward()
            self.policy_optimizer.step()
            metrics.update(pi_metrics)

        polyak_update(self.q1_target, self.q1, self.target_update_rate)
        polyak_update(self.q2_target, self.q2, self.target_update_rate)
        self.train_steps += 1
        metrics["train_steps"] = float(self.train_steps)
        return metrics

    update_from_batch = update
    train_step = update

    # -- acting -------------------------------------------------------------
    @torch.no_grad()
    def select_action(
        self,
        states: Any,
        goals: Any = None,
        deterministic: bool = False,
    ) -> np.ndarray:
        """Act with the goal-conditioned policy (evaluation: the task's ground-truth goal)."""
        states_t = self._as_tensor(states)
        if states_t.ndim == 1:
            states_t = states_t.unsqueeze(0)
        if goals is None:
            goals_t = torch.zeros(states_t.shape[0], self.goal_dim, device=states_t.device)
        else:
            goals_t = self._as_tensor(goals)
            if goals_t.ndim == 1:
                goals_t = goals_t.unsqueeze(0)
            if goals_t.shape[0] == 1 and states_t.shape[0] > 1:
                goals_t = goals_t.expand(states_t.shape[0], -1)
        x = self.compose(states_t, goals_t)
        actions = self.policy.sample(x, deterministic=deterministic)
        return actions.detach().cpu().numpy()

    def act(self, states: Any, goals: Any = None, deterministic: bool = False) -> np.ndarray:
        return self.select_action(states, goals, deterministic=deterministic)

    def __call__(self, states: Any, goals: Any = None) -> np.ndarray:  # pragma: no cover - convenience
        return self.select_action(states, goals, deterministic=True)

    def select_actions(self, states: Any, goals: Any = None, deterministic: bool = False) -> np.ndarray:
        return self.select_action(states, goals, deterministic=deterministic)

    # -- misc ---------------------------------------------------------------
    def hparams(self) -> Dict[str, Any]:
        return {
            "name": self.name,
            "state_dim": self.state_dim,
            "action_dim": self.action_dim,
            "goal_dim": self.goal_dim,
            "hidden_dims": list(self.hidden_dims),
            "expectile": self.expectile,
            "awr_temperature": self.awr_temperature,
            "discount": self.discount,
            "target_update_rate": self.target_update_rate,
            "learning_rate": self.learning_rate,
            "activation": self.activation,
            "use_layer_norm": self.use_layer_norm,
        }

    def to(self, device: Any) -> "GCIQLAgent":  # type: ignore[override]
        super().to(device)
        self.q1_target.requires_grad_(False)
        self.q2_target.requires_grad_(False)
        return self

    def extra_repr(self) -> str:  # pragma: no cover - cosmetic
        return (
            f"state_dim={self.state_dim}, goal_dim={self.goal_dim}, action_dim={self.action_dim}, "
            f"hidden_dims={self.hidden_dims}"
        )


