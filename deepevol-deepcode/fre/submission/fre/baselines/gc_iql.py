"""Goal-Conditioned IQL (GC-IQL) baseline for FRE zero-shot offline RL.

Reference
---------
Kostrikov et al. (2021), *Offline Reinforcement Learning with Implicit
Q-Learning*, in its goal-conditioned form.  The paper's addendum specifies the
variant used by the FRE benchmark:

    GC-IQL is just IQL with the additional goal state.

    Specifically, given a random state, a random goal state is sampled from
    1) future states in the trajectory using a geometric distribution,
    2) a random goal in the dataset, or
    3) the current state is the goal, in which case the reward is 0 and the
    mask/terminal flag is True.  In other cases, reward is -1.
    The ratio is p_randomgoal=0.3, p_geometric_goal=0.5, p_current_goal=0.2.

    To give the information to the neural network, goals and observations are
    concatenated.

    No environment rewards are used to train GC-IQL.  The reward passed to IQL
    are the goal-conditioned rewards generated by the preprocessor as described
    above, which is 0 if the state==goal and -1 otherwise.

    Evaluation: the goal-conditioned agent is given the ground-truth goal that
    the specific evaluation task contains, to condition on.

And Section 5.2:

    All methods are evaluated using a mean over twenty evaluation episodes, and
    each agent is trained using five random seeds [...].  FRE, GC-IQL, and
    GC-BC are implemented within the same codebase and with the same network
    structure.

Implementation notes (nothing in the paper fixes these, so sensible defaults):
  * Q(s,g,a), V(s,g) and pi(a|s,g) are `[512, 512, 512]` ReLU MLPs taking the
    concatenation ``[observation, goal]`` as input (no LayerNorm for GC-IQL).
  * Expectile 0.8, AWR temperature 3.0, discount 0.88, Polyak rate 0.001 and
    Adam lr 1e-4 (identical to the FRE agent's IQL hyperparameters).
  * The Bellman target uses the paper's `max_a' Q_target(s',g,a')` form, i.e.
    the classic IQL (non-pessimistic) target.
  * Geometric future-goal sampling uses ``p = 0.5`` over future offsets within
    the same trajectory.
"""

