def _filter_kwargs(fn: Callable[..., Any], kwargs: Mapping[str, Any]) -> Dict[str, Any]:
    """Keep only kwargs accepted by ``fn`` (tolerant interface matching)."""
    try:
        params = inspect.signature(fn).parameters
    except (TypeError, ValueError):  # pragma: no cover
        return dict(kwargs)
    if "kwargs" in params or "kwargs" in [p.name for p in params.values() if p.kind == p.VAR_KEYWORD]:
        return dict(kwargs)
    allowed = set(params)
    return {k: v for k, v in kwargs.items() if k in allowed}


