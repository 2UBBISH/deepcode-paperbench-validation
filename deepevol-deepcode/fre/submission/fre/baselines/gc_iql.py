def _trajectory_bounds(dataset: Any, indices: np.ndarray) -> Tuple[np.ndarray, np.ndarray]:
    """Return ``(traj_start, traj_end)`` for each index (inclusive endpoints)."""
    n = len(indices)
    starts = getattr(dataset, "traj_starts", None)
    ends = getattr(dataset, "traj_ends", None)
    traj_ids = getattr(dataset, "trajectory_ids", None)

    if starts is not None and ends is not None and traj_ids is not None:
        starts = np.asarray(starts, dtype=np.int64)
        ends = np.asarray(ends, dtype=np.int64)
        traj_ids = np.asarray(traj_ids, dtype=np.int64)
        # trajectory_ids maps transition -> trajectory slot
        slots = traj_ids[indices]
        if starts.shape[0] == int(traj_ids.max()) + 1:
            return starts[slots].astype(np.int64), ends[slots].astype(np.int64)
        # traj_ids may directly be the start index of the transition's trajectory
        base = traj_ids[indices].astype(np.int64)
        length = getattr(dataset, "max_trajectory_length", None)
        if length is None:
            length = getattr(dataset, "episode_length", None)
        if length is None:
            # fall back to the whole dataset as a single trajectory chunk
            length = max(1, int(len(dataset)) // max(1, len(np.unique(base))))
        return base, np.minimum(base + int(length) - 1, len(dataset) - 1)

    # Fallback: treat the dataset as one long trajectory.
    return np.zeros(n, dtype=np.int64), np.full(n, len(dataset) - 1, dtype=np.int64)


def sample_goal_indices(
    dataset_or_num_states: Any,
    indices: np.ndarray,
    rng: np.random.Generator,
    p_current: float = DEFAULT_P_CURRENT_GOAL,
    p_future: float = DEFAULT_P_FUTURE_GOAL,
    p_random: float = DEFAULT_P_RANDOM_GOAL,
    geometric_p: float = DEFAULT_GEOMETRIC_P,
    min_offset: int = 1,
) -> np.ndarray:
    """Sample goal indices for a batch of state indices.

    Mixing distribution (addendum): ``p_current=0.2`` (goal is the current
    state), ``p_future=0.5`` (a future state in the same trajectory drawn from a
    geometric distribution), ``p_random=0.3`` (a random dataset state).
    """
    dataset = dataset_or_num_states
    indices = np.asarray(indices, dtype=np.int64).reshape(-1)
    n = indices.shape[0]
    if n == 0:
        return indices.copy()

    num_states = int(len(dataset)) if hasattr(dataset, "__len__") else int(dataset)

    probs = np.asarray([p_current, p_future, p_random], dtype=np.float64)
    probs = probs / max(probs.sum(), 1e-8)
    mode = rng.choice(3, size=n, p=probs)

    goals = indices.copy()

    # --- future goals (geometric offset inside the same trajectory) ---------
    fut = np.flatnonzero(mode == 1)
    if fut.size:
        starts, ends = _trajectory_bounds(dataset, indices)
        offsets = rng.geometric(p=geometric_p, size=fut.size).astype(np.int64)
        offsets = np.maximum(offsets, min_offset)
        candidate = indices[fut] + offsets
        # keep the goal inside the same trajectory
        candidate = np.minimum(candidate, ends[fut])
        goal_idx = np.maximum(candidate, starts[fut])
        goals[fut] = goal_idx

    # --- random goals -------------------------------------------------------
    rnd = np.flatnonzero(mode == 2)
    if rnd.size:
        goals[rnd] = rng.integers(0, max(num_states, 1), size=rnd.size)

    # --- current goals ------------------------------------------------------
    cur = np.flatnonzero(mode == 0)
    if cur.size:
        goals[cur] = indices[cur]

    goals = np.clip(goals, 0, max(num_states - 1, 0))
    return goals


def sample_hindsight_goals(
    dataset: Any,
    indices: np.ndarray,
    rng: np.random.Generator,
    p_current: float = DEFAULT_P_CURRENT_GOAL,
    p_future: float = DEFAULT_P_FUTURE_GOAL,
    p_random: float = DEFAULT_P_RANDOM_GOAL,
    geometric_p: float = DEFAULT_GEOMETRIC_P,
    min_offset: int = 1,
) -> np.ndarray:
    """Goals (states) sampled with the GC-IQL HER distribution."""
    goal_idx = sample_goal_indices(
        dataset,
        indices,
        rng,
        p_current=p_current,
        p_future=p_future,
        p_random=p_random,
        geometric_p=geometric_p,
        min_offset=min_offset,
    )
    states = np.asarray(dataset.observations, dtype=np.float32)
    return states[goal_idx]


class GoalSampler:
    """Stateless helper bundling the GC-IQL HER goal distribution."""

    def __init__(
        self,
        p_current: float = DEFAULT_P_CURRENT_GOAL,
        p_future: float = DEFAULT_P_FUTURE_GOAL,
        p_random: float = DEFAULT_P_RANDOM_GOAL,
        geometric_p: float = DEFAULT_GEOMETRIC_P,
        min_offset: int = 1,
        seed: int = 0,
    ) -> None:
        self.p_current = float(p_current)
        self.p_future = float(p_future)
        self.p_random = float(p_random)
        self.geometric_p = float(geometric_p)
        self.min_offset = int(min_offset)
        self.rng = np.random.default_rng(seed)

    def __call__(self, dataset: Any, indices: np.ndarray) -> np.ndarray:
        return sample_hindsight_goals(
            dataset,
            indices,
            self.rng,
            p_current=self.p_current,
            p_future=self.p_future,
            p_random=self.p_random,
            geometric_p=self.geometric_p,
            min_offset=self.min_offset,
        )


