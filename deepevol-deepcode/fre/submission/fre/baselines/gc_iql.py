def _to_numpy(x: Any) -> np.ndarray:
    if isinstance(x, np.ndarray):
        return x
    if _HAS_TORCH and torch is not None and isinstance(x, torch.Tensor):
        return x.detach().cpu().numpy()
    return np.asarray(x)


def goal_conditioned_reward(
    states: Any,
    goals: Any,
    threshold: Optional[float] = None,
    distance_dims: Optional[Sequence[int]] = None,
    state_std: Optional[np.ndarray] = None,
    reward_unachieved: float = DEFAULT_REWARD_UNACHIEVED,
    reward_reached: float = DEFAULT_REWARD_REACHED,
) -> np.ndarray:
    """Binary goal-conditioned reward: ``reward_reached`` at the goal else ``reward_unachieved``.

    ``threshold=None`` reproduces the addendum exactly (``reward is 0 if the
    state==goal and -1 otherwise``, i.e. exact equality).  A numeric threshold
    switches to a Euclidean radius test (used when goals are not drawn from the
    dataset itself, e.g. for evaluation).
    """
    states = np.asarray(_to_numpy(states), dtype=np.float64)
    goals = np.asarray(_to_numpy(goals), dtype=np.float64)
    if states.ndim == 1:
        states = states[None, :]
    if goals.ndim == 1:
        goals = goals[None, :]
    if distance_dims is not None:
        dims = np.asarray(list(distance_dims), dtype=np.int64)
        states = states[..., dims]
        goals = goals[..., dims]
    if state_std is not None:
        std = np.asarray(state_std, dtype=np.float64).reshape(1, -1)
        if std.shape[-1] != states.shape[-1]:
            std = std[:, : states.shape[-1]]
        states = states / np.maximum(std, 1e-8)
        goals = goals / np.maximum(std, 1e-8)

    if threshold is None:
        diff = np.abs(states - goals)
        reached = np.all(diff <= 1e-8, axis=-1)
    else:
        dist = np.linalg.norm(states - goals, axis=-1)
        reached = dist < float(threshold)

    return np.where(reached, float(reward_reached), float(reward_unachieved)).astype(np.float32)


