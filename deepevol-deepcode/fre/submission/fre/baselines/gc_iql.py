def train_gc_iql(
    dataset: Any = None,
    config: Optional[GCIQLConfig] = None,
    steps: Optional[int] = None,
    device: Optional[Any] = None,
    agent: Optional[GCIQLAgent] = None,
    progress: bool = True,
    log_every: int = 5000,
    log_fn: Optional[Callable[[int, Dict[str, float]], None]] = None,
    **config_overrides: Any,
) -> Dict[str, Any]:
    """Train a GC-IQL agent on an offline dataset (no environment rewards)."""
    if not _HAS_TORCH:
        raise RuntimeError("torch is required to train GC-IQL")

    config = config or GCIQLConfig()
    if config_overrides:
        config = config.replace(**{k: v for k, v in config_overrides.items() if hasattr(config, k)})
    steps = int(steps if steps is not None else config.steps)

    if device is not None:
        config = config.replace(device=str(device))
    device_t = torch.device(config.device)

    obs = _dataset_array(dataset, "observations", "states")
    actions = _dataset_array(dataset, "actions")
    if obs is None:
        raise ValueError("dataset does not expose observations/states")
    state_dim = int(config.state_dim or obs.shape[-1])
    action_dim = int(config.action_dim or (actions.shape[-1] if actions is not None else 0))
    goal_dim = int(config.goal_dim or state_dim)

    if agent is None:
        agent = GCIQLAgent(
            state_dim=state_dim,
            action_dim=action_dim,
            goal_dim=goal_dim,
            hidden_dims=config.hidden_dims,
            expectile=config.expectile,
            awr_temperature=config.awr_temperature,
            discount=config.discount,
            target_update_rate=config.target_update_rate,
            learning_rate=config.learning_rate,
            activation=config.activation,
            use_layer_norm=config.use_layer_norm,
            action_low=config.action_low,
            action_high=config.action_high,
            log_std_min=config.log_std_min,
            log_std_max=config.log_std_max,
            exp_adv_clamp=config.exp_adv_clamp,
            update_policy=config.update_policy,
            device=device_t,
        )
    agent.to(device_t)
    agent.train()

    rng = np.random.default_rng(config.seed)
    sampler = GoalSampler(
        p_current=config.p_current,
        p_future=config.p_future,
        p_random=config.p_random,
        geometric_p=config.geometric_p,
        min_offset=config.min_offset,
        seed=config.seed,
    )

    iterator = range(steps)
    if progress:
        try:
            from tqdm.auto import tqdm  # type: ignore

            iterator = tqdm(iterator, desc="gc-iql", total=steps)
        except Exception:  # pragma: no cover
            pass

    history: List[Dict[str, float]] = []
    last_metrics: Dict[str, float] = {}
    start = time.time()
    for step in iterator:
        batch = sample_gc_batch(dataset, config.batch_size, rng, config=config, goal_sampler=sampler)
        metrics = agent.update(batch)
        last_metrics = metrics
        if log_every and (step + 1) % log_every == 0:
            history.append({"step": step + 1, **metrics})
            if log_fn is not None:
                log_fn(step + 1, metrics)
            if progress:
                try:
                    iterator.set_postfix(  # type: ignore[attr-defined]
                        q=metrics.get("q_mean", float("nan")),
                        v=metrics.get("v_mean", float("nan")),
                    )
                except Exception:  # pragma: no cover
                    pass

    return {
        "agent": agent,
        "config": config.to_dict(),
        "steps": steps,
        "history": history,
        "final_metrics": last_metrics,
        "wall_time": time.time() - start,
    }


