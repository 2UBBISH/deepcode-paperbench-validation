def _resolve_device(agent: Any, device: Optional[Any]) -> Any:
    if device is not None:
        return device
    try:
        iter_params = getattr(agent, "parameters")
        return next(iter_params()).device
    except Exception:  # pragma: no cover
        return "cpu"


def antmaze_goal_to_observation(
    goal_xy: Sequence[float],
    dataset: Any = None,
    state_dim: Optional[int] = None,
    discretize: bool = True,
    num_bins: int = 32,
    xy_indices: Sequence[int] = (0, 1),
    xy_min: Optional[Sequence[float]] = None,
    xy_max: Optional[Sequence[float]] = None,
) -> np.ndarray:
    """Convert an AntMaze ``(x, y)`` goal into the observation space used by the agent.

    AntMaze XY coordinates are discretized into 32 bins for FRE/GC-IQL/GC-BC/OPAL
    (Appendix C.1 / addendum), so goals must live in the same space.
    """
    state_dim = int(state_dim or 29)
    goal = np.zeros(state_dim, dtype=np.float32)
    xy = np.asarray(goal_xy, dtype=np.float32).reshape(2)

    if discretize:
        if xy_min is None or xy_max is None:
            obs = _dataset_array(dataset, "observations", "states") if dataset is not None else None
            if obs is not None:
                xy_min = np.min(obs[:, list(xy_indices)], axis=0)
                xy_max = np.max(obs[:, list(xy_indices)], axis=0)
            else:
                xy_min = np.zeros(2, dtype=np.float32)
                xy_max = np.full(2, 36.0, dtype=np.float32)
        xy_min = np.asarray(xy_min, dtype=np.float32).reshape(2)
        xy_max = np.asarray(xy_max, dtype=np.float32).reshape(2)
        rng_span = np.maximum(xy_max - xy_min, 1e-8)
        norm = np.clip((xy - xy_min) / rng_span, 0.0, 1.0)
        binned = np.clip(np.floor(norm * num_bins), 0, num_bins - 1)
        xy = binned.astype(np.float32)

    goal[list(xy_indices)] = xy.astype(np.float32)
    return goal


def goal_from_task(
    task: Any,
    dataset: Any = None,
    state_dim: Optional[int] = None,
    discretize_antmaze: bool = True,
    domain: Optional[str] = None,
    num_bins: int = 32,
) -> np.ndarray:
    """Extract the ground-truth goal a GC agent is conditioned on (addendum)."""
    goal = getattr(task, "goal", None)
    if goal is None:
        metadata = getattr(task, "metadata", None) or {}
        goal = metadata.get("goal") if isinstance(metadata, Mapping) else None

    state_dim = int(state_dim or getattr(task, "state_dim", None) or 29)
    if goal is None:
        return np.zeros(state_dim, dtype=np.float32)

    goal = np.asarray(_to_numpy(goal), dtype=np.float32).reshape(-1)
    if goal.shape[0] == state_dim:
        return goal.astype(np.float32)

    domain = domain or ("antmaze" if getattr(task, "name", "").startswith("ant") else None)
    if domain == "antmaze" and goal.shape[0] >= 2:
        return antmaze_goal_to_observation(
            goal[:2],
            dataset=dataset,
            state_dim=state_dim,
            discretize=discretize_antmaze,
            num_bins=num_bins,
        )

    padded = np.zeros(state_dim, dtype=np.float32)
    dims = min(state_dim, goal.shape[0])
    padded[:dims] = goal[:dims]
    return padded


def gc_iql_action_fn(
    agent: GCIQLAgent,
    goal: Any,
    deterministic: bool = True,
    state_fn: Optional[Callable[[Any], Any]] = None,
) -> Callable[[Any], np.ndarray]:
    """Build an ``action_fn`` for :func:`fre.evaluation.evaluate.rollout_episode`."""

    def action_fn(state: Any) -> np.ndarray:
        obs = state_fn(state) if state_fn is not None else state
        action = agent.select_action(obs, goal, deterministic=deterministic)
        return np.asarray(action).reshape(-1)

    return action_fn


def evaluate_gc_agent(
    agent: GCIQLAgent,
    domain: str = "antmaze",
    task_set: str = "all",
    dataset: Any = None,
    num_episodes: int = 20,
    seeds: Sequence[int] = (0, 1, 2, 3, 4),
    deterministic: bool = True,
    max_episode_steps: Optional[int] = None,
    device: Optional[Any] = None,
    verbose: bool = False,
    discretize_antmaze: bool = True,
    goal_override: Optional[Mapping[str, Any]] = None,
    **task_kwargs: Any,
) -> Dict[str, Any]:
    """Zero-shot style evaluation of GC-IQL using each task's ground-truth goal.

    Returns the same summary structure as ``fre.evaluation.evaluate.evaluate_fre``
    so the CLI/reporting helpers can be shared.
    """
    from fre.envs import build_tasks, domain_from_task_name  # local import (heavy deps)
    from fre.evaluation.metrics import NUM_EVAL_EPISODES, NUM_SEEDS, aggregate_seeds, aggregate_tasks
    from fre.evaluation.evaluate import (
        RolloutResult,
        normalize_episode_return,
        resolve_return_range,
        rollout_episode,
    )

    domain = domain_from_task_name(task_set) if task_set and str(task_set).startswith(("ant", "exorl", "kitchen")) else domain
    base = str(domain).split(":")[0]
    tasks = build_tasks(domain, task_set=task_set, dataset_states=None, **task_kwargs) if hasattr(build_tasks, "__call__") else []
    if not tasks:
        raise ValueError(f"no evaluation tasks found for domain={domain!r} task_set={task_set!r}")

    num_episodes = int(num_episodes or NUM_EVAL_EPISODES)
    seeds = tuple(seeds or tuple(range(NUM_SEEDS)))
    goal_override = dict(goal_override or {})

    per_task: Dict[str, Any] = {}
    for task in tasks:
        env = None
        task_name = getattr(task, "name", str(task))
        per_seed: List[Dict[str, float]] = []
        for seed in seeds:
            env = _make_task_env_for_domain(base, task, seed=seed, max_episode_steps=max_episode_steps)
            goal = goal_override.get(task_name)
            if goal is None:
                state_dim = getattr(agent, "state_dim", None)
                goal = goal_from_task(
                    task,
                    dataset=dataset,
                    state_dim=state_dim,
                    discretize_antmaze=discretize_antmaze,
                    domain=base,
                )
            else:
                goal = np.asarray(_to_numpy(goal), dtype=np.float32).reshape(-1)
            action_fn = gc_iql_action_fn(agent, goal, deterministic=deterministic)

            returns: List[float] = []
            successes = 0
            for ep in range(num_episodes):
                result: "RolloutResult" = rollout_episode(
                    env,
                    action_fn,
                    task,
                    max_episode_steps=max_episode_steps,
                    seed=int(seed) * 10_000 + ep,
                )
                returns.append(float(result.return_))
                successes += int(bool(result.success))
            aggregated = aggregate_seeds([{"seed": int(seed), "mean_return": float(np.mean(returns))}])
            per_seed.append(
                {
                    "seed": int(seed),
                    "mean_return": float(np.mean(returns)),
                    "std_return": float(np.std(returns)),
                    "success_rate": successes / max(num_episodes, 1),
                    "normalized_mean": aggregated.get("normalized_mean", float("nan")),
                }
            )
            if env is not None:
                try:
                    env.close()
                except Exception:  # pragma: no cover
                    pass
                env = None

        raw_mean = float(np.mean([s["mean_return"] for s in per_seed]))
        raw_std = float(np.std([s["mean_return"] for s in per_seed]))
        ref_min, ref_max = resolve_return_range(task)
        per_task[task_name] = {
            "task": task_name,
            "task_set": getattr(task, "task_set", task_set),
            "mean": raw_mean,
            "std": raw_std,
            "normalized": normalize_episode_return(raw_mean, ref_min, ref_max, clip=True),
            "success_rate": float(np.mean([s["success_rate"] for s in per_seed])),
            "num_seeds": len(per_seed),
            "per_seed": per_seed,
        }
        if verbose:
            print(f"[gc-iql] {task_name}: {per_task[task_name]['normalized']:.1f}")

    summary = {
        "method": "gc_iql",
        "domain": domain,
        "task_set": task_set,
        "tasks": per_task,
        "task_sets": aggregate_tasks(list(per_task.values())),
    }
    try:
        summary["task_sets"] = aggregate_tasks(list(per_task.values()))
    except Exception:  # pragma: no cover
        pass
    return summary


def _make_task_env_for_domain(domain: str, task: Any, seed: Optional[int] = None, max_episode_steps: Optional[int] = None) -> Any:
    domain = str(domain).split(":")[0]
    if domain == "antmaze":
        from fre.envs.antmaze_tasks import make_antmaze_task_env

        return make_antmaze_task_env(task, seed=seed, max_episode_steps=max_episode_steps)
    if domain in ("exorl", "walker", "cheetah"):
        from fre.envs.exorl_tasks import make_exorl_task_env

        return make_exorl_task_env(task, seed=seed, max_episode_steps=max_episode_steps)
    if domain == "kitchen":
        from fre.envs.kitchen_tasks import make_kitchen_task_env

        return make_kitchen_task_env(task, seed=seed, max_episode_steps=max_episode_steps)
    raise ValueError(f"unknown domain {domain!r}")


def evaluate_gc_iql(*args: Any, **kwargs: Any) -> Dict[str, Any]:
    """Alias for :func:`evaluate_gc_agent`."""
    return evaluate_gc_agent(*args, **kwargs)


