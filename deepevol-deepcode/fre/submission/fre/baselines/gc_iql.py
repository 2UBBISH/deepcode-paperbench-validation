def _dataset_array(dataset: Any, *names: str) -> Optional[np.ndarray]:
    for name in names:
        value = getattr(dataset, name, None)
        if value is None:
            continue
        if callable(value):
            try:
                value = value()
            except TypeError:
                continue
        return np.asarray(value, dtype=np.float32)
    return None


def _next_state_indices(dataset: Any, indices: np.ndarray) -> np.ndarray:
    """Next-state indices respecting trajectory boundaries."""
    n_states = len(dataset)
    next_idx = np.minimum(np.asarray(indices, dtype=np.int64) + 1, n_states - 1)
    traj_ids = getattr(dataset, "trajectory_ids", None)
    if traj_ids is not None:
        traj_ids = np.asarray(traj_ids, dtype=np.int64)
        last_of_traj = np.arange(1, n_states)[traj_ids[1:] != traj_ids[:-1]] if n_states > 0 else np.array([], dtype=np.int64)
        if last_of_traj.size:
            bad = np.isin(next_idx, last_of_traj)
            next_idx[bad] = indices[bad]
    return next_idx


def sample_gc_batch(
    dataset: Any,
    batch_size: int,
    rng: np.random.Generator,
    config: Optional[GCIQLConfig] = None,
    goal_sampler: Optional[GoalSampler] = None,
) -> Dict[str, np.ndarray]:
    """Sample a GC-IQL training batch with hindsight-relabelled goals and rewards."""
    config = config or GCIQLConfig()
    obs = _dataset_array(dataset, "observations", "states")
    if obs is None:  # pragma: no cover - defensive
        raise ValueError("dataset does not expose observations/states")
    actions = _dataset_array(dataset, "actions")
    n = len(dataset)

    # --- sample transition indices ----------------------------------------
    indices = None
    for candidate in ("sample_indices", "sample"):
        fn = getattr(dataset, candidate, None)
        if callable(fn):
            try:
                indices = np.asarray(fn(batch_size), dtype=np.int64).reshape(-1)
                break
            except TypeError:
                try:
                    indices = np.asarray(fn(batch_size, rng=rng), dtype=np.int64).reshape(-1)
                    break
                except Exception:  # pragma: no cover
                    continue
            except Exception:  # pragma: no cover
                continue
    if indices is None or indices.size == 0:
        indices = rng.integers(0, max(n, 1), size=batch_size)

    next_idx = _next_state_indices(dataset, indices)

    # --- sample goals (HER mixture) ---------------------------------------
    sampler = goal_sampler or GoalSampler(
        p_current=config.p_current,
        p_future=config.p_future,
        p_random=config.p_random,
        geometric_p=config.geometric_p,
        min_offset=config.min_offset,
        seed=config.seed,
    )
    goal_idx = sample_goal_indices(
        dataset,
        indices,
        sampler.rng,
        p_current=config.p_current,
        p_future=config.p_future,
        p_random=config.p_random,
        geometric_p=config.geometric_p,
        min_offset=config.min_offset,
    )
    goals = obs[goal_idx]

    reward_states = obs[next_idx] if config.relabel_target == "next" else obs[indices]
    rewards = goal_conditioned_reward(
        reward_states,
        goals,
        threshold=config.goal_threshold,
        distance_dims=config.goal_distance_dims,
        state_std=config.state_std,
    )
    dones = (rewards > DEFAULT_REWARD_UNACHIEVED + 1e-6).astype(np.float32)

    batch: Dict[str, np.ndarray] = {
        "observations": obs[indices].astype(np.float32),
        "actions": (actions[indices] if actions is not None else np.zeros((len(indices), 0), dtype=np.float32)).astype(np.float32),
        "rewards": rewards.astype(np.float32),
        "next_observations": obs[next_idx].astype(np.float32),
        "dones": dones.astype(np.float32),
        "goals": goals.astype(np.float32),
        "next_goals": goals.astype(np.float32),
        "indices": indices.astype(np.int64),
    }
    return batch


