def build_arg_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="GC-IQL baseline for zero-shot offline RL")
    parser.add_argument("--domain", type=str, default="antmaze")
    parser.add_argument("--task-set", type=str, default="all")
    parser.add_argument("--steps", type=int, default=DEFAULT_GC_TRAIN_STEPS)
    parser.add_argument("--batch-size", type=int, default=DEFAULT_GC_BATCH_SIZE)
    parser.add_argument("--lr", type=float, default=DEFAULT_GC_LEARNING_RATE)
    parser.add_argument("--expectile", type=float, default=DEFAULT_EXPECTILE)
    parser.add_argument("--temperature", type=float, default=DEFAULT_AWR_TEMPERATURE)
    parser.add_argument("--discount", type=float, default=DEFAULT_GC_DISCOUNT)
    parser.add_argument("--tau", type=float, default=DEFAULT_TARGET_UPDATE_RATE)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--device", type=str, default="cpu")
    parser.add_argument("--dataset-path", type=str, default=None)
    parser.add_argument("--dataset-dir", type=str, default=None)
    parser.add_argument("--env-name", type=str, default=None)
    parser.add_argument("--run-dir", type=str, default=None)
    parser.add_argument("--num-episodes", type=int, default=20)
    parser.add_argument("--eval-seeds", type=int, default=5)
    parser.add_argument("--eval", action="store_true", help="run zero-shot evaluation after training")
    parser.add_argument("--log-every", type=int, default=5000)
    return parser


def main(argv: Optional[Sequence[str]] = None) -> int:
    args, _unknown = build_arg_parser().parse_known_args(argv)
    if not _HAS_TORCH:
        print("torch is required for the GC-IQL baseline")
        return 1

    from fre.data import load_dataset

    dataset = load_dataset(
        domain=args.domain,
        env_name=args.env_name,
        dataset_path=args.dataset_path,
        dataset_dir=args.dataset_dir,
    )

    config = GCIQLConfig(
        domain=args.domain,
        steps=args.steps,
        batch_size=args.batch_size,
        learning_rate=args.lr,
        expectile=args.expectile,
        awr_temperature=args.temperature,
        discount=args.discount,
        target_update_rate=args.tau,
        seed=args.seed,
        device=args.device,
    )
    result = train_gc_iql(dataset=dataset, config=config, progress=True, log_every=args.log_every)
    agent = result["agent"]

    run_dir = args.run_dir or os.path.join("runs", "gc_iql", str(args.domain))
    os.makedirs(run_dir, exist_ok=True)
    torch.save(
        {
            "agent": agent.state_dict(),
            "hparams": agent.hparams(),
            "config": result["config"],
        },
        os.path.join(run_dir, "checkpoint.pt"),
    )
    with open(os.path.join(run_dir, "history.json"), "w", encoding="utf-8") as fh:
        json.dump(result["history"], fh, indent=2)

    if args.eval:
        summary = evaluate_gc_agent(
            agent,
            domain=args.domain,
            task_set=args.task_set,
            dataset=dataset,
            num_episodes=args.num_episodes,
            seeds=tuple(range(args.eval_seeds)),
        )
        with open(os.path.join(run_dir, "eval.json"), "w", encoding="utf-8") as fh:
            json.dump(summary, fh, indent=2, default=float)
        print(json.dumps(summary.get("task_sets", {}), indent=2, default=float))
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
