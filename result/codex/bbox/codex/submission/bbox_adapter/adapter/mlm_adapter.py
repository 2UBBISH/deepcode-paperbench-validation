"""Masked language modelling adapter (ablation of Section 4.5).

"For the MLM-based approach, we generate text chunks from the ground-truth
data, randomly masking words, and then train the adapter using the masked word
as supervision.  During inference, we apply a similar process: masking a random
word in each sequence generated by beam search and scoring the sequence based
on the probability of the masked word."
"""

from __future__ import annotations

import json
import os
import random
from typing import List, Optional, Sequence

import torch
import torch.nn as nn

from .base import BaseAdapter, TrainLog, TrainingExample
from .energy import format_pairs


class MLMAdapter(BaseAdapter, nn.Module):
    loss_type = "mlm"

    def __init__(self, model, tokenizer, name: str = "mlm-adapter", max_length: int = 512,
                 device: Optional[str] = None) -> None:
        nn.Module.__init__(self)
        BaseAdapter.__init__(self, name=name, max_length=max_length, device=device)
        self.model = model
        self.tokenizer = tokenizer
        if self._device is not None:
            self.to(self._device)

    @classmethod
    def from_pretrained(cls, model_name: str, max_length: int = 512,
                        device: Optional[str] = None) -> "MLMAdapter":
        from transformers import AutoModelForMaskedLM, AutoTokenizer  # type: ignore

        tokenizer = AutoTokenizer.from_pretrained(model_name)
        model = AutoModelForMaskedLM.from_pretrained(model_name)
        return cls(model=model, tokenizer=tokenizer, name=model_name,
                   max_length=max_length, device=device)

    # ------------------------------------------------------------- utilities
    def _masked_encoding(self, text: str, mask_index: int):
        encoding = self.tokenizer(text, return_tensors="pt", truncation=True,
                                  max_length=self.max_length)
        input_ids = encoding["input_ids"].clone()
        attention_mask = encoding["attention_mask"].clone()
        label = input_ids[0, mask_index].item()
        input_ids[0, mask_index] = self.tokenizer.mask_token_id
        return input_ids, attention_mask, label

    def _content_indices(self, input_ids: torch.Tensor) -> List[int]:
        special = set(self.tokenizer.all_special_ids)
        return [i for i, token in enumerate(input_ids[0].tolist()) if token not in special]

    # ------------------------------------------------------------------- fit
    def fit(self, examples: Sequence[TrainingExample], num_steps: Optional[int] = None,
            config=None, **kwargs) -> TrainLog:
        from ..config import AdapterConfig

        cfg = config or AdapterConfig(seed=0)
        num_steps = int(num_steps or cfg.num_train_steps)
        rng = random.Random(cfg.seed)
        self.train()
        optimizer = torch.optim.AdamW(
            [p for p in self.parameters() if p.requires_grad],
            lr=cfg.learning_rate,
            weight_decay=cfg.weight_decay,
        )
        # Ground-truth chunks used as the MLM training corpus.
        corpus = [example.positive for example in examples]
        log = TrainLog()
        for step in range(1, num_steps + 1):
            batch_texts = [rng.choice(corpus) for _ in range(cfg.batch_size)]
            input_ids_list, attention_list, labels, positions = [], [], [], []
            for text in batch_texts:
                tokens = self.tokenizer(text, truncation=True, max_length=self.max_length)
                ids = torch.tensor([tokens["input_ids"]])
                indices = self._content_indices(ids)
                if not indices:
                    continue
                mask_index = rng.choice(indices)
                ids = ids.clone()
                labels.append(ids[0, mask_index].item())
                positions.append(mask_index)
                ids[0, mask_index] = self.tokenizer.mask_token_id
                input_ids_list.append(ids[0])
                attention_list.append(torch.tensor(tokens["attention_mask"]))
            if not input_ids_list:
                continue
            input_ids = torch.nn.utils.rnn.pad_sequence(
                input_ids_list, batch_first=True, padding_value=self.tokenizer.pad_token_id or 0
            ).to(self.device)
            attention_mask = torch.nn.utils.rnn.pad_sequence(
                attention_list, batch_first=True, padding_value=0
            ).to(self.device)
            outputs = self.model(input_ids=input_ids, attention_mask=attention_mask)
            logits = outputs.logits
            target = torch.tensor(labels, device=self.device)
            rows = torch.arange(input_ids.size(0), device=self.device)
            masked_logits = logits[rows, torch.tensor(positions, device=self.device)]
            loss = nn.functional.cross_entropy(masked_logits, target)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(list(self.parameters()), 1.0)
            optimizer.step()
            optimizer.zero_grad(set_to_none=True)
            if step % 100 == 0 or step == 1 or step == num_steps:
                log.append(step, float(loss.detach().cpu()), 0.0, 0.0, 0.0)
        self.eval()
        return log

    # --------------------------------------------------------------- scoring
    @torch.no_grad()
    def score_batch(self, questions: Sequence[str], answers: Sequence[str]) -> torch.Tensor:
        self.eval()
        scores: List[float] = []
        for question, answer in zip(questions, answers):
            text = format_pairs([question], [answer])[0]
            tokens = self.tokenizer(text, truncation=True, max_length=self.max_length)
            ids = torch.tensor([tokens["input_ids"]])
            indices = self._content_indices(ids)
            if not indices:
                scores.append(0.0)
                continue
            # Deterministic "random" word selection so that repeated scoring of
            # the same sequence is stable.
            mask_index = indices[abs(hash((question, answer))) % len(indices)]
            input_ids, attention_mask, label = self._masked_encoding(text, mask_index)
            input_ids = input_ids.to(self.device)
            attention_mask = attention_mask.to(self.device)
            logits = self.model(input_ids=input_ids, attention_mask=attention_mask).logits
            log_probs = nn.functional.log_softmax(logits[0, mask_index], dim=-1)
            scores.append(float(log_probs[label].item()))
        return torch.tensor(scores)

    def score_lists(self, question: str, answers: Sequence[str]) -> List[float]:
        if not answers:
            return []
        return self.score_batch([question] * len(answers), list(answers)).tolist()

    # --------------------------------------------------------------- storage
    def save(self, directory: str) -> None:
        directory = self._ensure_dir(directory)
        self.model.save_pretrained(os.path.join(directory, "model"))
        self.tokenizer.save_pretrained(os.path.join(directory, "model"))
        with open(os.path.join(directory, "adapter_config.json"), "w", encoding="utf-8") as handle:
            json.dump({"name": self.name, "max_length": self.max_length, "loss_type": "mlm"}, handle)

    @classmethod
    def load(cls, directory: str, device: Optional[str] = None) -> "MLMAdapter":
        from transformers import AutoModelForMaskedLM, AutoTokenizer  # type: ignore

        model_dir = os.path.join(directory, "model")
        return cls(
            model=AutoModelForMaskedLM.from_pretrained(model_dir),
            tokenizer=AutoTokenizer.from_pretrained(model_dir),
            name=model_dir,
            device=device,
        )
