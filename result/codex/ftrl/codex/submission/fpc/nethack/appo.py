"""Asynchronous PPO (APPO) with knowledge retention for NetHack.

APPO (Petrenko et al., 2020) decouples sampling from learning: a pool of rollout
workers produces trajectories with a slightly stale copy of the policy, a
batcher assembles them into batches (``batch_size = 128`` trajectories of
``unroll_length = 32`` steps, Table 1) and the learner performs clipped PPO
updates.  The importance-sampling ratio between the worker policy and the
learner policy is clamped like in Sample Factory.

Knowledge retention (Appendix B.1):

* **Fine-tuning + KS**: auxiliary KL loss ``D_KL(pi_* || pi_theta)`` on the data
  generated by the online policy, scaled by ``0.5`` and decayed with ``0.99998``
  at every training step.  Entropy is switched off.
* **Fine-tuning + BC**: auxiliary loss on the expert (AutoAscend) trajectories,
  scaled by ``2.0`` with no decay.
* **Fine-tuning + EWC**: regularization coefficient ``2e6`` with the Fisher
  matrix computed from 10 000 batches of NLD-AA.

The encoders are frozen and retention is applied to the policy (actor) only.
"""

from __future__ import annotations

import queue
import threading
import time
from dataclasses import dataclass, field
from typing import Callable, Dict, List, Optional, Tuple

import numpy as np
import torch
import torch.nn as nn
import torch.nn.functional as F
from torch import Tensor
from torch.distributions import Categorical

from ..retention.base import RetentionConfig
from ..retention.distillation import kl_divergence
from ..retention.ewc import EWC
from .config import NetHackConfig
from .dataset import NetHackObservation, build_bc_buffer, fisher_batches, to_observation
from .model import NetHackModel


@dataclass
class Trajectory:
    """A trajectory segment produced by a rollout worker."""

    observations: NetHackObservation        # (T, H, W) style, one timestep per entry
    actions: Tensor
    log_probs: Tensor
    values: Tensor
    rewards: Tensor
    dones: Tensor
    policy_version: int = 0
    worker_id: int = 0

    def __len__(self) -> int:
        return int(self.actions.shape[0])


class RolloutWorker(threading.Thread):
    """Worker thread that samples trajectories with the shared policy."""

    def __init__(
        self,
        worker_id: int,
        env,
        config: NetHackConfig,
        output_queue: "queue.Queue[Trajectory]",
        model: NetHackModel,
        stop_event: threading.Event,
        policy_lock: threading.Lock,
        device: str = "cpu",
    ) -> None:
        super().__init__(daemon=True, name=f"worker-{worker_id}")
        self.worker_id = worker_id
        self.env = env
        self.config = config
        self.output_queue = output_queue
        self.local_model = NetHackModel(config).to(device)
        self.shared_model = model
        self.stop_event = stop_event
        self.policy_lock = policy_lock
        self.device = device
        self.policy_version = 0
        self.state = None

    # ------------------------------------------------------------------
    def sync_weights(self) -> None:
        with self.policy_lock:
            self.local_model.load_state_dict(self.shared_model.state_dict())
            self.policy_version = getattr(self.shared_model, "policy_version", 0)

    def _obs_to_tensors(self, obs) -> NetHackObservation:
        return NetHackObservation(
            glyphs=torch.as_tensor(obs["glyphs"][None, None, ...], dtype=torch.long, device=self.device),
            colors=torch.as_tensor(obs["colors"][None, None, ...], dtype=torch.long, device=self.device),
            blstats=torch.as_tensor(obs["blstats"][None, None, ...], dtype=torch.float32, device=self.device),
            message=torch.as_tensor(obs["message"][None, None, ...], dtype=torch.long, device=self.device),
        )

    def run(self) -> None:  # pragma: no cover - exercised through APPO.train
        self.sync_weights()
        obs = self.env.reset()
        self.state = self.local_model.initial_states(1, self.device)
        while not self.stop_event.is_set():
            # Refresh the policy every trajectory (approximate APPO behaviour).
            self.sync_weights()
            glyphs, colors, blstats, messages = [], [], [], []
            actions, log_probs, values, rewards, dones = [], [], [], [], []
            for _ in range(self.config.unroll_length):
                obs_t = self._obs_to_tensors(obs)
                with torch.no_grad():
                    action, log_prob, value, self.state = self.local_model.act(obs_t, self.state)
                next_obs, reward, done, _info = self.env.step(int(action.item()))
                if done:
                    next_obs = self.env.reset()
                    self.state = self.local_model.initial_states(1, self.device)
                glyphs.append(obs["glyphs"])
                colors.append(obs["colors"])
                blstats.append(obs["blstats"])
                messages.append(obs["message"])
                actions.append(int(action.item()))
                log_probs.append(float(log_prob.item()))
                values.append(float(value.item()))
                rewards.append(float(reward))
                dones.append(float(done))
                obs = next_obs
            trajectory = Trajectory(
                observations=NetHackObservation(
                    glyphs=torch.as_tensor(np.stack(glyphs), dtype=torch.long),
                    colors=torch.as_tensor(np.stack(colors), dtype=torch.long),
                    blstats=torch.as_tensor(np.stack(blstats), dtype=torch.float32),
                    message=torch.as_tensor(np.stack(messages), dtype=torch.long),
                ),
                actions=torch.as_tensor(actions, dtype=torch.long),
                log_probs=torch.as_tensor(log_probs, dtype=torch.float32),
                values=torch.as_tensor(values, dtype=torch.float32),
                rewards=torch.as_tensor(rewards, dtype=torch.float32),
                dones=torch.as_tensor(dones, dtype=torch.float32),
                policy_version=self.policy_version,
                worker_id=self.worker_id,
            )
            self.output_queue.put(trajectory)


class APPO:
    """Asynchronous PPO learner with knowledge-retention hooks."""

    def __init__(
        self,
        config: NetHackConfig,
        env_factory: Callable[[int], object],
        device: str = "cpu",
        teacher: Optional[NetHackModel] = None,
        bc_buffer: Optional[Dict[str, torch.Tensor]] = None,
        fisher: Optional[Dict[str, Tensor]] = None,
    ) -> None:
        self.config = config
        self.device = device
        self.model = NetHackModel(config).to(device)
        self.model.policy_version = 0
        self.optimiser = torch.optim.Adam(
            self.model.parameters(),
            lr=config.adam_learning_rate,
            betas=(config.adam_beta1, config.adam_beta2),
            eps=config.adam_eps,
            weight_decay=config.weight_decay,
        )
        if config.freeze_encoders:
            self.model.freeze_encoders()

        self.teacher = teacher.to(device) if teacher is not None else None
        if self.teacher is not None:
            for p in self.teacher.parameters():
                p.requires_grad_(False)
        self.bc_buffer = bc_buffer
        self.retention = self._build_retention(fisher)

        self.env_factory = env_factory
        self.output_queue: "queue.Queue[Trajectory]" = queue.Queue()
        self.policy_lock = threading.Lock()
        self.stop_event = threading.Event()
        self.workers: List[RolloutWorker] = []
        self.global_step = 0
        self.train_steps = 0
        self._rng = np.random.default_rng(config.seed)

    # ------------------------------------------------------------------
    def _build_retention(self, fisher: Optional[Dict[str, Tensor]]):
        cfg: RetentionConfig = self.config.retention
        if cfg.method in ("none", "em"):
            return None
        if cfg.method == "ewc":
            method = EWC(cfg)
            method.register_anchor(self.model)
            if fisher is not None:
                method.set_fisher(fisher)
            return method
        if cfg.method == "bc":
            from ..retention.distillation import BehavioralCloning

            return BehavioralCloning(cfg)
        if cfg.method == "ks":
            from ..retention.distillation import Kickstarting

            return Kickstarting(cfg)
        raise ValueError(f"Unsupported retention method {cfg.method!r}")

    # ------------------------------------------------------------------
    def start_workers(self) -> None:
        for worker_id in range(self.config.num_workers):
            worker = RolloutWorker(
                worker_id,
                self.env_factory(worker_id),
                self.config,
                self.output_queue,
                self.model,
                self.stop_event,
                self.policy_lock,
                self.device,
            )
            worker.start()
            self.workers.append(worker)

    def stop_workers(self) -> None:
        self.stop_event.set()
        for worker in self.workers:
            worker.join(timeout=5.0)
        self.workers.clear()

    # ------------------------------------------------------------------
    def sample_batch(self, max_wait: float = 30.0) -> List[Trajectory]:
        """Collect ``batch_size`` trajectories from the workers."""

        batch: List[Trajectory] = []
        deadline = time.time() + max_wait
        while len(batch) < self.config.batch_size and time.time() < deadline:
            try:
                batch.append(self.output_queue.get(timeout=1.0))
            except queue.Empty:
                continue
        return batch

    # ------------------------------------------------------------------
    def _gather(self, batch: List[Trajectory]) -> Dict[str, Tensor]:
        """Flatten a batch of trajectories into ``(B, T, ...)`` tensors."""

        glyphs = torch.stack([t.observations.glyphs for t in batch])
        colors = torch.stack([t.observations.colors for t in batch])
        blstats = torch.stack([t.observations.blstats for t in batch])
        message = torch.stack([t.observations.message for t in batch])
        return {
            "observations": NetHackObservation(glyphs=glyphs, colors=colors, blstats=blstats, message=message),
            "actions": torch.stack([t.actions for t in batch]).to(self.device),
            "log_probs": torch.stack([t.log_probs for t in batch]).to(self.device),
            "values": torch.stack([t.values for t in batch]).to(self.device),
            "rewards": torch.stack([t.rewards for t in batch]).to(self.device),
            "dones": torch.stack([t.dones for t in batch]).to(self.device),
        }

    def _retention_loss(self, batch_tensors: Dict[str, Tensor]) -> Tensor:
        if self.retention is None:
            return torch.zeros((), device=self.device)
        if isinstance(self.retention, EWC):
            if self.retention.fisher is None:
                self.compute_fisher()
            return self.retention.aux_loss(self.model)
        if self.teacher is None:
            return torch.zeros((), device=self.device)

        if self.config.retention.method == "bc" and self.bc_buffer is not None:
            size = min(128, self.bc_buffer["actions"].shape[0])
            idx = torch.randint(0, self.bc_buffer["actions"].shape[0], (size,))
            obs = NetHackObservation(
                glyphs=self.bc_buffer["glyphs"][idx].to(self.device).unsqueeze(1),
                colors=self.bc_buffer["colors"][idx].to(self.device).unsqueeze(1),
                blstats=self.bc_buffer["blstats"][idx].to(self.device).unsqueeze(1),
                message=self.bc_buffer["message"][idx].to(self.device).unsqueeze(1),
            )
            # The buffer stores the Expert (AutoAscend) actions: the BC loss is the
            # cross-entropy of the current policy on those expert actions, which
            # equals the forward KL up to the constant teacher entropy.
            expert_actions = self.bc_buffer["actions"][idx].to(self.device).unsqueeze(1)
            logits, _, _ = self.model(obs)
            dist = Categorical(logits=logits)
            return -dist.log_prob(expert_actions).mean()

        # Kickstarting: KL(pi_* || pi_theta) on the states visited online.
        obs = batch_tensors["observations"]
        with torch.no_grad():
            teacher_logits, _, _ = self.teacher(obs)
        student_logits, _, _ = self.model(obs)
        return kl_divergence(teacher_logits, student_logits, direction="forward").mean()

    def compute_fisher(self, num_batches: int = 100) -> None:
        """Estimate the diagonal Fisher from the pre-training distribution.

        In the full experiments the Fisher is computed from **10 000 batches** of
        NLD-AA (the addendum) and passed to the constructor.  When that is not
        available this method falls back to the states of the behavioral-cloning
        buffer, which come from the same distribution.
        """

        from ..retention.fisher import DiagonalFisher

        if not isinstance(self.retention, EWC):
            return
        if self.bc_buffer is None:
            raise RuntimeError(
                "EWC needs a Fisher matrix computed from NLD-AA; pass `fisher=` or "
                "`bc_buffer=` to APPO (see scripts/train_nethack.py --compute-fisher)."
            )

        def log_prob_fn(observations: NetHackObservation, **_):
            logits, _, _ = self.model(observations)
            dist = Categorical(logits=logits)
            return dist.log_prob(dist.sample())

        size = min(64, self.bc_buffer["actions"].shape[0])
        batches = []
        for _ in range(num_batches):
            idx = torch.randint(0, self.bc_buffer["actions"].shape[0], (size,))
            batches.append(
                {
                    "observations": NetHackObservation(
                        glyphs=self.bc_buffer["glyphs"][idx].to(self.device).unsqueeze(1),
                        colors=self.bc_buffer["colors"][idx].to(self.device).unsqueeze(1),
                        blstats=self.bc_buffer["blstats"][idx].to(self.device).unsqueeze(1),
                        message=self.bc_buffer["message"][idx].to(self.device).unsqueeze(1),
                    )
                }
            )
        self.retention.set_fisher(
            DiagonalFisher.estimate(self.model, log_prob_fn, batches, num_batches=num_batches)
        )

    # ------------------------------------------------------------------
    def ppo_update(self, batch: List[Trajectory]) -> Dict[str, float]:
        """One clipped PPO update on a batch of trajectories."""

        cfg = self.config
        tensors = self._gather(batch)
        obs, actions = tensors["observations"], tensors["actions"]
        old_log_probs, old_values = tensors["log_probs"], tensors["values"]
        rewards, dones = tensors["rewards"], tensors["dones"]

        with torch.no_grad():
            _, baseline, _ = self.model(obs)
            baseline = baseline.squeeze(-1)
            advantages = rewards + cfg.discounting * baseline * (1 - dones) - old_values
            returns = advantages + old_values
        advantages = (advantages - advantages.mean()) / (advantages.std() + 1e-8)

        logits, baseline, _ = self.model(obs)
        dist = Categorical(logits=logits)
        new_log_probs = dist.log_prob(actions)
        entropy = dist.entropy().mean()

        # Clipped PPO objective.  Sample Factory's APPO additionally corrects for
        # the policy lag of the asynchronous workers with a truncated importance
        # sampling ratio; here the worker policy is refreshed once per trajectory
        # (see RolloutWorker.run), so ``old_log_probs`` already come from the
        # behaviour policy and the standard single-clip objective applies.
        log_ratio = new_log_probs - old_log_probs
        ratio = torch.exp(log_ratio)
        surr1 = ratio * advantages
        surr2 = (
            torch.clamp(ratio, 1.0 - cfg.appo_clip_policy, 1.0 + cfg.appo_clip_policy) * advantages
        )
        policy_loss = -torch.min(surr1, surr2).mean()

        baseline_clipped = old_values + torch.clamp(
            baseline.squeeze(-1) - old_values, -cfg.appo_clip_baseline, cfg.appo_clip_baseline
        )
        baseline_loss = torch.max(
            (baseline.squeeze(-1) - returns) ** 2,
            (baseline_clipped - returns) ** 2,
        ).mean()

        entropy_cost = 0.0 if self.retention is not None else cfg.entropy_cost
        loss = policy_loss + cfg.baseline_cost * baseline_loss - entropy_cost * entropy

        retention_loss = self._retention_loss(tensors)
        if self.retention is not None:
            loss = loss + self.retention.coefficient * retention_loss

        self.optimiser.zero_grad()
        loss.backward()
        nn.utils.clip_grad_norm_(self.model.parameters(), cfg.grad_norm_clipping)
        self.optimiser.step()
        self.model.policy_version = getattr(self.model, "policy_version", 0) + 1
        if self.retention is not None:
            self.retention.on_train_step()
        self.train_steps += 1

        return {
            "policy_loss": float(policy_loss.item()),
            "baseline_loss": float(baseline_loss.item()),
            "entropy": float(entropy.item()),
            "retention_loss": float(retention_loss.item()),
        }

    # ------------------------------------------------------------------
    def pretrain_baseline_head(self, steps: Optional[int] = None) -> None:
        """Freeze everything but the baseline head and pre-train it for 500M steps.

        Appendix B.1: "To improve stability during the beginning of the
        fine-tuning we additionally pre-train the baseline head by freezing the
        rest of the model for 500M environment steps."

        Usage::

            appo.pretrain_baseline_head()          # freeze everything but the baseline
            appo.train(total_steps=500_000_000)    # baseline-only pre-training
            appo.finish_baseline_pretraining()     # unfreeze the policy/encoders
            appo.train(total_steps=500_000_000)    # actual fine-tuning with retention
        """

        steps = steps or self.config.bc_head_only_steps
        for name, p in self.model.named_parameters():
            p.requires_grad_(name.startswith("baseline_head"))
        self._baseline_pretrain_steps = steps
        self.baseline_pretraining = True

    def finish_baseline_pretraining(self) -> None:
        """Restore the trainable parameters after the baseline-head pre-training.

        The encoders stay frozen when ``config.freeze_encoders`` is set (Appendix
        B.1), everything else becomes trainable again.
        """

        for p in self.model.parameters():
            p.requires_grad_(True)
        if self.config.freeze_encoders:
            self.model.freeze_encoders()
        self.baseline_pretraining = False

    def train(self, total_steps: Optional[int] = None, callback: Optional[Callable] = None) -> Dict[str, list]:
        """Run the asynchronous training loop."""

        total_steps = total_steps or self.config.total_steps
        self.start_workers()
        history: Dict[str, list] = {"steps": [], "policy_loss": [], "baseline_loss": [], "entropy": []}
        try:
            while self.global_step < total_steps:
                batch = self.sample_batch()
                if not batch:
                    continue
                stats = self.ppo_update(batch)
                self.global_step += sum(len(t) for t in batch)
                history["steps"].append(self.global_step)
                for key in ("policy_loss", "baseline_loss", "entropy"):
                    history[key].append(stats[key])
                if callback is not None:
                    callback(self)
        finally:
            self.stop_workers()
        return history
