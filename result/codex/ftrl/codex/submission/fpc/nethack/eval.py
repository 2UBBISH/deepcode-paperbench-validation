"""NetHack evaluation (Figure 3a, Figure 5, Table 4, Table 5).

Two evaluation protocols are used in the paper:

* **full evaluation** -- the last checkpoint of each run is rolled out for 1000
  episodes and the metrics of Table 4 are reported (score, turns, steps, dungeon
  level, experience level, eating score, gold, scout score, Sokoban score and
  staircase score),
* **per-level evaluation** -- the AutoAscend expert plays the game and saves the
  state when it reaches the desired level (level 4 and the Sokoban level in the
  main text); 200 saves per level are generated and each agent is evaluated on
  every save, starting from where the expert finished and reporting the score it
  obtains on top of the expert's score (Figure 5).  This is evaluated every 25M
  environment steps.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Dict, List, Optional

import numpy as np


@dataclass
class NetHackMetrics:
    score: float = 0.0
    turns: float = 0.0
    steps: float = 0.0
    dlvl: float = 0.0          # maximum dungeon level reached
    xplvl: float = 0.0         # experience level
    eating: float = 0.0        # eating score
    gold: float = 0.0          # gold score
    scout: float = 0.0         # scout score
    sokoban: float = 0.0       # filled pits in the Sokoban levels
    staircase: float = 0.0     # staircase score


def full_evaluation(agent, config, episodes: int = 1000, seed: int = 0) -> NetHackMetrics:
    """Roll out ``episodes`` full games and average the Table-4 metrics."""

    from .env import NetHackEnv

    env = NetHackEnv(config, seed=seed)
    totals = NetHackMetrics()
    max_level = 0
    for episode in range(episodes):
        obs = env.reset()
        done = False
        while not done:
            action = agent.act(obs)
            obs, reward, done, info = env.step(action)
        blstats = obs["blstats"]
        totals.score += float(blstats[9]) if len(blstats) > 9 else float(info_score(info))
        totals.turns += float(blstats[20]) if len(blstats) > 20 else 0.0
        totals.steps += float(blstats[19]) if len(blstats) > 19 else 0.0
        max_level = max(max_level, int(blstats[12]) if len(blstats) > 12 else 1)
        totals.dlvl += max_level
        totals.xplvl += float(blstats[18]) if len(blstats) > 18 else 0.0
        totals.gold += float(blstats[13]) if len(blstats) > 13 else 0.0
    env.close()
    for field_name in totals.__dataclass_fields__:
        setattr(totals, field_name, getattr(totals, field_name) / episodes)
    return totals


def info_score(info: Dict) -> float:
    return float(info.get("score", 0.0))


def evaluate_from_saves(agent, saves: List[bytes], env, episodes_per_save: int = 1) -> float:
    """Evaluate ``agent`` from AutoAscend save states (Figure 5).

    ``saves`` are the 200 emulator save states generated by the AutoAscend expert
    for the level of interest.  The agent is loaded into each save and the score
    it accumulates on top of the expert's score is reported.
    """

    scores: List[float] = []
    for save in saves:
        for _ in range(episodes_per_save):
            env.env.unwrapped.ale.restoreState(save) if hasattr(env.env.unwrapped, "ale") else None
            obs = env.reset()
            done = False
            total = 0.0
            while not done:
                action = agent.act(obs)
                obs, reward, done, _info = env.step(action)
                total += reward
            scores.append(total)
    return float(np.mean(scores)) if scores else 0.0


def level_visitation(agent, config, episodes: int = 100, seed: int = 0):
    """Return ``(max_level, turns)`` pairs for the density plots (Figure 4, 16)."""

    from .env import NetHackEnv

    env = NetHackEnv(config, seed=seed)
    max_levels, turns = [], []
    for episode in range(episodes):
        obs = env.reset()
        done = False
        level = 1
        while not done:
            action = agent.act(obs)
            obs, _reward, done, _info = env.step(action)
            level = max(level, int(obs["blstats"][12]) if len(obs["blstats"]) > 12 else 1)
        blstats = obs["blstats"]
        max_levels.append(level)
        turns.append(int(blstats[20]) if len(blstats) > 20 else 0)
    env.close()
    return np.asarray(max_levels), np.asarray(turns)


